int l, r;
int n, m;
int stx, sty;
char a[N][N];
int dis[N][N];
struct node
{
    int x, y;
    int l, r;
};
deque<node> q;
vector<int> dy = {0, 0, 1, -1};
vector<int> dx = {1, -1, 0, 0};
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m && a[x][y] != '*');
}
void bfs()
{
    q.push_back({stx, sty, 0, 0});
    dis[stx][sty] = 0;
    while(!q.empty())
    {
        node u = q.front();
        q.pop_front();
        int x = u.x;
        int y = u.y;
        int left = u.l;
        int right = u.r;
        if(dis[x][y] < u.l + u.r) continue;
        for(int i = 0; i < 4; i++)
        {
            int xx = x + dx[i];
            int yy = y + dy[i];
            if(i < 2)
            {
                if(check(xx, yy) && dis[xx][yy] > dis[x][y])
                {
                    dis[xx][yy] = dis[x][y];
                    q.push_front({xx, yy, left, right});
                }
            }
            else
            {
                if(check(xx, yy) && dis[xx][yy] > dis[x][y] + 1)
                {
                    if(i == 2 && right + 1 <= r)
                    {
                        dis[xx][yy] = dis[x][y] + 1;
                        q.push_back({xx, yy, left, right + 1});
                    }
                    if(i == 3 && left + 1 <= l)
                    {
                        dis[xx][yy] = dis[x][y] + 1;
                        q.push_back({xx, yy, left + 1, right});
                    }
                }
            }
        }
    }

}
