int sum[N];
int ans = 0;
void dfs(int u, int p)
{
    // dp[u] = a[u];
    sum[u] = a[u];
    for(auto v : g[u])
    {
        if(v == p) continue;
        dis[v] = dis[u] + 1;
    
        dfs(v, u);
        sum[u] += sum[v];
        // dp[u] += a[v] + dp[v];
    }
}
void dfs2(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p) continue;
        dp[v] = dp[u] + sum[1] - 2 * sum[v];
        dfs2(v, u);
        // ans = max(ans, dp[v]);
        
    }
    // ans = max(ans, dp[u]);
}
