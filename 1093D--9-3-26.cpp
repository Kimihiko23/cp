int n, m;
vector<int> g[N];
int col[N];
int pow2[N];
void cal()
{
    pow2[0] = 1;
    for(int i = 1; i < N; i++)
    {
        pow2[i] = (pow2[i - 1] * 2) % MOD;
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        col[i] = -1;
        g[i].clear();
    }
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    int ans = 1;
    // for(int i = 1; i <= n; i++)
    // {
    //     col[i] = -1;
    // }
    for(int i = 1; i <= n; i++)
    {
        if(col[i] != -1) continue;
        queue<int> q;
        int cnt0 = 0, cnt1 = 0;
        q.push(i);
        col[i] = 0;
        cnt0++;
        while(!q.empty())
        {
            int u = q.front();
            q.pop();
            for(auto v : g[u])
            {
                if(col[v] == -1)
                {
                    col[v] = col[u] ^ 1;
                    if(col[v] == 0) cnt0++;
                    else cnt1++;
                    q.push(v);
                }
                else
                {
                    if(col[v] == col[u])
                    {
                        cout << 0 << "\n";
                        return;
                    }
                }
            }
        }
        ans = (ans * ((pow2[cnt0] + pow2[cnt1]) % MOD)) % MOD;
    }
    cout << ans << "\n";
}
