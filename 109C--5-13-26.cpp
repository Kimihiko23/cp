const int N = 1e5 + 23;
int par[N];
vector<pair<int ,int>> g;
int sz[N];
int n;
int find(int x)
{
    if(x != par[x])
    {
        par[x] = find(par[x]);
    }
    return par[x];
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(u == v)
        return;
    int sz1 = sz[u];
    int sz2 = sz[v];
    if(sz1 > sz2)
        swap(u, v);
    sz[v] += sz[u];
    par[u] = v;
}
void read()
{
    cin >> n;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        string s;
        cin >> u >> v >> s;
        bool dd = true;
        for(auto j : s)
        {
            if(j != '4' && j !='7')
            {
                dd = false;
                break;
            }
        }
        if(!dd)
        g.push_back({u, v});
    }
}
void solve()
{
    // cout << g.size();
    for(int i = 1; i <= n; i++)
    {
        sz[i] = 1;
        par[i] = i;
    }
    for(auto i : g)
    {
        join(i.fi, i.se);
        // cout << i.fi << " " << i.se;
    }
    // cout << find(1);
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int acs = find(i);
        int szz = sz[acs];
        ans += (n - szz) * (n - szz - 1);
        // cout << sz[acs];
    }
    cout << ans;
}
