const int N =2e5+23;
int a[N];
int n, q;
struct ar
{
    int sum;
    int mn;
    int cmn;
    int mx;
    int cmx;
    int gc;
    int cgcd;
    int lcm;
    int clcm;
    int lazy;
    ar()
    {
        sum = 0;
        mn = 1e18;
        cmn = 0;
        mx = -1e18;
        cmx = 0;
        gc = 0;
        cgcd = 0;
        lcm = 1;
        clcm = 0;
        lazy = 0;
    }
};
ar st[N*4];
ar emp;
ar combine(ar a,ar b)
{
    if(a.cmn == emp.cmn)
		return b;
	if(b.cmn == emp.cmn)
		return a;
     ar res;
     res.sum = a.sum + b.sum;
     if(a.mn < b.mn)
     {
        res.mn = a.mn;
        res.cmn = a.cmn;
     }
     else
     if(a.mn > b.mn)
     {
        res.mn = b.mn;
        res.cmn = b.cmn;
     }
     else
     {
        res.mn = a.mn;
        res.cmn = b.cmn + a.cmn;
     }

     if(a.mx > b.mx)
     {
        res.mx = a.mx;
        res.cmx = a.cmx;
     }
     else
     if(a.mx < b.mx)
     {
        res.mx = b.mx;
        res.cmx = b.cmx;
     }
     else
     {
        res.mx = a.mx;
        res.cmx = b.cmx + a.cmx;
     }
    res.gc = __gcd(a.gc, b.gc);
    if(res.gc == a.gc)
        res.cgcd += a.cgcd;
    if(res.gc == b.gc)
        res.cgcd += b.cgcd;
    if(res.gc != a.gc && res.gc != b.gc)
        res.cgcd = 0;
    res.lcm = (a.lcm / __gcd(a.lcm, b.lcm)) * b.lcm;
    if(res.lcm == a.lcm)
        res.clcm += a.clcm;
    if(res.lcm == b.lcm)
        res.clcm += b.clcm;
    if(res.lcm != a.lcm && res.lcm != b.lcm)
        res.clcm = 0;
    return res;
     
}
void lazy_equal(int id , int l , int r , int x)
{
	st[id].sum = (r - l + 1) * x;
	st[id].mn = x;
	st[id].cmn = r - l + 1;
	st[id].mx = x;
	st[id].cmx = r - l + 1;
	st[id].gc = x;
	st[id].cgcd = r - l + 1;
	st[id].lcm = x;
	st[id].clcm = r - l + 1;
	st[id].lazy = x;
}
void push(int id , int l , int r , int mid)
{
	if(st[id].lazy != 0)
	{
		lazy_equal(id * 2 , l , mid , st[id].lazy);
		lazy_equal(id * 2 + 1 , mid + 1 , r , st[id].lazy);
		st[id].lazy = 0;
	}
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].sum = a[l];
        st[id].mn = a[l];
        st[id].cmn = 1;
        st[id].mx = a[l];
        st[id].cmx = 1;
        st[id].gc = a[l];
        st[id].cgcd = 1;
        st[id].lcm = a[l];
        st[id].clcm = 1;
        st[id].lazy = 0;
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        lazy_equal(id, l, r, val);
        return;
    }
    push(id, l, r, (l + r) / 2);
    int mid = (l + r) / 2;
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1, u, v, val);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
ar get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return emp;
    if(l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    return combine(get(l, mid, id * 2, u, v), get(mid + 1, r, id * 2 + 1, u, v));
}
