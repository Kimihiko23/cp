int n;
int a[N];
int dp[N][N][2];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[i][j][1] = 1e18;
            dp[i][j][0] = 1e18;
        }
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        dp[i][i][1] = 0;
        dp[i][i][0] = 0;
    }
}
void solve()
{
    for(int len = 2; len <= n; len++)
    {
        for(int i = 1; i <= n; i++)
        {
            int j = i + len - 1;
            if(a[i] == a[i + 1])
                dp[i][j][0] = min(dp[i][j][0], dp[i + 1][j][0]);
            else
                dp[i][j][0] = min(dp[i][j][0], dp[i + 1][j][0] + 1);

            if(a[j] == a[j - 1])
                dp[i][j][1] = min(dp[i][j][1], dp[i][j - 1][1]);
            else
                dp[i][j][1] = min(dp[i][j][1], dp[i][j - 1][1] + 1);
            
            if(a[i] == a[j])
            {
                dp[i][j][0] = min(dp[i][j][0], dp[i + 1][j][1]);
                dp[i][j][1] = min(dp[i][j][1], dp[i][j - 1][0]);
            }
            else
            {
                dp[i][j][0] = min(dp[i][j][0], dp[i + 1][j][1] + 1);
                dp[i][j][1] = min(dp[i][j][1], dp[i][j - 1][0] + 1);
            }
        }
    }
    cout << min(dp[1][n][0], dp[1][n][1]);
}
