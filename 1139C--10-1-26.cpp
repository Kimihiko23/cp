void solve()
{
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    set<int> s;
    for(auto i : edg)
    {
        join(i.fi, i.se);
    }
    for(int i = 1; i <= n; i++)
    {
        int tam = i;
        tam = findpar(tam);
        s.insert(tam);
    }
    int sum = 0;
    for(auto i : s)
    {
        sum += binpow(sz[i], k);
        sum %= MOD;
    }
    cout << ((ans - sum) % MOD + MOD) % MOD;

}
