int n, k;
int binpow(int x, int pw)
{
    int res = 1;
    while(pw)
    {
        if(pw & 1)
            res *= x;
        res %= MOD;
        x *= x;
        x %= MOD;
        pw >>= 1;
    }
    return res;
}
vector<pair<int, int>> edg;
int par[N], sz[N];
int findpar(int x)
{
    if(par[x] != x)
        par[x] = findpar(par[x]);
    return par[x];
}
void join(int u, int v)
{
    u = findpar(u);
    v = findpar(v);
    if(u == v)
        return;
    if(sz[v] > sz[u])
        swap(u, v);
    sz[u] += sz[v];
    par[v] = u;
}
