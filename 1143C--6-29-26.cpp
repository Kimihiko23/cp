const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int n;
vector<int> del;
int c[N];
vector<int> g[N];
int par[N];
int dirsum[N];
int st = 0;
void dfs(int u, int p)
{
    for(int v : g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dirsum[u] += c[v];
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> par[i] >> c[i];
        if(par[i] != -1)
        {
            g[par[i]].pb(i);
            g[i].pb(par[i]);
        }
        if(par[i] == -1)
        {
            st = i;
        }
        if(c[i])
        {
            del.pb(i);
        }
    }
}
void solve()
{
    dfs(st, 0);
    sort(del.begin(), del.end());
    bool ok = 1;
    for(auto u : del)
    {
        if(g[u].size() - 1 == dirsum[u])
        {
            cout << u << " ";
            ok = 0;
        }
    }
    if(ok)
    {
        cout << -1;
    }
}
