const int N = 5e5 + 23;
int par[N];
int sz[N];
int find(int x)
{
    if (par[x] == x) return x;
    return par[x] = find(par[x]);
}
void join(int x, int y)
{
    x = find(x);
    y = find(y);
    if (x == y) return;
    if (sz[x] < sz[y]) swap(x, y);
    par[y] = x;
    sz[x] += sz[y];
}
int n, m;
void read()
{
    cin >> n >> m;
    int x, vt;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> x;
        vector<int> a;
        for(int j = 1; j <= x; j++)
        {
            cin >> vt;
            a.pb(vt);
        }
        for(int j = 1; j < a.size(); j++)
        {
            join(a[j], a[j - 1]);
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        cout << sz[find(i)] << " ";
    }
}
