mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int sz[N];
int n;
vector<int> g[N];
int h[N];
int dp[N];
void dfs(int u, int p)
{
    sz[u] = 1;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        h[v] = h[u] + 1;
        dfs(v, u);
        sz[u] += sz[v];
    }
}
void dfs2(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dp[v] = dp[u] - sz[v] + (n - sz[v]);
        dfs2(v, u);
    }
}
void read()
{
    cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0);
    int tam = 0;
    for(int i = 1; i <= n; i++)
    {
        tam += sz[i];
    }
    dp[1] = tam;
    dfs2(1, 0);
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
