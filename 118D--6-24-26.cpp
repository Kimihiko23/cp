const int MOD1 = 1000020409;
const int MOD = 1e8;
const int N = 1e5 + 23;
int n1, n2, k1, k2;
int dp[105][105][15][15];
void read()
{
    cin >> n1 >> n2 >> k1 >> k2;
}
void solve()
{
    dp[1][0][0][1] = 1;
    dp[0][1][1][1] = 1;
    //i, j, ty, k = men, hourse, who end, contiously
    for(int i = 0; i <= n1; i++)
    {
        for(int j = 0; j <= n2; j++)
        {
            for(int k = 2; k <= k1; k++)
            {
                if(i == 0)
                    continue;
                dp[i][j][0][k] += dp[i - 1][j][0][k - 1];
                dp[i][j][0][k] %= MOD;
            }
            for(int k = 1; k <= k2; k++)
            {
                if(i == 0)
                    continue;
                dp[i][j][0][1] += dp[i - 1][j][1][k];
                dp[i][j][0][1] %= MOD;
            }
            for(int k = 2; k <= k2; k++)
            {
                if(j == 0)
                    continue;
                dp[i][j][1][k] += dp[i][j - 1][1][k - 1];
                dp[i][j][1][k] %= MOD;
            }
            for(int k = 1; k <= k1; k++)
            {
                if(j == 0)
                    continue;
                dp[i][j][1][1] += dp[i][j - 1][0][k];
                dp[i][j][1][1] %= MOD;
            }
        }
    }
    int ans = 0;
    for(int k = 1; k <= k1; k++)
    {
        ans += dp[n1][n2][0][k];
        ans %= MOD;
    }
    for(int k = 1; k <= k2; k++)
    {
        ans += dp[n1][n2][1][k];
        ans %= MOD;
    }
    cout << ans << "\n";
}
