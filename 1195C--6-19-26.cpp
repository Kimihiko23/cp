void solve()
{
    dp[1][0] = a[1];
    dp[1][1] = b[1];
    for(int i = 2; i <= n; i++)
    {
        dp[i][0] = max(dp[i - 1][0], dp[i - 1][1] + a[i]);
        dp[i][1] = max(dp[i - 1][1], dp[i - 1][0] + b[i]);
    }
    cout << max(dp[n][0], dp[n][1]);
}
