using namespace std;
#define name "input"

const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;

int n, k;
vector<int> a;

void read()
{
    cin >> n >> k;
    a.resize(n);
    for (int &x : a) cin >> x;
}

bool check(int x)
{
    int mid = n / 2;
    long long need = 0;

    for (int i = mid; i < n; i++)
    {
        if (a[i] < x)
        {
            need += x - a[i];
            if (need > k) return false;
        }
    }

    return need <= k;
}

void solve()
{
    sort(a.begin(), a.end());

    int l = a[n / 2];
    int r = (int)2e9;
    int ans = l;

    while (l <= r)
    {
        int mid = (l + r) >> 1;

        if (check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    cout << ans;
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    if (fopen("input.txt","r"))
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }

    read();
    solve();
}