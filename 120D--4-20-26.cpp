using namespace std;
const int N =100;
const int MOD = 1000020409;
int n, m;
int pre[N][N];
int ans = 0;
vector<int> check;
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            int x;
            cin >> x;
            pre[i][j] = pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1] + x;
        }   
    }
    for(int i = 1; i <= 3; i++)
    {
        int x;
        cin >> x;
        check.pb(x);
    }
}
void solve()
{
    //cot duoc dat o giua i va i + 1, j va j + 1
    //dang dat cot ngang
    sort(check.begin(), check.end());
    vector<int> tam;
    for(int i = 1; i < n; i++)
    {
        for(int j = i + 1; j < n; j++)
        {
            tam.clear();
            tam.pb(cal(1, 1, i, m));
            tam.pb(cal(i + 1, 1, j, m));
            tam.pb(cal(j + 1, 1, n, m));
            sort(tam.begin(), tam.end());
            if(tam == check)
            {
                ans++;
            }
        }
    }
    for(int i = 1; i < m; i++)
    {
        for(int j = i + 1; j < m; j++)
        {
            tam.clear();
            tam.pb(cal(1, 1, n, i));
            tam.pb(cal(1, i + 1, n, j));
            tam.pb(cal(1, j + 1, n, m));
            sort(tam.begin(), tam.end());
            if(tam == check)
            {
                ans++;
            }
        }
    }
    cout << ans;

}   

