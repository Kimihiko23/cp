const int MOD = 1000020409;
const int N = 1e2 + 23;
int n;
vector<int> g[N];
vector<int> ans;
int dist[N];
void dfs(int u, int p)
{
    // dist[u] = 1;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dist[v] = dist[u] + 1;
        dfs(v, u);

    }
}
void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        int m;
        cin >> m;
        for(int j = 1; j < m; j++)
        {
            int u, v;
            cin >> u >> v;
            g[u].pb(v);
            g[v].pb(u);
        }
        dfs(1, 0);
        int vt = 1;
        int mx = 0;
        for(int j = 1; j <= m; j++)
        {
            if(dist[j] > mx)
            {
                mx = dist[j];
                vt = j;
            }
            // cout << dist[j] << " ";
        }
        // cout << vt;
        dist[vt] = 0;
        dfs(vt, 0);
        mx = 0;
        for(int j = 1; j <= m; j++)
        {
            if(dist[j] > mx)
            {
                mx = dist[j];
                vt = j;
            }
            // cout << dist[j] << " ";
        }
        ans.pb(mx);
        for(int j = 1; j <= m; j++)
        {
            g[j].clear();
            dist[j] = 0;
        }
    }
}
void solve()
{
    int res = 0;
    for(auto v : ans)
    {
        res += v;
    }
    cout << res;
}
