set<int> s[N];
int n, m;
int dd[N];
set<int> needvis;
void bfs(int st)
{
    queue<int> q;
    q.push(st);
    dd[st] = 1;
    needvis.erase(needvis.find(st));
    while(!q.empty())
    {
        int u = q.front();
        q.pop();
        vector<int> del;
        del.clear();
        for(auto v : needvis)
        {            
            if(v != u && s[u].find(v) == s[u].end() &&!dd[v])
            {
                del.pb(v);
                dd[v] = 1;
                q.push(v);
            }
        }
        for(auto i : del)
        {
            needvis.erase(needvis.find(i));
        }
        
        
    }
    
}
void read()
{
    cin >> n >> m;
    int u, v;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v;
        s[u].insert(v);
        s[v].insert(u);
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        needvis.insert(i);
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        if(!dd[i])
        {
            ans++;
            bfs(i);
        }
    }
    cout << ans - 1;
}
