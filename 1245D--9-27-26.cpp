void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = i + 1; j <= n; j++)
        {
            edg.pb({(k[i] + k[j]) * (abs(cord[i].fi - cord[j].fi) + abs(cord[i].se - cord[j].se)), {i, j}});
        }
    }
    for(int i = 0; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    int ans = 0, conect = 0, buil = 0;
    sort(edg.begin(), edg.end());
    for(auto i : edg)
    {
        int x = i.se.fi;
        int y = i.se.se;
        int w = i.fi;
        if(findpar(x) != findpar(y))
        {
            if(y == 0)
            {
                buil++;
                power.pb(x);
            }
            else
            {
                conect++;
                edgb.pb({x, y});
            }
            ans += w;
            join(x, y);
        }
    }
    cout << ans << "\n";
    cout << buil << "\n";
    for(auto i : power)
        cout << i << " ";
    cout << "\n";
    cout << conect << "\n";
    for(auto i : edgb)
    {
        cout << i.fi << " " << i.se << "\n";
    }
}
