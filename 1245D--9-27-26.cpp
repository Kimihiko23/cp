pair<int, int> cord[N];
int c[N], k[N], n, par[N], sz[N];
int findpar(int x)
{
    if(par[x] != x)
        par[x] = findpar(par[x]);
    return par[x];
}
void join(int u, int v)
{
    u = findpar(u);
    v = findpar(v);
    if(u == v)
        return;
    if(sz[v] > sz[u])
        swap(u, v);
    sz[u] += sz[v];
    par[v] = u;
}
