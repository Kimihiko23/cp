const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m, k, q;
vector<pair<int, int>> g[N], g2[N];
vector<pair<int, pair<int, int>>> edg2, edg;
int dis[N];
int par[N];
int sz[N];
int parlca[N][30];
int mx[N][30];
int h[N];
int own[N];
priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
void dijkstra()
{
    while(!pq.empty())
    {
        auto i = pq.top();
        pq.pop();
        int u = i.se;
        int w = i.fi;
        if(w > dis[u]) continue;
        for(auto j : g[u])
        {
            int v = j.fi;
            int w2 = j.se;
            if(dis[v] > dis[u] + w2)
            {
                own[v] = own[u];
                dis[v] = dis[u] + w2;
                pq.push({dis[v], v});
            }
        }
    }
}
int findp(int x)
{
    if(par[x] != x)
        par[x] = findp(par[x]);
    return par[x];
}
void dfs(int u, int p)
{
    for(auto i : g2[u])
    {
        int v = i.fi;
        int w = i.se;
        if(v == p) continue;
        parlca[v][0] = u;
        h[v] = h[u] + 1;
        mx[v][0] = w;
        dfs(v, u);
    }
}
void init()
{
    for(int i = 1; i < 30; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            parlca[j][i] = parlca[parlca[j][i - 1]][i - 1];
            mx[j][i] = max(mx[j][i - 1], mx[parlca[j][i - 1]][i - 1]);
        }
    }
}
void join(int u, int v)
{
    u = findp(u);
    v = findp(v);
    if(v == u) return;
    if(sz[u] < sz[v]) swap(u, v);
    sz[u] += sz[v];
    par[v] = u;
}
void read()
{
    cin >> n >> m >> k >> q;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
        edg.pb({w, {u, v}});
    }
}
int lca(int u, int v)
{
    int ans = -1e18;
    if(h[u] < h[v])
        swap(u, v);
    for(int i = 29; i >= 0; i--)
    {
        if(h[parlca[u][i]] >= h[v])
        {
            ans = max(ans, mx[u][i]);
            u = parlca[u][i];
        }
    }
    if(u == v)
        return ans;
    for(int i = 29; i >= 0; i--)
    {
        if(parlca[u][i] != parlca[v][i])
        {
            ans = max(ans, mx[u][i]);
            ans = max(ans, mx[v][i]);
            u = parlca[u][i];
            v = parlca[v][i];
        }
    }
    ans = max(ans, mx[u][0]);
    ans = max(ans, mx[v][0]);
    return ans;
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        own[i] = i;
        par[i] = i;
        sz[i] = 1;
        dis[i] = INF;
    }
    for(int i = 1; i <= k; i++)
    {
        dis[i] = 0;
        pq.push({0, i});
    }
    dijkstra();
    for(auto i : edg)
    {
        int u = i.se.fi;
        int v = i.se.se;
        int w = i.fi + dis[u] + dis[v];
        if(own[u] == own[v]) continue;
        edg2.pb({w, {own[u], own[v]}});
        // edg2.pb({w, {u, v}});
    }
    sort(edg2.begin(), edg2.end());
    for(auto i : edg2)
    {
        int u = i.se.fi;
        int v = i.se.se;
        // cout << u << " " << v << " " << i.fi << "\n";
        u = findp(u);
        v = findp(v);
        if(u == v) continue;
        join(u, v);
        g2[u].pb({v, i.fi});
        g2[v].pb({u, i.fi});
        // cout << u << " " << v << " " << i.fi << "\n";
    }
    dfs(1, 0);
    parlca[1][0] = 1;
    init();
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        cout << lca(u, v) << "\n";
    }

}
