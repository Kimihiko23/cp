void solve()
{
    int ans = 0;
    int tam = 0;
    for(int i = 1; i < n; i++)
    {
        tam += a[i];
        ans = max(ans, tam);
        if(tam < 0)
            tam = 0;
        ans = max(ans, tam);
    }
    tam = 0;
    for(int i = 2; i <= n; i++)
    {
        tam += a[i];
        // cout << tam << "\n";
        ans = max(ans, tam);
        if(tam < 0)
            tam = 0;
        ans = max(ans, tam);
    }
    // cout << ans << "\n";
    // cout << sum << "\n";
    if(ans < sum)
    {
        cout << "YES\n";
    }
    else
        cout << "NO\n";
}
