int n, h, l, r;
int a[N];
int dp[N][N];

void read()
{
    cin >> n >> h >> l >> r;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}

void solve()
{
    for (int i = 0; i <= n; i++)
    {
        for (int j = 0; j < h; j++)
        {
            dp[i][j] = -1;
        }
    }

    dp[0][0] = 0;

    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < h; j++)
        {
            if (dp[i][j] == -1) continue;
            int t1 = (j + a[i + 1]) % h;
            int good1 = (l <= t1 && t1 <= r);
            dp[i + 1][t1] = max(dp[i + 1][t1], dp[i][j] + good1);

           
            int t2 = (j + a[i + 1] - 1) % h;
            int good2 = (l <= t2 && t2 <= r);
            dp[i + 1][t2] = max(dp[i + 1][t2], dp[i][j] + good2);
        }
    }

    int ans = 0;
    for (int j = 0; j < h; j++)
    {
        ans = max(ans, dp[n][j]);
    }
    cout << ans;
}

