int n;
vector<pair<int, int>> edg;
vector<pair<int, int>> g[N];
int ans[N];
int in[N];
set<int> remain;
int dd[N];
bool first = false;
void dfs(int u, int p)
{
    if(in[u] >= 3 && !first)
    {
        first = true;
        // cout << "gei";
        for(int i = 0; i < 3; i++)
        {
            // int v = g[u][i].fi;
            int id = g[u][i].se;
            if(ans[id] == -1)
            {
                ans[id] = *remain.begin();
                remain.erase(remain.begin());
            }
        }
    }
    else
    {
        for(auto [v, id] : g[u])
        {
            if(v == p) continue;
            if(ans[id] == -1)
            {
                ans[id] = *remain.begin();
                remain.erase(remain.begin());
            }
        }
    }
    return;
}
void read()
{
    cin >> n;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        edg.pb({u, v});
        g[u].pb({v, i});
        g[v].pb({u, i});
        in[u]++;
        in[v]++;
        
    }
}
void solve()
{
    memset(ans, -1, sizeof(ans));
    for(int i = 0; i <= n - 2; i++)
    {
        remain.insert(i);
    }
    for(int i = 1; i <= n; i++)
    {
        if(in[i] >= 3)
        {
            dd[i] = 1;
            dfs(i, -1);
            // break;
        }
    }
    for(int i = 1; i <= n; i++)
    {
        if(dd[i] == 0)
        {
            dfs(i, -1);
        }
    }
    for(int i = 1; i < n; i++)
    {
        cout << ans[i] << "\n";
    }
}
