mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int L[N], R[N];
int n, q;
int cnt = 0;
vector<int> g[N];
int par[N];
int depth[N];
bool is_ancestor(int par, int u)
{
    return L[par] <= L[u] && R[u] <= R[par];
}
void dfs(int u, int p)
{
    L[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        par[v] = u;
        depth[v] = depth[u] + 1;
        dfs(v, u);
    }
    R[u] = cnt;
}
void read()
{
    cin >> n >> q;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0);
    int k;
    while(q--)
    {
        cin >> k;
        vector<int> ned;
        ned.clear();
        int u = 1, v;
        for(int i = 1; i <= k; i++)
        {
            cin >> v;
            ned.pb(v);
            if(depth[v] > depth[u])
                u = v;
        }
        bool ok = true;
        for(auto i : ned)
        {
            if(i == u)
                continue;
            if(!is_ancestor(i, u) && !is_ancestor(par[i], u))
            {
                ok = false;
                break;
            }
        }
        if(ok)
            cout << "YES\n";
        else
            cout << "NO\n";
    }
}
