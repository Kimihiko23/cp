int szsub[N];
vector<int> g[N];
int n, m;
bool dd[N];
int mx = 0;
int ans = 0;
vector<int> posi;
void dfs(int u, int p)
{
    szsub[u] = 1;
    for(int v : g[u])
    {
        if(v == p) continue;
        h[v] = h[u] + 1;
        dfs(v, u);
        szsub[u] += szsub[v];
    }
    posi.pb(h[u] - szsub[u] + 1);
}
void dfs2(int u, int p)
{
    if(dd[u])
    {
        ans += szsub[u] * h[u];
        return;
    }
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs2(v, u);
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    h[1] = 0;
    dfs(1, 0);
    sort(posi.begin(), posi.end());
    for(int i = n; i > n - m; i--)
    {
        ans += posi[i - 1];
    }
    cout << ans;

}
