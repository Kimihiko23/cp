int n, k;
set<int> s;
void read()
{
    cin >> n >> k;
    int x;
    s.clear();
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        s.insert(x);
    }
}
void solve()
{
    if(s.size() > k)
    {
        cout << "-1\n";
        return;
    }
    cout << n * k << "\n";
    for(int i = 1; i <= n; i++)
    {
        for(auto j : s)
        {
            cout << j << " ";
        }
        for(int j = 1; j <= k - s.size(); j++)
        {
            cout << "1 ";
        }
    }
    cout << "\n";
}
