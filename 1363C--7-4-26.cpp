int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int in[N];
int n, k;
vector<int> g[N];
int sz[N];
void dfs(int u, int p)
{
    sz[u] = 1;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dfs(v, u);
        sz[u] += sz[v];
    }
}
void read()
{
    cin >> n >> k;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
        in[u]++;
        in[v]++;
    }
}
void solve()
{
    dfs(k, 0);
    // cout << in[k] << " ";
    if(in[k] == 1 || n == 1)
    {
        cout << "Ayush";
    }
    else
    {
        if(sz[k] % 2 == 1)
        {
            cout << "Ashish";
        }
        else
        {
            cout << "Ayush";
        }
    }
    cout << "\n";
    for(int i = 1; i <= n; i++)
    {
        in[i] = 0;
        g[i].clear();
    }
}
