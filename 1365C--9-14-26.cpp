int pos1[N], pos2[N];
int ans[N];
int n;
void read()
{
    cin >> n;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        pos1[x] = i;
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        pos2[x] = i;
        if(pos1[x] == pos2[x]) ans[0]++;
        else
        {
            int d = pos2[x] - pos1[x];
            if(d < 0) d += n;
            ans[d]++;
        }
    }
}
void solve()
{
    int ans = 0;
    for(int i = 0; i < n; i++)
    {
        ans = max(ans, ::ans[i]);
    }
    //:: for global ans is used to avoid conflict with local variable ans
    cout << ans << "\n";
}
