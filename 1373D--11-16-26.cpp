vector<int> rev0, rev1;
int n, a[N];
int sumeven = 0;
void read()
{
    sumeven = 0;
    cin >> n;
    for(int i = 0; i < n; i++)
    {
        cin >> a[i];
        if(i % 2 == 0) sumeven += a[i];
    }

}
void solve()
{
    for(int i = 0; i < n - 1; i += 2)
    {
        rev0.pb(a[i + 1] - a[i]);
    }
    for(int i = 1; i < n - 1; i += 2)
    {
        rev1.pb(a[i] - a[i + 1]);
    }
    int tam = 0;
    int best = 0;
    for(int i = 0; i < rev0.size(); i++)
    {
        tam += rev0[i];
        best = max(best, tam);
        if(tam < 0) tam = 0;
    }
    tam = 0;
    for(int i = 0; i < rev1.size(); i++)
    {
        tam += rev1[i];
        best = max(best, tam);
        if(tam < 0) tam = 0;
    }
    // cout << sumeven << "\n";
    cout << sumeven + best << "\n";
    rev0.clear();
    rev1.clear();
}
