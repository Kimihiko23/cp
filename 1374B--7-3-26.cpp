int get_power(int &n, int p)
{
    int cnt = 0;
    while (n % p == 0)
    {
        n /= p;
        cnt++;
    }
    return cnt;
}

void solve()
{
    int n;
    cin >> n;

    int a = get_power(n, 2);
    int b = get_power(n, 3);

    if (n != 1)
    {
        cout << -1 << "\n";
        return;
    }

    if (a > b)
    {
        cout << -1 << "\n";
        return;
    }

    cout << (b + (b - a)) << "\n";
}

