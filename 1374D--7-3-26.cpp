mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}

int n, k;
map<int, int> cnt;

void read()
{
    cin >> n >> k;
    cnt.clear();

    for (int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;

        int r = (k - x % k) % k;
        if (r != 0)
        {
            cnt[r]++;
        }
    }
}

void solve()
{
    if (cnt.empty())
    {
        cout << 0 << "\n";
        return;
    }

    long long ans = 0;

    for (auto &it : cnt)
    {
        long long r = it.fi;
        long long c = it.se;

        long long cur = r + (c - 1) * k;
        ans = max(ans, cur);
    }

    cout << ans + 1 << "\n";
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    int t;
    cin >> t;

    while (t--)
    {
        read();
        solve();
    }
}