int n, k, z;
int a[N];
int pre[N];
void read()
{
    cin >> n >> k >> z;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
}
void solve()
{
    int ans = 0;
    int mx = 0;

    for (int i = 1; i <= min(n, k + 1); i++)
    {
        if (i < n)
        {
            mx = max(mx, a[i] + a[i + 1]);
        }

        int moves = i - 1;
        if ((k - moves) % 2 == 0)
        {
            int tmp = (k - moves) / 2;
            if (tmp <= z)
            {
                ans = max(ans, pre[i] + mx * tmp);
            }
        }
    }

    cout << ans << "\n";
}
