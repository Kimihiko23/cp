const int N = 1e5 + 23;
int n;
int pre[N];
string s;
map<int, int> mp;
void read()
{
    cin >> n >> s;
    s = " " + s;
    for (int i = 1; i <= n; i++)
    {
        pre[i] = pre[i - 1] + (s[i] - '0');
    }
}
void solve()
{
    int ans = 0;
    mp.clear();
    mp[0] = 1;
    for(int i = 1; i <= n; i++)
    {
        int val = pre[i] - i;
        ans += mp[val];
        mp[val]++;
    }
    cout << ans << "\n";
}
