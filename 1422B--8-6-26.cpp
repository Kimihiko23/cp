mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int par[N];
int sz[N];
int find(int x)
{
    if(par[x] != x)
        par[x] = find(par[x]);
    return par[x];
}
vector<vector<int>> a;
int n, m;
// vector<pair<int, int>> row[N], col[N];
vector<int> ins[N];
int idx(int x, int y)
{
    return (x - 1) * m + y;
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(u == v) return;
    if(sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
}
void reset() 
{
    for (int i = 1; i <= n * m; i++) 
    {
        par[i] = i;
        sz[i] = 1;
        ins[i].clear();
    }
    a.clear();
}
void read()
{
    cin >> n >> m;
    a.resize(n + 2, vector<int>(m + 2));
    int x;
    for(int i = 1; i <= n * m; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    for(int i = 1; i <= n; i++)
    {
        int old = 1;
        int sz = 0;
        for(int j = 1; j <= m; j++)
        {
            cin >> x;
            a[i][j] = x;
            if(x == -1 && sz != 0)
            {
                // row[i].pb({old, j - 1});
                int l = old, r = j - 1;
                while(l < r)
                {
                    int u = idx(i, l);
                    int v = idx(i, r);
                    join(u, v);
                    l++;
                    r--;
                }
                sz = 0;
                old = j + 1;
                
            }
            else
            if(x == -1)
                old = j + 1;
            if(a[i][j] != -1) sz++;
        }
        if(sz != 0)
        {
            int l = old, r = m;
            while(l < r)
            {
                int u = idx(i, l);
                int v = idx(i, r);
                join(u, v);
                l++;
                r--;
            }
        }
    }
}
void solve()
{
    for(int j = 1; j <= m; j++)
    {
        int old = 1;
        int sz = 0;
        for(int i = 1; i <= n; i++)
        {
            if(a[i][j] == -1 && sz != 0)
            {
                // col[j].pb({old, i - 1});
                int l = old, r = i - 1;
                while(l < r)
                {
                    int u = idx(l, j);
                    int v = idx(r, j);
                    join(u, v);
                    l++;
                    r--;
                }
                sz = 0;
                old = i + 1;
            }
            else
            if(a[i][j] == -1)
                old = i + 1;
            if(a[i][j] != -1) sz++;
        }
        if(sz != 0)
        {
            // col[j].pb({old, n});
            int l = old, r = n;
            while(l < r)
            {
                int u = idx(l, j);
                int v = idx(r, j);
                join(u, v);
                l++;
                r--;
            }
        }
    }
    ll ans = 0;
    set<int> st;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            int id = idx(i, j);
            if(a[i][j] != -1)
            {
                int p = find(id);
                ins[p].pb(a[i][j]);
                st.insert(p);
            }
        }
    }
    for(auto i :st)
    {
        if(ins[i].size() == 1)
            continue;
        sort(ins[i].begin(), ins[i].end());
        int l = 0, r = ins[i].size() - 1;
        int mid = (l + r) / 2;
        int tar = ins[i][mid];
        for(auto j : ins[i])
        {
            ans += abs(tar - j);
        }
    }
    cout << ans << "\n";
}
