int binpow(int x, int pw)
{
    int res = 1;
    while(pw)
    {
        if(pw & 1)
            res *= x;
        res %= MOD;
        x *= x;
        x %= MOD;
        pw >>= 1;
    }
    return res;
}
void precom()
{
    fact[0] = 1;
    for(int i = 1; i < N; i++)
    {
        fact[i] = (fact[i - 1] * i) % MOD;
    }
    inv[N - 1] = binpow(fact[N - 1], MOD - 2);
    for(int i = N - 2; i >= 0; i--)
    {
        inv[i] = (inv[i + 1] * (i + 1)) % MOD;
    }
}
int cnk(int n, int k)
{
    if(k > n || k < 0)
        return 0;
    return (((fact[n] * inv[k]) % MOD) * inv[n - k]) % MOD;
}
