#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =200+23;

vector<pair<int, int>> g[N];
int n;
int dist[N];
vector<pair<int, int>> que;
int del = -1;
void dfs(int u, int p)
{
    for(auto i: g[u])
    {
        int v = i.se;
        if(del==i.fi) continue;
        if(v==p) continue;
        dist[v] = dist[u]+1;
        dfs(v,u);
    }
}
void read()
{
    cin >> n;
    for(int i=1;i<n;i++)
    {
        int u,v;
        cin >> u >> v;
        g[u].pb({i, v});
        g[v].pb({i, u});
        que.pb({u,v});
    }
}
void solve()
{
    int res = 0;
    for(int i = 1; i < n; i++)
    {
        del = i;
        memset(dist, 0, sizeof dist);
        int u = que[i-1].fi;
        dfs(u, -1);
        int ans1 = 0, ans2 = 0;
        int vtmx = u;
        int mx = 0;
        for(int j = 1; j <= n; j++)
        {
            if(dist[j] > mx)
            {
                mx = dist[j];
                vtmx = j;
            }
        }
        memset(dist, 0, sizeof dist);
        dfs(vtmx, -1);
        for(int j = 1; j <= n; j++)
        {
            ans1 = max(ans1, dist[j]);
        }
        memset(dist, 0, sizeof dist);
        int v = que[i-1].se;
        dfs(v, -1);
        mx = 0;
        vtmx = v;
        for(int j = 1; j <= n; j++)
        {
            if(dist[j] > mx)
            {
                mx = dist[j];
                vtmx = j;
            }
        }
        memset(dist, 0, sizeof dist);
        dfs(vtmx, -1);
        for(int j = 1; j <= n; j++)
        {
            ans2 = max(ans2, dist[j]);
        }
        res = max(res, ans1 * ans2);
    }
    cout << res << "\n";
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
} 