void solve()
{
    //dp[i][j] make i to j good
    sort(a + 1, a + n + 1);
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[i][j] = INF;
        }
    }
    for(int i = 1; i <= n; i++)
    {
        dp[i][i] = 0;
    }
    for(int len = 2; len <= n; len++)
    {
        for(int i = 1; i + len - 1 <= n; i++)
        {
            int j = i + len - 1;
            dp[i][j] = min(dp[i + 1][j] + abs(a[i] - a[j]), dp[i][j - 1] + abs(a[i] - a[j]));
        }
    }
    cout << dp[1][n];
}
