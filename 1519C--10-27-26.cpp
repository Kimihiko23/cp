void solve()
{
    for(int i = 1; i <= n; i++)
    {
        sort(team[i].begin(), team[i].end(), greater<int>());
        vector<int> pre(team[i].size() + 1, 0);
        for(int j = 1; j <= team[i].size(); j++)
        {
            pre[j] = pre[j - 1] + team[i][j - 1];
        }
        for(int j = 1; j <= team[i].size(); j++)
        {
            int left = team[i].size() % j;
            ans[j] += pre[team[i].size() - left];
        }
    }
    for(int i = 1; i <= n; i++)
    {
        cout << ans[i] << " ";
        team[i].clear();
        ans[i] = 0;
    }
    cout << "\n";

}
