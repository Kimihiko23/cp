int n, a[5005], b[5005], ans, s;

void read()
{
    cin >> n;
    for (int i = 1; i <= n; ++i) cin >> a[i];
    for (int i = 1; i <= n; ++i) cin >> b[i];
}

void solve()
{
    for (int i = 1; i <= n; ++i) s += a[i] * b[i];
    ans = s;

    for (int i = 1; i <= n; ++i)
    {
        int cur = s;
        int l = i - 1, r = i + 1;
        while (l >= 1 && r <= n)
        {
            cur -= a[l] * b[l] + a[r] * b[r];
            cur += a[l] * b[r] + a[r] * b[l];
            ans = max(ans, cur);
            --l;
            ++r;
        }
    }

    for (int i = 1; i < n; ++i)
    {
        int cur = s;
        int l = i, r = i + 1;
        while (l >= 1 && r <= n)
        {
            cur -= a[l] * b[l] + a[r] * b[r];
            cur += a[l] * b[r] + a[r] * b[l];
            ans = max(ans, cur);
            --l;
            ++r;
        }
    }

    cout << ans << "\n";
}

