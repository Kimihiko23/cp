void solve()
{
    memset(dd, 0, sizeof(dd));
    for(int i = 0; i <= n; i++)
    {
        for(int j = 0; j <= n; j++)
        {
            a[i][j] = 1e18;
        }
    }
    bool good = true;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            bool change = false;
            for(int z = 1; z <= n * n; z += 2)
            {
                if(dd[z]) continue;
                bool can = true;
                for(int k = 0; k < 4; k++)
                {
                    int x = i + dx[k];
                    int y = j + dy[k];
                    if(check(x, y) && abs(a[x][y] - z) == 1)
                    {
                        can = false;
                        break;
                    }
                }
                if(can)
                {
                    dd[z] = true;
                    a[i][j] = z;
                    change = true;
                    break;
                    // change = true;
                }
            }
            if(!change)
            {
                for(int z = 2; z <= n * n; z += 2)
                {
                    if(dd[z]) continue;
                    bool can = true;
                    for(int k = 0; k < 4; k++)
                    {
                        int x = i + dx[k];
                        int y = j + dy[k];
                        if(check(x, y) && abs(a[x][y] - z) == 1)
                        {
                            can = false;
                            break;
                        }
                    }
                    if(can)
                    {
                        dd[z] = true;
                        a[i][j] = z;
                        break;
                    }
                }
            }
        }
    }
    // for(int i = 1; i <= n * n; i++)
    // {
    //     cout << dd[i] << "\n";
    // }
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            // cout << a[i][j] << " ";
            if(a[i][j] == 1e18)
            {
                good = false;
                break;
            }
        }
        // cout << "\n";
    }
    if(good)
    {
        for(int i = 1; i <= n; i++)
        {
            for(int j = 1; j <= n; j++)
            {
                cout << a[i][j] << " ";
            }
            cout << "\n";
        }
    }
    else
    {
        cout << "-1\n";
    }
    
}
