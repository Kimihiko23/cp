const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int dis[N][N];
int n, m, w;
int a[N][N];
priority_queue<pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>>> pq;
vector<pair<int, int>> tele;
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
void dikjstra()
{
    dis[1][1] = 0;
    pq.push({0, {1, 1}});
    while(!pq.empty())
    {
        auto u = pq.top();
        pq.pop();
        int x = u.se.fi, y = u.se.se;
        int we = u.fi;
        if(we > dis[x][y]) continue;
        if(x != 0 && y != 0)
        {
            for(int i = 0; i < 4; i++)
            {
                int xx = x + dx[i], yy = y + dy[i];
                if(check(xx, yy) && dis[xx][yy] > dis[x][y] + w && a[xx][yy] != -1)
                {
                    dis[xx][yy] = dis[x][y] + w;
                    pq.push({dis[xx][yy], {xx, yy}});
                }
            }
            if(a[x][y] > 0)
            {
                if(we + a[x][y] < dis[0][0])
                {
                    dis[0][0] = we + a[x][y];
                    pq.push({dis[0][0], {0, 0}});
                }
            }
        }
        else
        {
            for(auto v : tele)
            {
                int xx = v.fi, yy = v.se;
                if(dis[xx][yy] > dis[0][0] + a[xx][yy])
                {
                    dis[xx][yy] = dis[0][0] + a[xx][yy];
                    pq.push({dis[xx][yy], {xx, yy}});
                }
            }
        }
    }
}
void read()
{
    dis[0][0] = INF;
    cin >> n >> m >> w;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            dis[i][j] = INF;
            cin >> a[i][j];
            if(a[i][j] > 0) tele.pb({i, j});
        }
    }
}
void solve()
{
    dikjstra();
    if(dis[n][m] == INF) cout << -1;
    else cout << dis[n][m];
}
