int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int dp[N][2];
//0 = L, 1 = R
int L[N], R[N];
int n;
vector<int> g[N];
void dfs(int u, int p)
{
    dp[u][0] = dp[u][1] = 0;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dp[u][0] += max(dp[v][0] + abs(L[u] - L[v]), dp[v][1] + abs(L[u] - R[v]));
        dp[u][1] += max(dp[v][0] + abs(R[u] - L[v]), dp[v][1] + abs(R[u] - R[v]));
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        g[i].clear();
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> L[i] >> R[i];
    }
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, -1);
    cout << max(dp[1][0], dp[1][1]) << "\n";
}
