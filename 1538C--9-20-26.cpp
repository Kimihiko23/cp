void solve()
{
    sort(a + 1, a + 1 + n);
    // int ans = 0;
    int res1 = 0, res2 = 0;
    for(int i = 1 ; i <= n; i++)
    {
        int tam = r - a[i];
        // if(tam < 0)
            // continue;
        int vt = upper_bound(a + 1 + i, a + 1 + n, tam) - a;
        vt--;
        if(vt > i)
            res1 += vt - i;

        tam = l - 1 - a[i];
        // if(tam < 0)
            // continue;
        vt = upper_bound(a + 1 + i, a + 1 + n, tam) - a;
        vt--;
        if(vt > i)
            res2 += vt - i;
    }
    // res1 /= 2;
    // res2 /= 2;
    cout << res1 - res2 << "\n";
}
