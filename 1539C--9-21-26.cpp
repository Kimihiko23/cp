void solve()
{
    sort(a + 1, a + n + 1);
    vector<int> v;
    for(int i = 2; i <= n; i++)
    {
        if(a[i] - a[i - 1] > x)
        {
            v.pb((a[i] - a[i - 1] + x - 1) / x - 1);
            // cout << i << "\n";
        }
    }
    int ans = v.size();
    // cout << v.size() << "\n";
    sort(v.begin(), v.end());
    for(int i = 0; i < v.size(); i++)
    {
        if(k >= v[i])
        {
            // cout << "gei\n";
            k -= v[i];
            ans--;
        }
    }
    cout << ans + 1;
}
