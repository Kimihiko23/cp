int n;
multiset<pair<int, int>> s;
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        if(x == 0) continue;
        s.insert({x, i});
    }
}
void solve()
{
    vector<pair<int, int>> ans;
    while(s.size() > 1)
    {
        auto itfi = s.begin();
        auto itse = prev(s.end());
        int id1 = itfi->second;
        int id2 = itse->second;
        ans.pb({id1, id2});
        int val1 = itfi->first;
        int val2 = itse->first;
        s.erase(itfi);
        s.erase(itse);
        val1--;
        val2--;
        if(val1 > 0) s.insert({val1, id1});
        if(val2 > 0) s.insert({val2, id2});
    }
    cout << ans.size() << "\n";
    for(auto x : ans) cout << x.first << " " << x.second << "\n";
    s.clear();
}
