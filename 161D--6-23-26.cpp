using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int n, k;
vector<int> g[N];
int dp[N][600];
int ans = 0;
void dfs(int u, int p)
{
    dp[u][0] = 1;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        for(int i = 1; i <= k; i++)
        {
            ans += dp[v][i - 1] * dp[u][k - i];
        }
        for(int i = 1; i <= k; i++)
            dp[u][i] += dp[v][i - 1];
    }
}
void read()
{
    cin >> n >> k;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0);
    cout << ans;
}
