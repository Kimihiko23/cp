void solve()
{
    sort(a + 1, a + n + 1);
    for(int i = 1; i <= n; i++)
    {
        // cout << a[i] << " ";
        pre[i] = pre[i - 1] + a[i];
    }
    // cout << "\n";
    // cout << (n / 2 - !(n & 1)) << "\n";
    int sum = 0;
    bool good = false;
    int cnt = 0;
    for(int i = n; i >= 1; i--)
    {
        sum += a[i];
        cnt++;
        int l = 1, r = i - 1;
        int vt = 1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(pre[mid] < sum)
            {
                vt = mid;
                l = mid + 1;
            }
            else
            {
                r = mid - 1;
            }
        }
        if(vt > cnt)
        {
            good = true;
            break;
        }
    }
    if(good)
    {
        cout << "YES\n";
    }
    else
    {
        cout << "NO\n";
    }
    
}
