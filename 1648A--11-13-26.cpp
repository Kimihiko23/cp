void solve()
{
    int ans = 0;
    for(int i = 1; i <= 1e5; i++)
    {
        sort(x[i].begin(), x[i].end());
        sort(y[i].begin(), y[i].end());
        int sum = 0;
        for(int j = 1; j <= x[i].size(); j++)
        {
            ans += x[i][j - 1] * (j - 1) - sum;
            sum += x[i][j - 1];
        }
        sum = 0;
        for(int j = 1; j <= y[i].size(); j++)
        {
            ans += y[i][j - 1] * (j - 1) - sum;
            sum += y[i][j - 1];
        }
    }
    cout << ans;
}
