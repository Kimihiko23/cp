mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int dis[N];
int n;
int a[N];
bool dd[N];
vector<int> g[N];
void bfs()
{
    queue<int> q;
    q.push(0);
    dd[0] = 1;
    while(!q.empty())
    {
        int u = q.front();
        // dd[u] = 1;
        q.pop();
        for(auto v : g[u])
        {
            if(!dd[v])
            {
                dis[v] = dis[u] + 1;
                dd[v] = 1;
                q.push(v);
            }
        }
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    for(int i = 0; i <= MOD + 1; i++)
    {
        g[(i + 1) % MOD].pb(i);
        g[(i * 2) % MOD].pb(i);
    }
    bfs();
    for(int i = 1; i <= n; i++)
    {
        cout << dis[a[i]] << " ";
    }
}
