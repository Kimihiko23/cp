int n, k;
int a[N];
int gut[N];
int pre[N];
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        gut[i] = 0;
        pre[i] = 0;
        cin >> a[i];
    }
}
void solve()
{
    for(int i = 1; i < n; i++)
    {
        if(a[i + 1] * 2 - a[i] > 0)
        {
            gut[i] = 1;
        }
        pre[i] = pre[i - 1] + gut[i];
    }
    int ans = 0;
    for(int i = 1; i <= n - k; i++)
    {
        if(pre[i + k - 1] - pre[i - 1] == k)
            ans++;
    }
    cout << ans << "\n";
}
