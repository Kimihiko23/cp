{
    cin >> a >> b >> x >> y;
}

void solve()
{
    int g = __gcd(x, y);
    x /= g;
    y /= g;
    int k = min(a / x, b / y);
    if (k == 0)
    {
        cout << "0 0" << endl;
    }
    else
    {
        cout << k * x << " " << k * y << endl;
    }
}

