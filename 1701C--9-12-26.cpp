    // }
    int l = 0, r = 1e9, ans = 1e18;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            // cout << check(mid) << "\n";
            ans = min(ans, mid);
            r = mid - 1;
        }
        else l = mid + 1;
    }
    cout << ans << "\n";
    mp.clear();
