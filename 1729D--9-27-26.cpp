void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> b[i];
        if(b[i] >= a[i])
        {
            gut.insert(b[i] - a[i]);
        }
        else
        {
            bad.insert(a[i] - b[i]);
        }
    }
}
void solve()
{
    // sort(gut.begin(), gut.end());
    // sort(bad.begin(), bad.end());
    int ans = 0;
    for(auto i : bad)
    {
        auto vt = gut.lower_bound(i);
        if(vt != gut.end())
        {
            ans++;
            gut.erase(vt);
        }
    }
    ans += gut.size() / 2;
    cout << ans << "\n";
    gut.clear();
    bad.clear();
}
