void solve()
{
    for(int i = 1; i <= n; i++)
    {
        kill[i] = {0, 0};
        alive[i] = 0;
        if(s[i] == '0') del.pb(i);
        if(s[i] == '1') alive[i] = 1;
        // cout << alive[i] << " ";
    }
    int ans = 0;
    // cout << del.size() << "\n";
    for(auto i : del)
    {
        // cout << ans << "\n";
        if(kill[i].fi) 
        {
            // cout << i << " " << kill[i].se << "\n";
            // cout << ans << "\n";
            ans += kill[i].se;
            // cout << ans << "\n";
            // continue;
        }
        else
        ans += i;
        // cout << i << " " << ans << "\n";
        for(int j = i; j <= n; j += i)
        {
            if(alive[j]) break;
            if(kill[j].fi) continue;
            kill[j] = {1, i};
        }
    }
    cout << ans << "\n";
    del.clear();


}
