using namespace std;
const int N =1e6+23;
int n;
unordered_map<int,int> mp;
int a[N], pre[N];
void read()
{   
    cin >> n;
}
void solve()
{
    int x;
    mp.clear();
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
    int ans = 0;
    int mx = 0;
    for(int i = 1; i <= n; i++)
    {
        if(a[i] == 0)
        {
            mx = 0;
            mp.clear();
            mp[pre[i]]++;
            mx = max(mx, mp[pre[i]]);
            int j = i + 1;
            while(a[j] != 0 && j <= n)
            {
                mp[pre[j]]++;
                mx = max(mx, mp[pre[j]]);
                j++;
            }
            ans += mx;
            i = j - 1;
        }
        else
        {
            if(pre[i] == 0)
                ans++;
        }
    }
    cout << ans << "\n";
}   

