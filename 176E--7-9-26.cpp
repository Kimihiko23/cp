vector<pair<int, int>> g[N];
int n;
int q;
int in[N];
int par[N][30];
int dis[N];
int dep[N];
set<pair<int, int>> s;
int cnt = 0;
void dfs(int u, int p)
{
    in[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v.fi == p)
            continue;
        par[v.fi][0] = u;
        dis[v.fi] = dis[u] + v.se;
        dep[v.fi] = dep[u] + 1;
        dfs(v.fi, u);
    }
}
void init()
{
    for(int j = 1; j < 30; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(dep[u] < dep[v])
        swap(u, v);
    for(int i = 29; i >= 0; i--)
    {
        if(dep[par[u][i]] >= dep[v])
            u = par[u][i];
    }
    if(u == v)
        return u;
    for(int i = 29; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
int sum = 0;

int dist(int u, int v)
{
    int p = lca(u, v);
    return dis[u] + dis[v] - 2 * dis[p];
}
void add(int u)
{
    s.insert({in[u], u});

    if(s.size() == 1)
        return;

    auto it = s.find({in[u], u});

    auto pre = (it == s.begin() ? prev(s.end()) : prev(it));

    auto nxt = next(it);
    if(nxt == s.end())
        nxt = s.begin();

    sum -= dist(pre->second, nxt->second);
    sum += dist(pre->second, u);
    sum += dist(u, nxt->second);
}
void del(int u)
{
    if(s.size() == 1)
    {
        s.erase({in[u], u});
        return;
    }

    auto it = s.find({in[u], u});

    auto pre = (it == s.begin() ? prev(s.end()) : prev(it));

    auto nxt = next(it);
    if(nxt == s.end())
        nxt = s.begin();

    sum += dist(pre->second, nxt->second);
    sum -= dist(pre->second, u);
    sum -= dist(u, nxt->second);

    s.erase(it);
}
void read()
{
    cin >> n;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
    }
}
void solve()
{
    dfs(1, 0);
    init();
    char ty;
    int u;
    cin >> q;
    while(q--)
    {
        cin >> ty;
        if(ty == '+')
        {
            cin >> u;
            add(u);
        }
        else if(ty == '-')
        {
            cin >> u;
            del(u);
        }
        else
        {
            cout << sum / 2 << '\n';
        }
    }
}
