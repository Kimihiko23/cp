using namespace std;
const int N =1e6+23;
int pre[N], suf[N];
string s;
void read()
{   
    cin >> s;
    s = " " + s;
}
void solve()
{
    int n = s.size() - 1;
    for(int i = 1; i <= n; i++)
    {
        if(!isupper(s[i]))
        {
            pre[i]++;
        }
        pre[i] += pre[i - 1];
    }
    for(int i = n; i >= 1; i--)
    {
        if(isupper(s[i]))
        {
            suf[i]++;
        }
        suf[i] += suf[i + 1];
    }
    int ans = 1e18;
    for(int i = 1; i <= n + 1; i++)
    {
        int tam = pre[i - 1] + suf[i];
        ans = min(tam, ans);
    }
    cout << ans;
}   

