void solve()
{
    int t;
    cin >> t;

    while (t--)
    {
        int n;
        cin >> n;

        for (int i = 1; i <= n; i++)
        {
            adj[i].clear();
            dp[i] = 0;
        }

        for (int i = 1; i < n; i++)
        {
            int u, v;
            cin >> u >> v;

            adj[u].pb({v, i});
            adj[v].pb({u, i});
        }

        dp[1] = 1;
        dfs(1, 0, 0);

        int ans = 1;

        for (int i = 1; i <= n; i++)
            ans = max(ans, dp[i]);

        cout << ans << '\n';
    }
}

