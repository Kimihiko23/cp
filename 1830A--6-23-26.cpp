const int N = 1e5 + 23;

vector<pair<int,int>> adj[N];
int dp[N];

void dfs(int u, int par, int last_edge)
{
    for (auto x : adj[u])
    {
        int v = x.fi;
        int idx = x.se;

        if (v == par) continue;

        dp[v] = dp[u];
        if (idx < last_edge) dp[v]++;

        dfs(v, u, idx);
    }
}

