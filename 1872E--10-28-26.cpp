int st1[N * 4], st2[N * 4], lz[N * 4];
int n;
int a[N];
string s;
void build(int l, int r, int id)
{
    if(l == r)
    {
        if(s[l] == '1') st1[id] = a[l];
        else st2[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st1[id] = st1[id * 2] ^ st1[id * 2 + 1];
    st2[id] = st2[id * 2] ^ st2[id * 2 + 1];
}
void change(int id)
{
    swap(st1[id], st2[id]);
    lz[id] ^= 1;
}
void push(int id)
{
    if(lz[id])
    {
        change(id * 2);
        change(id * 2 + 1);
        lz[id] = 0;
    }
}
void update(int l, int r, int id, int u, int v)
{
    if(l > v || r < u) return;
    if(l >= u && r <= v)
    {
        change(id);
        return;
    }
    push(id);
    int mid = (l + r) / 2;
    update(l, mid, id * 2, u, v);
    update(mid + 1, r, id * 2 + 1, u, v);
    st1[id] = st1[id * 2] ^ st1[id * 2 + 1];
    st2[id] = st2[id * 2] ^ st2[id * 2 + 1];
}
