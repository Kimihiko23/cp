void solve()
{
    sort(a1.begin(), a1.end());
    sort(b.begin(), b.end());
    int ans = 0;
    int idx = 0;
    for(int i = 0; i < n; i++)
    {
        while(idx < n && b[idx] <= a1[i])
        {
            idx++;
        }
        if(idx < n && b[idx] > a1[i])
        {
            ans++;
            idx++;
        }
    }
    // cout << n - ans << "\n";
    res = n - ans;
    int limit = 0;
    int l = 1, r = m;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            limit = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }
    // cout << res << "\n";
    // cout << check(1) << "\n";
    cout << res * limit + (m - limit) * (res + 1) << "\n";
}
