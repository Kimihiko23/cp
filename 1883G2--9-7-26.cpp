int n, m;
vector<int> a, b, a1;
int res = 0;
bool check(int x)
{
    int idx = 0;
    vector<int> c;
    c.pb(x);
    for(int i = 0; i < n - 1; i++)
    {
        c.pb(a[i]);
    }
    sort(c.begin(), c.end());
    int ans = 0;
    for(int i = 0; i < n; i++)
    {
        while(idx < n && b[idx] <= c[i])
        {
            idx++;
        }
        if(idx < n && b[idx] > c[i])
        {
            ans++;
            idx++;
        }
    }
    ans = n - ans;
    // cout << ans << " " << x << "\n";
    return ans == res;
}
