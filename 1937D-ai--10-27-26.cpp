int n;
string s;
vector<int> P, Q;

int sumL(int a, int k)
{
    return P[a] - P[a - k];
}
int sumR(int c, int k)
{
    return Q[c + k] - Q[c];
}
void read()
{
    cin >> n >> s;
}
void solve()
{
    P.assign(1, 0);
    Q.assign(1, 0);
    for (int i = 1; i <= n; i++)
    {
        if (s[i - 1] == '>') P.pb(P.back() + i);
        else Q.pb(Q.back() + i);
    }
    int total = Q.size() - 1;
    int gt = 0, lt = 0;
    for (int i = 1; i <= n; i++)
    {
        if (s[i - 1] == '<') lt++;
        int a = gt;
        int b = total - lt;
        int ans;
        if (s[i - 1] == '>')
        {
            if (b <= a) ans = 2 * sumR(lt, b) - 2 * sumL(a, b) - i + n + 1;
            else ans = 2 * sumR(lt, a + 1) - 2 * sumL(a, a) - i;
        }
        else
        {
            if (a <= b) ans = 2 * sumR(lt, a) - 2 * sumL(a, a) + i;
            else ans = 2 * sumR(lt, b) - 2 * sumL(a, b + 1) + i + n + 1;
        }
        cout << ans << " ";
        if (s[i - 1] == '>') gt++;
    }
    cout << "\n";
}
