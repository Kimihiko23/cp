bool bad = true;
void read()
{
    cin >> n;
    bad = true;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        if(i > 1 && a[i] != a[i - 1]) bad = false;
    }
}
void solve()
{
    if(bad) cout << -1 << "\n";
    else
    {
        if(a[1] != a[n])
        {
            cout << 0;
            return;
        }
        int ans = 1e18;
        int tam = 0;
        int tar = a[1];
        for(int i = 2; i <= n; i++)
        {
            if(a[i] == tar && a[i - 1] == tar)
            {
                tam++;
            }
            else
            {
                if(a[i - 1] == tar)
                ans = min(ans, tam);
                tam = 0;
            }
            // cout << tam << "\n";
        }
        ans = min(ans, tam);
        cout << ans + 1 << "\n";
    }
}
