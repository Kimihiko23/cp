enum class Direction { N, S, E, W };

Direction charToDirection(char c) {
    switch (c) {
        case 'N': return Direction::N;
        case 'S': return Direction::S;
        case 'E': return Direction::E;
        case 'W': return Direction::W;
        default: throw std::invalid_argument("Invalid direction character");
    }
}

void read() {
    cin >> n >> s;

    if (n % 2 != 0) {
        cout << "NO\n";
        return;
    }

    if (n == 2) {
        if (s[0] != s[1]) {
            cout << "NO\n";
            return;
        } else {
            cout << "RH\n";
            return;
        }
    }

    array<int, 4> counts = {0, 0, 0, 0}; // N, S, E, W

    for (char c : s) {
        Direction dir = charToDirection(c);
        switch (dir) {
        case Direction::N:
            counts[0]++;
            break;
        case Direction::S:
            counts[1]++;
            break;
        case Direction::E:
            counts[2]++;
            break;
        case Direction::W:
            counts[3]++;
            break;
        }
    }

    int verticalBalance = (
        counts[static_cast<int>(Direction::N)]
        - counts[static_cast<int>(Direction::S)]
    ); // N - S
    int horizontalBalance = (
        counts[static_cast<int>(Direction::E)]
        - counts[static_cast<int>(Direction::W)]
    ); // E - W

    if (
        n == 4
        && counts[static_cast<int>(Direction::N)] == 1
        && counts[static_cast<int>(Direction::S)] == 1
        && counts[static_cast<int>(Direction::E)] == 1
        && counts[static_cast<int>(Direction::W)] == 1
    ) {
        for (char c : s) {
            if (c == 'N' || c == 'S') {
                cout << 'R';
            } else {
                cout << 'H';
            }
        }
        cout << "\n";
        return;
    }

    if (verticalBalance % 2 != 0 || horizontalBalance % 2 != 0) {
        cout << "NO\n";
        return;
    }

    array<int, 4> used = {0, 0, 0, 0}; // N, S, E, W

    for (char c : s) {
        Direction dir = charToDirection(c);

        if (++used[static_cast<int>(dir)] <= counts[static_cast<int>(dir)] / 2) {
            cout << 'R';
        } else {
            cout << 'H';
        }    
    }
    
    cout << "\n";
}

