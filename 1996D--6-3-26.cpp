void solve()
{
    int t;
    cin >> t;

    while(t--)
    {
        int n, x;
        cin >> n >> x;

        int ans = 0;

        for(int a = 1; a <= x - 2; a++)
        {
            int lims = x - a;

            for(int b = 1; b < lims; b++)
            {
                int rem = n - a * b;
                if(rem <= 0) break;

                int c1 = rem / (a + b);
                int c2 = lims - b;

                ans += max(0LL, min(c1, c2));
            }
        }

        cout << ans << '\n';
    }
}

