{
    int n;
    cin >> n;

    vector<int> a(n);

    for (int i = 0; i < n; i++) 
    {
        vector<int> b(n);

        for (int j = 0; j < n; j++) cin >> b[j];

        for (int j = n - 1; j >= 0 && b[j] == 1; j--) 
        {
            a[i]++;
        }
    }

    sort(a.begin(), a.end());

    int ans = 0;

    for (int x : a) {
        if (x >= ans) ans++;
    }

    cout << ans << '\n';
}
