#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int MOD = 1000020409;
const int N =1e5+23;
const int INF = 1e18;

int n, m, d[N], p[N];
vector<pair<int, int>> g[N];

void dijkstra()
{
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    for (int i = 1; i <= n; i++) d[i] = INF;
    d[1] = 0;
    pq.push({0, 1});
    while (!pq.empty())
    {
        int u = pq.top().se;
        int w = pq.top().fi;
        pq.pop();
        if (w > d[u]) continue;
        for (auto &e : g[u])
        {
            int v = e.se;
            int cost = e.fi;
            if (d[u] + cost < d[v])
            {
                d[v] = d[u] + cost;
                p[v] = u;
                pq.push({d[v], v});
            }
        }
    }
}

