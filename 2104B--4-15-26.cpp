int n;
int a[N];
int ans[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
        ans[i] = 0;
        // cout << a[i] << " ";
        mx[i] = 0;
        mx[i] = max(mx[i - 1], a[i]);
    }
    
}
void solve()
{
    // int mx = 0;
    // ans[1] = 0;
    for(int i = 1; i <= n; i++)
    {
        ans[1] = max(ans[1], a[i]);
    }
    // cout << ans[1];
    for(int i = 2; i <= n; i++)
    {
        ans[i] = mx[n - i + 1] + pre[n] - pre[n - i + 1];
        // cout << pre[n] - pre[n - i + 1] << " ";
    }
    for(int i = 1; i <= n; i++)
    {
        cout << ans[i] << " ";
        // cout << mx[i] << " ";
    }
    cout << "\n";


}
