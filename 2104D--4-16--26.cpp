const int MOD = 1000020409;
const int N =1e7+23;
const int MS =  1e7;
int pre1[N];
int pre2[N];
int a[N];
vector<int> prime;
bool dd[N];
int n;
int sum;
void sieve()
{
    dd[1] = true;
    for(int i = 2; i < MS - 10; i++)
    {
        if(dd[i])
            continue;
        prime.pb(i);
        for(int j = i * i; j < MS - 10; j += i)
        {
            dd[j] = true;
        }
    }

    // for(int i = 2; i < MS; i++) if(!dd[i]) prime.pb(i);
}
void read()
{
    cin >> n;
    sum = 0;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + 1 + n, greater());
    for(int i = 1; i <= n; i++)
    {
        pre2[i] = pre2[i - 1] + a[i];
    }
    int l = 0, r = n;
    int ans = 0;
    while(l <= r)
    {
        int mid = (l + r)/2;
        if(pre1[mid] <= pre2[mid])
        {
            ans = max(ans, mid);
            l = mid + 1;
        }
        else
            r = mid - 1;
    }
    cout << n - ans << "\n";
}
