using namespace std;
const int N =1e6+23;
const int MOD = 1000020409;
int nxt[N][30];
int ans[N];
int n, k;
string in;
void read()
{   
    cin >> n >> k;
    cin >> in;
}
void solve()
{
    in = " " + in;
    ans[n + 1] = 0;
    for(int i = 0; i < k; i++)
    {
        nxt[n + 1][i] = n + 1;
    }
    for(int i = n; i >= 1; i--)
    {
        for(int j = 0; j < k; j++)
        {
            nxt[i][j] = nxt[i + 1][j];
        }
        int mx = nxt[i][0];
        for(int j = 0; j < k; j++)
        {
            mx = max(mx, nxt[i][j]);
        }
        ans[i] = 1 + ans[mx];
        nxt[i][in[i] - 'a'] = i;
        
    }
    int q;
    cin >> q;
    while(q--)
    {
        string s;
        cin >> s;
        s = " " + s;
        int vt = 0;
        for(int i = 1; i < s.size(); i++)
        {
            if(vt < in.size())
            {
                vt = nxt[vt + 1][s[i] - 'a'];
            }
        }
        if(vt > n)
        {
            cout << "0\n";
        }
        else
            cout << ans[vt] << "\n";
    }
}   

