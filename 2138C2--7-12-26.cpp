int n, k;
vector<int> g[N];
int dep[N];
int szde[N];
vector<int> leaf;
int minde = INF;
vector<int> item;
int dp[N];
bitset<N> dp2;
int cnt[N];
void dfs(int u, int p)
{
    szde[dep[u]]++;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dep[v] = dep[u] + 1;
        dfs(v, u);
    }
}
void read()
{
    cin >> n >> k;
    int v;
    for(int i = 2; i <= n; i++)
    {
        cin >> v;
        g[v].pb(i);
        g[i].pb(v);
    }
}
