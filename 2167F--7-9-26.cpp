int dp[N];
int sz[N];
int n, k;
vector<int> g[N];
int ans = 0;
int sum = 0;
void dfs(int u, int p)
{
    sz[u] = 1;
    for(auto v: g[u])
    {
        if(v == p)
            continue;
        dfs(v, u);
        sz[u] += sz[v];
        dp[u] += dp[v];
    }
    if(sz[u] >= k)
        dp[u] = 1;

}
void dfs2(int u, int p)
{
    for(auto v: g[u])
    {
        if(v == p)
            continue;
        int oldu = sz[u];
        int oldv = sz[v];
        int oldsum = sum;
        int dpv = dp[v];
        int dpu = dp[u];
        sz[v] = sz[u];
        sz[u] = sz[u] - oldv;
        sum -= dp[v] + dp[u];
        if(sz[v] >= k)
            dp[v] = 1;
        else
            dp[v] = 0;
        if(sz[u] >= k)
            dp[u] = 1;
        else
            dp[u] = 0;
        sum += dp[v] + dp[u];
        ans += sum;

        dfs2(v, u);

        sum = oldsum;
        sz[u] = oldu;
        sz[v] = oldv;
        dp[v] = dpv;
        dp[u] = dpu;
    }
}
void read()
{
    cin >> n >> k;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    ans = 0;
    sum = 0;
    dfs(1, 0);
    for(int i = 1; i <= n; i++)
    {
        ans += dp[i];
        sum += dp[i];
    }
    dfs2(1, 0);
    cout << ans << "\n";
    for(int i = 1; i <= n; i++)
    {
        sz[i] = 0;
        dp[i] = 0;
        g[i].clear();
    }
}
