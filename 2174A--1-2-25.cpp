#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
using namespace std;
const int N =1e5+23;
string s1,s2;
int t;
map<char,int> mp1;
map<char,int> mp2;
void read()
{
   cin >> s1 >> s2;
}
void solve()
{
    mp1.clear();
    mp2.clear();
    for(auto i: s1)
        mp1[i]++;
    for(auto i: s2)
        mp2[i]++;
    for(auto i: mp1)
        if (mp1[i.fi] > mp2[i.fi])
            {
                cout << "Impossible\n";
                return;
            }
        else
        {
            mp2[i.fi]-=mp1[i.fi];
        }
   
    string ans=s1;
    int tt=0;
    while(tt < ans.size())
    {
        char i= ans[tt];
        for(auto j: mp2)
        {
            if (i > j.fi & j.se!=0)
            {
                string temp(1,j.fi);
                for(int z=1; z <= j.se; z++)
                    ans.insert(tt,temp);
                mp2[j.fi]=0;
                tt--;
                break;
            }
        }
        tt++;
    }
    for(auto i: mp2)
    {
        for(int j = 1; j <= i.se; j++)
        {
            ans= ans + i.fi;
        }
    }
    cout << ans << "\n";

    
}
main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    cin >> t;
    while(t--)
    {
        read();
        solve();
    }
   
    
}
