using namespace std;
const int N =1e6+23;
int n;
vector<int> odd;
vector<int> even;
int ans[N];
void read()
{
    odd.clear();
    even.clear();
    cin >> n;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        if(x % 2 == 0)
        {
            even.pb(x);
        }
        else
        {
            odd.pb(x);
        }
    }
}
void solve()
{
    sort(odd.begin(), odd.end());
    sort(even.begin(), even.end());

    if(odd.size() == 0)
    {
        for(int i = 1; i <= n; i++)
        {
            cout << "0 ";
        }
        cout << "\n";
        return;
    }

    if(even.size() == 0)
    {
        for(int i = 1; i <= n; i++)
        {
            if(i % 2 == 0)
            {
                cout << 0 << " ";
            }
            else
            {
                cout << odd[odd.size() - 1] << " ";
            }
        }
        cout << "\n";
        return;
    }
    int mxsz = even.size() + 1;

    ans[1] = odd[odd.size() - 1];

    cout << ans[1] << " ";

    int mneven = even[0];

    int vte = even.size() - 1;

    for(int i = 2; i <= mxsz; i++)
    {
        ans[i] = ans[i - 1] + even[vte];
        vte--;
        cout << ans[i] << " ";
    }
    if(mxsz != n)
    {
        for(int i = mxsz + 1; i < n; i++)
        {
            if((i - mxsz) % 2 == 1)
            {
                ans[i] = ans[mxsz] - mneven;
            }
            else
            {
                ans[i] = ans[mxsz];
            }
            cout << ans[i] << " ";
        }
        if(odd.size() % 2 == 0)
        {
            cout << "0";
        }
        else
        {
            cout << ans[mxsz];
        }
    }
    cout << "\n";

}

