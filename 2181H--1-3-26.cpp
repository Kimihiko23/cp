vector<int> gcd(int V, int N) 
{
    vector<int> divs;
    for (int i = 1; i * i <= V; i++) 
    {
        if (V % i == 0) 
        {
            if (N % i == 0) divs.push_back(i);
            int other = V / i;
            if (other != i && N % other == 0) 
            {
                divs.push_back(other);
            }
        }
    }
    return divs;
}
