using namespace std;
const int N =1e5+23;
int a[N];
int b[N];
int c[N];
int n;
bool check1(int x)
{
    for(int j = 0; j < n; j++)
    {
        if(a[(j + x) % (n)] >= b[j])
        {
            return false;
        }
    }
    return true;
}
bool check2(int x)
{
    for(int j = 0; j < n; j++)
    {
        if(b[(j + x) % (n)] >= c[j])
        {
            return false;
        }
    }
    return true;
}
void read()
{
    cin >> n;
    for(int i = 0; i < n; i++)
    {
        cin >> a[i];
    }
    for(int i = 0; i < n; i++)
    {
        cin >> b[i];
    }
    for(int i = 0; i < n; i++)
    {
        cin >> c[i];
    }
}
void solve()
{
    int tam1 = 0, tam2 = 0;
    for(int i = 0; i < n; i++)
    {
        if(check1(i))
            tam1++;
        if(check2(i))
            tam2++;
    }
    cout << tam1*tam2*n << "\n";
}
