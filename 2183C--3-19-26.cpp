int n, m, st;

void read()
{   
    cin >> n >> m >> st;
}
void solve()
{
    int ans = 0;
    int rmx = n - st;
    int lmx = st - 1;
    for(int l = 0; l <= lmx; l++)
    {
        if(l > 0 && l * 2 - 1 > m) continue;
        int r = 0;
        int r1 = min(l, m + 1 - 2 * l);
        r = max(r, r1);
        int r2 = (m - l + 1) / 2;
        if(r2 > l)
            r = max(r, r2);
        r = min(r, rmx);
        ans = max(l + r + 1, ans);
    }
    cout << ans << "\n";
}

