using namespace std;
const int N =1e6+23;
int sz[N];
vector<int> g[N];
int n;
int dis[N];
int lw = 0;
int mxchil;
void dfs(int u, int par, int de)
{
    lw = max(lw, de);
    sz[de]++;
    int chil = 0;
    for(auto i : g[u])
    {
        if(i == par)
            continue;
        chil++;
        dfs(i, u, de + 1);
    }
    mxchil = max(mxchil, chil);

}
void read()
{   
    cin >> n;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0, 0);
    int ans = mxchil + 1;
    for(int i = 0; i <= lw; i++)
    {
        ans = max(ans, sz[i]);
    }
    cout << ans << "\n";
    fill(sz, sz + 1 + lw, 0);
    lw = 0;
    mxchil = 0;
    ans = 0;
    for(int i = 1; i <= n; i++)
    {
        g[i].clear();
    }
}

