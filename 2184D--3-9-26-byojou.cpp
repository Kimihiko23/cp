using namespace std;
const int N =1e5+23;

int n, k, ans;

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    int t; cin >> t;
    int ha = 0;
    while(t --){
        cin >> n >> k;
        ans = 0;
        int h = __lg(n);
        if(h + 1 <= k) ans ++;
        for(int i = 0; i < h; i++){
            int cur = 1, ma = i + 1;

            if(ma <= k) ans ++;
            for(int j = i; j > 0; j--){
                ma ++;
                cur *= j;
                cur /= (i - j + 1);
                if(ma <= k) ans += cur;
            }        
        }
        cout << max(ha, n - ans) << "\n";
    }
} 
