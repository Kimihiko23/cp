#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
using namespace std;
const int N =2e5+23;

int n, m, h, q;
int a[N], b[N];

void read()
{
   cin >> n >> m >> h;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
        b[i] = 0;
   }
}
void solve()
{
   set<int> tam;
   for(auto i : tam)
   {
        b[i] = 0;
   }
   tam.clear();
   while(m--)
   {
        int vt, val;
        cin >> vt >> val;
        b[vt] += val;
        tam.insert(vt);
        if (a[vt] + b[vt] > h)
        {
            for(auto i: tam)
            {
                b[i] = 0;
            }
            tam.clear();
        }
   }
   for(int i = 1; i <= n; i++)
   {
        cout << a[i] + b[i] << " ";
   }
   cout << "\n";
}
main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    cin >> q;
    while(q--)
    {
        read();
        solve();
    }

   
    
} 
