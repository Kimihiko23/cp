#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
using namespace std;
const int N = 2e5+23;
const int INF = 1e18;

int n, m, k;
void read()
{
   cin >> n >> m >> k;
}

void solve()
{
    vector<int> a(n);
    for(int i = 0; i < n; i++) cin >> a[i];
    vector<int> b(m);
    for(int i = 0; i < m; i++) cin >> b[i];
    string s;
    cin >> s;

    sort(b.begin(), b.end());
    vector<pair<int, int>> evel, ever;
    // thời gian sẽ chết


    for(int i = 0; i < n; i++) 
    {
        auto it = lower_bound(b.begin(), b.end(), a[i]);
    
        if (it != b.end()) 
        {
            ever.pb({*it - a[i], i});
        } else {
            ever.pb({INF, i});
        }

       
        if (it != b.begin()) 
        {
            it--;
            evel.pb({a[i] - *it, i});
        } else 
        {
            evel.pb({INF, i});
        }
    }

    
    sort(evel.begin(), evel.end());
    sort(ever.begin(), ever.end());

    vector<bool> dd(n, false);
    int ans = n;

    int ptr_l = 0;
    int ptr_r = 0;
    int cur = 0;
    int min_pos = 0;
    int max_pos = 0;

    for(char c : s) 
    {
        if (c == 'L') cur--;
        else cur++;

     
        if (cur < min_pos) 
        {
            min_pos = cur;
            int distl = -min_pos; 
            while(ptr_l < n && evel[ptr_l].fi <= distl) 
            {
                int id = evel[ptr_l].se;
                if (!dd[id])
                 {
                    dd[id] = true;
                    ans--;
                }
                ptr_l++;
            }
        }


        if (cur > max_pos) 
        {
            max_pos = cur;
            int distr = max_pos;
            while(ptr_r < n && ever[ptr_r].fi <= distr) 
            {
                int id = ever[ptr_r].se;
                if (!dd[id])
                {
                    dd[id] = true;
                    ans--;
                }
                ptr_r++;
            }
        }

        cout << ans << " ";
    }
    cout << "\n";
}

main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    int t;
    cin >> t;
    while(t--) 
    {
        read();
        solve();
    }
}