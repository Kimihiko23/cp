using namespace std;
const int N =2e5+23;
int pre1[N], pre2[N];
int n;
string s;



void read()
{
   cin >> n >> s;
   s = " " + s;
   for(int i = 1; i <= n; i++)
   {
        if(s[i] == '(')
        {
            pre1[i] = 1;
        }
        else
        {
            pre2[i] = 1;
        }
        pre1[i] += pre1[i-1];
        pre2[i] += pre2[i-1];
   }
}
void solve()
{
   int ans = -1;
   int len = 0;
   for(int i = 1; i <= n; i++)
   {
        if(s[i] == ')')
        {
            int len1 = min(pre1[i-1], pre2[i-1]);
            // cout << len1 << "\n";
            int tam1 = pre1[i - 1] - len1 + 1;
            //tam1 la so luong ( con lai o ben trai i
            // cout << tam1 << "\n";
            int tam2 = pre2[n] - pre2[i];
            //tam2 la so luong ) con lai o ben phai i
            // cout << tam2 << "\n";
            if(tam2 >= tam1)
            {
                int tam3 = tam2 - tam1;
                int tam4 = min(tam3, pre1[n] - pre1[i]);
                int dem = tam4 + len1 + min(tam1, tam2);
                ans = max(dem * 2, ans);
            }
            // break;
        }
        // cout << pre1[i] << " " << pre2[i] << "\n";
   }
   cout << ans << "\n";
   memset(pre1, 0, sizeof pre1);
   memset(pre2, 0, sizeof pre2);
}
