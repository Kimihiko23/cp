const int N =1e6+23;
int n;
int a[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
        cin >> a[i];
}
void solve()
{
    int l = 1, r = 1;
    for(int i = 1; i <= n; i++)
    {
        if(a[i] != n - i + 1)
        {
            l = i;
            for(int j = i ; j <= n; j++)
            {
                if(a[j] == n - i + 1)
                {
                    r = j;
                    break;
                }
            }
            break;
        }
    }
    reverse(a + l, a + r + 1);
    for(int i = 1; i <= n; i++)
    {
        cout << a[i] << " ";
    }
    cout << "\n";
}

