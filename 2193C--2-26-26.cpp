using namespace std;
const int N =2e5+23;
int a[N];
int b[N];
int pre[N];
int n, t, q;


void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
       cin >> a[i];
   }
   for(int i = 1; i <= n; i++)
   {
       cin >> b[i];
       if(a[i] < b[i])
        a[i] = b[i];
   }
}
void solve()
{
   int mx = -1e18;
   for(int i = n; i >= 1; i--)
   {
        mx = max(mx, a[i]);
        a[i] = mx;
   }
   for(int i = 1; i <= n; i++)
   {
        pre[i] = pre[i - 1] + a[i];
   }
   int l, r;
   while(q--)
   {
        cin >> l >> r;
        cout << pre[r] - pre[l - 1] << " ";
   }
   cout << "\n";
}
