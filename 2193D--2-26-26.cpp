using namespace std;
const int N =1e6+23;
int a[N], prea[N];
int b[N], preb[N];
int n;
set<int> s;
void read()
{
    cin >> n;
    s.clear();
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        s.insert(a[i]);
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> b[i];
        preb[i] = preb[i - 1] + b[i];
    }
}
void solve()
{
    int ans = 0;
    sort(a + 1, a + 1 + n);
    for(auto i : s)
    {
        int l = 1, r = n;
        int vt = 0;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(a[mid] >= i)
            {
                vt = mid;
                r = mid - 1;
            }
            else
            {
                l = mid + 1;
            }
        }
        int power = n - vt + 1;
        l = 1, r = n;
        vt = 0;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(preb[mid] <= power)
            {
                vt = mid;
                l = mid + 1;
            }
            else
            {
                r = mid - 1;
            }
        }
        ans = max(ans, vt * i);
    }
    cout << ans << "\n";
}

