#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =2e5+23;
int n, stx, sty, edx, edy;
int dp[N][2];
int top[N], bot[N];
set<int> s;
vector<pair<int, int>> a;
int cal(int x1, int y1, int x2, int y2)
{
    return abs(x1 - x2) + abs(y1 - y2);
}
void read()
{
   cin >> n >> stx >> sty >> edx >> edy;
   int x, y;
   s.clear();
   a.clear();
   s.insert(0);
   vector<int> inx;
   vector<int> iny;
   for(int i = 1; i <= n; i++)
   {
        cin >> x;
        s.insert(x);
        inx.pb(x);
   }
   for(int i = 1; i <= n; i++)
   {
        cin >> y;
        a.pb({inx[i - 1], y});
   }
}
void solve()
{
    sort(a.begin(), a.end());
    int dem = 1;
    top[dem] = a[0].se;
    for(int i = 1; i < n; i++)
    {
        if(a[i].fi != a[i - 1].fi)
        {
              bot[dem] = a[i - 1].se;
              dem++;
              top[dem] = a[i].se;
        }
    }
    bot[dem] = a[n - 1].se;
    // for(int i = 1; i <= dem ; i++)
    // {
    //     cout << top[i] <<  " " << bot[i] << "\n";
    // }
    auto vt = s.begin();
    //dp[x][0] la ket thuc o top
    //dp[x][1] la ket thuc o bot;
    dp[1][0] = cal(stx, sty, *++vt, bot[1]) + abs(bot[1] - top[1]);
    dp[1][1] = cal(stx, sty, *vt, top[1]) + abs(bot[1] - top[1]);
    // cout << dp[1][1] << " ";
    for(int i = 2; i <= dem; i++)
    {
        int oldvt = *vt;
        vt++;
        dp[i][0] = min(
            dp[i - 1][0] + cal(oldvt, top[i - 1], *vt, bot[i]) + abs(bot[i] - top[i]),
            dp[i - 1][1] + cal(oldvt, bot[i - 1], *vt, bot[i]) + abs(bot[i] - top[i]));
        dp[i][1] = min(
            dp[i - 1][0] + cal(oldvt, top[i - 1], *vt, top[i]) + abs(bot[i] - top[i]),
            dp[i - 1][1] + cal(oldvt, bot[i - 1], *vt, top[i]) + abs(bot[i] - top[i]));
    }
    int ans = min(
        dp[dem][0] + cal(*vt, top[dem], edx, edy),
        dp[dem][1] + cal(*vt, bot[dem], edx, edy));
    cout << ans << "\n";
    for(int i = 1; i <= dem; i++)
    {
        dp[i][1] = 0;
        dp[i][0] = 0;
    }
   

}
