const int N =1e5+23;
int tam(int n) {
    if (n == 0) return 0;
    while (n % 2 == 0) {
        n /= 2;
    }
    return n;
}

void solve() 
{
    int n;
    cin >> n;
    
    vector<int> a(n + 1);
    bool possible = true;
    
    for (int i = 1; i <= n; i++) 
    {
        cin >> a[i];
    }
    

    for (int i = 1; i <= n; i++) 
    {
       
       
        if (tam(a[i]) != tam(i))
        {
            possible = false;
            break;
        }
    }
    
    if (possible)
    {
        cout << "YES" << endl;
    } 
    else 
    {
        cout << "NO" << endl;
    }
}

