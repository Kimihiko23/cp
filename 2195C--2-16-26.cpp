void solve()
{
    for (int v = 1; v <= 6; v++) 
    {
        dp[1][v] = (a[1] == v ? 0 : 1);
    }
    for (int i = 2; i <= n; i++) 
    {
        for (int v = 1; v <= 6; v++) 
        {
            dp[i][v] = 1e18;
            for (int u = 1; u <= 6; u++) 
            {
                if (u != v && u + v != 7) 
                {
                    dp[i][v] = min(dp[i][v], dp[i-1][u] + (a[i] == v ? 0 : 1));
                }
            }
        }
    }
    int ans = 1e18;
    for(int i = 1; i <= 6; i++)
    {
        ans = min(ans, dp[n][i]);
    }
    cout << ans << "\n";
}
