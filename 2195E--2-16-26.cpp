const int N = 3e5+23;
const int MOD = 1e9 + 7;

int n;
int l[N], r[N];
long long dp[N], ans[N];

void dfs_calc(int u) 
{
    if (l[u] == 0) {
        dp[u] = 1;
        return;
    }
    dfs_calc(l[u]);
    dfs_calc(r[u]);
    dp[u] = (dp[l[u]] + dp[r[u]] + 3) % MOD;
}

void dfs_solve(int u, long long par_val) 
{
    ans[u] = (par_val + dp[u]) % MOD;
    if (l[u]) {
        dfs_solve(l[u], ans[u]);
        dfs_solve(r[u], ans[u]);
    }
}
