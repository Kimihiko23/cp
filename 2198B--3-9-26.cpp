#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;

struct ty
{
    int a, b, c;
};
int n, m;
ty q[N];
pair<int, int> ch[N];
int mx;
bool che;
void read()
{
   cin >> n >> m;
   che = true;
   mx = 0;
   for(int i = 1; i <= n; i++)
   {
       cin >> q[i].a >> q[i].b >> q[i].c;
       mx += q[i].a * (q[i].b - 1);
       ch[i].fi = q[i].a * q[i].b - q[i].c;
       if(ch[i].fi > 0)
       {
            che = false;
       }
       ch[i].se = i;
   }
}
void solve()
{
   if(mx >= m)
   {
        cout << 0 << "\n";
        return;
   }
   if(che)
   {
        cout << "-1\n";
        return;
   }
   sort(ch + 1, ch + n + 1, greater<pair<int, int>>());
   int remain = m - mx;
   int best = ch[1].fi;
   cout << (remain + best - 1) / best << "\n";
   memset(ch, 0, sizeof(ch));
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    int t;
    cin >> t;
    while(t--)
    {
        read();
        solve();
    }
} 
