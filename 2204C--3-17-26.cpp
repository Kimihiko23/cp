int gcd(int a, int b) 
{
    while (b) 
    {
        a %= b;
        swap(a, b);
    }
    return a;
}

int lcm(int a, int b, int m) 
{
    if (a > m || b > m) return m + 1;
    int g = gcd(a, b);
    __int128 res = (__int128)a * (b / g);
    if (res > m) return (int)m + 1;
    return (int)res;
}

