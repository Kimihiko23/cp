#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m, k, p;
vector<pair<int, int>> a;
void read()
{   
    a.clear();
    a.pb({0, 0});
    cin >> n >> k >> p >> m;
    for(int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        a.pb({x, 0});
    }
    a[p].se = 1;
}
void solve()
{
    int ans = 0;
    while(m > 0)
    {
        int vtmn = 1;
        int mn = 1e18;
        for(int i = 1; i <= k; i++)
        {
            if(a[i].se == 1)
            {
                vtmn  = i;
                mn = a[i].fi;
                // ans++;
                break;
            }
            if(a[i].fi <= mn)
            {
                mn = a[i].fi;
                vtmn = i;
            }
        }
        m -= mn;
        if(m >= 0 && a[vtmn].se == 1)
        {
            ans++;
        }
        a.pb({a[vtmn].fi, a[vtmn].se});
        a.erase(a.begin() + (vtmn));
        // cout << vtmn << " ";
    }
    cout << ans << "\n";
}

