int mx = 0;
void read()
{   
    ans = 0;
    mx = 0;
    cin >> n >> k;
    for(int i = 1; i <= k; i++)
    {
        int x;
        cin >> x;
    }
    for(int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        // cout << x << " ";
        if(x <= k)
        {
            a[x].pb(i);
            ans += k + 1 - x;
            mx = max(mx, x);
        }
    }
}
void solve()
{
    cout << ans << "\n";
    if(ans == 0)
    {
        cout << "\n";
        for(int i = 0; i <= mx; i++)
        {
            a[i].clear();
        }
    }
    for(int i = k; i >= 1; i--)
    {
        for(auto j : a[i])
        {
            for(int z = 1; z <= k + 1 - i; z++)
            {
                cout << j << " ";
            }
        }
    }
    for(int i = 0; i <= mx; i++)
    {
        a[i].clear();
    }
    cout << "\n";
}
 

