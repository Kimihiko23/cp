void read()
{
    int t;
    cin >> t;
    while (t--)
    {
        int n;
        cin >> n;
        vector<int> a(n);
        for (int &x : a) cin >> x;

        auto ok = [&](int k) -> bool
        {
            multiset<int> st(a.begin(), a.end());
            for (int x = k - 1; x >= 0; --x)
            {
                auto it = st.find(x);
                if (it != st.end())
                {
                    st.erase(it);
                }
                else
                {
                    it = st.upper_bound(2 * x);
                    if (it == st.end()) return false;
                    st.erase(it);
                }
            }
            return true;
        };

        int l = 0, r = n, mexwf = 0;
        while (l <= r)
        {
            int mid = (l + r) >> 1;
            if (ok(mid))
            {
                mexwf = mid;
                l = mid + 1;
            }
            else r = mid - 1;
        }

        cout << mexwf << '\n';
    }
}

