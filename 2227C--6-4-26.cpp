void solve()
{
    int T;
    cin >> T;

    while (T--)
    {
        int n;
        cin >> n;

        vector<int> d6, d2, d3, oth;

        for (int i = 1; i <= n; i++)
        {
            int x;
            cin >> x;

            if (x % 6 == 0)
                d6.pb(x);
            else if (x % 2 == 0)
                d2.pb(x);
            else if (x % 3 == 0)
                d3.pb(x);
            else
                oth.pb(x);
        }

        vector<int> ans;

        for (auto x : d6) ans.pb(x);
        for (auto x : d2) ans.pb(x);
        for (auto x : oth) ans.pb(x);
        for (auto x : d3) ans.pb(x);

        for (int i = 0; i < n; i++)
        {
            if (i) cout << ' ';
            cout << ans[i];
        }
        cout << '\n';
    }
}

