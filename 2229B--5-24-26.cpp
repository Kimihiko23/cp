int b[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(a[i] > b[i])
        {
            swap(a[i], b[i]);
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        ans = max(ans, a[i]);
    }
    for(int i = 1; i <= n; i++)
    {
        ans += b[i];
    }
    cout << ans << "\n";

}
