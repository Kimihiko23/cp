const int MOD = 1000020409;
const int N = 2e5 + 23;
int n;
int a[N];
bool dd[N];
int best[N];
int pre[N];
void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        dd[i] = 0;
        pre[i] = pre[i - 1] + a[i];
        best[i] = best[i - 1] + abs(a[i]);
    }
}
void solve()
{
    int mod = 0;
    int ans = 0;
    int vtqt = 0;
    int duong = 0;
    int mx = pre[n];
    for(int i = 1; i <= n; i++)
    {
        if(a[i] > 0)
        {
            duong++;
            if((best[i - 1] - a[i] + pre[n] - pre[i]) > mx)
            {
                vtqt = i;
                mx = best[i - 1] - a[i] + pre[n] - pre[i];
            }
        }
    }
    if(duong != n && vtqt != 0)
    for(int i = vtqt - 1; i >= 1; i--)
    {
        if(a[i] > 0 && mod == 0)
        {
            ans++;
            mod = 1;
            dd[i] = 1;
        }
        else if(a[i] < 0 && mod == 1)
        {
            ans++;
            mod = 0;
            dd[i] = 1;
        }
    }
    if(vtqt != 0)
        ans++;
    cout << ans << "\n";
    for(int i = n; i >= 1; i--)
    {
        if(dd[i]) cout << i << " ";
    }
    if(ans != 0)
        cout << vtqt;
    cout << "\n";
}
