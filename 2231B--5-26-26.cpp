void solve()
{
    int k = 0;
    for (int i = 1; i < n; i++) 
    {
        k = max(k, a[i] - a[i + 1]);
    }
    
    for (int i = 2; i <= n; i++) 
    {
        if (a[i - 1] > a[i]) 
        {
            a[i] += k;
        }
    }
    
    for (int i = 1; i < n; i++) 
    {
        if (a[i] > a[i + 1]) 
        {
            cout << "NO\n";
            return;
        }
    }
    cout << "YES\n";
}
