int n;
int a[N];
void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
        cin >> a[i];
}
void solve()
{
    sort(a + 1, a + n + 1, greater<int>());
    int x = a[1], y = a[2];
    int cnt = 2;
    vector<int> ck;
    while(cnt <= n)
    {
        if(y == 0) break;
        int nx = x % y;
        x = y;
        y = nx;
        ck.push_back(nx);
        cnt++;
    }
    bool dd = true;
    for(int i = 3; i <= n; i++)
    {
        if(a[i] != ck[i - 3] || cnt < n)
        {
            dd = false;
            break;
        }
    }
    if(dd) 
        cout << a[1] << " " << a[2];
    else 
        cout << "-1";
    cout << "\n";
}
