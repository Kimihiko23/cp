const int N = 1e5 + 23;
int pre[N], suf[N];
int a[N];
int n;
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }

}
void solve()
{
    for(int s = 1; s <= n; s++)
    {
        pre[s] = 0;
        suf[s] = 0;

        for(int i = 1; i < n; i++)
        {
            int cur = (s + i - 1) % n + 1;
            int prv = (s + i - 2 + n) % n + 1;

            pre[cur] = max(pre[prv], a[prv]);
        }

     
        for(int i = 1; i < n; i++)
        {
            int cur = (s - i - 1 + n * 2) % n + 1;
            int nxt = (s - i + n * 2) % n + 1;

            suf[cur] = max(suf[nxt], a[cur]);
        }

        long long sum = 0;

        for(int i = 1; i <= n; i++)
        {
            sum += min(pre[i], suf[i]);
        }

        cout << sum << " ";
        
        for(int i = 1; i <= n; i++)
        {
            pre[i] = 0;
            suf[i] = 0;
        }
    }

    cout << '\n';
}
