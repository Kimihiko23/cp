#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 1e5 + 23;
int a, b, x;
vector<pair<int, int>> res1, res2;
void read()
{
    cin >> a >> b >> x;
    res1.clear();
    res2.clear();
    res1.pb({a, 0});
    res2.pb({b, 0});

}
void solve()
{
    int cnt = 0;
    while(a > 0)
    {
        cnt++;
        a /= x;
        res1.pb({a, cnt});
    }
    cnt = 0;
    while(b > 0)
    {
        cnt++;
        b /= x;
        res2.pb({b, cnt});
    }
    int ans = 1e18;
    for(int i = 0; i < res1.size(); i++)
    {
        for(int j = 0; j < res2.size(); j++)
        {
            int tam = res1[i].se + res2[j].se + abs(res1[i].fi - res2[j].fi);
            ans = min (ans, tam);
        }
    }
    cout << ans << "\n";
}
