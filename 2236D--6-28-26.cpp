void solve()
{
    int t;
    cin >> t;

    while (t--)
    {
        int n, k;
        cin >> n >> k;

        vector<int> a(n);

        for (int i = 0; i < n; i++)
            cin >> a[i];

        sort(a.begin(), a.end());

        vector<pair<int, int>> v;

        for (int x : a)
        {
            if (v.empty() || v.back().fi != x)
                v.pb({x, 1});
            else
                v.back().se++;
        }

        bool ok = false;

        while (!v.empty())
        {
            int m = v.size();

            if (v.back().se % 2 == 0)
            {
                ok = true;
                break;
            }

            if (m == 1)
                break;

            if (v.back().fi - v[m - 2].fi <= k)
            {
                ok = true;
                break;
            }

            v.pop_back();
        }

        cout << (ok ? "YES\n" : "NO\n");
    }
}
