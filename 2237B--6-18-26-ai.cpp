const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 5;

int n;
int a[N], b[N];
int st[4 * N];

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = 1;
        return;
    }

    int mid = (l + r) >> 1;

    build(id << 1, l, mid);
    build(id << 1 | 1, mid + 1, r);

    st[id] = st[id << 1] + st[id << 1 | 1];
}

void update(int id, int l, int r, int pos)
{
    if (l == r)
    {
        st[id] = 0;
        return;
    }

    int mid = (l + r) >> 1;

    if (pos <= mid)
        update(id << 1, l, mid, pos);
    else
        update(id << 1 | 1, mid + 1, r, pos);

    st[id] = st[id << 1] + st[id << 1 | 1];
}

int get(int id, int l, int r, int u, int v)
{
    if (u > r || v < l) return 0;

    if (u <= l && r <= v)
        return st[id];

    int mid = (l + r) >> 1;

    return get(id << 1, l, mid, u, v)
         + get(id << 1 | 1, mid + 1, r, u, v);
}

