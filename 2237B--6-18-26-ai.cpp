void solve()
{
    int tc;
    cin >> tc;

    while (tc--)
    {
        cin >> n;

        for (int i = 1; i <= n; i++) cin >> a[i];
        for (int i = 1; i <= n; i++) cin >> b[i];

        vector<pair<int,int>> p;

        for (int i = 1; i <= n; i++)
            p.pb({a[i], i});

        sort(p.begin(), p.end());

        priority_queue<
            pair<int,int>,
            vector<pair<int,int>>,
            greater<pair<int,int>>
        > pq;

        build(1, 1, n);

        int ptr = 0;
        int ans = 0;
        bool ok = true;

        for (int i = 1; i <= n; i++)
        {
            while (ptr < n && p[ptr].fi <= b[i])
            {
                pq.push({p[ptr].se, p[ptr].fi});
                ptr++;
            }

            if (pq.empty())
            {
                ok = false;
                break;
            }

            int pos = pq.top().fi;
            pq.pop();

            ans += get(1, 1, n, 1, pos) - 1;

            update(1, 1, n, pos);
        }

        if (!ok) cout << -1 << '\n';
        else cout << ans << '\n';
    }
}

