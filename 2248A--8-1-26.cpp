void solve()
{
    int t;
    cin >> t;

    while (t--)
    {
        string s;
        cin >> s;

        string ans = "";
        for (int i = 0; i < s.size(); i++)
        {
            if (s[i] == '0')
            {
                string afAL = s.substr(0, i) + s.substr(i + 1);

                string tam = string(200, '1');
                for (int j = 0; j < afAL.size(); j++)
                {
                    if (afAL[j] == '1')
                    {
                        string afBB = afAL.substr(0, j) 
                                         + afAL.substr(j + 1);

                        tam = min(tam, afBB);
                    }
                }

                
                ans = max(ans, tam);
            }
        }

        cout << ans << '\n';
    }
}

