int n, m;
vector<int> a;
int b[N];

void read()
{
    a.clear();

    cin >> n >> m;

    a.resize(n);

    for(int i = 0; i < n; i++)
        cin >> a[i];

    for(int i = 1; i <= m; i++)
        cin >> b[i];
}

void solve()
{
    sort(a.begin(), a.end());
    sort(b + 1, b + m + 1);
    bool ok = true;
    if(n < 2 * m)
    {
        cout << "NO\n";
        return;
    }
    for(int i = 1; i <= m; i++)
    {
        int le = a[i - 1];
        int ri = a[n - m + i - 1];

        if(!(le < b[i] && b[i] < ri))
        {
            ok = false;
            break;
        }
    }
    if(ok)
        cout << "YES\n";
    else
        cout << "NO\n";
}
