mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, q;
string s, t;
int pref1[N], pref2[N], pref3[N];
void read()
{
    cin >> n >> q;
    cin >> s >> t;
    for (int i = 1; i <= n; i++) 
    {
        pref1[i] = pref1[i - 1];
        pref2[i] = pref2[i - 1];
        pref3[i] = pref3[i - 1];
        char a = s[i - 1];
        char b = t[i - 1];
        if (a == b) 
        {
            pref1[i]++;
        } 
        else if (a == '1' && b == '0') 
        {
            pref2[i]++;
        } 
        else 
        { 
            pref3[i]++;
        }
    }
}
void solve()
{
    while (q--) 
    {
        int l, r;
        cin >> l >> r;
        int c1 = pref1[r] - pref1[l - 1];
        int c2 = pref2[r] - pref2[l - 1];
        int c3 = pref3[r] - pref3[l - 1];
        if (c1 >= abs(c2 - c3)) 
        {
            cout << "YES\n";
        } 
        else 
        {
            cout << "NO\n";
        }
    }
}
