void solve()
{
    int cnt0 = (n + 1) / 2;
    int cnt1 = n / 2;
    // cout << cnt0 << " " << cnt1 << "\n";
    if (n > 1 && k == n - 1) 
    {
		cout << -1 << '\n';
		return;
	}
    // if(k > n - 2)
    // {
    //     cout << "-1\n";
    //     return;
    // }
    cnt0 -= (need + 1) / 2;
    cnt0++;
    cnt1 -= need / 2;
    cnt1++;
    for(int i = 1; i <= cnt0; i++)
    {
        cout << 0;
    }
    for(int i = 1; i <= cnt1; i++)
    {
        cout << 1;
    }
    int dem = 0;
    n -= (cnt1 + cnt0);
    while(n--)
    {
        if(dem % 2 == 0)
        {
            cout << 0;
        }
        else
        {
            cout << 1;
        }
        dem++;
    }
    cout << "\n";
}
