void solve()
{
    while (t--)
    {
        cin >> n >> k >> s;

        int ans = 0;

        for (int i = 0; i < n; i += k)
        {
            bool ok = 1;

            for (int j = i; j < i + k; j++)
                if (s[j] == '0')
                {
                    ok = 0;
                    break;
                }

            ans += ok;
        }

        cout << ans << '\n';
    }
}

