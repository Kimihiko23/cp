vector<int> vt1, vt2;
int n;
int a[N];
void read()
{
    vt1.clear();
    vt2.clear();
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        if(a[i] == 1) vt1.pb(i);
        if(a[i] == -1) vt2.pb(i);
    }
}
void solve()
{
    int L = -1, R = -1;
    int best = 0;
    if (vt1.empty())
    {
        if (vt2.size() >= 2)
        {
            L = vt2.front();
            R = vt2.back();
        }
        else if (vt2.size() == 1)
        {
            a[vt2[0]] = 1;
        }
    }
    else
    {
        for (int i = 0; i + 1 < vt1.size(); i++)
        {
            int l = vt1[i];
            int r = vt1[i + 1];

            if (r - l + 1 > best)
            {
                best = r - l + 1;
                L = l;
                R = r;
            }
        }
        if (!vt2.empty() && vt2.front() < vt1.front())
        {
            int l = vt2.front();
            int r = vt1.front();

            if (r - l + 1 > best)
            {
                best = r - l + 1;
                L = l;
                R = r;
            }
        }
        if (!vt2.empty() && vt2.back() > vt1.back())
        {
            int l = vt1.back();
            int r = vt2.back();

            if (r - l + 1 > best)
            {
                best = r - l + 1;
                L = l;
                R = r;
            }
        }
    }
    if (L != -1)
    {
        a[L] = 1;
        a[R] = 1;

        for (int i = L + 1; i < R; i++)
            if (a[i] == -1)
                a[i] = 0;
    }
    for (int i = 1; i <= n; i++)
        if (a[i] == -1)
            a[i] = 0;
    for (int i = 1; i <= n; i++)
        cout << a[i] << ' ';
    cout << '\n';
}
