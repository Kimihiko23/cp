void solve()
{
    int t;
    cin >> t;
    while (t--) 
    {
        int n;
        cin >> n;
        vector<int> a(n), cnt(n + 2, 0);
        for (int &x : a) 
        {
            cin >> x;
            if (x <= n) cnt[x]++;
        }
        if (cnt[0] == 0) 
        {
            cout << "YES\n" << string(n, 'A') << "\n";
            continue;
        }
        if (cnt[0] == 1) 
        {
            cout << "NO\n";
            continue;
        }
        int m = 0;
        while (cnt[m] > 0) m++;
        int k = m;
        for (int v = 0; v < m; v++) if (cnt[v] < 2) { k = v; break; }
        int u = -1;
        for (int v = 0; v < k; v++) if (cnt[v] == 2) { u = v; break; }
        int md = (u != -1) ? 0 : (m <= 2 * k ? 1 : 2);
        vector<int> tb(n + 2, 0), tc(n + 2, 0);
        string s(n, 'A');
        for (int i = 0; i < n; i++) 
        {
            int v = a[i];
            if (v < k) 
            {
                if (tb[v]++ < 1) s[i] = 'B';
                else if (tc[v]++ < 1) s[i] = 'C';
            } 
            else if (md == 2) 
            {
                s[i] = (v == k) ? 'A' : 'B';
            }
        }
        cout << "YES\n" << s << "\n";
    }
}
