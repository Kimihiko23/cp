void solve() 
{
    int t;
    cin >> t;
    while (t--) 
    {
        int n;
        cin >> n;
        vector<int> a(n + 1), d(n + 2);

        for (int i = 1; i <= n; i++) 
        {
            cin >> a[i];
            if (a[i] != -1) 
            {
                int l = max(1LL, i - a[i] + 1);
                int r = min(n, i + a[i] - 1);

                if (l <= r) {
                    d[l]++;
                    d[r + 1]--;
                }
            }
        }

        string s;
        int sum = 0;
        bool f = false;

        for (int i = 1; i <= n; i++) 
        {
            sum += d[i];
            if (sum > 0)
                s += '0';
            else {
                s += '1';
                f = true;
            }
        }
        if (!f) 
        {
            cout << -1 << '\n';
            continue;
        }
        f = true;
        for (int i = 1; i <= n; i++) 
        {
            if (a[i] == -1)
                continue;
            int l = i - a[i];
            int r = i + a[i];
            bool x = false;
            if (l >= 1 && s[l - 1] == '1')
                x = true;
            if (r <= n && s[r - 1] == '1')
                x = true;
            if (!x) {
                f = false;
                break;
            }
        }
        if (f)
            cout << s << '\n';
        else
            cout << -1 << '\n';
    }
}
