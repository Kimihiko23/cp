int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};

int t, n, m, k;
const int LIM = 1000000000000000000LL;
vector<int> L, R, pre;
int G(int x)
{
    int j = upper_bound(L.begin(), L.end(), x) - L.begin();
    if (j == 0) return 0;
    j--;
    return pre[j] + min(R[j], x) - L[j] + 1;
}
int ins(int x)
{
    int j = upper_bound(L.begin(), L.end(), x) - L.begin();
    return j > 0 && R[j - 1] >= x;
}
void read()
{
    cin >> t;
}
void solve()
{
    while (t--)
    {
        cin >> n >> m >> k;
        L.assign(n, 0);
        R.assign(n, 0);
        pre.assign(n + 1, 0);
        for (int i = 0; i < n; i++)
        {
            cin >> L[i] >> R[i];
            pre[i + 1] = pre[i] + R[i] - L[i] + 1;
        }
        vector<int> p{1};
        for (int i = 0; i < n; i++)
        {
            for (int x : {L[i], R[i] + 1, L[i] - m, R[i] + 1 - m})
                if (x >= 1 && x <= LIM) p.pb(x);
        }
        sort(p.begin(), p.end());
        p.erase(unique(p.begin(), p.end()), p.end());
        p.pb(LIM + 1);
        bool dd = false;
        for (int j = 0; j + 1 < (int)p.size() && !dd; j++)
        {
            int a = p[j];
            int len = p[j + 1] - 1 - a;
            int fa = G(a + m - 1) - G(a - 1);
            int d = ins(a + m) - ins(a);
            if (d == 0)
            {
                if (fa == k)
                {
                    cout << a << "\n";
                    dd = true;
                }
            }
            else
            {
                int tt = (k - fa) * d;
                if (tt >= 0 && tt <= len)
                {
                    cout << a + tt << "\n";
                    dd = true;
                }
            }
        }
        if (!dd) cout << -1 << "\n";
    }
}

