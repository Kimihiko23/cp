int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int a, x, k;
bool ok(int R)
{
    int m = k + 1;
    int q = R / m, r = R % m;
    if (q >= 60) return false;
    __int128 c = (__int128)(m - r) * ((1LL << q) - 1) + (__int128)r * ((1LL << (q + 1)) - 1);
    return (__int128)a + (__int128)R * x > c;
}
void read()
{
    cin >> a >> x >> k;
}
void solve()
{
    int l = 1, r = 60 * (k + 1), ans = 1;
    while (l <= r)
    {
        int mid = (l + r) >> 1;
        if (ok(mid)) ans = mid, l = mid + 1;
        else r = mid - 1;
    }
    cout << a + ans * x << '\n';
}
