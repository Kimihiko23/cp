vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m, deg[N][3];
bool dead[N], vis[N];
vector<pair<int, int>> g[N];
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; ++i)
    {
        g[i].clear();
        deg[i][1] = deg[i][2] = 0;
        dead[i] = vis[i] = false;
    }
    for (int i = 1; i <= m; ++i)
    {
        int u, v, c;
        cin >> u >> v >> c;
        g[u].pb({v, c});
        g[v].pb({u, c});
        deg[u][c]++;
        deg[v][c]++;
    }
}
void solve()
{
    queue<int> q;
    for (int i = 1; i <= n; ++i)
    {
        if (deg[i][1] == 0 || deg[i][2] == 0)
        {
            dead[i] = true;
            q.push(i);
        }
    }
    while (!q.empty())
    {
        int u = q.front();
        q.pop();
        for (auto [v, c] : g[u])
        {
            if (!dead[v])
            {
                deg[v][c]--;
                if (deg[v][1] == 0 || deg[v][2] == 0)
                {
                    dead[v] = true;
                    q.push(v);
                }
            }
        }
    }
    int ans = 0;
    for (int i = 1; i <= n; ++i)
    {
        if (!vis[i])
        {
            bool ok = false;
            vis[i] = true;
            q.push(i);
            while (!q.empty())
            {
                int u = q.front();
                q.pop();
                if (!dead[u]) ok = true;
                for (auto [v, c] : g[u])
                {
                    if (!vis[v])
                    {
                        vis[v] = true;
                        q.push(v);
                    }
                }
            }
            if (ok) ans++;
        }
    }
    cout << ans << '\n';
}
