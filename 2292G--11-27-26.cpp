int m, k, a[N], s[N];
void read()
{
    cin >> m >> k;
    for (int i = 1; i <= m; ++i) cin >> a[i];
}
void solve()
{
    sort(a + 1, a + m + 1, greater<int>());
    for (int i = 1; i <= m; ++i) s[i] = s[i - 1] + a[i];
    int r = 0;
    for (int p = 1; (1LL << p) <= m; ++p)
    {
        int n = 1LL << p;
        int c = p * a[1] - (s[m] - s[m - (n >> 1)]) - (n - 1) * k;
        for (int j = 0; j <= p - 3; ++j)
            c += (p - 2 - j) * (s[1LL << (j + 1)] - s[1LL << j]);
        r = max(r, c);
    }
    cout << r << '\n';
}
