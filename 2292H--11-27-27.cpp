int n, m, u[N], v[N], e[N], sz[N], lst[N], au[N], av[N], ans[N];
void read()
{
    cin >> n >> m;
    for (int i = 1; i < n; ++i) cin >> u[i] >> v[i];
    for (int i = 1; i <= m; ++i) cin >> e[i];
}
void solve()
{
    for (int i = 1; i <= n; ++i) sz[i] = 1;
    for (int i = 1; i < n; ++i) lst[i] = 0;
    for (int i = 1; i <= m; ++i)
    {
        int id = e[i], x = u[id], y = v[id];
        au[i] = sz[x] - lst[id];
        av[i] = sz[y] - lst[id];
        int nw = sz[x] + sz[y] - lst[id];
        sz[x] = sz[y] = lst[id] = nw;
    }
    for (int i = 1; i <= n; ++i) sz[i] = 1;
    for (int i = 1; i < n; ++i) lst[i] = 0;
    for (int i = m; i >= 1; --i)
    {
        int id = e[i], x = u[id], y = v[id];
        int bu = sz[x] - lst[id];
        int bv = sz[y] - lst[id];
        ans[i] = au[i] * bv + av[i] * bu;
        int nw = sz[x] + sz[y] - lst[id];
        sz[x] = sz[y] = lst[id] = nw;
    }
    for (int i = 1; i <= m; ++i)
    {
        cout << ans[i];
        if (i == m) cout << '\n';
        else cout << ' ';
    }
}
