using namespace std;
const int N =1e3+23;
int n, m;
int pre[N][N];
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            char s;
            cin >> s;
            int x = s -'0';
            pre[i][j] = x + pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1];
        }
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1;i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            for(int i2 = i; i2 <= n; i2++)
            {
                for(int j2 = j; j2 <= m; j2++)
                {
                    if(cal(i, j, i2, j2) == 0)
                    {
                        ans = max(ans, (j2 - j + 1 + i2 - i + 1) * 2);
                    }
                }
            }
        }
    }
    cout << ans;
}   

