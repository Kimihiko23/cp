void solve()
{
    if(k == 1)
    {
        cout << 1 << " " << 2 << "\n";
        dd[2] = true;
    }
    else
    {
        cout << k << " " << k - 1 << "\n";
        dd[k - 1] = true;
    }
    m--;
    vector<int> s;
    for(int i = 1; i <= n; i++)
    {
        if(!dd[i]) s.push_back(i);
    }
    for(int i = 0; i < s.size() && m > 0; i++)
    {
        for(int j = i + 1; j < s.size() && m > 0; j++)
        {
            cout << s[i] << " " << s[j] << "\n";
            m--;
        }
    }
    
}
