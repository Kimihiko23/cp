int m, k, n;
int cnt[N];
int ans[N];
void read()
{
    cin >> m >> k;
    int x;
    for(int i = 1; i <= k; i++)
    {
        cin >> x;
        cnt[x]++;
    }
}
void solve()
{
    vector<pair<int, int>> a;
    cin >> n;
    string s;
    int mem;
    int mx = 0;
    for (int i = 1; i <= n; i++)
    {
        cin >> s >> mem;
        int fav = 0;
        int zero = 0;
        int nonfav = 0;
        for (int j = 1; j <= mem; j++)
        {
            int x;
            cin >> x;

            if (x == 0)
            {
                zero++;
            }
            else if (cnt[x])
            {
                fav++;
            }
            else
            {
                nonfav++;
            }
        }
        int mn = fav + max(0LL, zero - ((m - k) - nonfav));
        int mx = fav + min(zero, k - fav);
        a.push_back({mn, mx});
    }
    for (int i = 0; i < n; i++)
    {
        bool best = true;
        bool notbest = false;

        for (int j = 0; j < n; j++)
        {
            if (i == j) continue;
            if (a[j].se > a[i].fi)
                best = false;
            if (a[j].fi > a[i].se)
                notbest = true;
        }

        if (best)
            ans[i] = 0;
        else if (notbest)
            ans[i] = 1;
        else
            ans[i] = 2;
    }
    for(int i = 0; i < n; i++)
    {
        cout << ans[i] << "\n";
    }
}
