int m, k, n;
int cnt[N];
int ans[N];
void read()
{
    cin >> m >> k;
    int x;
    for(int i = 1; i <= k; i++)
    {
        cin >> x;
        cnt[x]++;
    }
}
void solve()
{
    vector<pair<int, int>> a;
    cin >> n;
    string s;
    int mem;
    int mx = 0;
    for(int i = 1; i <= n; i++)
    {
        cin >> s >> mem;
        int x;
        int cnt0 = 0;
        int sum = 0;
        for(int j = 1; j <= mem; j++)
        {
            cin >> x;
            sum += cnt[x];
            if(x == 0) cnt0++;
        }
        int more = 0;
        if(sum < k) more = min(cnt0, k - sum);
        a.pb({sum, sum + more});
        mx = max(mx, a[i - 1].se);
        // cout << sum << " " << sum + more << "\n";
    }
    for(int i = 0; i < n; i++)
    {
        if (a[i].fi == mx)
            ans[i] = 0;
        else if (a[i].se < mx)
            ans[i] = 1;
        else
            ans[i] = 2;
    }
    for(int i = 0; i < n; i++)
    {
        cout << ans[i] << "\n";
    }
}
