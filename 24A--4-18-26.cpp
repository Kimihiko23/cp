using namespace std;
const int N =3e3+23;
const int MOD = 1000020409;
set<int> g[N];
int cost[N][N];
int n;
vector<int> loop;
bool dd[N];
void dfs(int u)
{
    dd[u] = true;
    loop.pb(u);
    for(auto i : g[u])
    {
        if(!dd[i])
        {
            dfs(i);
        }
    }
}
void read()
{   
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        g[u].insert(v);
        g[v].insert(u);
        cost[u][v] = 0;
        cost[v][u] = w;
    }
}
void solve()
{
    dfs(1);
    int sum1 = 0;
    for(int i = 0; i < n - 1; i++)
    {
        sum1 += cost[loop[i]][loop[i + 1]];
    }
    sum1 += cost[loop[n - 1]][loop[0]];
    int sum2 = 0;
    for(int i = n - 1; i >= 1; i--)
    {
        sum2 += cost[loop[i]][loop[i - 1]];
    }
    sum2 += cost[loop[0]][loop[n - 1]];
    cout << min(sum1, sum2);
}   

