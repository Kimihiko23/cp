int n;
int d[N][N];
int k;
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            cin >> d[i][j];
        }
    }
    cin >> k;
}
void solve()
{
    int u, v, w;
    while(k--)
    {
        cin >> u >> v >> w;
        for(int i = 1; i <= n; i++)
        {
            for(int j = 1; j <= n; j++)
            {
                int road = d[i][u] + w + d[v][j];
                if(road < d[i][j])
                {
                    d[i][j] = road;
                    d[j][i] = road;
                }
                road = d[i][v] + w + d[u][j];
                if(road < d[i][j])
                {
                    d[i][j] = road;
                    d[j][i] = road;
                }
            }
        }
        int ans = 0;
        for(int i = 1; i <= n; i++)
        {
            for(int j = i + 1; j <= n; j++)
            {
                ans += d[i][j];
            }
        }
        cout << ans << "\n";
    }
    
}
