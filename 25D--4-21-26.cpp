#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
const int MOD = 1000020409;
int n;
int par[N];
int dem = 0;
vector<pair<int, int>> notused;
vector<pair<int, int>> ans;
int find(int u)
{
    if (par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    par[u] = v;
}
void read()
{   
    cin >> n;
    for(int i = 1; i <= n; i++) par[i] = i;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        int uu = u;
        int vv = v;
        u = find(u);
        v = find(v);
        if(u != v)
        {
            join(u, v);
            dem++;
        }
        else
        {
            notused.pb({uu, vv});
        }
    }
}
void solve()
{
    cout << notused.size() << "\n";
    for(int i = 1; i <= n; i++)
    {
        if(find(i) != find(1))
        {
            ans.pb({i, 1});
            join(i, 1);
        }
    }
    for(int i = 0; i < notused.size(); i++)
    {
        cout << notused[i].fi << " " << notused[i].se << " " << ans[i].fi << " " << ans[i].se << "\n";
    }
}   

