vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
vector<pair<int, int>> dir{{0, 0}, {0, 1}, {1, 1}, {1, 0}};
int n, m, a, b, c;
char ans[205][205];
bool used[27];

char getChar(const vector<pair<int, int>>& cells)
{
    bool mark[26] = {};

    for(auto [x, y] : cells)
    {
        for(int k = 0; k < 4; k++)
        {
            int nx = x + dx[k];
            int ny = y + dy[k];

            if(nx < 1 || nx > n || ny < 1 || ny > m)
                continue;

            if(ans[nx][ny] != '-')
            {
                mark[ans[nx][ny] - 'a'] = true;
            }
        }
    }

    for(char ch = 'a'; ch <= 'z'; ch++)
    {
        if(!mark[ch - 'a'])
            return ch;
    }

    return '?';
}

void placePlank(const vector<pair<int, int>>& cells)
{
    char ch = getChar(cells);

    if(ch == '?')
    {
        cout << "IMPOSSIBLE";
        exit(0);
    }

    for(auto [x, y] : cells)
        ans[x][y] = ch;
}

void read()
{
    cin >> n >> m >> a >> b >> c;

    if((n * m) % 2)
    {
        cout << "IMPOSSIBLE";
        exit(0);
    }

    for(int i = 0; i < 205; i++)
    {
        for(int j = 0; j < 205; j++)
        {
            ans[i][j] = '-';
        }
    }
}

void solve()
{
    if(n % 2 == 1)
    {
        int need = m / 2;

        if(a < need)
        {
            cout << "IMPOSSIBLE";
            exit(0);
        }

        for(int j = 1; j <= m; j += 2)
        {
            vector<pair<int, int>> cells = {
                {n, j},
                {n, j + 1}
            };

            placePlank(cells);
        }

        a -= need;
    }

    if(m % 2 == 1)
    {
        int need = n / 2;

        if(b < need)
        {
            cout << "IMPOSSIBLE";
            exit(0);
        }

        for(int i = 1; i <= n; i += 2)
        {
            vector<pair<int, int>> cells = {
                {i, m},
                {i + 1, m}
            };

            placePlank(cells);
        }

        b -= need;
    }

    for(int i = 1; i + 1 <= n; i += 2)
    {
        for(int j = 1; j + 1 <= m; j += 2)
        {
            if(c > 0)
            {
                vector<pair<int, int>> cells = {
                    {i, j},
                    {i, j + 1},
                    {i + 1, j},
                    {i + 1, j + 1}
                };

                placePlank(cells);
                c--;
            }
            else if(a >= 2)
            {
                vector<pair<int, int>> cells1 = {
                    {i, j},
                    {i, j + 1}
                };

                vector<pair<int, int>> cells2 = {
                    {i + 1, j},
                    {i + 1, j + 1}
                };

                placePlank(cells1);
                placePlank(cells2);

                a -= 2;
            }
            else if(b >= 2)
            {
                vector<pair<int, int>> cells1 = {
                    {i, j},
                    {i + 1, j}
                };

                vector<pair<int, int>> cells2 = {
                    {i, j + 1},
                    {i + 1, j + 1}
                };

                placePlank(cells1);
                placePlank(cells2);

                b -= 2;
            }
            else
            {
                cout << "IMPOSSIBLE";
                exit(0);
            }
        }
    }

    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(ans[i][j] == '-')
            {
                cout << "IMPOSSIBLE";
                return;
            }
        }
    }

    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cout << ans[i][j];
        }
        cout << '\n';
    }
}

