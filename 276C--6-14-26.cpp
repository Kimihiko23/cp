#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 2e5 + 23;
int n, q;
int p[N];
vector<int> in;
int change[N];
vector<pair<int, int>> tt, que;
int pre[N];
void read()
{
    cin >> n >> q;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        in.pb(x);
    }
    int l, r;
    for(int i = 1; i <= q; i++)
    {
        cin >> l >> r;
        change[l]++;
        change[r + 1]--;
        que.pb({l, r});
    }
    for(int i = 1; i <= n; i++)
    {
        p[i] += p[i - 1];
        p[i] += change[i];
        tt.pb({p[i], i});
    }
}
void solve()
{
    sort(tt.begin(), tt.end(), greater());
    sort(in.begin(), in.end(), greater());
    for(int i = 0; i < n; i++)
    {
        int vt = tt[i].se;
        pre[vt] = in[i];
    }
    for(int i = 1; i <= n; i++)
    {
        pre[i] += pre[i - 1];
    }
    int ans = 0;
    for(int i = 0; i < q; i++)
    {
        int l = que[i].fi;
        int r = que[i].se;
        ans += pre[r] - pre[l - 1];
    }
    cout << ans;
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt","r")) 
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }
    // freopen(name ".inp", "r", stdin);
    // freopen(name ".out", "w", stdout);
    read();
    solve();
} 
