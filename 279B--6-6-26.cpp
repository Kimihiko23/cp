#define name "input"
const int MOD = 1000020409;
const int N = 1e5 + 23;
int n, k;
int a[N], pre[N];
void read()
{
    cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        if(a[i] <= k)
        {
            int l = i, r = n, res = i;
            while(l <= r)
            {
                int mid = (l + r) / 2;
                if(pre[mid] - pre[i - 1] <= k)
                {
                    res = mid;
                    l = mid + 1;
                }
                else
                    r = mid - 1;
            }
            ans = max(ans, res - i + 1);
        }
    }
    cout << ans << "\n";
}
