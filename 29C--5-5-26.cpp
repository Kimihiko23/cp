using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N =1e5+23;
int n;
vector<int> g[N];
bool dd[N];
set<int> s;
map<int, int> mp;
map<int, int> mp2;
vector<pair<int, int>> a;
void bfs(int st)
{
    queue<int> q;
    q.push(st);
    dd[st] = true;
    while(!q.empty())
    {
        int u = q.front();
        cout << mp2[u] << " ";
        q.pop();
        for(int v : g[u])
        {
            if(!dd[v])
            {
                dd[v] = true;
                q.push(v);
            }
        }
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        int u, v;
        cin >> u >> v;
        s.insert(u);
        s.insert(v);
        // g[u].pb(v);
        // g[v].pb(u);
        a.pb({u, v});
    }
}
void solve()
{
    int dem = 1;
    for(auto x : s)
    {
        mp2[dem] = x;
        mp[x] = dem++;
    }
    for(auto x : a)
    {
        g[mp[x.fi]].pb(mp[x.se]);
        g[mp[x.se]].pb(mp[x.fi]);
    }
    for(int i = 1; i < dem; i++)
    {
        if(g[i].size() == 1)
        {
            bfs(i);
            break;
        }
    }
}
