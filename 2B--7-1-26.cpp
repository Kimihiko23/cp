#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"

const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1005;
const int INF = 1e18;
const int NINF = -1e18;

mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r)
{
    return uniform_int_distribution<int>(l, r)(rng);
}

int n;
int c2[N][N], c5[N][N];
int dp2[N][N], dp5[N][N];
char tr2[N][N], tr5[N][N];

bool dd = false;
int zx, zy;

int cnt(int x, int p)
{
    if (x == 0) return 1;
    int res = 0;
    while (x % p == 0)
    {
        res++;
        x /= p;
    }
    return res;
}

void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= n; j++)
        {
            int x;
            cin >> x;
            if (x == 0)
            {
                dd = true;
                zx = i;
                zy = j;
                c2[i][j] = c5[i][j] = 1;
            }
            else
            {
                c2[i][j] = cnt(x, 2);
                c5[i][j] = cnt(x, 5);
            }
        }
}

void solve()
{
    for (int i = 0; i <= n; i++)
        for (int j = 0; j <= n; j++)
            dp2[i][j] = dp5[i][j] = INF;

    dp2[1][1] = c2[1][1];
    dp5[1][1] = c5[1][1];

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (i == 1 && j == 1) continue;

            if (i > 1 && dp2[i - 1][j] + c2[i][j] < dp2[i][j])
            {
                dp2[i][j] = dp2[i - 1][j] + c2[i][j];
                tr2[i][j] = 'D';
            }
            if (j > 1 && dp2[i][j - 1] + c2[i][j] < dp2[i][j])
            {
                dp2[i][j] = dp2[i][j - 1] + c2[i][j];
                tr2[i][j] = 'R';
            }

            if (i > 1 && dp5[i - 1][j] + c5[i][j] < dp5[i][j])
            {
                dp5[i][j] = dp5[i - 1][j] + c5[i][j];
                tr5[i][j] = 'D';
            }
            if (j > 1 && dp5[i][j - 1] + c5[i][j] < dp5[i][j])
            {
                dp5[i][j] = dp5[i][j - 1] + c5[i][j];
                tr5[i][j] = 'R';
            }
        }
    }

    int ans = min(dp2[n][n], dp5[n][n]);

    if (dd && ans > 1)
    {
        cout << 1 << '\n';

        for (int i = 1; i < zx; i++) cout << 'D';
        for (int i = 1; i < zy; i++) cout << 'R';
        for (int i = zx; i < n; i++) cout << 'D';
        for (int i = zy; i < n; i++) cout << 'R';
        cout << '\n';
        return;
    }

    cout << ans << '\n';

    string path;

    if (dp2[n][n] < dp5[n][n])
    {
        int x = n, y = n;
        while (x != 1 || y != 1)
        {
            if (tr2[x][y] == 'D')
            {
                path.pb('D');
                x--;
            }
            else
            {
                path.pb('R');
                y--;
            }
        }
    }
    else
    {
        int x = n, y = n;
        while (x != 1 || y != 1)
        {
            if (tr5[x][y] == 'D')
            {
                path.pb('D');
                x--;
            }
            else
            {
                path.pb('R');
                y--;
            }
        }
    }

    reverse(path.begin(), path.end());
    cout << path << '\n';
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    if (fopen("input.txt","r"))
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }

    read();
    solve();
}