void solve()
{
    int ans = 0;
    int mx = -1e18;
    int mn = 1e18;
    while(!s1.empty())
    {
        ans++;
        pair<int, int> mnn = *s1.begin();
        pair<int, int> mxx = *s1.rbegin();
        int low = min(mnn.second, mxx.second);
        int high = max(mnn.second, mxx.second);

        auto it_start = s2.lower_bound({low, -1e18});
        auto it_end = s2.upper_bound({high, 1e18});

        for (auto it = it_start; it != it_end; )
        {
            pair<int, int> tam = *it;
            s1.erase({tam.se, tam.fi}); 
            it = s2.erase(it);
        }
    }
    cout << ans;
    // cout << ans;
}
