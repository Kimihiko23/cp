struct fen
{
    int n;
    vector<int> bit;

    fen(int _n)
    {
        n = _n;
        bit.assign(n + 23, 0);
    }

    void upd(int i, int val)
    {
        for (; i <= n; i += i & -i) bit[i] += val;
    }

    int get(int i)
    {
        int res = 0;
        for (; i > 0; i -= i & -i) res += bit[i];
        return res;
    }

    int get(int l, int r)
    {
        if (l > r) return 0;
        return get(r) - get(l - 1);
    }
};

int n, l, r;
vector<int> a;
vector<int> pref, comp, id;

void read()
{
    cin >> n >> l >> r;

    a.resize(n + 1);
    int sum = 0;

    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        sum += a[i];
    }
    for (int i = 1; i <= n; i++) 
        a.pb(a[i]);

    pref.assign(2 * n + 1, 0);

    for (int i = 1; i <= 2 * n; i++)
    {
        pref[i] = pref[i - 1] + a[i];
        comp.pb(pref[i]);
    }

    sort(comp.begin(), comp.end());
    comp.erase(unique(comp.begin(), comp.end()), comp.end());

    id.resize(2 * n + 1);

    for (int i = 1; i <= 2 * n; i++)
        id[i] = lower_bound(comp.begin(), comp.end(), pref[i]) - comp.begin() + 1;
}

void solve()
{
    int sum = pref[n];

    fen L(2 * n), R(2 * n);

    L.upd(id[1], 1);

    int cur = 0;

    for (int i = 2; i < 2 * n; i++)
    {
        if (i > n)
        {
            if (i - n > 1)
                R.upd(id[i - n], -1);
            int l1 = lower_bound(comp.begin(), comp.end(),
                                 pref[i - n] - r + sum) - comp.begin() + 1;
            int r1 = upper_bound(comp.begin(), comp.end(),
                                 pref[i - n] - l + sum) - comp.begin();
            cur -= R.get(l1, r1);

            L.upd(id[i - n], -1);
        }
        int l2 = lower_bound(comp.begin(), comp.end(),
                             l - sum + pref[i]) - comp.begin() + 1;
        int r2 = upper_bound(comp.begin(), comp.end(),
                             r - sum + pref[i]) - comp.begin();
        cur += L.get(l2, r2);
        L.upd(id[i], 1);
        R.upd(id[i], 1);

        if (i >= n) cout << cur << ' ';
    }
}

