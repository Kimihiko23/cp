int dis[N];
void dijkstra()
{
    priority_queue<pair<int,int>, vector<pair<int,int>>, greater<pair<int,int>>> pq;

    for(int i : dg)
    {
        dis[i] = 0;
        pq.push({0, i});
    }

    while(!pq.empty())
    {
        auto [du, u] = pq.top();
        pq.pop();
        for(auto [w, v] : g[u])
        {
            if(dis[v] > dis[u] + w)
            {
                dis[v] = dis[u] + w;
                pq.push({dis[v], v});
            }
        }
    }
}
void dfs(int u)
{
    dd[u] = true;
    for(auto i : g[u])
    {
        int v = i.se;
        if(!dd[v])
        {
            h[v] = h[u] + 1;
            dp[0][v] = u;
            mn[0][v] = min(dis[u], dis[v]);
            dfs(v);
        }
    }
}
void init()
{
    for(int i = 1; i <= log2(n); i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[i][j] = dp[i - 1][dp[i - 1][j]];
            mn[i][j] = min(mn[i - 1][j], mn[i - 1][dp[i - 1][j]]);
        }
    }
}
int find(int x)
{
    if(par[x] == x) return x;
    return par[x] = find(par[x]);
}
void join(int x, int y)
{
    // int xx = x;
    // int yy = y;
    x = find(x);
    y = find(y);
    if(x == y)
        return;
    if(sz[x] > sz[y])
        swap(x, y);
    par[x] = y;
    sz[y] +=sz[x];

}
int lca(int u, int v)
{
    int ans = 1e18;
    if(h[u] < h[v])
        swap(u, v);
    ans = min(dis[u], dis[v]);
    for(int i = log2(n); i >= 0; i--)
    {
        if(h[dp[i][u]] >= h[v])
        {
            ans = min(ans, mn[i][u]);
            u = dp[i][u];
        }
    }
    
    if(u == v)
        return ans;
    for(int i = log2(n); i >= 0; i--)
    {
        if(dp[i][u] != dp[i][v])
        {
            ans = min(ans, mn[i][u]);
            ans = min(ans, mn[i][v]);
            u = dp[i][u];
            v = dp[i][v];
        }
    }
    // ans = min(ans, dis[dp[0][u]]);
    ans = min(ans, mn[0][v]);
    ans = min(ans, mn[0][u]);
    return ans;
}
