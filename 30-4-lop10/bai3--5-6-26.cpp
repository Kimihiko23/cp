void solve()
{
    for (int i = 0; i < log2(n); i++) 
        mn[i][0] = 1e18;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
        dis[i] = 1e18;
    }
    for(auto i : dg)
    {
        dis[i] = 0;
    }
    sort(edg.begin(), edg.end(), greater());
    int ans = 0;
    for(auto i : edg)
    {
        int u = i.se.fi;
        int v = i.se.se;
        if(find(u) != find(v))
        {
            join(u, v);
            g[u].pb({i.fi, v});
            g[v].pb({i.fi, u});
            // g[u].pb({w, v})
            ans += i.fi;
        }
    }
    dijkstra();
    dfs(1);
    init();
    int q;
    cin >> q;
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        cout << lca(u, v) << "\n";
    }
}
