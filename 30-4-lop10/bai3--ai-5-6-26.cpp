const int MOD = 1000020409;
const int N =1e5+23;
const int LOG = 20;

int dp[LOG][N];
int mn[LOG][N];
int par[N];
int h[N];
int sz[N];
bool dd[N];

int n, m, k;

vector<pair<int ,int>> adj[N];
vector<int> g[N];
vector<pair<int,int>> edg;

vector<int> dg;

int dis[N];

int find(int x)
{
    if(par[x] == x) return x;
    return par[x] = find(par[x]);
}

void join(int x, int y)
{
    x = find(x);
    y = find(y);
    if(x == y)
        return;
    if(sz[x] > sz[y])
        swap(x, y);
    par[x] = y;
    sz[y] += sz[x];
}

void dijkstra()
{
    priority_queue<pair<int,int>, vector<pair<int,int>>, greater<pair<int,int>>> pq;

    for(int i = 1; i <= n; i++)
        dis[i] = 1e18;

    for(int i : dg)
    {
        dis[i] = 0;
        pq.push({0, i});
    }

    while(!pq.empty())
    {
        auto [du, u] = pq.top();
        pq.pop();

        if(du != dis[u]) continue;

        for(auto [v, w] : adj[u])
        {
            if(dis[v] > dis[u] + w)
            {
                dis[v] = dis[u] + w;
                pq.push({dis[v], v});
            }
        }
    }
}

void dfs(int u, int p)
{
    for(int v : g[u])
    {
        if(v == p) continue;

        h[v] = h[u] + 1;
        dp[0][v] = u;
        mn[0][v] = min(dis[u], dis[v]);

        for(int i = 1; i < LOG; i++)
        {
            dp[i][v] = dp[i-1][dp[i-1][v]];
            mn[i][v] = min(mn[i-1][v], mn[i-1][dp[i-1][v]]);
        }

        dfs(v, u);
    }
}

int lca(int u, int v)
{
    int ans = min(dis[u], dis[v]);

    if(h[u] < h[v])
        swap(u, v);

    int diff = h[u] - h[v];

    for(int i = 0; i < LOG; i++)
    {
        if(diff >> i & 1)
        {
            ans = min(ans, mn[i][u]);
            u = dp[i][u];
        }
    }

    if(u == v)
        return ans;

    for(int i = LOG - 1; i >= 0; i--)
    {
        if(dp[i][u] != dp[i][v])
        {
            ans = min(ans, mn[i][u]);
            ans = min(ans, mn[i][v]);
            u = dp[i][u];
            v = dp[i][v];
        }
    }

    ans = min(ans, mn[0][u]);
    ans = min(ans, mn[0][v]);

    return ans;
}

