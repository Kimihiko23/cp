const int N = 2e5 + 23;
int n, q;
int st[N * 4];
int a[N];
int deep = 0;
void build(int id, int l, int r, int de)
{
    deep = max(deep, de);
    if(l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid, de + 1);
    build(id * 2 + 1, mid + 1, r, de + 1);
    int where = deep - de;
    if(where % 2 == 1)
    {
        st[id] = st[id * 2] | st[id * 2 + 1];
    }
    else
    {
        st[id] = st[id * 2] ^ st[id * 2 + 1];
    }
}
void update(int id, int l, int r, int de, int pos, int val)
{
    if(l > pos || r < pos)
    {
        return;
    }
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, de + 1, pos, val);
    update(id * 2 + 1, mid + 1, r, de + 1, pos, val);
    int where = deep - de;
    if(where % 2 == 1)
    {
        st[id] = st[id * 2] | st[id * 2 + 1];
    }
    else
    {
        st[id] = st[id * 2] ^ st[id * 2 + 1];
    }
}
void read()
{
    cin >> n >> q;
    n = 1 << n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    
}
void solve()
{
    int pos, val;
    build(1, 1, n, 0);
    while(q--)
    {
        cin >> pos >> val;
        update(1, 1, n, 0, pos, val);
        cout << st[1] << "\n";
    }
}
