const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<int> g[N];
vector<int> st;
int n, m;
int par[N][30];
int dep[N];
int dis[N];
void init()
{
    for(int j = 1; j < 30; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
void dfs(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p) continue;
        par[v][0] = u;
        dep[v] = dep[u] + 1;
        dfs(v, u);
    }
}
void bfs()
{
    for(int i = 1; i <= n; i++) dis[i] = INF;
    queue<int> q;
    for(auto u : st)
    {
        dis[u] = 0;
        q.push(u);
    }
    while(!q.empty())
    {
        int u = q.front();
        q.pop();
        for(auto v : g[u])
        {
            if(dis[v] > dis[u] + 1)
            {
                dis[v] = dis[u] + 1;
                q.push(v);
            }
        }
    }
}
int cal(int u, int v)
{
    if(dep[u] < dep[v]) swap(u, v);
    int res = 0;
    int dif = dep[u] - dep[v];
    int mxn = log2(n);
    while(dif > 0)
    {
        for(int i = mxn; i >= 0; i--)
        {
            if((1 << i) <= dif)
            {
                dif -= (1 << i);
                u = par[u][i];
                res += (1 << i);
            }
        }
    }
    if(u == v) return res;
    for(int i = mxn; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
            res += (1 << (i + 1));
        }
    }
    return res + 2;
}
void read()
{
    cin >> n >> m;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0);
    init();
    int ty, u;
    int tam = sqrt(m);
    vector<int> nx;
    st.pb(1);
    for(int i = 1; i <= m; i++)
    {
        if(i % tam == 0 || i == m || i == 1)
        {
            for(auto u : nx) st.pb(u);
            nx.clear();
            bfs();
        }
        cin >> ty >> u;
        if(ty == 1)
        {
            nx.pb(u);
        }
        else
        {
            int ans = dis[u];
            for(auto v : nx)
            {
                ans = min(ans, cal(u, v));
            }
            cout << ans << "\n";
        }
    }
}
