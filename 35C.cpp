const int MOD = 1000020409;
const int N =2e3+23;
int dis[N][N];
int n, m, k;
int ansx = 1, ansy = 1, ans = 0;
queue<pair<int, int>> q;
bool check(int x, int y)
{
    return(x >= 1 && x <= n && y >= 1 && y <= m);
}
void bfs()
{
    vector<int> dx{0, 0, -1, 1};
    vector<int> dy{1, -1, 0, 0};
    while(!q.empty())
    {
        int ux = q.front().fi;
        int uy = q.front().se;
        q.pop();
        for(int i = 0; i < 4; i++)
        {
            int xx = ux + dx[i];
            int yy = uy + dy[i];
            if(check(xx, yy) && dis[xx][yy] > dis[ux][uy] + 1)
            {
                q.push({xx, yy});
                dis[xx][yy] = dis[ux][uy] + 1;

            }
        }
    }
}
