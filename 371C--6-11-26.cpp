#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;

const int N = 1e5 + 23;
int b, s, c;
string re;
int B, S, C;
int P1, P2, P3;
int w;

void read()
{
    cin >> re
    >> B >> S >> C 
    >> P1 >> P2 >> P3
    >> w;
}
bool check(int x)
{
    int needB = max(0LL, x * b - B);
    int needS = max(0LL, x * s - S);
    int needC = max(0LL, x * c - C);

    int cost =
        needB * P1 +
        needS * P2 +
        needC * P3;

    return cost <= w;
}

void solve()
{
    for(auto i : re)
    {
        if(i == 'B') b++;
        else if(i == 'S') s++;
        else c++;
    }

    int l = 0;
    int r = 1e13;
    int ans = 0;

    while(l <= r)
    {
        int mid = (l + r) / 2;

        if(check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
            r = mid - 1;
    }

    cout << ans;
}
