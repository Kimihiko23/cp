struct node
{
    int op, cl, sum;
};
char a[N];
node st[N * 4];
int n;
string s;
void build(int id, int l, int r)
{
    if(l == r)
    {
        if(s[l] == '(')
        {
            st[id].op = 1;
            st[id].cl = 0;
            st[id].sum = 0;
        }
        else
        {
            st[id].op = 0;
            st[id].cl = 1;
            st[id].sum = 0;
        }
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    int tmp = min(st[id * 2].op, st[id * 2 + 1].cl);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum + tmp;
    st[id].op = st[id * 2].op + st[id * 2 + 1].op - tmp;
    st[id].cl = st[id * 2].cl + st[id * 2 + 1].cl - tmp;
}
node get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return {0, 0, 0};
    if(l >= u && r <= v) return st[id];
    int mid = (l + r) / 2;
    node left = get(id * 2, l, mid, u, v);
    node right = get(id * 2 + 1, mid + 1, r, u, v);
    node result;
    int tmp = min(left.op, right.cl);
    result.sum = left.sum + right.sum + tmp;
    result.op = left.op + right.op - tmp;
    result.cl = left.cl + right.cl - tmp;
    return result;
}
void read()
{
    cin >> s;
    n = s.size();
    s = " " + s;
}
void solve()
{
    build(1, 1, n);
    int q;
    cin >> q;
    while(q--)
    {
        int l, r;
        cin >> l >> r;
        cout << get(1, 1, n, l, r).sum * 2 << "\n";
    }
}
