const int N =1e6+23;
const int MOD = 1000020407;
int n, k;
vector<pair<int, int>> a[3];
int pre[3][N];
void read()
{   
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        int id, w;
        cin >> id >> w;
        a[id].pb({w, i});
    }
}
void solve()
{
    int sl1 = a[1].size();
    sort(a[1].begin(), a[1].end(), greater());
    sort(a[2].begin(), a[2].end(), greater());
    int ans = 0, vtans = 0;
    for(int i = 0; i < a[2].size(); i++)
    {
        pre[2][i + 1] = pre[2][i] + a[2][i].fi; 
    }
    for(int i = 0; i < a[1].size(); i++)
    {
        pre[1][i + 1] = pre[1][i] + a[1][i].fi; 
    }
    for(int i = 1; i <= a[2].size(); i++)
    {
        int res = k - i * 2;
        if(res >= 0)
        {
            int sum = pre[2][i] + pre[1][min(res, (int)a[1].size())];
            // cout << sum << "\n";
            if(sum > ans)
            {
                ans = sum;
                vtans = i;
            }
        }
    }
    for(int i = 1; i <= a[1].size(); i++)
    {
        int res = (k - i) / 2;
        if(res >= 0)
        {
            int sum = pre[1][i] + pre[2][min(res, (int)a[2].size())];
            // cout << sum << "\n";
            if(sum > ans)
            {
                ans = sum;
                vtans = res;
            }
        }
    }
    cout << ans << "\n";
    // if(ans == 0)
    // {
    //     exit(0);
    // }
    for(int i = 0; i < vtans; i++)
    {
        cout << a[2][i].se << " ";
    }
    for(int i = 0; i < min(k - vtans * 2, (int)a[1].size()); i++)
    {
        cout << a[1][i].se << " ";
    }
}   

