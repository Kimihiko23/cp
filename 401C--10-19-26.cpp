void solve()
{
    if(n >= m)
    {
        for(int i = 1; i <= n + m; i++)
        {
            if(i % 2 == 1)
            {
                cout << 0;
            }
            else
            {
                cout << 1;
            }
        }
    }
    else
    {
        int need = n + 1;
        int left = m - need;
        m -= left;
        for(int i = 1; i <= n + m; i++)
        {
            if(i % 2 == 1)
            {
                cout << 1;
            }
            else
            {
                if(left > 0)
                {
                    cout << 1;
                    left--;
                }
                cout << 0;
            }
        }
        while(left > 0)
        {
            cout << 1;
            left--;
        }
    }
}
