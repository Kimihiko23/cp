const int N = 2e3 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, k;
int dp[N][N];
vector<int> g[N];
void read()
{
    cin >> n >> k;
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = i; j <= n; j += i)
        {
            g[j].pb(i);
        }
    }
    for(int i = 1; i <= n; i++)
    {
        dp[i][1] = 1;
        // cout << g[i].size() << "\n";
    }
    for(int i = 2; i <= k; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            for(auto z : g[j])
            {
                dp[j][i] += dp[z][i - 1];
                dp[j][i] %= MOD;
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        ans += dp[i][k];
    }
    cout << ans % MOD;
}
