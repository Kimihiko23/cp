const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
const int INF = 0x3f3f3f3f3f3f3f3f;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m;
int a[N];
vector<pair<int, int>> g[N];
vector<int> mem[N];
int ndfs[N], low[N];
int nen[N];
int timer = 0;
stack<int> st;
int scc = 0;
int out[N];
void dfs(int u, int p)
{
    st.push(u);
    ndfs[u] = low[u] = ++timer;
    for(auto edge : g[u])
    {
        int v = edge.fi;
        int id = edge.se;
        if(id == p || out[v])
        {
            continue;
        }
        if(ndfs[v])
        {
            low[u] = min(low[u], ndfs[v]);
        }
        else
        {
            dfs(v, id);
            low[u] = min(low[u], low[v]);
        }
    }
    if(ndfs[u] == low[u])
    {
        scc++;
        while(st.top() != u)
        {
            int v = st.top();
            st.pop();
            nen[v] = scc;
            mem[scc].pb(v);
            out[v] = 1;
        }
        int v = st.top();
        st.pop();
        nen[v] = scc;
        mem[scc].pb(v);
        out[v] = 1;
    }
}
