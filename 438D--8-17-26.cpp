mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, q;
pair<int, int> st[N * 4];
int a[N];
pair<int, int> merg(pair<int, int> l, pair<int, int> r)
{
    return {max(l.fi, r.fi), l.se + r.se};
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].fi = a[l];
        st[id].se = a[r];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = merg(st[id * 2], st[id * 2 + 1]);
}
void update1(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u || st[id].fi < val)
        return;
    if(l == r)
    {
        st[id].fi %= val;
        st[id].se %= val;
        return;
    }
    int mid = (l + r) / 2;
    update1(l, mid, id * 2, u, v, val);
    update1(mid + 1, r, id * 2 + 1, u ,v, val);
    st[id] = merg(st[id * 2], st[id * 2 + 1]);
}
void update2(int l, int r, int id, int vt, int val)
{
    if(l > vt || r < vt)
        return;
    if(l == r)
    {
        st[id].fi = val;
        st[id].se = val;
        return;
    }
    int mid = (l + r) / 2;
    update2(l, mid, id * 2, vt, val);
    update2(mid + 1, r, id * 2 + 1, vt, val);
    st[id] = merg(st[id * 2], st[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
    {
        return st[id].se;
    }
    int mid = (l + r) / 2;
    return get(l, mid, id * 2, u, v) + get(mid + 1, r, id * 2 + 1, u, v);
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    build(1, n, 1);
    while(q--)
    {
        int ty, l, r, val;
        cin >> ty >> l >> r;
        if(ty == 1)
        {
            cout << get(1, n, 1, l, r) << "\n";
        }
        else
        if(ty == 2)
        {
            cin >> val;
            update1(1, n, 1, l, r, val);
        }
        else
        {
            update2(1, n, 1, l, r);
        }
    }
}
