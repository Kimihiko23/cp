int n, m, k;
bool check(int x)
{
    int cnt = 0;
    for(int i = 1; i <= n; i++)
    {
        cnt += min(m, x/i);
    }
    return cnt >= k;
}
void read()
{
    cin >> n >> m >> k;
}
void solve()
{
    int ans = 1;
    int l = 1, r = 1e18;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {   
            ans = mid;
            r = mid - 1;
        }
        else
        l = mid + 1;
    }
    cout << ans;
}
