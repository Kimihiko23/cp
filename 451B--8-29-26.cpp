void solve()
{
    // sort(a + 1, a + )
    int st = -1, ed = -1;
    for(int i = 1; i <= n - 1; i++)
    {
        if(a[i] > a[i + 1])
        {
            st = i;
            break;
        }
    }
    for(int i = n; i > 1; i--)
    {
        if(a[i] < a[i - 1])
        {
            ed = i;
            break;
        }
    }
    if(st == -1 && ed == -1)
    {
        cout << "yes\n1 1";
        exit(0);
    }
    int st1 = st;
    int ed1 = ed;
    while(st1 <= ed1)
    {
        swap(a[st1], a[ed1]);
        st1++;
        ed1--;
    }
    for(int i = 1; i < n; i++)
    {
        // cout << a[i] << "\n";
        if(a[i] > a[i + 1])
        {
            cout << "no\n";
            exit(0);
        }
    }
    cout << "yes\n";
    cout << st << " " << ed;



}
