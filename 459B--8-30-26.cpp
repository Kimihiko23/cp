int mn = 1e18;
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mx = max(mx, a[i]);
        mn = min(mn, a[i]);
    }
}
void solve()
{
    int ans = 0;
    int dif = mx - mn;
    // if(dif == 0)
    // {
    //     cout << dif << " " << n/2;
    //     exit(0);
    // }
    // cout << dif << "\n";
    for(int i = 1; i <= n; i++)
    {
        if(a[i] - dif >= 0)
        {
            ans += mp[a[i] - dif];
            // ans += mp[a[i] + dif];
        }
        if(dif != 0)
            ans += mp[a[i] + dif];
        mp[a[i]]++;
    }
    cout << dif << " " << ans;
}
