int pre[N];
void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
}
void solve()
{
    if(pre[n] % 3 != 0)
    {
        cout << 0;
        return;
    }
    int tar = pre[n] / 3;
    int cnt = 0;
    for(int i = 1; i <= n - 1; i++)
    {
        if(pre[i] == 2 * tar)
        {
            ans += cnt;
        }
        if(pre[i] == tar)
        {
            cnt++;
        }
    }
    cout << ans;
}
