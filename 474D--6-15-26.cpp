void solve()
{
    pre[0] = 1;
    for(int i = 1; i < k; i++)
    {
        dp[i] = 1;
        dp[i] %= MOD;
        pre[i] = pre[i - 1] + dp[i];
        pre[i] %= MOD;
    }
    dp[0] = 1;
    for(int i = k; i < N; i++)
    {
        dp[i] = dp[i - 1] + dp[i - k];
        dp[i] %= MOD;
        pre[i] = pre[i - 1] + dp[i];
        pre[i] %= MOD;
    }
    int l, r;
    // cout << dp[3];
    for(int i = 1; i <= n; i++)
    {
        cin >> l >> r;
        cout << (pre[r] - pre[l - 1] + MOD) % MOD << "\n";
    }
}
