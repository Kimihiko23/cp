string s1, s2;
int target;
int correct;

void read()
{
    cin >> s1 >> s2;
}

void dfs(int pos, int cur)
{
    if (pos == s2.size())
    {
        if (cur == target)
            correct++;
        return;
    }

    if (s2[pos] == '+')
    {
        dfs(pos + 1, cur + 1);
    }
    else if (s2[pos] == '-')
    {
        dfs(pos + 1, cur - 1);
    }
    else
    {
        dfs(pos + 1, cur + 1);
        dfs(pos + 1, cur - 1);
    }
}

void solve()
{
    for (char c : s1)
    {
        if (c == '+')
            target++;
        else
            target--;
    }
    dfs(0, 0);
    int question = 0;
    for (char c : s2)
    {
        if (c == '?')
            question++;
    }

    
    double total = pow(2.0, question);

    double ans = correct / total;

    cout << fixed << setprecision(12) << ans << '\n';
}

