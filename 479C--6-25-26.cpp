void solve()
{
    sort(a.begin(), a.end());
    int ans = a[0].second;
    for(int i = 1; i < n; i++)
    {
        if(a[i].se < ans)
        {
            ans = a[i].fi;
        }
        else
        {
            ans = a[i].se;
        }
    }
    cout << ans << "\n";
}
