void update(int l, int r, int id, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(l, mid, id * 2, pos, val);
    update(mid + 1, r, id * 2 + 1, pos, val);
    st[id] = min(st[id * 2], st[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return 1e18;
    if(l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    return min(get(l, mid, id * 2, u, v), get(mid + 1, r, id * 2 + 1, u, v));
}
stack<int> sta;
vector<int> bcc[N];
bool cut[N];
int cnt;
void tarjan(int u, int pe)
{
    ndfs[u] = low[u] = ++ttarj;
    int child = 0;

    for (auto [v, id] : g[u])
    {
        if (id == pe) continue;

        if (!ndfs[v])
        {
            child++;
            sta.push(id);
            tarjan(v, id);
            low[u] = min(low[u], low[v]);
            //get bcc:?
            if (low[v] >= ndfs[u])
            {
                if (pe != 0 || child > 1)
                    cut[u] = 1;

                cnt++;
                while (1)
                {
                    int e = sta.top();
                    sta.pop();

                    int x = edg[e].fi;
                    int y = edg[e].se;
                    bcc[cnt].pb(x);
                    bcc[cnt].pb(y);

                    if (e == id) break;
                }
            }
        }
        else if (ndfs[v] < ndfs[u])
        {
            sta.push(id);
            low[u] = min(low[u], ndfs[v]);
        }
    }
}

int par[N];
void dfs1(int u, int p)
{
    par[u] = p;
    dep[u] = dep[p] + 1;
    sz[u] = 1;

    for (auto v : tree[u])
    {
        if (v == p) continue;

        dfs1(v, u);
        sz[u] += sz[v];

        if (sz[v] > sz[heavy[u]])
            heavy[u] = v;
    }
}

void dfs2(int u, int h)
{
    head[u] = h;
    pos[u] = ++cur;

    if (heavy[u])
        dfs2(heavy[u], h);

    for (auto v : tree[u])
    {
        if (v == par[u] || v == heavy[u])
            continue;

        dfs2(v, v);
    }
}

int query_path(int u, int v)
{
    int ans = INF;

    while (head[u] != head[v])
    {
        if (dep[head[u]] < dep[head[v]])
            swap(u, v);

        ans = min(ans, get(1, tot, 1, pos[head[u]], pos[u]));
        u = par[head[u]];
    }

    if (dep[u] > dep[v])
        swap(u, v);

    ans = min(ans, get(1, tot, 1, pos[u], pos[v]));
    return ans;
}


void build_tree()
{
    tot = cnt;

    for (int u = 1; u <= n; u++)
    {
        if (cut[u])
        {
            mp[u] = ++tot;
            who[tot] = u;
        }
    }

    for (int i = 1; i <= cnt; i++)
    {
        for (auto u : bcc[i])
        {
            if (cut[u])
            {
                tree[i].pb(mp[u]);
                tree[mp[u]].pb(i);
            }
            else
                mp[u] = i;
        }
    }
}

void init()
{
    dfs1(1, 0);
    dfs2(1, 1);

    for (int i = 1; i <= cnt; i++)
    {
        for (auto u : bcc[i])
        {
            if (cut[u] && par[i] == mp[u])
                continue;

            s[i].insert(w[u]);
        }

        val[i] = *s[i].begin();
    }

    for (int u = 1; u <= n; u++)
        if (cut[u])
            val[mp[u]] = w[u];

    for (int u = 1; u <= tot; u++)
        update(1, tot, 1, pos[u], val[u]);
}

int lca(int u, int v)
{
    while (head[u] != head[v])
    {
        if (dep[head[u]] < dep[head[v]])
            swap(u, v);

        u = par[head[u]];
    }

    return dep[u] < dep[v] ? u : v;
}

