vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int llm[N], rlm[N];
//llm = left limit, rlm right limit
pair<int, int> stmnmx[N * 4];
int st[N * 4];
int dp[N];
int a[N], n, s, l;
void build(int l, int r, int id)
{
    if(l == r)
    {
        stmnmx[id ]= {a[l], a[r]};
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    auto le = stmnmx[id * 2];
    auto ri = stmnmx[id * 2 + 1];
    stmnmx[id] = {min(le.fi, ri.fi), max(le.se, ri.se)};
}
pair<int, int> get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return {1e18, -1e18};
    if(l >= u && r <= v)
        return stmnmx[id];
    int mid = (l + r) / 2;
    auto le = get(l, mid, id * 2, u, v);
    auto ri = get(mid + 1, r, id * 2 + 1, u, v);
    return {min(le.fi, ri.fi), max(le.se, ri.se)};
}
void update(int l, int r, int id, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(l, mid, id * 2, pos, val);
    update(mid + 1, r, id * 2 + 1, pos, val);
    st[id] = min(st[id * 2], st[id * 2 + 1]);
}
int getdp(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return 1e18;
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return min(getdp(l, mid, id * 2, u, v), getdp(mid + 1, r, id * 2 + 1, u, v));
}
void read()
{
    cin >> n >> s >> l;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        llm[i] = 1;
        rlm[i] = n;
        dp[i] = 1e18;
        update(0, n, 1, i, 1e18);
    }
}
void solve()
{
    build(1, n, 1);
    int j = n;
    for(int i = n; i >= 1; i--)
    {
        while(j >= 1)
        {
            auto tam = get(1, n, 1, j, i);
            if(tam.se - tam.fi <= s)
            {
                j--;
            }
            else
            break;
        }
        llm[i] = max(llm[i], j + 1);
        rlm[i] = min(rlm[i], i - l + 1);
    }
    dp[0] = 0;
    update(0, n, 1, 0, 0);
    for(int i = 1; i <= n; i++)
    {
        if(rlm[i] - llm[i] + 1 <= 0)
        {
            continue;
        }
        auto tam = getdp(0, n, 1, llm[i] - 1, rlm[i] - 1);
        if(tam == 1e18)
            continue;
        dp[i] = tam + 1;
        update(0, n, 1, i, tam + 1);
    }
    if(dp[n] < 1e18)
    cout << dp[n];
    else
        cout << -1;

}
