void solve()
{
    if((s == 0 && m != 1) || 9 * m < s)
    {
        cout << "-1 -1";
        return;
    }
    int limit = min((int)9, s);
    vector<int> num;
    int tam = s;
    while(tam != 0)
    {
        num.pb(limit);
        tam -= limit;
        limit = min(limit, tam);
    }
    while(num.size() < m)
    {
        num.pb(0);
    }
    sort(num.begin(), num.end(), greater());
    int mn = 1e18;
    string ans1, ans2;
    for(auto i : num)
    {
        ans2 += to_string(i);
    }
    if(s >= 1)
    {
        ans1 += to_string(1);
        s--;
    }
    while(ans1.size() != m)
    {
        ans1 += '0';
    }
    limit = 9;
    // cout << s;
    for(int i = m - 1; i >= 0; i--)
    {
        limit = min(limit, s);
        int change = abs(ans1[i] - '0' - limit);
        ans1[i] += limit;
        s -= change;
    }
    cout << ans1 << " " << ans2;

    
}
