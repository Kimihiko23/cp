using namespace std;
const int N =1e5+23;
const int MOD = 1000020409;
int maxn;
vector<pair<int, int>> a[N];
int vt[N];
int n;
int ans[N];
void read()
{   
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        vt[x] = 0;
        a[x].pb({i, x});
        maxn = max(maxn, x);
    }
}
void solve()
{
    for(int i = 2; i <= maxn; i++)
    {
        if(a[i].size() > a[i - 1].size())
        {
            cout << - 1;
            return;
        }
    }
    cout << a[1].size() << "\n";
    int dem = 1;
    while(vt[1] < a[1].size())
    {
        for(int i = 1; i <= maxn; i++)
        {
            if(vt[i] < a[i].size())
            {
                int x = a[i][vt[i]].fi;
                ans[x] = dem;
                vt[i]++;
            }
        }
        dem++;
    }
    for(int i = 1; i <= n; i++)
    {
        cout << ans[i] << " ";
    }
}   

