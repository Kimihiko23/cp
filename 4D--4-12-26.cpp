#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
const int MOD = 1000020407;
pair<pair<int, int>, int> wh[N];
int dp[N];
int n;
int a, b;
int dem = 0;
void read()
{   
    cin >> n >> a >> b;
    for(int i = 1; i <= n; i++)
    {
        int ww, hh;
        cin >> ww >> hh;
        if(ww <= a || hh <= b)
        {
            continue;
        }
        else
        {
            dem++;
            wh[dem] = {{ww, hh}, i};
            dp[dem] = 1;
        }
    }
}
void solve()
{
    sort(wh + 1, wh + dem + 1);
    for(int i = 1; i <= dem; i++)
    {
        for(int j = 1; j < i; j++)
        {
            if(wh[i].fi.fi > wh[j].fi.fi && wh[i].fi.se > wh[j].fi.se)
            {
                dp[i] = max(dp[i], dp[j] + 1);
            }
        }
    }
    int ans = 0, vtans = 1, afvt = 1;
    for(int i = 1; i <= n; i++)
    {
        
        if(dp[i] >= ans)
        {
            ans = dp[i];
            vtans = wh[i].se;
            afvt = i;
        }
    }
    cout << ans << "\n";
    if(ans == 0)
    {
        return;
    }
    vector<int> res {vtans};
    int vt = afvt;
    while(dp[vt] != 1)
    {
        for(int i = vt - 1; i >= 1; i--)
        {
            if(dp[i] == dp[vt] - 1 && wh[i].fi.fi < wh[vt].fi.fi && wh[i].fi.se < wh[vt].fi.se)
            {
                res.pb(wh[i].se);
                vt = i;
                break;
            }
        }
    }
    reverse(res.begin(), res.end());
    for(auto i : res)
    {
        cout << i << " ";
    }
    
}   

