using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int n;
string s[N];
vector<pair<char, char>> v;
vector<int> g[26];
int indeg[26];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> s[i];
    }
}
void solve()
{
    for(int i = 1; i < n; i++)
    {
        int len = s[i + 1].size();
        if(s[i].size() > len)
        {
            string tam = s[i].substr(0, len);
            if(tam == s[i + 1])
            {
                cout << "Impossible";
                return;
            }
        }
        for(int j = 0; j < min(s[i].size(), s[i + 1].size()); j++)
        {
            if(s[i][j] != s[i + 1][j])
            {
                v.pb({s[i][j], s[i + 1][j]});
                break;
            }
        }
    }
    sort(v.begin(), v.end());
    v.erase(unique(v.begin(), v.end()), v.end());
    queue<int> q;
    for(auto x : v)
    {
        g[x.fi - 'a'].pb(x.se - 'a');
        indeg[x.se - 'a']++;
    }
    for(int i = 0; i < 26; i++)
    {
        if(indeg[i] == 0)
            q.push(i);
    }

    string ans;

    while(!q.empty())
    {
        int u = q.front();
        q.pop();

        ans += char(u + 'a');

        for(auto x : g[u])
        {
            indeg[x]--;
            if(indeg[x] == 0)
                q.push(x);
        }
    }
    if(ans.size() != 26)
    {
        cout << "Impossible";
        return;
    }
    cout << ans;
}
