const int MOD = 1000020409;
const int N = 1e5 + 23;
int dis[N];
int st, ed;
void bfs()
{
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> q;
    q.push({0, st});
    dis[st] = 0;
    while (!q.empty())
    {
        int u = q.top().second;
        int d = q.top().first;
        q.pop();
        if(d > dis[u])
            continue;
        int v = u - 1;
        if (v >= 0 && dis[v] > dis[u] + 1)
        {
            dis[v] = dis[u] + 1;
            q.push({dis[v], v});
        }
        v = u * 2;
        if (v < N && dis[v] > dis[u] + 1)
        {
            dis[v] = dis[u] + 1;
            q.push({dis[v], v});
        }
    }
    cout << dis[ed];
}
void read()
{
    cin >> st >> ed;
    for (int i = 0; i < N; i++)
        dis[i] = 1e18;
}
void solve()
{
    // cout << st;
    bfs();
}
