map<string, int> mp;
string s1[N], s2[N];
int n;
vector<int> g[N];
int dis[N];
void dfs(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p) continue;
        dis[v] = dis[u] + 1;
        dfs(v, u);
    }
}
void read()
{
    cin >> n;
    cin.ignore();
    for(int i = 1; i <= n; i++)
    {
        string tam1, tam2, tam3;
        cin >> tam1 >> tam2 >> tam3;
        for(int j = 0; j < tam1.size(); j++)
        {
            tam1[j] = tolower(tam1[j]);
        }
        for(int j = 0; j < tam3.size(); j++)
        {
            tam3[j] = tolower(tam3[j]);
        }
        // getline(cin, s[i]);
        // cin.ignore();
        // cout << s[i] << "\n";
        s1[i] = tam1;
        s2[i] = tam3;
        mp[tam1] = 0;
        mp[tam3] = 0;
    }
    int cnt = 1;
    for(auto &x : mp)
    {
        x.se = cnt;
        cnt++;
    }
    for(int i = 1; i <= n; i++)
    {
        g[mp[s1[i]]].pb(mp[s2[i]]);
        g[mp[s2[i]]].pb(mp[s1[i]]);
    }
}
void solve()
{
    dfs(mp["polycarp"], 0);
    int ans = 0;
    for(int i = 1; i <= mp.size(); i++)
    {
        ans = max(ans, dis[i]);
    }
    cout << ans + 1;
}
