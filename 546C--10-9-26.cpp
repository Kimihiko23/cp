void solve()
{
    int turn = 0;
    int winner = 0;
    while(!a.empty() && !b.empty() && turn <= 100000000)
    {
        turn++;
        int x = a.front();
        a.pop();
        int y = b.front();
        b.pop();
        if(x > y)
        {
            a.push(y);
            a.push(x);
        }
        else
        {
            b.push(x);
            b.push(y);
        }
        if(a.empty())
        {
            winner = 2;
            break;
        }
        else if(b.empty())
        {
            winner = 1;
            break;
        }
    }
    if(turn > 100000000)
    {
        cout << -1;
        return;
    }
    cout << turn << " " << winner;
}
