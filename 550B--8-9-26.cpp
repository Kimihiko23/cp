mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
int a[N];
int l, r, n, x;
int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int ans = 0;
void dequy(string s)
{
    if(s.size() == n)
    {
        int mx = 0;
        int mn = 1e18;
        int sum = 0;
        for(int i = 0; i < n; i++)
        {
            if(s[i] == '1')
            {
                sum += a[i];
                mx = max(mx, a[i]);
                mn = min(mn, a[i]);
            }
        }
        if(mx - mn >= x && sum >= l && sum <= r)
        {
            ans++;
        }
        return;
    }
    dequy(s + '1');
    dequy(s + '0');
}
void read()
{
    cin >> n >> l >> r >> x;
    for(int i = 0; i < n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    dequy("");
    cout << ans;
}
