#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;

int n, m, q;
vector<pair<int, int>> g[N];
vector<int> t[N];
int num[N], low[N], id[N], timer, bcc;
int p[N][20], h[N], up[N], dn[N], vis[N], comp[N];
stack<int> st;
bool ok = true;

void dfs1(int u, int pa)
{
    num[u] = low[u] = ++timer;
    st.push(u);
    for (auto e : g[u])
    {
        int v = e.fi;
        int idx = e.se;
        if (idx == pa)
        {
            continue;
        }
        if (num[v])
        {
            low[u] = min(low[u], num[v]);
        }
        else
        {
            dfs1(v, idx);
            low[u] = min(low[u], low[v]);
        }
    }
    if (low[u] == num[u])
    {
        bcc++;
        while (true)
        {
            int v = st.top();
            st.pop();
            id[v] = bcc;
            if (u == v)
            {
                break;
            }
        }
    }
}

void dfs2(int u, int pa, int rt)
{
    vis[u] = 1;
    comp[u] = rt;
    p[u][0] = pa;
    for (int i = 1; i < 20; i++)
    {
        p[u][i] = p[p[u][i - 1]][i - 1];
    }
    for (int v : t[u])
    {
        if (v == pa)
        {
            continue;
        }
        h[v] = h[u] + 1;
        dfs2(v, u, rt);
    }
}

int lca(int u, int v)
{
    if (h[u] < h[v])
    {
        swap(u, v);
    }
    for (int i = 19; i >= 0; i--)
    {
        if (h[p[u][i]] >= h[v])
        {
            u = p[u][i];
        }
    }
    if (u == v)
    {
        return u;
    }
    for (int i = 19; i >= 0; i--)
    {
        if (p[u][i] != p[v][i])
        {
            u = p[u][i];
            v = p[v][i];
        }
    }
    return p[u][0];
}

void dfs3(int u, int pa)
{
    for (int v : t[u])
    {
        if (v == pa)
        {
            continue;
        }
        dfs3(v, u);
        up[u] += up[v];
        dn[u] += dn[v];
    }
    if (up[u] > 0 && dn[u] > 0)
    {
        ok = false;
    }
}

void read()
{
    cin >> n >> m >> q;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb({v, i});
        g[v].pb({u, i});
    }
}

void solve()
{
    for (int i = 1; i <= n; i++)
    {
        if (!num[i])
        {
            dfs1(i, 0);
        }
    }
    for (int u = 1; u <= n; u++)
    {
        for (auto e : g[u])
        {
            int v = e.fi;
            if (id[u] != id[v])
            {
                t[id[u]].pb(id[v]);
            }
        }
    }
    for (int i = 1; i <= bcc; i++)
    {
        sort(t[i].begin(), t[i].end());
        t[i].erase(unique(t[i].begin(), t[i].end()), t[i].end());
    }
    for (int i = 1; i <= bcc; i++)
    {
        if (!vis[i])
        {
            h[i] = 1;
            dfs2(i, 0, i);
        }
    }
    while (q--)
    {
        int u, v;
        cin >> u >> v;
        u = id[u];
        v = id[v];
        if (u == v)
        {
            continue;
        }
        if (comp[u] != comp[v])
        {
            ok = false;
            continue;
        }
        int l = lca(u, v);
        up[u]++;
        up[l]--;
        dn[v]++;
        dn[l]--;
    }
    for (int i = 1; i <= bcc; i++)
    {
        if (h[i] == 1)
        {
            dfs3(i, 0);
        }
    }
    if (ok)
    {
        cout << "Yes\n";
    }
    else
    {
        cout << "No\n";
    }
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt","r")) 
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }
    read();
    solve();
}