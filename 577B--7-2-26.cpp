mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l,int r)
{
    return uniform_int_distribution<int>(l,r)(rng);
}

int n,m;
int a[N];
bool dp[1005];

void read()
{
    cin >> n >> m;
    for(int i=1;i<=n;i++)
        cin >> a[i];
}

void solve()
{
    if(n > m)
    {
        cout << "YES";
        return;
    }

    memset(dp,false,sizeof(dp));

    for(int i=1;i<=n;i++)
    {
        bool ndp[1005];

        memcpy(ndp,dp,sizeof(dp));

        ndp[a[i]%m]=true;

        for(int j=0;j<m;j++)
        {
            if(dp[j])
                ndp[(j+a[i])%m]=true;
        }

        memcpy(dp,ndp,sizeof(dp));

        if(dp[0])
        {
            cout << "YES";
            return;
        }
    }

    cout << "NO";
}

