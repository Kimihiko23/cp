using namespace std;
#define name "input";

const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;

int n, d;

pair<int,int> a[N];

void read()
{
    cin >> n >> d;

    for (int i = 1; i <= n; i++)
        cin >> a[i].fi >> a[i].se;
}

void solve()
{
    sort(a + 1, a + n + 1);

    int l = 1;
    int sum = 0;
    int ans = 0;

    for (int r = 1; r <= n; r++)
    {
        sum += a[r].se;

        while (a[r].fi - a[l].fi >= d)
        {
            sum -= a[l].se;
            l++;
        }

        ans = max(ans, sum);
    }

    cout << ans;
}

