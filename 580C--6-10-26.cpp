const int N = 1e5 + 23;
int n, m;
int a[N];
vector<int> g[N];
bool dd[N];
int sz[N];
void dfs(int u, int p, int sum)
{
    if(a[u] == 1)
        sum++;
    else
        sum = 0;
    if(sum > m)
        return;
    dd[u] = true;
    for(int v : g[u])
    {
        if(v == p)
            continue;
        dfs(v, u, sum);
    }
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    for (int i = 1; i <= n - 1; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
        sz[u]++;
        sz[v]++;
    }
}
void solve()
{
    dfs(1, 0, 0);
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        if(dd[i] && sz[i] == 1 && i != 1)
            ans++;
    }
    cout << ans;
}
