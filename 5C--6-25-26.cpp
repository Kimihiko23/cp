void solve()
{
    int n = s.size();
    s = " " + s;
    int mx = 0;
    st.push(0);
    v.pb(0);
    int cnt = 0;
    for(int i = 1; i <= n; i++)
    {
        if(s[i] == '(')
        {
            st.push(i);
            v.pb(i);
        }
        else
        {
            st.pop();
            v.pop_back();
            if(st.empty())
            {
                st.push(i);
                v.pb(i);
            }
            else
            {
                if(i - st.top() > mx)
                {
                    mx = i - st.top();
                    cnt = 1;
                }
                else if(i - st.top() == mx)
                {
                    cnt++;
                }
            }
        }
        // for(auto x : v)
        // {
        //     cout << x << " ";
        // }
        // cout << "\n";
    }
    if(mx == 0)
    {
        cnt = 1;
    }
    cout << mx << " " << cnt;
}
