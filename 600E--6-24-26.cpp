#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int n;
int a[N];
int cnt[N];
int sumf[N];
vector<int> g[N];
int ans[N];
int mx = 0;
int sz[N];
int heavy[N];
void dfssz(int u, int p)
{
    int best = 0;
    sz[u] = 1;
    heavy[u] = -1;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dfssz(v, u);
        sz[u] += sz[v];
        if(sz[v] > best)
        {
            heavy[u] = v;
            best = sz[v];
        }
    }
}
void sub(int u, int p, int ty)
{
    int c = a[u];
    if(ty == 1)
    {
        sumf[cnt[c]] -= c;
        cnt[c]++;
        sumf[cnt[c]] += c;
        mx = max(mx, cnt[c]);
    }
    else
    {
        sumf[cnt[c]] -= c;
        cnt[c]--;
        sumf[cnt[c]] += c;
    }
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        sub(v, u, ty);
    }
}
void dfs(int u, int p, bool gud)
{
    for(auto v : g[u])
    {
        if(v == p || v == heavy[u])
            continue;
        dfs(v, u, 0);
    }
    if(heavy[u] != -1)
        dfs(heavy[u], u, 1);
    for(auto v : g[u])
    {
        if(v == p || v == heavy[u])
            continue;
        sub(v, u, 1);
    }
    int c = a[u];
    sumf[cnt[c]] -= c;
    cnt[c]++;
    sumf[cnt[c]] += c;
    mx = max(mx, cnt[c]);
    
    ans[u] = sumf[mx];

    if(!gud)
    {
        sub(u, p, -1);
        mx = 0;
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfssz(1, -1);
    dfs(1, -1, 1);
    for(int i = 1; i <= n; i++)
    {
        cout << ans[i] << " " ;
    }
}
