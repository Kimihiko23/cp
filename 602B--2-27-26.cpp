const int N =1e5+23;


ll n,m,i,a[N];
void read()
{
    cin>>n;
    for(i=1;i<=n;i++){
        cin>>a[i];
    }
}
void solve()
{
    multiset<ll> s;
    ll cur=1,ans=0;
   for(i=1;i<=n;i++){
    if(cur==i){
        s.insert(a[i]);
        cur++;
    }
    while(cur<=n && abs(*s.begin()-a[cur])<=1 && abs(*s.rbegin()-a[cur])<=1){
        s.insert(a[cur]);
        cur++;
    }
    ans=max(ans,cur-i);
    s.erase(s.find(a[i]));
   }
   cout<<ans;
}
