int n;
int c[N];
int f[N][N];

void read()
{
    cin >> n;
    for (int i = 1; i <= n; ++i)
    {
        cin >> c[i];
    }
}

void solve()
{
    for (int i = 1; i <= n; ++i)
    {
        for (int j = 1; j <= n; ++j)
        {
            if (i > j)
            {
                f[i][j] = 0;
            }
            else if (i == j)
            {
                f[i][j] = 1;
            }
            else
            {
                f[i][j] = 1e9;
            }
        }
    }

    for (int l = 2; l <= n; ++l)
    {
        for (int i = 1; i <= n - l + 1; ++i)
        {
            int j = i + l - 1;
            f[i][j] = 1 + f[i + 1][j];
            
            if (c[i] == c[i + 1])
            {
                f[i][j] = min(f[i][j], 1 + f[i + 2][j]);
            }
            
            for (int k = i + 2; k <= j; ++k)
            {
                if (c[i] == c[k])
                {
                    f[i][j] = min(f[i][j], f[i + 1][k - 1] + f[k + 1][j]);
                }
            }
        }
    }

    cout << f[1][n] << "\n";
}

