mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
vector<pair<int, int>> g[N];
struct edg
{
    int u, v, w;
};
bool cmp(edg &a, edg &b)
{
    return a.w < b.w;
}
vector<edg> edge, edge2;
int n, m;
int dp[N][33];
int mx[N][33];
int par[N];
int sz[N];
int h[N];
int findp(int x)
{
    if(par[x] != x)
        par[x] = findp(par[x]);
    return par[x];
}
void join(int u, int v)
{
    u = findp(u);
    v = findp(v);
    if(u == v)
        return;
    if(sz[v] > sz[u])
        swap(u, v);
    sz[u] += sz[v];
    par[v] = u;
}
void dfs(int u, int p)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        int w = i.se;
        if(v == p)
            continue;
        dp[v][0] = u;
        mx[v][0] = w;
        h[v] = h[u] + 1;
        dfs(v, u);
    }
}
void init()
{
    for(int i = 1; i <= 30; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[j][i] = dp[dp[j][i - 1]][i - 1];
            mx[j][i] = max(mx[j][i - 1], mx[dp[j][i - 1]][i - 1]);
        }
    }
}
int lca(int u, int v)
{
    int res = -1e18;
    if(h[v] > h[u])
        swap(u, v);
    for(int i = 30; i >= 0; i--)
    {
        if(h[dp[u][i]] >= h[v])
        {
            res = max(res, mx[u][i]);
            u = dp[u][i];
        }
    }
    if(u == v)
        return res;
    for(int i = 30; i >= 0; i--)
    {
        if(dp[u][i] != dp[v][i])
        {
            res = max(res, mx[u][i]);
            u = dp[u][i];
            res = max(res, mx[v][i]);
            v = dp[v][i];
        }
    }
    res = max(res, mx[u][0]);
    res = max(res, mx[v][0]);
    return res;
}
void read()
{
    cin >> n >> m;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        edge.pb({u, v, w});
        edge2.pb({u, v, w});
    }
}
void solve()
{
    int tam = 0;
    sort(edge.begin(), edge.end(), cmp);
    for(int i = 1; i <= n; i++)
    {
        sz[i] = 1;
        par[i] = i;
    }
    for(auto i : edge)
    {
        int u = i.u;
        int v = i.v;
        int w = i.w;
        if(findp(u) != findp(v))
        {
            tam += w;
            join(u, v);
            g[u].pb({v, w});
            g[v].pb({u, w});
        }
    }
    dfs(1, 0);
    // dp[1][0] = 1;
    init();
    for(auto i : edge2)
    {
        int u = i.u;
        int v = i.v;
        int w = i.w;
        int ans = lca(u, v);
        cout << tam - ans + w << "\n";
    }

}
