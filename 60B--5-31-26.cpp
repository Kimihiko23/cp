#define name "input"
const int MOD = 1000020409;
const int N = 10 + 23;
char a[N][N][N];
int dis[N][N][N];
// z, x, y;
int k, n, m;
int stx, sty, stz = 1;
struct vt
{
    int z, x, y;
};
queue<vt> q;
bool check(int zz, int xx, int yy)
{
    return (zz >= 1 && zz <= k && xx >= 1 && xx <= n && yy >= 1 && yy <= m);
}
vector<int> dx{0, 0, -1, 1, 0, 0};
vector<int> dy{-1, 1, 0, 0, 0, 0};
vector<int> dz{0, 0, 0, 0, -1, 1};
void read()
{
    cin >> k >> n >> m;
    for(int z = 1; z <= k; z++)
    {
        for(int x = 1; x <= n; x++)
        {
            for(int y = 1; y <= m; y++)
            {
                cin >> a[z][x][y];
                dis[z][x][y] = 1e18;
            }
        }
    }
    cin >> stx >> sty;
    dis[stz][stx][sty] = 0;
    
}
void solve()
{
    q.push({stz, stx, sty});
    while(!q.empty())
    {
        int ux = q.front().x;
        int uy = q.front().y;
        int uz = q.front().z;
        q.pop();
        for(int i = 0; i < 6; i++)
        {
            int vx = ux + dx[i];
            int vy = uy + dy[i];
            int vz = uz + dz[i];
            if(check(vz, vx, vy) && dis[vz][vx][vy] == 1e18 && a[vz][vx][vy] != '#')
            {
                dis[vz][vx][vy] = dis[uz][ux][uy] + 1;
                q.push({vz, vx, vy});
            }
        }
    }
    int ans = 0;
    for(int z = 1; z <= k; z++)
    {
        for(int x = 1; x <= n; x++)
        {
            for(int y = 1; y <= m; y++)
            {
                if(dis[z][x][y] != 1e18)
                {
                    ans++;
                }
            }
            // cout << "\n";
        }
        // cout << "\n";
    }
    cout << ans;

}
