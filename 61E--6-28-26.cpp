const int N = 1e6 + 23;
int n;
int a[N];
map<int, int> mp;
int st[N * 4];
int L[N], R[N];
void update(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mp[a[i]]++;
    }   
}
void solve()
{
    int cnt = 0;
    for(auto i : mp)
    {
        mp[i.fi] = ++cnt;
    }
    for(int i = 1; i <= n; i++)
    {
        a[i] = mp[a[i]];
    }
    for(int i = 1; i <= n; i++)
    {
        L[i] = get(1, 1, cnt, a[i] + 1, cnt);
        update(1, 1, cnt, a[i], 1);
    }
    memset(st, 0, sizeof(st));
    for(int i = n; i >= 1; i--)
    {
        R[i] = get(1, 1, cnt, 1, a[i] - 1);
        update(1, 1, cnt, a[i], 1);
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        ans += L[i] * R[i];
    }
    cout << ans;

}
