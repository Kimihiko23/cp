int n;
int a[N];
int dp[N][3];

void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
        cin >> a[i];
}

void solve()
{
    memset(dp, 0x3f, sizeof(dp));

    dp[0][0] = 0;
    dp[0][1] = 0;
    dp[0][2] = 0;

    for(int i = 1; i <= n; i++)
    {
    
        dp[i][0] = min({dp[i - 1][0], dp[i - 1][1], dp[i - 1][2]}) + 1;

        if(a[i] == 1 || a[i] == 3)
        {
            dp[i][1] = min(dp[i - 1][0], dp[i - 1][2]);
        }

        if(a[i] == 2 || a[i] == 3)
        {
            dp[i][2] = min(dp[i - 1][0], dp[i - 1][1]);
        }
    }

    cout << min({dp[n][0], dp[n][1], dp[n][2]});
}

