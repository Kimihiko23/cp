int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m;
int a[N], b[N];
int dd[N];
bool check(int x)
{
    memset(dd, 0, sizeof(dd));
    for(int i = 1; i <= m; i++)
    {
        int left = lower_bound(a + 1, a + n + 1, b[i] - x) - a;
        int right = upper_bound(a + 1, a + n + 1, b[i] + x) - a - 1;
        dd[left]++;
        dd[right + 1]--;
    }
    for(int i = 1; i <= n; i++)
    {
        dd[i] += dd[i - 1];
        if(dd[i] == 0) return false;
    }
    return true;
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    int ans = 1e18;
    int l = 0, r = 1e18;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            ans = mid;
            r = mid - 1;
        }
        else l = mid + 1;
    }
    cout << ans;
}
