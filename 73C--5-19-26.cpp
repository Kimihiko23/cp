int dp[123][27][123];
int n, k;
string s;
int w[27][27];
void read()
{
    cin >> s >> k;
    cin >> n;
    char x, y;
    int b;
    for(int i = 1; i <= n; i++)
    {
        cin >> x >> y >> b;
        w[x - 'a'][y - 'a'] = b;
    }
}
void solve()
{
    for(int i = 0; i <= 120; i++)
    {
        for(int j = 0; j <= 26; j++)
        {
            for(int z = 0; z <= k+2; z++)
            {
                dp[i][j][z] = -1e18;
            }
        }
    }
    dp[0][26][0] = 0;
    int len = s.size();
    for(int i = 0; i < len; i++)
    {
        for(int j = 0; j <= 26; j++)
        {
            for(int z = 0; z <= k; z++)
            {
                if(dp[i][j][z] == -1e18)
                    continue;
                for(int c = 0; c < 26; c++)
                {
                    int w1 = 1;
                    if(s[i] - 'a' == c)
                        w1 = 0;
                    // int p = w[j][c];
                    int p = (j == 26 ? 0 : w[j][c]);
                    if(z + w1 <= k)
                    {
                        dp[i + 1][c][z + w1] = max(dp[i + 1][c][z + w1], dp[i][j][z] + p);
                    }
                }
            }
        }
    }
    int ans = -1e18;
    for(int j = 0; j < 26; j++)
    {
        for(int z = 0; z <= k; z++)
        {
            ans = max(ans, dp[len][j][z]);
        }
    }
    
    cout << ans << "\n";
    
}
