int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int sz[N], cntedg[N];
vector<pair<int, int>> edg;
int n, m;
int par[N];
int find(int u)
{
    if(par[u] != u) par[u] = find(par[u]);
    return par[u];
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    if (sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    cntedg[u] += cntedg[v];
}
int need(int x)
{
    return x * (x - 1) / 2;
}
void read()
{
    cin >> n >> m;
    int u, v;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v;
        edg.pb({u, v});
        join(u, v);
        u = find(u);
        cntedg[u]++;
    }
}
void solve()
{
    set<int> st;
    for(int i = 1; i <= n; i++)
    {
       int u = i;
       u = find(u);
       st.insert(u);
    }
    // cout << st.size() << "\n";
    for(auto u : st)
    {
        if (need(sz[u]) != cntedg[u])
        {
            cout << "NO";
            return;
        }
    }
    cout << "YES";
}
