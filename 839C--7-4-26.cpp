const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int in[N];
int dis[N];
int n;
vector<int> g[N];
long double ans = 0;
void dfs(int u, int p, long double rat)
{
    if(in[u] == 1 && u != 1)
    {
        // cout << rat << "\n";
        ans += (long double)rat * (long double)dis[u];
        return;
    }
    for(auto v : g[u])
    {
        if(v == p)
        {
            continue;
        }
        dis[v] = dis[u] + 1;
        if(u == 1)
            dfs(v, u, (long double)rat / (long double)g[u].size());
        else
            dfs(v, u, (long double)rat / (long double)(g[u].size() - 1));
    }
}
void read()
{
    cin >> n;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
        in[u]++;
        in[v]++;
    }

}
void solve()
{
    dfs(1, 0, 1);
    cout << fixed << setprecision(15) << ans;
}
