int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
vector<int> g[N];
int n;
int ty[N];
int cnt[3];
void dfs(int u, int p)
{
    cnt[ty[u]]++;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        if(ty[u] == 1)
            ty[v] = 2;
        else
            ty[v] = 1;
        dfs(v, u);
    }
}
void read()
{
    cin >> n;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    ty[1] = 1;
    dfs(1, 0);
    cout << cnt[1] * cnt[2] - (n - 1);
}
