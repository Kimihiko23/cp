int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n;
int a[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n * 2; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + 2 * n + 1);
    int ans = 1e18;
    for(int vt1 = 1; vt1 <= n * 2; vt1++)
    {
        for(int vt2 = vt1 + 1; vt2 <= n * 2; vt2++)
        {
            vector<int> tam;
            for(int i = 1; i <= n * 2; i++)
            {
                if(i == vt1 || i == vt2)
                    continue;
                tam.pb(a[i]);
                // cout << a[i] << " ";
            }
            // cout << "\n";
            sort(tam.begin(), tam.end());
            int sum = 0;
            for(int i = 0; i < tam.size() - 1; i += 2)
            {
                sum += tam[i + 1] - tam[i];
            }
            ans = min(ans, sum);
            // cout << sum << "\n";
            // cout << tam.size() << "\n";
        }
    }
    cout << ans;
}
