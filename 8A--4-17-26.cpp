    bool backward = 0;

    if(vta != npos && vtb != npos && vta <= vta + vtb + 1 + a.size())
    {
        forward = true;
    }
    reverse(s.begin(), s.end());
    vta = npos;
    vtb = npos;
    vta = s.find(a);
    if(vta != npos)
        vtb = s.substr(vta + a.size()).find(b);
