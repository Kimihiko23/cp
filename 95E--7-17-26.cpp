#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, m;
int sz = 0;
vector<int> g[N];
int f[N];
bool dd[N];
int dp[N];
vector<pair<int, int>> item;
vector<int> good;
void bfs(int st)
{
    dd[st] = 1;
    sz = 0;
    queue<int> q;
    q.push(st);
    while(!q.empty())
    {
        sz++;
        int u = q.front();
        q.pop();
        for(auto v : g[u])
        {
            if(!dd[v])
            {
                dd[v] = 1;
                q.push(v);
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    int u, v;
    for (int i = 1; i <= m; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(!dd[i])
        {
            bfs(i);
            f[sz]++;
            // cout << sz << "\n";
        }
    }
    //item = number of u, cost;
    for(int i = 1; i <= n; i++)
    {
        dp[i] = INF;
        if(f[i] > 0)
        {
            int j = 1;
            while(f[i] > 0)
            {
                int k = min(j, f[i]);
                item.pb({i * k, k});
                f[i] -= k;
                j *= 2;
            }
        }

        int tam = i;
        bool pu = 1;
     
        while(tam > 0)
        {
            int x = tam % 10;
            if(x != 4 && x != 7)
            {
                pu = 0;
                break;
            }
            tam /= 10;
        }
        if(pu) good.pb(i);
        
    }
    for(auto i : item)
    {
        for(int j = n; j >= i.fi; j--)
        {
            dp[j] = min(dp[j], dp[j - i.fi] + i.se);
        }
    }
    int ans = INF;
    for(auto i : good)
    {
        ans = min(ans, dp[i]);
    }
    if(ans == INF) cout << -1;
    else cout << ans - 1;
}
