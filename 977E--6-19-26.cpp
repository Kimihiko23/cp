const int N = 2e5 + 23;
int n, m;
int sz[N];
int par[N];
vector<int> in[N];
int dem[N];
vector<pair<int, int>> edges;
int find(int u)
{
    if (par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    if (sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    in[u].insert(in[u].end(), in[v].begin(), in[v].end());
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++) 
    {
        par[i] = i;
        sz[i] = 1;
        in[i].push_back(i);
    }
    for (int i = 0; i < m; i++) 
    {
        int u, v;
        cin >> u >> v;
        dem[u]++;
        dem[v]++;
        edges.push_back({u, v});
    }
}
void solve()
{
    int res = 0;
    for(auto i : edges)
    {
        int u = i.fi, v = i.se;
        join(u, v);
    }
    vector<int> tam;
    for(int i = 1; i <= n; i++)
    {
        tam.push_back(find(i));
    }
    sort(tam.begin(), tam.end());
    tam.erase(unique(tam.begin(), tam.end()), tam.end());
    for(auto i : tam)
    {
        bool good = true;
        for(auto j : in[i])
        {
            // cout << j << " ";
            if(dem[j] != 2)
            {
                good = false;
                break;
            }
        }
        // cout << "\n";
        if(good) res++;
    }
    cout << res;

    
}
