#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
vector<pair<int, int>> g[N];
int a[N];
int n;
vector<int> s;
int dist[N];
int dp[N];
void search(int x)
{
    int l = 1, r = s.size() - 1;
    int vt = -1;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(dist[s[mid]] >= x)
        {
            vt = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }
    if(vt != -1)
    {
        dp[s.back()]++;
        dp[s[vt - 1]]--;
    }
}
void dfs(int u, int par)
{
    search(dist[u] - a[u]);
    s.pb(u);
    for(auto i : g[u])
    {
        int v = i.fi;
        int w = i.se;
        if(v != par)
        {
            dist[v] = dist[u] + w;
            dfs(v, u);
        }
    }
    s.pop_back();
}
void dfs2(int u, int par)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        if(v != par)
        {
            dfs2(v, u);
            dp[u] += dp[v];
        }
    }
}
