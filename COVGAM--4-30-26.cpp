#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int MOD = 1000020409;
const int N =1e3+23;
int a[N][N];
int n, m;
int sz[N][N];
pair<int, int> par[N][N];
bool dd[N][N];
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
pair<int, int> find(int x, int y)
{
    if (par[x][y] == make_pair(x, y))
        return {x, y};
    return par[x][y] = find(par[x][y].fi, par[x][y].se);
}
void join(int x1, int y1, int x2, int y2)
{
    pair<int, int> p1 = find(x1, y1);
    pair<int, int> p2 = find(x2, y2);
    if (p1 == p2)
        return;
    if (sz[p1.fi][p1.se] < sz[p2.fi][p2.se])
        swap(p1, p2);
    par[p2.fi][p2.se] = p1;
    sz[p1.fi][p1.se] += sz[p2.fi][p2.se];
}
void bfs(int stx, int sty)
{
    queue<pair<int, int>> q;
    q.push({stx, sty});
    dd[stx][sty] = true;
    vector<int> dx = {0, 0, 1, -1};
    vector<int> dy = {1, -1, 0, 0};
    while (!q.empty())
    {
        pair<int, int> u = q.front();
        q.pop();
        for (int i = 0; i < 4; i++)
        {
            int x = u.fi + dx[i];
            int y = u.se + dy[i];
            if (check(x, y) && !dd[x][y] && a[x][y] == a[stx][sty])
            {
                dd[x][y] = true;
                join(stx, sty, x, y);
                q.push({x, y});
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            par[i][j] = {i, j};
            if(a[i][j] == 1)
                sz[i][j] = 1;
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (!dd[i][j] && a[i][j] == 1)
            {
                bfs(i, j);
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(a[i][j] == 0)
            {
                set<pair<int, int>> s;
                s.clear();
                vector<int> dx = {0, 0, 1, -1};
                vector<int> dy = {1, -1, 0, 0};
                for(int z = 0; z < 4; z++)
                {
                    int ux = i + dx[z];
                    int uy = j + dy[z];
                    if(!check(ux, uy))
                        continue;
                    auto tam = find(ux, uy);
                    s.insert(tam);
                }
                int tong = 1;
                for(auto z : s)
                {
                    int x = z.fi;
                    int y = z.se;
                    tong += sz[x][y];
                }
                ans = max(ans, tong);
                // exit(0);
            }
            else
            {
                auto tam = find(i, j);
                int x = tam.fi;
                int y = tam.se;
                ans = max(ans, sz[x][y]);
            }
        }
    }
    cout << ans;
}
