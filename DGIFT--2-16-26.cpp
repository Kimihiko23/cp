using namespace std;
const int N =2e5+23;
int n, k;
int stmn[N * 4];
int dp[N];
int a[N];
void build(int l, int r, int id)
{
    if(l == r)
    {
        stmn[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    stmn[id] = min(stmn[id * 2], stmn[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return 1e18;
    }
    if(l >= u && r <= v)
    {
        return stmn[id];
    }
    int mid = (l + r) / 2;
    int tam1 = get(l, mid, id * 2, u, v);
    int tam2 = get(mid + 1, r, id * 2 + 1, u, v);
    return min(tam1, tam2);
}


void read()
{
   cin >> n >> k;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
}
void solve()
{
    build(1, n, 1);
   for(int i = 1; i < k; i++)
   {
        dp[i] = 0;
   }
   dp[k] = get(1, n, 1, 1, k);
   for(int i = k + 1; i <= n; i++)
   {
        for(int j = 1; j <= i - k + 1; j++)
        {
            dp[i] = max(dp[i], dp[j - 1] + min(get(1, n, 1, j, i-1), a[i]));
        }
   }
   cout << dp[n];
   
}
