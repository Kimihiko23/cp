using namespace std;
const int N =1e5+23;
unordered_map<int, int> mp;
int n, k;
int pre[N];
void read()
{
   cin >> n >> k;
   int x;
   mp[0] = 1;
   for(int i = 1; i <= n; i++)
   {
        cin >> x;
        pre[i] = pre[i - 1] + x;
   }
}
void solve()
{
   int ans = 0;
   for(int i = 1; i <= n; i++)
   {
        // cout << pre[i] << " ";
        ans += mp[pre[i] - k];
        mp[pre[i]]++;
   }
   cout << ans;
}
