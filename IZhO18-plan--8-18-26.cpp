int n, m, k, q;
int depth[N], up[N][20];
int val[N], minval[N][20];
pair<int, int> edges[5 * N];
vector<pair<int, int>> adj[N];
vector<int> adj2[N];

struct DSU {
    vector<int> par, sizes;
    DSU(int _n): par(_n+1), sizes(_n+1, 1) {iota(par.begin(), par.end(), 0);}
    int findset(int v) {return par[v] == v ? v : par[v] = findset(par[v]);}
    bool unite(int u, int v) {
        u = findset(u), v = findset(v);
        if (u == v) return false;
        if (sizes[u] < sizes[v]) swap(u, v);
        sizes[u] += sizes[v];
        par[v] = u;
        return true;
    }
};

void dfs(int u, int p) {
    for (auto v : adj2[u]) {
        if (v == p) continue;
        depth[v] = depth[u] + 1;
        up[v][0] = u;
        minval[v][0] = min(val[u], val[v]);
        for (int i = 1; i < 20; ++i) {
            up[v][i] = up[up[v][i-1]][i-1];
            minval[v][i] = min(minval[v][i-1], minval[up[v][i-1]][i-1]);
        }
        dfs(v, u);
    }
}

int lca(int u, int v) {
    int res = min(val[u], val[v]);
    if (depth[u] < depth[v]) swap(u, v);
    int h = depth[u] - depth[v];
    for (int i = 0; i < 20; ++i) if (h >> i & 1) res = min(res, minval[u][i]), u = up[u][i];
    if (u == v) return res;
    for (int i = 19; i >= 0; --i) {
        if (up[u][i] != up[v][i]) {
            res = min({res, minval[u][i], minval[v][i]});
            u = up[u][i];
            v = up[v][i];
        }
    }
    return min(res, minval[u][0]);
    
}

