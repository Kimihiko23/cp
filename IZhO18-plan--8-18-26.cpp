void solve()
{
    cin >> n >> m >> k >> q;
    for (int i = 1; i <= m; ++i) {
        int u, v, w; cin >> u >> v >> w;
        edges[i] = {u, v};
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    priority_queue<pair<int, int>> pq;
    for (int i = 0; i <= n; ++i) val[i] = INF;
    for (int i = 0; i < N; ++i) {
        for(int j = 0; j < 20; ++j) minval[i][j] = INF;
    }
    for (int i = 1; i <= k; ++i) {
        int x; cin >> x;
        val[x] = 0;
        pq.push({0, x});
    }
    while (!pq.empty()) {
        int d = -pq.top().fi, u = pq.top().se;
        pq.pop();
        if (d != val[u]) continue;
        for (auto v : adj[u]) {
            if (d + v.se < val[v.fi]) {
                val[v.fi] = d + v.se;
                pq.push({-val[v.fi], v.fi});
            }
        }
    }

    DSU d(n);
    sort(edges+1, edges+1+m, [&](pair<int, int> &x, pair<int, int> &y) {return min(val[x.fi], val[x.se]) > min(val[y.fi], val[y.se]);});
    for (int i = 1; i <= m; ++i) {
        if (d.unite(edges[i].fi, edges[i].se)) {
            adj2[edges[i].fi].pb(edges[i].se);
            adj2[edges[i].se].pb(edges[i].fi);
        }
    }
    dfs(1, 0);
    while (q--) {
        int u, v; cin >> u >> v;
        cout << lca(u, v) << '\n';
    }
}
