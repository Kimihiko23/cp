#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =2e5+23;
int h[N];
int n;
vector<int> g[N];
int par[N][60];
int dp[N];
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        if(i != old)
        {
            h[i] = h[u] + 1;
            par[i][0] = u;
            dfs(i, u);
        }
    }
}
void init()
{
    for(int j = 1; (1 << j) <= n; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);
    while(x > 0)
    {
        for(int i = tam; i >= 0; i--)
        {
            if((1 << i) <= x)
            {
                x -= 1 << i;
                u = par[u][i];
            }
        }
    }
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n - 1; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void ldfs(int u, int parent)
{
    for(auto i : g[u])
    {
        if(i != parent)
        {
            ldfs(i, u);
            dp[u] += dp[i];
            // cout << "gay" ;
        }
    }
}
void solve()
{
    int q, u, v;
    cin >> q;
    dfs(1, -1);
    init();
    while(q--)
    {
        cin >> u >> v;
        dp[u]++;
        dp[v]++;
        dp[lca(u, v)] -= 2;
        // cout << lca(u, v) << "\n";
    }
    int ans = 0;
    ldfs(1, -1);
    for(int i = 2; i <= n; i++)
    {
        if(dp[i] == 0)
        {
            ans++;
        }
        // cout << dp[i] << "\n";
    }
    cout << ans;

}
