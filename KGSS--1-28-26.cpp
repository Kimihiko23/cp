#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
using namespace std;
const int N =1e6+23;
int a[N];
int n, q;
struct ar
{
    int mx1;
    int mx2;
};
ar st[N*4];
ar combine(ar a,ar b)
{
    ar c;
    c.mx1=max(a.mx1,b.mx1);
    c.mx2=min(max(a.mx1,b.mx2),max(a.mx2,b.mx1));
    return c;
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].mx1 = a[l];
        st[id].mx2 = -1e18;
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
void update(int l, int r, int id, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id].mx1 = val;
        st[id].mx2= - 1e18;
        return;
    }
    int mid = (l + r) / 2;
    update(l, mid, id * 2, pos, val);
    update(mid + 1, r, id * 2 + 1, pos, val);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
ar get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return {(int)-1e18, (int)-1e18};
    if(l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    return combine(get(l, mid, id * 2, u, v), get(mid + 1, r, id * 2 + 1, u, v));
}
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
   cin >> q;
}
void solve()
{
   build(1, n, 1);
   while(q--)
   {
        char ty;
        int l, r;
        cin >> ty >> l >> r;
        if(ty == 'U')
        {
            update(1, n, 1, l, r);
        }
        else
        {
            ar res = get(1, n, 1, l, r);
            cout << res.mx1 + res.mx2 << "\n";
        }
   }
}
