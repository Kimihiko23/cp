int mxx = 0;
int mxy = 0;
int type[N];
int a[N][N];
void push(int id, int l, int r, int mid)
{
    if(lz[id] == 0)
        return;
    int x = lz[id];
    lz[id] = 0;

    lz[id * 2] += x;
    lz[id * 2 + 1] += x;

    st[id * 2] += (mid - l + 1) * x;
    st[id * 2 + 1] += (r - mid) * x;
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id] += (r - l + 1) * val;
        lz[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return 0;
    if(l >= u || r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
int res = 0;
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        int x1, y1, x2, y2;
        cin >> x1 >> y1 >> x2 >> y2;
        mxx = max(mxx, x2);
        mxy = max(mxy, y2);
        for(int j = x1; j <= x2; j++)
        {
            for(int z = y1; z <= y2; z++)
            {
                a[j][z] = max(a[j][z], (int)1);
            }
        }
    }
    // cout << mxx << "\n";
}
void solve()
{
    // cout << mxx << "\n";
    for(int i = 1; i <= mxx; i++)
    {   
        int tam = 0;
        for(int j = 1; j <= mxy; j++)
        {
            tam += a[i][j];
        }
        sum[i] = tam;
        type[i] = 1;
        res += sum[i];
    }
    // cout << "\n";
    cout << res << "\n";
    int ty, l, r, k;
    while(q--)
    {
        cin >> ty >> l >> r;
        if(ty == 1)
        {
            for(int i = l; i <= r; i++)
            {
                    dd[i] = true;
            }
        }
        else
        if(ty == 2)
        {
            for(int i = l; i <= r; i++)
            {
                    dd[i] = false;
            }
        }
        else
        {
            cin >> k;
            for(int i = l; i <= r; i++)
            {
                type[i] = k;
            }
        }
        res = 0;
        for(int i = 1; i <= mxx; i++)
        {
            if(!dd[i])
                res += sum[i] * type[i];
        }
        cout << res << "\n";
    }

}
