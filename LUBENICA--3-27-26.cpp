#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =2e5+23;
int h[N];
int n, m;
vector<pair<int, int>> g[N];
int par[N][32];
int mn[N][32];
int mx[N][32];
vector<int> k[N];
int ansmn = 1e18;
int ansmx = -1e18;
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        int v = i.se;
        int w = i.fi;
        if(v != old)
        {
            h[v] = h[u] + 1;
            par[v][0] = u;
            mn[v][0] = w;
            mx[v][0] = w;
            dfs(v, u);
        }
    }
}
void init()
{
    for(int j = 1; j <= log2(n); j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
            mx[i][j] = max(mx[i][j - 1], mx[par[i][j - 1]][j - 1]);
            mn[i][j] = min(mn[i][j - 1], mn[par[i][j - 1]][j - 1]);
        }
    }
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);

    for(int i = tam; i >= 0; i--)
    {
        if((1 << i) <= x)
        {
            ansmn = min(ansmn, mn[u][i]);
            ansmx = max(ansmx, mx[u][i]);
            x -= (1 << i);
            u = par[u][i];
            
        }
    }
    
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            ansmn = min(ansmn, mn[u][i]);
            ansmn = min(ansmn, mn[v][i]);
            ansmx = max(ansmx, mx[u][i]);
            ansmx = max(ansmx, mx[v][i]);
            u = par[u][i];
            v = par[v][i];
            
            
        }
    }

    ansmn = min(ansmn, mn[u][0]);
    ansmn = min(ansmn, mn[v][0]);
    ansmx = max(ansmx, mx[u][0]);
    ansmx = max(ansmx, mx[v][0]);
    return par[u][0];
}
void read()
{
    cin >> n ;
    for(int i = 1; i <= n - 1; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        g[u].pb({w, v});
        g[v].pb({w, u});
    }

}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= 30; j++)
        {
            mn[i][j] = 1e18;
            mx[i][j] = -1e18;
        }
    }
    dfs(1, -1);
    init();
    int q;
    cin >> q;
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        ansmn = 1e18;
        ansmx = -1e18;
        lca(u, v);
        cout << ansmn << " " << ansmx << "\n";

    }
    
    

}
