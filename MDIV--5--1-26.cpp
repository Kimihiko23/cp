using namespace std;
const int MOD = 1000020409;
const int N =5e5+23;
pair<int,int> trace[N];
int n, k;
int a[N];
bool dd[N];
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    bool good = false;
    queue<int> q;
    sort(a+1, a+n+1);
    for(int i = 1; i <= n; i++)
    {
        int tam = a[i] % k;
        if(!dd[tam])
        {
            dd[tam] = 1;
            trace[tam] = {-2, a[i]};
            q.push(tam);
        }
    }
    if(dd[0])
    {
        cout << trace[0].se;
        return;
    }
    while(!q.empty())
    {
        int u = q.front();
        q.pop();
        for(int i = 1; i <= n; i++)
        {
            int tam = (u * 10 + a[i]) % k;
            if(!dd[tam])
            {
                dd[tam] = 1;
                trace[tam] = {u, a[i]};
                q.push(tam);
            }
        }
    }
    if(!dd[0])
    {
        cout << -1;
        return;
    }
    vector<int> res;
    while(1)
    {
        res.pb(trace[0].se);
        trace[0] = trace[trace[0].fi];
        if(trace[0].fi == -2)
        {
            res.pb(trace[0].se);
            break;
        }
    }
    for(int i = res.size() - 1; i >= 0; i--)
    {
        cout << res[i];
    }

}
