void solve()
{
   int ans =0;
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= n; j++)
        {
            if(i != j && mp.count(a[i] + a[j]))
            ans += mp[a[i] + a[j]];
        }
        // mp[a[i]]++;
   }
   cout << ans << "\n";
}
