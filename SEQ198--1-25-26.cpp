using namespace std;
const int N = 1e5+23;
int m;
vector<int> a;
bool check(string tar)
{
    for(int i = 0; i < tar.size(); i++)
    {
        for(int j = 0; j < tar.size(); j++)
        {
            if(tar[i] == '1' && tar[j] == '1')
            {
                int tam = abs(a[i] - a[j]);
                if(tam == 1 || tam == 8 || tam == 9)
                    return false;
            }
            
        }
    }
    return true;
}
string fun;
void read()
{
   cin >> m;
   for(int i = 1; i <= m; i++)
   {
        int x;
        cin >> x;
        a.pb(x);
        fun.pb('1');
   }
}
int ans = 1e18;

void sinh(string tam, int dem)
{
    if(tam.size() == m)
    {
        //cout << tam << " " << dem << "\n";
        if(check(tam))
        {
            ans = min(ans, (int)(m - dem));
        }
        return;
    }
    sinh(tam + '0', dem);
    sinh(tam + '1', dem + 1);
}
void solve()
{
    if(check(fun))
    {
        cout << 0;
        return;
    }

   sinh("", 0);
   cout << ans;
}

