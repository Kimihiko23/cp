struct thing
{
    int v, w, k;
};
thing it[N];
int n, s;
int dp[N];
void read()
{
    cin >> s >> n;
    for(int i = 1; i <= n; i++)
    {
        // cin >> V[i] >> W[i] >> K[i];
        cin >> it[i].v >> it[i].w >> it[i].k;
        // K[i] = min(K[i], s / W[i]);
    }   
}
bool cmp(const thing &a, const thing &b)
{
    if(a.w != b.w)
        return a.w < b.w;
    return a.v > b.v;
}
void solve()
{
    sort(it + 1, it + 1 + n, cmp);
    int cnt = 0;
    for(int i = 1; i <= n; i++)
    {
        if(it[i].w != it[i - 1].w)
            cnt = s / it[i].w;
        for(int j = 1; j <= min(cnt, it[i].k); j++)
        {
            for(int we = s; we >= it[i].w; we--)
            {
                dp[we] = max(dp[we], dp[we - it[i].w] + it[i].v);
            }
        }
        cnt -= min(cnt, it[i].k);
    }
    cout << *max_element(dp, dp+s+1);
}
