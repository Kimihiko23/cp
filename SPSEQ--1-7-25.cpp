using namespace std;
const int N =1e5+23;
int st1[N*4], st2[N*4];
map<int,int> nenso;
int dppre[N], dpsuf[N];
int a[N];
int n;
void update(int l, int r, int id, int pos, int val, int type)
{
    if (l > pos || r < pos)
        return;
    if (l==r)
    {
        if(type == 1)
            st1[id]=val;
        else
            st2[id]=val;
        return;
    }
    int mid=(l+r)/2;
    update(l, mid, id*2, pos, val, type);
    update(mid+1, r, id*2+1, pos, val, type);
    if (type==1)
        st1[id]=max(st1[id*2], st1[id*2+1]);
    else
        st2[id]=max(st2[id*2], st2[id*2+1]);
}
int get(int l, int r, int u, int v, int id, int type)
{
    if ( v < l || u > r ) return 0;
    if(l >= u && r <= v)
    {
        if (type==1)
            return st1[id];
        else
            return st2[id];
    }
    int mid=(l+r)/2;
    return max(get(l, mid, u ,v ,id*2,type),get(mid+1, r, u, v, id*2+1, type));

}
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
        nenso[a[i]];
   }

}
void solve()
{
    int dem=0;
   for(auto i : nenso)
   {
        nenso[i.first]=dem;
        dem++;
   }
   for(int i = 1; i <= n; i++)
   {
        a[i]=nenso[a[i]];
   }
   int l[N], r[N];
   for(int i = 1; i <= n; i++)
   {
        
        update(0, dem, 1, a[i], 1, 1);
        update(0, dem, 1, a[i], get(0, dem, 0, a[i]-1, 1, 1)+1,1);
        l[i]=get(0, dem, a[i], a[i], 1, 1);
   }
   for(int i = n; i >= 1; i--)
   {
        update(0, dem, 1, a[i], 1, 2);
        update(0, dem, 1, a[i], get(0, dem, 0, a[i]-1, 1, 2)+1,2);
        r[i]=get(0, dem, a[i], a[i], 1, 2);
   }
   int ans=0;
   for(int i = 1; i <= n; i++)
   {
        int tam= min(l[i],r[i]);
        ans=max(ans,tam*2 - 1);
   }
   cout << ans;
    
}
