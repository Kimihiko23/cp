priority_queue<pair<int, int>> pq;
int n;
bool dd[N];
void read()
{
    cin >> n;
    int val;
    for(int i = 1; i <= n * 2; i++)
    {
        cin >> val;
        pq.push({val, i});
    }
    // cin >> val;
    // dd[n] = true;
}
void solve()
{
    int ans = 0;
    for(int i = n * 2; i >= 1; i--)
    {
        if(dd[i])
            continue;
        while(!pq.empty())
        {
            auto u = pq.top();
            int vt = u.se;
            int val = u.fi;
            pq.pop();
            if(vt == i || dd[vt])
            {
                continue;
            }
            else
            {
                ans += val;
                dd[vt] = true;
                break;
            }
        }
        dd[i] = true;
    }
    cout << ans << "\n";
    for(int i = 1; i <= n * 2; i++)
    {
        dd[i] = 0;
    }
}
