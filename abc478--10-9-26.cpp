int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int dif[N];
// int ans[N];
int n, q;
vector<pair<int, int>> query[N];
vector<pair<int, int>> res[N];
void read()
{
    cin >> n >> q;
    int l, r, x;
    for(int i = 1; i <= q; i++)
    {
        cin >> l >> r >> x;
        query[x].pb({l, r});
    }
}
void solve()
{
    for(int i = 1; i <= q; i++)
    {
        sort(query[i].begin(), query[i].end());
        for(auto j : query[i])
        {
            int l = j.fi, r = j.se;
            if(res[i].empty() || res[i].back().se < l)
            {
                res[i].pb({l, r});
            }
            else
            {
                res[i].back().se = max(res[i].back().se, r);
            }
        }
        for(auto j : res[i])
        {
            dif[j.fi]++;
            dif[j.se + 1]--;
        }
    }
    for(int i = 1; i <= n; i++)
    {
        dif[i] += dif[i - 1];
        cout << dif[i] << " ";
    }
}
