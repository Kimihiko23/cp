int par[N];
int sz[N];
int sum[N];
bool on[N];
int a[N];
int n;
int find(int x)
{
    if(par[x] != x)
        return par[x] = find(par[x]);
    return par[x];
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(u == v)
        return;
    if(sz[v] > sz[u])
        swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    sum[u] += sum[v];
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        par[i] = i;
        sz[i] = 1;
        sum[i] = a[i];
    }
}
void solve()
{
    int ans = 0;
    int vt = 0;
    for(int i = 1; i <= n; i++)
    {
        cin >> vt;
        int nx = min(vt + 1, n);
        int prv = max(1ll, vt - 1);
        if(on[nx])
        {
            join(vt, nx);
        }
        if(on[prv])
        {
            join(vt, prv);
        }
        on[vt] = 1;
        vt = find(vt);
        ans = max(ans, sum[vt]);
        cout << ans << "\n";
    }
}
