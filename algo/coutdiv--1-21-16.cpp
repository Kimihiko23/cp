#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
using namespace std;
const int N =1e6+23;
bool dd[N];
vector<int> prime;
void sieve()
{
    dd[1] = true;
    for(int i = 2; i <= N; i++)
    {
        if (dd[i])
        { 
            continue;
        }
        prime.pb(i);
        for(int j = i * i; j <= N; j += i)
        {
                dd[j] = true;
        }
    }
}
int coutdiv(int tar)
{
    if ( tar == 1) return 1;
    vector<int> pow;
    for(auto i : prime)
    {
        int cnt = 0;
        while(tar % i == 0)
        {
            tar/=i;
            cnt++;
        }
        if(cnt != 0)
            pow.pb(cnt);
    }
    if(tar>1)
        pow.pb(1);
    int ans = 1;
    for(auto i : pow) ans*=(i + 1);
    return ans;
}


