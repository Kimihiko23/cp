int n, m;
int dp[N][70000];
//dp[i][j] = den thang thu i, mask j;
int a[N][N];
void read()
{
    cin >> n;
    m = pow(2, n);
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < n; j++)
        {
            cin >> a[i][j];
        }
    }
}
void solve()
{
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < (1 << n); j++)
        {
            dp[i][j] = 1e18;
        }
    }
    for(int i = 0; i < n; i++)
    {
        dp[i][(1 << i)] = 0;
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        on.clear();
        for(int x = 0; x < n; x++)
        {
            if(mask & (1 << x))
            {
                on.pb(x);
            }
        }
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i != j)
                {
                    dp[i][mask] = min(dp[i][mask], dp[j][mask ^ (1 << i)] + a[j][i]);
                }
            }
        }
        
    }
    int ans = 1e18;
    for(int i = 0; i < n; i++)
    {
        ans = min(ans, dp[i][(1 << n) - 1]);
    }
    cout << ans;
}
