using namespace std;
const int MOD = 1000020409;
const int N =3e5+23;
int dp[30][N];
int mx[30][N];
int par[N];
int h[N];
int sz[N];
bool dd[N];
int n, m;
vector<pair<int ,int>> g[N];
vector<pair<int, pair<int, int>>> edg, edg2;
// vector<pair<int, int>> edg2;
void dfs(int u)
{
    dd[u] = true;
    for(auto i : g[u])
    {
        int v = i.se;
        int w = i.fi;
        if(!dd[v])
        {
            h[v] = h[u] + 1;
            dp[0][v] = u;
            mx[0][v] = w;
            dfs(v);
        }
    }
}
void init()
{
    for(int i = 1; i <= log2(n); i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[i][j] = dp[i - 1][dp[i - 1][j]];
            mx[i][j] = max({mx[i - 1][j], mx[i - 1][dp[i - 1][j]], mx[i][j]});
        }
    }
}
int find(int x)
{
    if(par[x] == x) return x;
    return par[x] = find(par[x]);
}
void join(int x, int y)
{
    // int xx = x;
    // int yy = y;
    x = find(x);
    y = find(y);
    if(x == y)
        return;
    if(sz[x] > sz[y])
        swap(x, y);
    par[x] = y;
    sz[y] +=sz[x];

}
int lca(int u, int v)
{
    int ans = -1e18;
    if(h[u] < h[v])
        swap(u, v);
    for(int i = log2(n); i >= 0; i--)
    {
        if(h[dp[i][u]] >= h[v])
        {
            ans = max(ans, mx[i][u]);
            u = dp[i][u];
        }
    }
    if(u == v)
        return ans;
    for(int i = log2(n); i >= 0; i--)
    {
        if(dp[i][u] != dp[i][v])
        {
            ans = max(ans, mx[i][u]);
            ans = max(ans, mx[i][v]);
            u = dp[i][u];
            v = dp[i][v];
        }
    }
    ans = max(ans, mx[0][u]);
    ans = max(ans, mx[0][v]);
    return ans;
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        edg.pb({w, {u, v}});
        edg2.pb({w, {u, v}});
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    sort(edg.begin(), edg.end());
    int ans = 0;
    for(auto i : edg)
    {
        // cout << i.fi << " " << i.se.fi << " " << i.se.se << "\n";
        int u = i.se.fi;
        int v = i.se.se;
        if(find(u) != find(v))
        {
            join(u, v);
            g[u].pb({i.fi, v});
            g[v].pb({i.fi, u});
            ans += i.fi;
        }
    }
    // cout << ans;
    dfs(1);
    init();
    for(int i = 0; i < edg2.size(); i++)
    {
        int u = edg2[i].se.fi;
        int v = edg2[i].se.se;
        int w = edg2[i].fi;
        int mxw = lca(u, v);
        cout << ans - mxw + w << "\n";
        // cout << mxw << "\n";
    }

}
