#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 32 + 23;
int w[N], v[N];
int n, U, V;
vector<pair<int, int>> s1, s2;
vector<pair<int, int>> afs1, afs2;
int st2[262144 * 4 + 23];
map<int, int> mp;
void buildst2(int id, int l, int r)
{
    if (l == r)
    {
        st2[id] = afs2[l].se;
        return;
    }
    int mid = (l + r) / 2;
    buildst2(id * 2, l, mid);
    buildst2(id * 2 + 1, mid + 1, r);
    st2[id] = max(st2[id * 2], st2[id * 2 + 1]);
}
int getmax2(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
        return - 1e18;
    if (u <= l && r <= v)
    {        
        return st2[id];
    }
    int mid = (l + r) / 2;
    return max(getmax2(id * 2, l, mid, u, v), getmax2(id * 2 + 1, mid + 1, r, u, v));
}
void sinh1(int i, int W, int V)
{
    if (i == n / 2 + 1)
    {
        s1.pb({W, V});
        return;
    }
    sinh1(i + 1, W, V);
    sinh1(i + 1, W + w[i], V + v[i]);
}
void sinh2(int i, int W, int V)
{
    if (i == n + 1)
    {
        s2.pb({W, V});
        return;
    }
    sinh2(i + 1, W, V);
    sinh2(i + 1, W + w[i], V + v[i]);
}
bool cmp(pair<int, int> a, pair<int, int> b)
{
    if (a.fi == b.fi)
        return a.se > b.se;
    return a.fi < b.fi;
}
void read()
{
    cin >> n >> U >> V;
    for (int i = 1; i <= n; i++)
        cin >> w[i] >> v[i];
}
void solve()
{
    sinh1(1, 0, 0);
    sinh2(n / 2 + 1, 0, 0);
    sort(s1.begin(), s1.end(), cmp);
    sort(s2.begin(), s2.end(), cmp);
    afs1.pb({0, 0});
    afs2.pb({0, 0});
    int ans = 0;
    for(int i = 0; i < s1.size(); i++)
    {
        afs1.pb(s1[i]);
    }
    for(int i = 0; i < s2.size(); i++)
    {
        if(mp.find(s2[i].fi) == mp.end())
        {
            mp[s2[i].fi] = s2[i].se;
            afs2.pb(s2[i]);
        }
    }
    buildst2(1, 1, afs2.size() - 1);
    for(int i = 1; i <= afs1.size() - 1; i++)
    {
        int l = 1, r = afs2.size() - 1, L = -1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(afs1[i].fi + afs2[mid].fi >= U)
            {
                L = mid;
                r = mid - 1;
            }
            else
                l = mid + 1;
        }
        l = 1, r = afs2.size() - 1;
        int R = -1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(afs1[i].fi + afs2[mid].fi <= V)
            {
                R = mid;
                l = mid + 1;
            }
            else
                r = mid - 1;
        }
        if(L != -1 && R != -1 && L <= R)
        {
            int tam = getmax2(1, 1, afs2.size() - 1, L, R);
            if(tam != - 1e18)
                ans = max(ans, afs1[i].se + tam);
        }
        if(afs1[i].fi >= U && afs1[i].fi <= V)
        ans = max(ans, afs1[i].se);
    }
    
    cout << ans;
}
