const int N = 1e6 + 23;
int n, r, k;
int a[N];
int pre[N];
int dif[N];
bool check(int x)
{
    vector<int> add(n + 5, 0);

    int used = 0;
    int curAdd = 0;

    for(int i = 1; i <= n; i++)
    {
        curAdd += add[i];

        int cur = pre[i] + curAdd;

        if(cur < x)
        {
            int need = x - cur;

            used += need;

            if(used > k)
                return false;

            curAdd += need;

            add[min((int)n + 1,
                    i + 2 * r + 1)] -= need;
        }
    }

    return true;
}
void read()
{
    cin >> n >> r >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        int L = max(1LL, i - r);
        int R = min(n + 1, i + r + 1);
        dif[L] += a[i];
        dif[R] -= a[i];
        // cout << L << " " << R << "\n";
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        pre[i] = pre[i - 1] + dif[i];
    }
    int l = 0, r = 1e15;
    int ans = 0;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }
    cout << ans;
}
