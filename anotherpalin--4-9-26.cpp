void solve()
{
    s1 = " " + s1;
    p[0] = {1, 1};

    for(int i = 1; i <= n; i++)
    {
        p[i] = mul(p[i - 1], base);
        pre[i][1] = sum(mul(pre[i - 1][1], base), {s1[i] - 'a' + 1, s1[i] - 'a' + 1});
    }
    for(int i = n; i >= 1; i--)
    {
        pre[i][2] = sum(mul(pre[i + 1][2], base), {s1[i] - 'a' + 1, s1[i] - 'a' + 1});
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int tam = 0;
        int l = 1, r = n;
        //truong hop tam o giua
        while(l <= r)
        {
            int mid = (l + r) / 2;
            int len = mid * 2 + 1;
            int L = i - mid, R = i + mid;
            if(i - mid >= 1 && i + mid <= n && f2(L, R) == f1(L, R))
            {
                tam = max(tam, len);
                l = mid + 1;
            }
            else r = mid - 1;
        }
        ans += (tam + 1) / 2;
        if(tam == 0) ans += 1;
        tam = 0;
        l = 1, r = n;
        // truong hop tam o trai
        while(l <= r)
        {
            int mid = (l + r) / 2;
            int len = mid * 2;
            int L = i - mid + 1, R = i + mid;
            if(i - mid + 1 >= 1 && i + mid <= n && f2(L, R) == f1(L, R))
            {
                tam = max(tam, len);
                l = mid + 1;
            }
            else r = mid - 1;
        }
        ans += tam / 2;
        // ans += 1;
    }
    // cout << f2(1, 4).fi << " " << f1(1, 4).fi << "\n";
    cout << ans;

}
