using namespace std;
const int MOD = 1000020407;
const int MOD2 = 1e9 + 7;
const int N =1e6+23;
pair<int, int> p[N], pre[N][3];
string s1, s2;
int n, m;
pair<int, int> base{257, 257};
pair<int, int> sum(pair<int, int> a, pair<int, int> b)
{
    int tam1 = (a.fi + b.fi) % MOD;
    int tam2 = (a.se + b.se) % MOD2;
    return {tam1, tam2};
}
pair<int, int> sub(pair<int, int> a, pair<int, int> b)
{
    int tam1 = ((a.fi - b.fi) % MOD + MOD) % MOD;
    int tam2 = ((a.se - b.se) % MOD2 + MOD2) % MOD2;
    return {tam1, tam2};
}
pair<int, int> mul(pair<int, int> a, pair<int, int> b)
{
    int tam1 = (a.fi * b.fi) % MOD;
    int tam2 = (a.se * b.se) % MOD2;
    return {tam1, tam2};
}
pair<int, int> f1(int l, int r)
{
    return sub(pre[r][1], mul(pre[l - 1][1], p[r - l + 1]));
}
pair<int, int> f2(int l, int r)
{
    return sub(pre[l][2], mul(pre[r + 1][2], p[r - l + 1]));
}
