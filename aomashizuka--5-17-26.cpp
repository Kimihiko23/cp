int n, m;
int a[N][N];
int dp[N][N];
// stack<int> st;
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dp[i][j] = 1;
            if(a[i - 1][j] == a[i][j])
            {
                dp[i][j] += dp[i - 1][j];
            }
            // cout << dp[i][j] << " ";
        }
        // cout << "\n";
        
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int j = 1;
        while (j <= m)
        {
            int str = j;
            int val = a[i][j];
            while (j <= m && a[i][j] == val)
            {
                j++;
            }
            int ed = j - 1; 
            

            stack<pair<int, int>> st; 
            
            int len = ed - str + 1;
            vector<int> H(len);
            for (int k = 0; k < len; k++) {
                H[k] = dp[i][str + k];
            }
            

            H.push_back(0); 
            

            for (int k = 0; k < H.size(); k++)
            {
                while (!st.empty() && st.top().first > H[k])
                {
                    int c = st.top().first;
                    st.pop();
                    
                    int left_bound = st.empty() ? -1 : st.top().second;
                    int r = k - left_bound - 1;
                    
                    ans = max(ans, c * r);
                }
                st.push({H[k], k});
            }
        }
    }
    cout << ans;
}
