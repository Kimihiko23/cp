int dp[N][N];
int pre[N][N];
int n;
string s;
void read()
{
    cin >> n >> s;
}
void solve()
{
    s = "  " + s;
    dp[1][1] = 1;
    pre[1][1] = 1;
    for(int i = 2; i <= n; i++)
    {
        for(int j = 1; j <= i; j++)
        {
            if(s[i] == '<')
            {
                dp[i][j] = pre[i - 1][j - 1] % MOD;
                pre[i][j] = pre[i][j - 1] + dp[i][j] % MOD;
            }
            else
            {
                dp[i][j] = (pre[i - 1][i - 1] - pre[i - 1][j - 1] + MOD) % MOD;
                pre[i][j] = pre[i][j - 1] + dp[i][j] % MOD;
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        ans += dp[n][i];
        ans %= MOD;
    }
    cout << ans;
    
}
