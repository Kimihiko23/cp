const int N =1e5+23;

vector<char> num{'1', '2', '3', '4', '5'};
vector<char> dau{'+', '-'};
int n, x;
vector<string> ans;
bool check(string tar)
{
    tar = '+' + tar;
    // cout << tar << "\n";
    int sum = 0;
    for(int i = 1; i < tar.size(); i+=2)
    {
        if(tar[i-1] == '+')
        {
            sum += tar[i] - '0';
        }
        else
        {
            sum -= tar[i] - '0';
        }
    }
    // cout << sum << "\n";
    return sum == x;
}
void sinh(string s)
{
    if(s.size() == n)
    {
        if(check(s))
        {
            ans.pb(s);
        }
        // cout << s << "\n";
        return;
    }
    if(s.size() % 2 == 0)
    {
        for(auto i: num)
        {
            sinh(s + i);
        }
    }
    else
    {
        for(auto i: dau)
        {
            sinh(s + i);
        }
    }
}
void read()
{
    cin >> n >> x;
    n = n * 2 - 1;
}
