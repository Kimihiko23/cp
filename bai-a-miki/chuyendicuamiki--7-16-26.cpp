int n, m;
int a[N];
int c[N][30], w[N][30];
int dis[N][30];
priority_queue< pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>> > pq;
//cost, where am i, type engine
void dijkstra()
{
    pq.push({0, {1, 0}});
    //engine = 0 = no engine
    while(!pq.empty())
    {
        int u = pq.top().se.fi;
        int ty = pq.top().se.se;
        int spend = pq.top().fi;
        pq.pop();
        if(spend > dis[u][ty] || u  > n)
            continue;
        int cost = 0;
        int nx = 0;
        if(ty == 0)
        {
            for(int i = 1; i <= m; i++)
            {
                cost = c[u][i];
                if(dis[u][i] > dis[u][ty] + cost)
                {
                    dis[u][i] = spend + cost;
                    pq.push({dis[u][i], {u, i}});
                }
            }
        }
        else
        {
            for(int i = 1; i <= m; i++)
            {
                cost = c[u][i];
                if(dis[u][i] > dis[u][ty] + cost)
                {
                    dis[u][i] = spend + cost;
                    pq.push({dis[u][i], {u, i}});
                }
            }
            cost = w[u][ty];
            nx = min(u + a[ty], n + 1);
            if(dis[nx][ty] > dis[u][ty] + cost)
            {
                dis[nx][ty] = spend + cost;
                pq.push({dis[nx][ty], {nx, ty}});
            }
        }
    }

}
