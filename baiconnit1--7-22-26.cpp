const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
bitset<N> bs[N];
int n;
int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
void read()
{
    cin >> n;
    static char s[N];
    for (int i = 1; i <= n; i++)
    {
        cin >> s;
        bs[i].reset();
        for (int j = 0; j < n; j++)
            if (s[j] == '1') bs[i].set(j); // pos (j+1) -> index j
    }
}
void solve()
{
    int q;
    cin >> q;
    int ty, vt1, vt2;
    while(q--)
    {
        cin >> ty >> vt1;
        if(ty == 1)
        {
            cin >> vt2;
            bs[vt1] &= bs[vt2];
        }
        if(ty == 2)
        {
            cin >> vt2;
            bs[vt1] ^= bs[vt2];
        }
        if(ty == 3)
        {
            cin >> vt2;
            bs[vt1] |= bs[vt2];
        }
        if(ty == 4)
        {
            cin >> vt2;
            vt2--;
            if(bs[vt1][vt2] == 1)
            {
                cout << "YES\n";
            }
            else
            {
                cout << "NO\n";
            }
            bs[vt1].flip(vt2);
        }
        if(ty == 5)
        {
            cout << bs[vt1].count() << "\n";
        }
        if(ty == 6)
        {
            if(bs[vt1].any())
            {
                cout << "YES\n";
                bs[vt1].reset();
            }
            else
            {
                cout << "NO\n";
            }
        }
        if(ty == 7)
        {
            if(bs[vt1].none())
            {
                cout << "-1\n";
            }
            else
            {
                cout << bs[vt1]._Find_first() + 1 << "\n";
            }
        }
    }
}
