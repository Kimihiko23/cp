const int N =1e4+23;
int ans = 0;
int dd[N];
int vt[N];
int val[N];
int n, m;
int a[N];
void read()
{   
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    for(int i = 1; i <= m; i++)
    {
        cin >> val[i];
    }
}
void solve()
{
    string s;
    queue<int> q;
    for(int i = 1; i <= m * 2; i++)
    {
        cin >> s;
        int tam = 0;
        if(s[0] == '-')
        {
            tam = stoll(s.substr(1));
            dd[vt[tam]] = 0;
        }
        else
        {
            tam = stoll(s);
            q.push(tam);
        }
        while(!q.empty())
        {
            bool full = true;
            int id = q.front();
            for(int j = 1; j <= n; j++)
            {
                if(!dd[j])
                {
                    q.pop();
                    ans += val[id] * a[j];
                    dd[j] = true;
                    vt[id] = j;
                    full = false;
                    break;
                }
            }
            if(full)
            {
                break;
            }
        }
    }
    cout << ans;
}

