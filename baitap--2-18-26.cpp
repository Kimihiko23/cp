using namespace std;
const int N = 5e5+23;
int ab[N];
int n, m;
int a[N];
int st[N * 4];
int lm;
bool check(int x)
{
    int need = 0;
    for(int i = 2; i <= n; i++)
    {
        if(ab[i] > x)
        {
            need += (ab[i] - 1) / x;
        }
    }
    return need <= lm;
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id] = ab[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = max(st[id * 2], st[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return -1e18;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    int tam1 = get(l, mid, id * 2, u, v);
    int tam2 = get(mid + 1, r, id * 2 + 1, u, v);
    return max(tam1, tam2);
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    ab[1] = 0;
    multiset<int> s;
    for(int i = 2; i <= n; i++)
    {
        ab[i] = a[i] - a[i - 1];
        s.insert(ab[i]);
    }
    if(n >= m)
    {
        build(1, n, 1);
        int ans = 1e18;
        for(int i = 2; i <= n - m + 2; i++)
        {
                ans = min(ans, get(1, n, 1, i, i + m - 2));
        }
        cout << ans;
    }
    else
    {
        lm = m - n;
        int l = 1, r = 1e9;
        int mid;
        int ans = 1e18;
        while(l <= r)
        {
            mid = (l + r) / 2;
            if(check(mid))
            {
                ans = mid;
                r = mid - 1;
            }
            else
            {
                l = mid + 1;
            }
        }
        cout << ans;
    }
}
