const int N =1e6+23;
int pre[N];
int n;
void read()
{
    pre[0] = 0;
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        int x;
        cin >> x;
        pre[i] = pre[i - 1] + x;
   }
}

void solve()
{
   int ans = 1e18;
   for(int i = 1; i <= n; i++)
   {
        ans = min(ans, abs(pre[n] - pre[i-1] - pre[i-1]));
   }
   cout << ans;
}

