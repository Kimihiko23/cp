using namespace std;
const int N =2e6+23;
int a[N];
int n, k;
int sum = 0;
void read()
{   
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        a[i + n] = a[i];
        sum += a[i];
    }
}
void solve()
{
    if(sum < k)
    {
        cout << -1;
        return;
    }
    int l = 1, r = 1;
    int tam = 0;
    int ans = 1e18;
    while(r <= n*2)
    {
        tam += a[r];
        while(tam >= k)
        {
            ans = min(ans, r - l + 1);
            tam -= a[l];
            l++;
        }
        r++;
        
    }
    cout << ans;
}

