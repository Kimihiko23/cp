using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 700 + 23;
int n, m;
int a[N][N];
bool dd[N][N];
vector<int> dx = {0, 0, 1, 1, 1, -1, -1, -1};
vector<int> dy = {1, -1, 0, 1, -1, 0, 1, -1};
int ans = 0;
int ok = true;
void bfs(int stx, int sty)
{
    queue<pair<int, int>> q;
    q.push({stx, sty});
    dd[stx][sty] = true;
    while(!q.empty())
    {
        pair<int, int> u = q.front();
        q.pop();
        for(int i = 0; i < 8; i++)
        {
            int x = u.fi + dx[i];
            int y = u.se + dy[i];
            if(x < 1 || x > n || y < 1 || y > m) continue;
            if(a[x][y] == a[stx][sty] && !dd[x][y])
            {
                dd[x][y] = true;
                q.push({x, y});
            }
            if(a[x][y] > a[stx][sty])
            {
                ok = false;
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(!dd[i][j])
            {
                ok = true;
                bfs(i, j);
                if(ok) ans++;
            }
        }
    }
    cout << ans;
}
