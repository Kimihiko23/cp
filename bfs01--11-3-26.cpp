mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m, s, t;
vector<pair<int, int>> g[N];
int dis[N];
void bfs()
{
    deque<pair<int, int>> q;
    for(int i = 1; i <= n; i++) dis[i] = INF;
    dis[s] = 0;
    q.push_back({s, 0});
    while(!q.empty())
    {
        int u = q.front().fi;
        int w = q.front().se;
        q.pop_front();
        for(auto i : g[u])
        {
            int v = i.fi;
            int ww = i.se;
            if(ww == 0)
            {
                if(dis[v] == INF)
                {
                    dis[v] = dis[u];
                    q.push_front({v, w});
                }
            }
            else
            {
                if(dis[v] == INF)
                {
                    dis[v] = dis[u] + 1;
                    q.push_back({v, w + 1});
                }
            }
        }
    }
}
void read()
{
    cin >> n >> m >> s >> t;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
    }
}
void solve()
{
    bfs();
    if(dis[t] == INF) cout << -1;
    else cout << dis[t];
}
