#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
int dp[N];
int cost[N];
int num[N];
int w[N];
int n, m;
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> cost[i];
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> w[i];
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> num[i];
    }
}

void solve()
{
    vector<pair<int, int>> item;
    for(int i = 1; i <= n; i++)
    {
        while(num[i] != 0)
        {
            int dem = 1;
            while(dem <= num[i])
            {
                item.pb({cost[i] * dem, w[i] * dem});
                num[i] -= dem;
                dem *= 2;
            }
        }
    }
    for(int i = 0; i < item.size(); i++)
    {
        for(int j = m; j >= 0; j--)
        {
            if(j - item[i].fi >= 0)
            dp[j] = max(dp[j], dp[j - item[i].fi] + item[i].se);
        }
    }
    int ans = 0;
    for(int i = 1; i <= m; i++)
    {
        ans = max(dp[i], ans);
    }
    cout << ans;
 
}

siesta()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
}
