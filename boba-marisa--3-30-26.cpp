#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, q;
vector<int> g[N];
int dp[N][36];
int h[N];
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    for(int i = 29; i >= 0; i--)
    {
        if(h[dp[u][i]] >= h[v]) u = dp[u][i];
    }
    if(u == v) return u;
    for(int i = 29; i >= 0; i--)
    {
        if(dp[u][i] != dp[v][i])
        {
            u = dp[u][i];
            v = dp[v][i];
        }
    }
    return dp[u][0];
}
int dis(int u, int v)
{
    return h[u] + h[v] - 2*h[lca(u, v)];
}
int sum(int a, int b, int c, int x)
{
    return dis(a, x) + dis(b, x) + dis(c, x);
}
void init()
{
    for(int j = 1; j < 30; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[i][j] = dp[dp[i][j-1]][j-1];
        }
    }
}
void dfs(int u, int p)
{
    for(auto i : g[u])
    {
        if(i == p) continue;
        dp[i][0] = u;
        h[i] = h[u] + 1;
        dfs(i, u);
    }
}
void read()
{   
    cin >> n >> q;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dp[1][0] = 1;
    dfs(1, -1);
    init();
    while(q--)
    {
        int a, b, c;
        cin >> a >> b >> c;
        int ans = 1e18;
        int vt = 1;
        int x = lca(a, b);
        if(ans > sum(a, b, c, x))
        {
            ans = sum(a, b, c, x);
            vt = x;
        }
        x = lca(a, c);
        if(ans > sum(a, b, c, x))
        {
            ans = sum(a, b, c, x);
            vt = x;
        }
        x = lca(b, c);
        if(ans > sum(a, b, c, x))
        {
            ans = sum(a, b, c, x);
            vt = x;
        }
        x = lca(lca(a, b), c);
        if(ans > sum(a, b, c, x))
        {
            ans = sum(a, b, c, x);
            vt = x;
        }
        cout << vt << "\n";
    }
}   

