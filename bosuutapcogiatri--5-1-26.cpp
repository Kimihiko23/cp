using namespace std;
const int MOD = 1000020409;
const int N =1e5+23;
int zz, ss, mm, tarz, tars, tarm;
int z1[N], s1[N], m1[N], z2[N], s2[N], m2[N];
int dis[6][6][6];
bool dd[6][6][6];
int n;
void read()
{
    cin >> zz >> ss >> mm >> tarz >> tars >> tarm;
    int dem = 1;
    while(cin >> z1[dem] >> s1[dem] >> m1[dem] >> z2[dem] >> s2[dem] >> m2[dem])
    {
        dem++;
    }
    n = dem - 1;
    // cout << n;
}
void solve()
{
    for(int i = 0; i < 6; i++)
    {
        for(int j = 0; j < 6; j++)
        {
            for(int z = 0; z < 6; z++)
            {
                dis[i][j][z] = 1e18;
            }
        }
    }
    dis[zz][ss][mm] = 0;
    dd[zz][ss][mm] = true;
    queue<tuple<int,int,int>> q;
    q.push({zz, ss, mm});
    while(!q.empty())
    {
        auto [z, s, m] = q.front();
        q.pop();
        if(z >= tarz && s >= tars && m >= tarm)
        {
            cout << dis[z][s][m];
            return;
        }
        for(int i = 1; i <= n; i++)
        {
            if(z >= z1[i] && s >= s1[i] && m >= m1[i])
            {
                int z3 = z - z1[i] + z2[i];
                int s3 = s - s1[i] + s2[i];
                int m3 = m - m1[i] + m2[i];
                if(z3 <= 4 && s3 <= 4 && m3 <= 4 && !dd[z3][s3][m3])
                {
                    dd[z3][s3][m3] = true;
                    dis[z3][s3][m3] = dis[z][s][m] + 1;
                    q.push({z3, s3, m3});
                }
            }
        }
    }
}
