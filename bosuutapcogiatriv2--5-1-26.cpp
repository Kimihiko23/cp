#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int MOD = 1000020409;
const int N =1e5+23;

int z, s, m, z0, s0, m0;
struct R
{
    int z1, s1, m1, z2, s2, m2;
};
vector<R> v;
int d[5][5][5];

void read()
{
    cin >> z >> s >> m >> z0 >> s0 >> m0;
    int a, b, c, x, y, k;
    while (cin >> a >> b >> c >> x >> y >> k)
    {
        v.pb({a, b, c, x, y, k});
    }
}

void solve()
{
    memset(d, -1, sizeof(d));
    queue<tuple<int, int, int>> q;
    q.push({z, s, m});
    d[z][s][m] = 0;
    while (!q.empty())
    {
        auto [cz, cs, cm] = q.front();
        q.pop();
        if (cz >= z0 && cs >= s0 && cm >= m0)
        {
            cout << d[cz][cs][cm];
            return;
        }
        for (auto p : v)
        {
            if (cz >= p.z1 && cs >= p.s1 && cm >= p.m1)
            {
                int nz = cz - p.z1 + p.z2;
                int ns = cs - p.s1 + p.s2;
                int nm = cm - p.m1 + p.m2;
                if (nz <= 4 && ns <= 4 && nm <= 4 && d[nz][ns][nm] == -1)
                {
                    d[nz][ns][nm] = d[cz][cs][cm] + 1;
                    q.push({nz, ns, nm});
                }
            }
        }
    }
    cout << -1;
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    read();
    solve();
}
