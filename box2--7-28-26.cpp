mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
pair<int, pair<int, int>> a[N];
int n;
vector<int> g[N];
pair<int, int> tail[N];
bool cmp(const pair<int, pair<int, int>> &a,
         const pair<int, pair<int, int>> &b)
{
    if (a.fi != b.fi)
        return a.fi < b.fi;
    return a.se.fi > b.se.fi;
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].fi >> a[i].se.fi;
        a[i].se.se = i;
    }
}
void solve()
{
    sort(a + 1, a + 1 + n, cmp);
    int sz = 0;
    for(int i = 1; i <= n; i++)
    {
        if(sz == 0)
        {
            sz++;
            g[sz].pb(a[i].se.se);
            tail[sz].fi = a[i].fi;
            tail[sz].se = a[i].se.fi;
        }
        else
        {
            int l = 1, r = sz;
            int vt = - 1;
            while(l <= r)
            {
                int mid = (l + r) / 2;
                if(tail[mid].fi < a[i].fi && tail[mid].se < a[i].se.fi)
                {
                    vt = mid;
                    r = mid - 1;
                }
                else
                {
                    l = mid + 1;
                }
            }
            if(vt != -1)
            {
                tail[vt].fi = a[i].fi;
                tail[vt].se = a[i].se.fi;
                g[vt].pb(a[i].se.se);
            }
            else
            {
                sz++;
                tail[sz].fi = a[i].fi;
                tail[sz].se = a[i].se.fi;
                g[sz].pb(a[i].se.se);
            }
            
        }
    }
    cout << sz << "\n";
    for(int i = 1; i <= sz; i++)
    {
        cout << g[i].size() << " ";
        for(int j = g[i].size() - 1; j >= 0; j--)
        {
            cout << g[i][j] << " ";
        }
        cout << "\n";
    }
    
}
