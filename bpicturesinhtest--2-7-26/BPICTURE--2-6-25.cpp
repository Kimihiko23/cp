const int N =1e5+23;
int n, m;
vector<int> g[N];
vector<int> dp[N];
int sz[N];
// sz is not size, size = sz + 1
//1 la left
//0 la right
deque<pair<int, int>> dq;
void push(int x, int y)
{
    if(!dq.empty())
    while(!dq.empty() && dp[dq.back().fi][dq.back().se] > dp[x][y])
    {
        dq.pop_back();
    }
    dq.push_back({x, y});
}

