using namespace std;
const int MAX = 1e5 + 5;
const int MOD = 1e9 + 7;
const int ha = 1;
int d1[] = {1, -1, 0, 0};
int d2[] = {0, 0, 1, -1};

int n, m;
pair<int,int> b[MAX];
int a[MAX];
int node[MAX * 4];

void build(int id, int l, int r) 
{
    if (l == r) 
    {
        node[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    node[id] = min(node[id * 2], node[id * 2 + 1]);
}

int get(int id, int l, int r, int u, int v) 
{
    if (l > v || r < u) return INT_MAX;
    if (l >= u && r <= v) return node[id];
    int mid = (l + r) / 2;
    return min(
        get(id * 2, l, mid, u, v),
        get(id * 2 + 1, mid + 1, r, u, v)
    );
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    freopen("input.txt","r",stdin);
    freopen("output2.txt","w",stdout);

    cin >> n >> m;

    vector<vector<int>> ans(n + 1, vector<int>(m + 1));

    for (int i = 1; i <= m; i++)
    {
        cin >> b[i].fi >> b[i].se;
    }

    for (int j = 1; j <= m; j++)
    {

        for (int i = b[j].se - b[j].fi + 1; i <= n; i++) 
        {
            int val = abs(i - b[j].se);
            int y = i + (b[j - 1].se - b[j - 1].fi);
            int x = i - (b[j].se - b[j].fi);

            int idk = get(1, 1, n, max(x, ha), min(y, n));
            ans[i][j] = idk + val;
            a[i] = idk + val;
        }

        for (int i = b[j].se - b[j].fi + 1; i > 0; i--)
        {
            ans[i][j] = ans[b[j].se - b[j].fi + 1][j];
            a[i] = a[b[j].se - b[j].fi + 1];
        }

        build(1, 1, n);
    }

    int res = INT_MAX;
    for (int i = b[m].se - b[m].fi + 1; i <= n; i++) 
    {
        res = min(res, ans[i][m]);
    }

    cout << res;

}
