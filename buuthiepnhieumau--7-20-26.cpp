mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<int> ord;
int n;
string s;
int a[N];
int st[N * 4];
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = max(st[id * 2], st[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    int le = get(l, mid, id * 2, u, v);
    int ri = get(mid + 1, r, id * 2 + 1, u, v);
    return max(le, ri);
}
void read()
{
    cin >> n >> s;
    s = " " + s;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    ord.pb(1);
}
void solve()
{
    build(1, n, 1);
    for(int i = 2; i <= n; i++)
    {
        if(s[i] != s[i - 1])
        {
            ord.pb(i);
        }
    }
    ord.pb(n + 1);
    int ans = 0;
    for(int i = 0; i < ord.size() - 1; i++)
    {
        int lef = ord[i];
        int rig = ord[i + 1] - 1;
        ans += get(1, n, 1, lef, rig);
    }
    cout << ans;
}
