const int N =1e5+23;

void solve() {
    int n;
    if (!(cin >> n)) return;
    vector<int> a(n);
    int min_val = 2e9, max_val = -2e9;
    
    for (int i = 0; i < n; i++) {
        cin >> a[i];
        min_val = min(min_val, a[i]);
        max_val = max(max_val, a[i]);
    }

    vector<int> b = a;
    sort(b.begin(), b.end());

    int ans = 2e9;
    bool changed = false;

    for (int i = 0; i < n; i++) {
        if (a[i] != b[i]) {
            changed = true;
            int can = max(a[i] - min_val, max_val - a[i]);
            ans = min(ans, can);
        }
    }

    if (!changed) {
        cout << -1 << "\n";
    } else {
        cout << ans << "\n";
    }
}

void read() {
    int t;
    cin >> t;
    while (t--) {
        solve();
    }
}

