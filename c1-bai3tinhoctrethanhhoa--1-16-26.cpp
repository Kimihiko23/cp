void update (int id, int l, int r, int pos, int val) {
    if (l > pos || r < pos) return;
    else if (l == r) {
        st[id] = val;
        return;
    }
    int mid = (l+r)/2;
    update (id*2, l, mid, pos, val);
    update (id*2+1, mid+1, r, pos, val);
    st[id] = max(st[id*2], st[id*2+1]);
}

int get (int id, int l, int r, int u, int v) {
    if (l > v || r < u) return -1e18;
    else if (l >= u && r <= v) return st[id];
    int mid = (l+r)/2;
    return max(get(id*2, l, mid, u, v), get(id*2+1, mid+1, r, u, v));
}
void read()
{
   cin >> n;
   for( int i = 1; i <= n ; i++)
   {
        for( int j = 1 ; j <= n ; j++)
        {
            int x;
            cin >> x;
            g[x].pb({i,j});
        }
   }
}
void solve()
{
   for(int i = 1; i <= n*n ; i++)
   {
        for(int j = 0; j < g[i].size() ; j++)
        {
            int val = g[i][j].se;
            L[j] = max( (int) 1, get(1, 1, n, 1, val) + 1);
            update(1, 1, n, val, L[j]);
            //cout << l[j] << " ";
        }
        for(int j = 0; j < g[i].size(); j++) update(1, 1, n, g[i][j].se, 0);
        for(int j = g[i].size() - 1 ; j >= 0; j--)
        {
            int val = g[i][j].se;
            R[j] = max( (int)1, get(1, 1, n, val, n) + 1);
            update(1, 1, n, val, R[j]);
        }
        for(int j = 0; j < g[i].size(); j++) update(1, 1, n, g[i][j].se, 0);
        for(int j = 0; j < g[i].size(); j++)
        {
            int tam= R[j] + L[j] - 1;
            ans[tam]++;
            R[j]=0;
            L[j]=0;
        }
   }
   for(int i = 1; i <= n*2-1; i++)
   {
        cout << ans[i] << "\n";
   }

}
