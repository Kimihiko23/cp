const int MOD = 1000020409;
const int N =2e3 + 23;
int a[N][N];
bool dd[N][N];
int tplt = 0;
int mx = 0;
int tymx;
int n, m;
int ansx, ansy;
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
void bfs(int stx, int sty)
{
    int dem = 0;
    queue<pair<int, int>> q;
    q.push({stx, sty});
    vector<int> dx{0, 0, 1, -1};
    vector<int> dy{1, -1, 0, 0};
    dd[stx][sty] = 1;
    while(!q.empty())
    {
        auto tam = q.front();
        q.pop();
        int ux = tam.fi;
        int uy = tam.se;
        // cout << ux << " " << uy << "\n";
        dem++;
        for(int i = 0; i < 4; i++)
        {
            int vx = ux + dx[i];
            int vy = uy + dy[i];
            if(check(vx, vy) && a[vx][vy] == a[stx][sty] && !dd[vx][vy])
            {
                q.push({vx, vy});
                dd[vx][vy] = 1;
            }
        }
    }
    if(dem > mx)
    {
        mx = dem;
        tymx = a[stx][sty];
        ansx = stx;
        ansy = sty;
    }
}
