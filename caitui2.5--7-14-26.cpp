mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, W;
struct thing
{
    int v, w;
};
vector<thing> item;
int dp[N];
void read()
{
    cin >> n >> W;
    int w, v, a;
    for(int i = 1; i <= n; i++)
    {
        cin >> w >> v >> a;
        for(int j = 0; (1 << j) <= a; j++)
        {
            int mul = 1 << j;
            int uv = v * mul;
            int uw = w * mul;
            a -= mul;
            item.pb({uv, uw});
        }
        if(a > 0)
        {
            int uv = v * a;
            int uw = w * a;
            item.pb({uv, uw});
        }
    }
}
void solve()
{
    // for(auto i : item)
    // {
    //     cout << i.v << " " << i.w << "\n";
    // }
    for(int i = 1; i <= W; i++)
    {
        dp[i] = -1e18;
    }
    dp[0] = 0;
    for(auto i : item)
    {
        for(int j = W; j >= 0; j--)
        {
            if(j - i.w >= 0)
            {
                dp[j] = max(dp[j], dp[j - i.w] + i.v);
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= W; i++)
    {
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
