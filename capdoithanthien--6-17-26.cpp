const int N = 4e5 + 23;
int st[N * 4];
int L[N], R[N];
vector<int> g[N];
int a[N];
int n, k;
int cnt = 0;
bool dd[N];
int start = 0;
pair<int, int> b[N];
// int a[N];
void dfs(int u, int par)
{
    L[u] = ++cnt;
    for(auto i : g[u])
    {
        if(i != par)
        {
            dfs(i, u);
        }
    }
    R[u] = cnt;
}
void update(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
void read()
{
    cin >> n >> k;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
        dd[v] = true;
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(!dd[i])
        {
            start = i;
        }
    }
    dfs(start, -1);
    for(int i = 1; i <= n; i++)
    {
        a[L[i]] = i;
    }
    for(int i = 1; i <= n; i++)
    {
        b[i] = {i, L[i]};
    }
    sort(b + 1, b + 1 + n);
    int l = 1, r = 1;
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        while(r <= n && b[r].fi <= i + k)
        {
            update(1, 1, n, b[r].se, 1);
            r++;
        }
        while(l <= n && b[l].fi < i - k)
        {
            update(1, 1, n, b[l].se, 0);
            l++;
        }
        ans += get(1, 1, n, L[i] + 1, R[i]);
    }
    cout << ans;
    
}
