using namespace std;
const int N =1e5+23;
int st[N*4], lazy[N*4];
int a[N];
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid= (l+r)/2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
void push(int id)
{
    if (lazy[id] == 0) return;
    int x = lazy[id];
    st[id*2] += x;
    st[id * 2 + 1] += x;
    lazy[id * 2] += x;
    lazy[id * 2 + 1] += x;
    lazy[id] = 0;
}
void update(int l, int r, int id, int u, int v, int val)
{
    if ( l > v || r < u ) return;
    if ( u <= l && v >= r)
    {
        st[id] += val;
        lazy[id] += val;
        return;
    }
    push(id);
    int mid=(l+r)/2;
    update(l, mid, id*2, u, v, val);
    update(mid+1, r, id*2+1, u, v, val);
    st[id]= st[id*2] + st[id*2+1];
}
int get(int l, int r, int id, int u, int v)
{
    if ( v < l || u > r ) return 0;
    if ( u <= l && r <= v )
    {
        return st[id];
    }
    push(id);
    int mid=(l+r)/2;
    return get(l, mid, id*2, u, v) + get( mid+1, r, id*2+1, u, v) ;
}
