using namespace std;
const int N =1e5+23;

int a[N];
int n, k;
void read()
{
   cin >> n >> k;
   for(int i = 1; i <= n; i++)
   {
       cin >> a[i];
   }
}
void solve()
{
   int l = 1, r = n;
   int ans1 = 0, ans2 = 0;
   while(r >= 1 && l != r)
   {
        // if(l == n - 1 && r == n)
        // {
        //     break;
        // }
        int tam = a[l] + a[r];
        if(tam == k)
        {
            ans1 = l;
            ans2 = r;
            break;
        }
        else
        {
            if(tam > k)
            {
                r--;
            }
            else
            {
                l++;
            }
        }
   }
   if(ans1 == 0)
   {
        cout <<"No solution";
   }
   else
   cout << ans1 << " " << ans2;
}
