void solve()
{
    char ty;
    int vt;
    for(int i = 1; i <= k; i++)
    {
        cin >> ty >> vt;
        if(ty == 'H')
        {
            // h2.insert(vt);
            auto it = h2.lower_bound(vt);
            if(*it == vt)
            {
                cout << (*h1.rbegin()) * (*w1.rbegin()) << "\n";
                continue;
            }
            // h2.insert(vt);
            int l = *prev(it);
            int r = *it;
            h2.insert(vt);
            h1.erase(h1.find(r - l));
            h1.insert(vt - l);
            h1.insert(r - vt);
            
        }
        else
        {
            auto it = w2.lower_bound(vt);
            if(*it == vt)
            {
                cout << (*h1.rbegin()) * (*w1.rbegin()) << "\n";
                continue;
            }

            // w2.insert(vt);
            int l = *prev(it);
            int r = *it;
            w2.insert(vt);
            w1.erase(w1.find(r - l));
            w1.insert(vt - l);
            w1.insert(r - vt);
        }
        cout << (*h1.rbegin()) * (*w1.rbegin()) << endl;
    }
}
