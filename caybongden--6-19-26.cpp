int L[N], R[N];
int dp[N][64];
int f[N];
int h[N];
vector<int> g[N];
int cnt = 0;
int st[N * 4];
int lz[N * 4];
// int sz[N];
void down(int id, int mid, int l, int r)
{
    if(lz[id] % 2 != 0)
    {
        st[id * 2] = (mid - l + 1) - st[id * 2];
        st[id * 2 + 1] = (r - mid) - st[id * 2 + 1];

        lz[id * 2]++;
        lz[id * 2 + 1]++;

        lz[id] = 0;

        
    }
}
void dfs(int u, int p)
{
    f[u] += a[u];
    L[u] = ++cnt;
    // sz[u] = 1;
    for(int v : g[u])
    {
        if(v == p) continue;
        dp[v][0] = u;
        h[v] = h[u] + 1;
        f[v] += f[u];
        dfs(v, u);
        // sz[u] += sz[v];
    }
    R[u] = cnt;
}
void init()
{
    for(int j = 1; j < 64; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[i][j] = dp[dp[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    int k = h[u] - h[v];
    for(int i = 0; i < 64; i++)
    {
        if(k & (1LL << i))
        {
            u = dp[u][i];
        }
    }
    if(u == v) return u;
    for(int i = 63; i >= 0; i--)
    {
        if(dp[u][i] != dp[v][i])
        {
            u = dp[u][i];
            v = dp[v][i];
        }
    }
    return dp[u][0];
}
void update(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return;
    if(l >= u && r <= v)
    {
        st[id] = (r - l + 1) - st[id];
        lz[id] ++;
        return;
    }
    int mid = (l + r) / 2;
    down(id, mid, l, r);
    update(id * 2, l, mid, u, v);
    update(id * 2 + 1, mid + 1, r, u, v);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return 0;
    if(l >= u && r <= v)
    {
        return st[id];
        // return;
    }
    int mid = (l + r) / 2;
    down(id, mid, l, r);
    int left = get(id * 2, l, mid, u, v);
    int right = get(id * 2 + 1, mid + 1, r, u, v);
    // st[id] = max(st[id * 2], st[id * 2 + 1]);
    return left + right;
}

