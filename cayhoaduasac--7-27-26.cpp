int L[N], R[N];
int n;
vector<int> g[N];
int dep[N];
int cnt = 0;
vector<int> h[N];
int mxdep = 0;
void dfs(int u, int p)
{
    L[u] = R[u] = ++cnt;
    h[dep[u]].pb(L[u]);
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dep[v] = dep[u] + 1;
        dfs(v, u);
    }
    R[u] = cnt;
    mxdep = max(dep[u], mxdep);
}
int cal(int u, int he)
{
    if(h[he].empty())
    {
        return 0;
    }
    int lef = -1, rig = -1;
    int l = 0, r = h[he].size() - 1;
    int tar1 = L[u];
    int tar2 = R[u];
    // cout << tar1 << " " << tar2 << "\n";
    // return 0;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(h[he][mid] >= tar1)
        {
            r = mid - 1;
            lef = mid;
        }
        else
        {
            l = mid + 1;
        }
    }
    l = 0, r = h[he].size() - 1;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(h[he][mid] <= tar2)
        {
            l = mid + 1;
            rig = mid;
        }
        else
        {
            r = mid - 1;
        }
    }
    if(rig == -1 || lef == -1)
    {
        return 0;
    }
    return rig - lef + 1;
}
