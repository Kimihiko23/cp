mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
struct edge
{
    int u;
    bool good;
};
vector<edge> g[N];
bool check(int x)
{
    string s = to_string(x);
    for(auto x: s)
    {
        if(x != '4' && x != '7')
        {
            return false;
        }
    }
    return true;
}
int dp1[N], dp2[N];
int n;
void dfs(int u, int p)
{
    dp1[u] = 1;
    for(auto i : g[u])
    {
        bool ty = i.good;
        int v = i.u;
        if(v == p)
            continue;
        dfs(v, u);
        if(!ty)
        {
            dp1[u] += dp1[v];
        }

    }
}
void reroot(int u, int p)
{
    for(auto i : g[u])
    {
        bool ty = i.good;
        int v = i.u;
        if(v == p)
            continue;
        if(ty)
        {
            dp2[v] = 0;
        }
        else
        {
            dp2[v] = dp1[u] + dp2[u] - dp1[v];
        }
        reroot(v, u);
    }
}
void read()
{
    cin >> n;
    // edge tam;s
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        bool tem = check(w);
        g[u].pb({v, tem});
        g[v].pb({u, tem});
    }
}
void solve()
{
    dp1[1] = 1;
    dfs(1, 0);
    reroot(1, 0);
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int res = n - (dp1[i] + dp2[i]);
        if(res >= 2)
            ans += res * (res - 1);
    }
    cout << ans;
}
