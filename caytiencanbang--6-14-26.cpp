#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;

const int N = 5e5 + 23;

int n, q;
vector<int> g[N];

int L[N], R[N], par[N];
int cnt = 0;

int a[N];
int f[N];

unordered_map<long long, vector<int>> w;

void dfs(int u, int p)
{
    par[u] = p;

    L[u] = ++cnt;

    f[u] = a[u];
    if(p != -1)
    {
        f[u] += f[p];
    }

    w[f[u]].pb(L[u]);

    for(auto v : g[u])
    {
        if(v == p)
            continue;

        dfs(v, u);
    }

    R[u] = cnt;
}

void read()
{
    cin >> n >> q;

    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];

        if(a[i] == 0)
        {
            a[i] = -1;
        }
    }

    int u, v;

    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;

        g[u].pb(v);
        g[v].pb(u);
    }
}

void solve()
{
    dfs(1, -1);

    while(q--)
    {
        int u;
        cin >> u;

        long long need;

        if(par[u] == -1)
        {
            need = 0;
        }
        else
        {
            need = f[par[u]];
        }

        auto &vec = w[need];

        cout <<
            upper_bound(vec.begin(), vec.end(), R[u])
            -
            lower_bound(vec.begin(), vec.end(), L[u])
            << '\n';
    }
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    read();
    solve();

}