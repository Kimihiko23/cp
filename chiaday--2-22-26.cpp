const int N =1e6+23;
int n, k;
int a[N];
int pre[N];
bool check(int x)
{
    if(n % x != 0) return false;
    int sum = 1e18;
    int l = 1, r = x;
    while(r <= n)
    {
        sum = min(sum, pre[r] - pre[l-1]);
        //cout << pre[r] - pre[l-1] << " ";
        l += x;
        r += x;
    }
    return sum >= k;
}

void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++) 
    {
        cin >> a[i];
        pre[i] = pre[i-1] + a[i];
    }
}
void solve()
{
   vector<int> divs;
   for(int i = 1; i * i <= n; i++)
    {
            if(n % i == 0)
            {
                divs.pb(i);
                if(i * i != n) divs.pb(n / i);
            }
    }
   sort(divs.begin(), divs.end());
   int l = 0, r = divs.size() - 1;
   int ans = 1;
   int mid;
   while(l <= r)
   {
       mid = (l + r) / 2;
       if(check(divs[mid]))
       {
           ans = divs[mid];
           r = mid - 1;
       }
       else l = mid + 1;
   }
   cout << ans;
}
