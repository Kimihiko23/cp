#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =3e6+23;
int n, q;
int ans[N];
set<int> s;


void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
        s.insert(i);
   }
}
void solve()
{
   while(q--)
   {
        int l, r, x;
        cin >> l >> r >> x;
        vector<int> cl;
        cl.clear();
        auto it = s.lower_bound(l);
        while(it != s.end() && *it <= r)
        {
            
            
            int tam = *it;
            if(tam != x)
            {
                ans[tam] = x;
                cl.pb(tam);
            }
            it++;
        }
        for(auto i : cl)
            s.erase(i);
   }
   for(int i = 1; i <= n; i++)
   {
        cout << ans[i] << " ";
   }
}
