const int N = 20 + 23;
vector<pair<int, int>> g[N];
int n, m, k;
int id[N][N];
int a[N][N];
int ed = 0;
int dis[N * N];
void dijkstra(int s)
{
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    pq.push({0, s});
    while(!pq.empty())
    {
        pair<int, int> p = pq.top();
        pq.pop();
        int u = p.se;
        if(p.fi > dis[u])
        {
            continue;
        }
        for(auto v : g[u])
        {
            if(dis[v.fi] > dis[u] + v.se)
            {
                dis[v.fi] = dis[u] + v.se;
                pq.push({dis[v.fi], v.fi});
            }
        }
    }
}
void read()
{
    int cnt = 0;
    cin >> n >> m >> k;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            id[i][j] = ++cnt;
        }
    }
    ed = cnt;
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            for(int i1 = i; i1 <= min(n, i + k); i1++)
            {
                for(int j1 = j; j1 <= min(m, j + k); j1++)
                {
                    if(i == i1 && j == j1)
                    {
                        continue;
                    }
                    if((i1 - i) + (j1 - j) <= k)
                    {
                        int w = 1e18;
                        for(int x = i; x <= i1; x++)
                        {
                            for(int y = j; y <= j1; y++)
                            {
                                w = min(w, a[x][y]);
                            }
                        }
                        int res = a[i1][j1] - w;
                        g[id[i][j]].pb({id[i1][j1], res});
                    }
                }
            }
        }
    }
    for(int i = 1; i <= ed; i++)
    {
        dis[i] = 1e18;
    }
    dis[1] = 0;
    dijkstra(1);
    cout << dis[ed];
}
