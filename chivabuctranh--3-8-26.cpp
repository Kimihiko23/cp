using namespace std;
const int N =1e6+23;
const int mod = 1e9+7;
vector<int> g[N];
int n;
int dp[N][2];
void dfs(int u, int p)
{
    dp[u][0] = 1;
    dp[u][1] = 1;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dp[u][0] = dp[u][0] * ((dp[v][1] + dp[v][0]) % mod);
        dp[u][0] %= mod;
        dp[u][1] = dp[u][1] * dp[v][0];
        dp[u][1] %= mod;

    }
}
void read()
{   
    cin >> n;
    for(int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
