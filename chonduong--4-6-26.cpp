#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N = 1e5+23;
const int M = log2(N);
int n, m;
vector<pair<int, pair<int, int>>> q;
vector<pair<int, pair<int, int>>> mst;
int h[N];
int par[N], sz[N];
int findpar(int u)
{
    if(par[u] != u)
    {
        par[u] = findpar(par[u]);
    }
    return par[u];
}
void uni(int u, int v)
{
    u = findpar(u);
    v = findpar(v);
    if(u == v) return;
    if(sz[u] < sz[v]) swap(u,v);
    par[v] = u;
    sz[u] += sz[v];
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
}
void solve()
{
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        q.pb({w, {u, v}});
        int tam = 0;
        for(int j = 1; j <= n; j++)
        {
            par[j] = j;
            sz[j] = 1;
        }
        sort(q.begin(), q.end());
        for(auto x : q)
        {
            int w = x.fi;
            int u = x.se.fi;
            int v = x.se.se;
            if(findpar(u) != findpar(v))
            {
                uni(u, v);
                tam += w;
                mst.pb({w, {u, v}});
            }
        }
        bool ok = true;
        for(int j = 1; j < n; j++)
        {
            if(findpar(j) != findpar(j+1))
            {
                // cout << -1 << "\n";
                ok = false;
                break;
            }
        }
        if(ok)
            cout << tam << "\n";
        else
            cout << -1 << "\n";
        q = mst;
        mst.clear();
    }
    
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
} 
