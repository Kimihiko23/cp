using namespace std;
const int N =1e6+23;
char a[N];
int n;
vector<char> need;
int dem = 0;
vector<string> ans;
bool check(string x)
{
    for(auto i : need)
    {
        if(x.find(i) == string::npos)
            return false;
    }
    return true;
}
bool com(string a, string b)
{
    if(a.size() != b.size())
    return a.size() < b.size();
    return a < b;
}
void dequy(string s, int vt)
{
    if(s.size() >= dem)
    {
        if(check(s))
            ans.pb(s);


    }
    if(s.size() > n)
    {
        return;
    }
    for(int i = vt; i <= n; i++)
    {
        dequy(s + a[i], i + 1);
    }
}
void read()
{   
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    char x;
    while(cin >> x)
    {
        dem++;
        need.pb(x);
    }
}
void solve()
{
    dequy("", 1);
    sort(ans.begin(), ans.end(), com);
    for(auto i : ans)
    {
        for(auto j : i)
        {
            cout << j << " ";
        }
        cout << "\n";
    }
}

