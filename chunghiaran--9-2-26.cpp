mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, 1, 1, -1, -1, -1}, dy{-1, 1, 1, 0, -1, 1, 0, -1};
int n, m;
int mx = 0;
int a[N][N];
int dis[N][N];
bool dd[N][N];
queue<pair<int, int>> q;
void bfs()
{
    while(!q.empty())
    {
        auto i = q.front();
        q.pop();
        for(int j = 0; j < 8; j++)
        {
            int x = i.fi + dx[j];
            int y = i.se + dy[j];
            if(x >= 1 && x <= n && y >= 1 && y <= m && !dd[x][y])
            {
                dd[x][y] = 1;
                dis[x][y] = dis[i.fi][i.se] + 1;
                q.push({x, y});
            }
        }
    }
}
void read()
{
    mx = 0;
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dd[i][j] = 0;
            mx = max(mx, a[i][j]);
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(a[i][j] == mx)
            {
                q.push({i, j});
                dis[i][j] = 0;
                dd[i][j] = 1;
            }
            // else
            // {
            //     dis[i][j] = INF;
            // }
        }
    }
    int ans = 0;
    bfs();
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            ans = max(ans, dis[i][j]);
        }
    }
    cout << ans << "\n";
}
