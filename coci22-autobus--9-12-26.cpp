int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int dis[N][N][N];
//start end used
int n, m;
int a[N][N];
void dijkstra(int st)
{
    priority_queue<pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>>> pq;
    pq.push({0, {st, 0}});
    dis[st][st][0] = 0;
    while(!pq.empty())
    {
        auto tam = pq.top();
        pq.pop();
        int d = tam.first;
        int u = tam.second.first;
        int used = tam.second.second;
        if(d > dis[st][u][used])
        {
            continue;
        }
        for(int i = 1; i <= n; i++)
        {
            if(i == u)
            {
                continue;
            }
            if(a[u][i] != INF && used + 1 <= n - 1)
            {
                if(dis[st][i][used + 1] > d + a[u][i])
                {
                    dis[st][i][used + 1] = d + a[u][i];
                    pq.push({dis[st][i][used + 1], {i, used + 1}});
                }
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    int u, v, w;
    // memset(a, 0x3f, sizeof(a));
    // memset(dis, 0x3f, sizeof(dis));
    for(int i = 0; i <= n; i++)
    {
        for(int j = 0; j <= n; j++)
        {
            a[i][j] = INF;
            for(int k = 0; k <= n - 1; k++)
            {
                dis[i][j][k] = INF;
            }
        }
    }
    for (int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        a[u][v] = min(a[u][v], w);
        // a[v][u] = min(a[v][u], w);
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        dijkstra(i);
    }
    int k, q;
    cin >> k >> q;
    k = min(k, n - 1);
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        int ans = INF;
        for(int i = 0; i <= k; i++)
        {
            ans = min(ans, dis[u][v][i]);
        }
        if(ans == INF)
        {
            cout << -1 << "\n";
        }
        else
        {
            cout << ans << "\n";
        }
    }
}
