int n, a, b;
vector<pair<int, int>> g[N];
pair<int, int> edge[N];
int dp[N];
int par[N];
int cut = 0;
void sol(int u, int p)
{
    dp[u] = 0;
    vector<int> tam;
    for(auto [v, id] : g[u])
    {
        if(v == p || id == cut)
        {
            continue;
        }
        sol(v, u);
        tam.pb(dp[v]);
    }
    sort(tam.begin(), tam.end(), greater<int>());
    for(int i = 0; i < tam.size(); i++)
    {
        dp[u] = max(dp[u], tam[i] + i + 1);
    }
}
void dfs(int u, int p)
{
    for(auto [v, id]: g[u])
    {
        if(v == p)
        {
            continue;
        }
        par[v] = u;
        dfs(v, u);
    }
}
