mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
struct query
{
    int c, d, l, r, id;
};
int n, m;
query q[N];
int a[N];
int ans[N];
bool cmp(query &a, query &b)
{
    return a.r < b.r;
}
int st[N * 4];
void update(int id, int l, int r, int i, int val)
{
    if(l > i || r < i)
        return;
    if (l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, i, val);
    update(id * 2 + 1, mid + 1, r, i, val);
    st[id] = min(st[id * 2], st[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if (l > v || r < u)
        return INF;
    if (l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    return min(get(id * 2, l, mid, u, v), get(id * 2 + 1, mid + 1, r, u, v));
}
int find(int id,int l,int r,int u,int v,int L)
{
    if(r < u || l > v) return -1;

    if(u <=l && r <= v && st[id] >= L)
        return -1;

    if(l == r) return l;

    int mid= (l + r) / 2;

    int t = find(id * 2,l, mid, u, v, L);
    if(t != -1) return t;

    return find(id * 2 + 1, mid+1, r, u, v, L);
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    for(int i = 1; i <= m; i++)
    {
        cin >> q[i].c >> q[i].d >> q[i].l >> q[i].r;
        q[i].id = i;
    }
}
void solve()
{
    sort(q + 1, q + m + 1, cmp);
    for (int i = 0; i < N * 4; i++)
        st[i] = 0;
    int j = 1;
    for (int i = 1; i <= m; i++)
    {
        while (j <= q[i].r)
        {
            update(1, 1, n, a[j], j);
            j++;
        }
        int x = find(1, 1, n, q[i].c, q[i].d, q[i].l);
        if (x == -1)
            ans[q[i].id] = -1;
        else
            ans[q[i].id] = x;
    }
    for (int i = 1; i <= m; i++)
    {
        if(ans[i] == -1)
            cout << "OK\n";
        else
            cout << ans[i] << "\n";
    }
}
