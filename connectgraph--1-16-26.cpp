#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N = 1e5+23;
int par[N], sz[N];
int n,m;
int findpar(int v)
{
    if (v == par[v]) return v;
    else
        return par[v] = findpar(par[v]);

}
void joinset(int a, int b)
{
    a = findpar(a);
    b = findpar(b);
    if(a == b) return;
    if (sz[a] < sz[b]) swap(a,b);
    par[b] = a;
    sz[a] += sz[b];
}

void read()
{
   cin >> n >> m;
}

void solve()
{
   for(int i = 1; i <= n; i++)
   {
        par[i] = i;
        sz[i] = 1;
   }
   while(m--)
   {
        char s;
        cin >> s;
        if (s == '+')
        {
            int a, b;
            cin >> a >> b;
            joinset(a,b);
        }
        else
        {
            int u;
            cin >> u;
            cout << sz[findpar(u)] << "\n";
        }
   }
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
    
   
}