const int N =1e6+23;
const int MOD = 1e9+7;
int par[N];
int sz[N];
int findpar(int x)
{
    if(par[x] == x) return x;
    return par[x] = findpar(par[x]);
}
void joinset(int x, int y)
{
    int u = findpar(x);
    int v = findpar(y);
    if(par[u] == par[v])
        return;
    if(sz[u] < sz[v])
        swap(u, v);
    par[v] = par[u];
    sz[u] = sz[v] + sz[u];
}
