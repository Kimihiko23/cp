int n;
struct thing
{
    int c, v;
};
thing a[N];
int in[N];
int cap[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].c;
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].v;
    }
    
    
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        in[i] = in[i - 1];
        cap[i] = cap[i - 1] + a[i].c;
        int dif = cap[i] - in[i];
        in[i] += min(dif, a[i].v);
        // cout << cap[i] << " " << in[i] << "\n";
    }
    int ans = in[n];
    int tam = in[n];
    int mn = 1e18;
    for(int i = n; i >= 1; i--)
    {
        if(cap[i] == in[i])
        {
            break;
        }
        mn = min(mn, cap[i] - in[i]);
        int res = min(mn, a[i].v) + tam;
        ans = max(ans, res);
    }
    cout << ans << "\n";
    
}
