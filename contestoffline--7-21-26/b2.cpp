int n, q, b, c;
string s;
bool check()
{
    int sum0 = 0;
    int cnt2 = 0;
    int tam = 0;
    if(s[1] == '0')
    {
        tam++;
        sum0++;
    }
    for(int i = 2; i <= n ; i++)
    {
        if(s[i] == '0')
        {
            sum0++;
            tam++;
        }
        if(s[i] == '1' && s[i - 1] == '0')
        {
            cnt2 += tam / 2;
            tam = 0;
        }
    }
    cnt2 += tam/2;
    int lef = cnt2 - c;
    int lef0 = sum0 - c * 2 - b;
    // cout << lef << " " << lef0;
    return (lef >= 0 && lef0 >= 0);
}
void read()
{
    cin >> n >> q >> b >> c >> s;
    s = " " + s;
}
void solve()
{
    if(check())
        cout << "YES\n";
    else
        cout << "NO\n";
    int vt = 0;
    while(q--)
    {
        cin >> vt;
        if(s[vt] == '1')
        {
            s[vt] = '0';
        }
        else
            s[vt] = '1';
        if(check())
            cout << "YES\n";
        else
            cout << "NO\n";
    }
}
