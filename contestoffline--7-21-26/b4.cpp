mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int l[N], r[N];
int n;
vector<int> g[N];
int dis[N][N];
void bfs()
{
    queue<pair<int, pair<int, int>>> q;
    //vt and type and w
    for(int i = l[1]; i <= r[1]; i++)
    {
        dis[1][i] = 0;
        q.push({1, {i, 0}});
    }
    while(!q.empty())
    {
        auto x = q.front();
        int u = x.fi;
        int ty = x.se.fi;
        int w = x.se.se;
        q.pop();
        if(dis[u][ty] < w)
        {
            continue;
        }
        for(auto v : g[u])
        {
            if(l[v] <= ty && ty <= r[v] && dis[v][ty] > w + 1)
            {
                dis[v][ty] = w + 1;
                q.push({v, {ty, w + 1}});
            }
        }
        for(int i = l[u]; i <= r[u]; i++)
        {
            // dis[1][i] = 0;
            if(dis[u][i] > w + 1)
            {
                dis[u][i] = w + 1;
                q.push({u, {i, w + 1}});
            }
        }
        

    }
}
void read()
{
    cin >> n;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> l[i] >> r[i];
    }

}
void solve()
{
    for(int i = 1; i < N; i++)
    {
        for(int j = 1; j < N; j++)
        {
            dis[i][j] = 1e18;
        }
    }
    bfs();
    int ans = 1e18;
    for(int i = l[n]; i <= r[n]; i++)
    {
        ans = min(ans, dis[n][i]);
    }
    cout << ans;
}
