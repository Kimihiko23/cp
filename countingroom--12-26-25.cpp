#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=1e3+23;
int dd[N][N];
int n,m;
bool check(int x1, int y1)
{
    return (x1 >= 1 && x1 <= n && y1 >=1 && y1 <= m);
}
void bfs(int stx, int sty)
{
    dd[stx][sty]=false;
    vector<int> dx{0,0,-1,1};
    vector<int> dy{1,-1,0,0};
    queue<pair<int,int>> q;
    q.push({stx,sty});
    while(!q.empty())
    {
        int x=q.front().fi;
        int y=q.front().se;
        q.pop();
        for(int i = 0; i <= dx.size(); i++)
        {
            int xx=x+dx[i];
            int yy=y+dy[i];
            if(check(xx,yy) && dd[xx][yy]==true)
            {
                dd[xx][yy]=false;
                q.push({xx,yy});
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            dd[i][j]=false;
            char x;
            cin >> x;
            if(x=='.')
            {
                dd[i][j]=true;
            }
        }
    }
}

void solve()
{
    int ans=0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(dd[i][j])
            {
                bfs(i,j);
                ans++;
            }
        }
    }
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
