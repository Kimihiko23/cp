#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
using namespace std;
const int N =1e6+23;
int n , m;
int dist[N][2];
priority_queue < pair < int , int > ,
                 vector < pair < int , int > > ,
                 greater < pair < int , int > > > q;
                 
vector < pair < int , int > > g[N][2];
vector < pair < int, pair<int, int> > > road;
void dijkstra(int start, int ty)
{
    for(int i = 1 ; i <= n ; i++)
        dist[i][ty] = 1e18;
    dist[start][ty] = 0;
    q.push({dist[start][ty] , start});
    
    
    /// (n + m) * log2(n)
    while(!q.empty())
    {
        int u = q.top().second;
        int cost = q.top().first;
        q.pop();
        if(cost > dist[u][ty])
            continue;
       
        for(auto e: g[u][ty])
        {
            int v = e.first;
            int w = e.second;
            if(dist[v][ty] > dist[u][ty] + w)
            {
                dist[v][ty] = dist[u][ty] + w;
                q.push({dist[v][ty] , v});
            }
        }
        
    }
    
}
void read()
{
   cin >> n >> m;
   for(int i = 1; i <= m; i++)
   {
        int u, v, w;
        cin >> u >> v >> w;
        g[u][0].push_back({v, w});
        g[v][1].push_back({u, w});
        road.push_back({u,{v,w}});
   }
}
void solve()
{
    dijkstra(1, 0);
    dijkstra(n, 1);
    int ans = 1e18;
    for(int i = 0; i < m; i++)
    {
        int u = road[i].fi;
        int v = road[i].se.fi;
        int w = road[i].se.se/2;
        int tam = dist[u][0] + dist[v][1] + w;
        ans=min(ans,tam);
    }
    cout << ans;
}
main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    /*freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);*/
    read();
    solve();

   
    
}
