int st[N * 4], lz[N * 4], seet[N * 4];
void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
void push(int id, int l, int r)
{
    int mid = (l + r) / 2;
    if(seet[id] != 0)
    {
        // st[id] = (r - l + 1) * seet[id];
        if(l != r)
        {
            st[id * 2] = (mid - l + 1) * seet[id];
            st[id * 2 + 1] = (r - mid) * seet[id];
            seet[id * 2] = seet[id];
            seet[id * 2 + 1] = seet[id];
            lz[id * 2] = 0;
            lz[id * 2 + 1] = 0;
        }
        seet[id] = 0;
    }
    if(lz[id] != 0)
    {
        // int mid = (l + r) / 2;
        st[id * 2] += (mid - l + 1) * lz[id];
        st[id * 2 + 1] += (r - mid) * lz[id];
        lz[id * 2] += lz[id];
        lz[id * 2 + 1] += lz[id];
        lz[id] = 0;
    }
}
void update(int id, int l, int r, int u, int v, int val)
{
    // push(id, l, r);
    if(v < l || r < u)
    {
        return;
    }
    if(u <= l && r <= v)
    {
        st[id] += (r - l + 1) * val;
        lz[id] += val;
        // push(id, l, r);
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
void update2(int id, int l, int r, int u, int v, int val)
{
    // push(id, l, r);
    if(l > v || r < u)
    {
        return;
    }
    if(l >= u && r <= v)
    {
        lz[id] = 0;
        seet[id] = val;
        st[id] = (r - l + 1) * val;
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update2(id * 2, l, mid, u, v, val);
    update2(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    // push(id, l, r);
    if(v < l || r < u)
    {
        return 0;
    }
    if(u <= l && r <= v)
    {
        return st[id];
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
