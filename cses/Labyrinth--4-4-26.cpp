using namespace std;
const int N =1e3+23;
const int MOD = 1000020407;
int trace[N][N];
int dis2[N][N];
bool dd[N][N];
int n, m;
bool check(int x, int y)
{
    if(x < 1 || y < 1 || x > n || y > m) return 0;
    return 1;
}
int stx, sty, edx, edy;
char a[N][N];
vector<int> dx = {0 , 0, 1, -1};
vector<int> dy = {1, -1, 0, 0};
// vector<char> dir = {'R', 'L', 'D', 'U'};
void dikjstra(int x, int y)
{
    priority_queue<pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>> > q;
    q.push({dis2[x][y],{x, y}});
    while(!q.empty())
    {
        int xx = q.top().se.fi;
        int yy = q.top().se.se;
        int w = q.top().fi;
        q.pop();
        if(dis2[xx][yy] < w)
        {
            continue;
        }
        for(int i = 0; i < 4; i++)
        {
            int nx = xx + dx[i];
            int ny = yy + dy[i];
            if(check(nx, ny) && a[nx][ny] != '#' && dis2[nx][ny] > dis2[xx][yy] + 1)
            {
                dis2[nx][ny] = dis2[xx][yy] + 1;
                trace[nx][ny] = i;
                q.push({dis2[nx][ny], {nx, ny}});
            }
        }
    }
}
void truy()
{
    vector<char> dir = {'R', 'L', 'D', 'U'};
    string ans = "";
    while(edx != stx || edy != sty)
    {
        int i = trace[edx][edy];
        ans += dir[i];
        edx -= dx[i];
        edy -= dy[i];
    }
    reverse(ans.begin(), ans.end());
    cout << ans;
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dis2[i][j] = 1e18;
            if(a[i][j] == 'A')
            {
                stx = i;
                sty = j;
            }
            if(a[i][j] == 'B')
            {
                edx = i;
                edy = j;
            }
        }
    }
    dis2[stx][sty] = 0;
}
void solve()
{
    dikjstra(stx, sty);
    if(dis2[edx][edy] != 1e18)
    {
        cout << "YES\n";
        cout << dis2[edx][edy] << "\n";
        truy();
    }
    else
    cout << "NO";
}   

