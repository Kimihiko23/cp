const int N =1e6+23;
const int MOD = 1000020407;
vector<int> ans;
int res = 0;
vector<int> g[N];
int n, m;
bool dd[N];
void dfs(int u)
{
    dd[u] = 1;
    for(auto v : g[u])
    {
        if(!dd[v])
        {
            dfs(v);
        }
    }
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(!dd[i])
        {
            res++;
            ans.pb(i);
            dfs(i);
        }
    }
    cout << ans.size() - 1;
    for(int i = 1; i < ans.size(); i++)
    {
        cout << "\n" << ans[i-1] << " " << ans[i];
    }
}   

