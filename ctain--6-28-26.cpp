const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;

int T;
int n;
int o[4], w[4];
int pw[5];

struct State
{
    unsigned char a[4];
};

void read()
{
    cin >> T;

    pw[0] = 1;
    for(int i = 1; i <= 4; i++)
        pw[i] = pw[i - 1] * 50;
}

inline int encode(const State &s)
{
    int id = 0;
    for(int i = 0; i < n; i++)
        id = id * 50 + s.a[i];
    return id;
}

void solve()
{
    while(T--)
    {
        cin >> n;

        State st, ed;

        for(int i = 0; i < n; i++)
        {
            cin >> o[i];
            st.a[i] = o[i];
        }

        for(int i = 0; i < n; i++)
        {
            cin >> w[i];
            ed.a[i] = w[i];
        }

        int S = encode(st);
        int E = encode(ed);

        queue<State> q;
        unordered_map<int,int> dist;

        dist[S] = 0;
        q.push(st);

        bool ok = false;

        while(!q.empty())
        {
            State cur = q.front();
            q.pop();

            int curID = encode(cur);

            if(curID == E)
            {
                cout << dist[curID] << '\n';
                ok = true;
                break;
            }

            int d = dist[curID];

          
            for(int i = 0; i < n; i++)
            {
                if(cur.a[i] == 0) continue;

                State nxt = cur;
                nxt.a[i] = 0;

                int id = encode(nxt);

                if(!dist.count(id))
                {
                    dist[id] = d + 1;
                    q.push(nxt);
                }
            }

            for(int i = 0; i < n; i++)
            {
                if(cur.a[i] == 0) continue;

                for(int j = 0; j < n; j++)
                {
                    if(i == j) continue;

              
                    if(cur.a[j] + cur.a[i] <= o[j])
                    {
                        State nxt = cur;
                        nxt.a[j] += nxt.a[i];
                        nxt.a[i] = 0;

                        int id = encode(nxt);

                        if(!dist.count(id))
                        {
                            dist[id] = d + 1;
                            q.push(nxt);
                        }
                    }

         
                    if(cur.a[j] < o[j])
                    {
                        int need = o[j] - cur.a[j];

                        if(cur.a[i] >= need)
                        {
                            State nxt = cur;
                            nxt.a[j] = o[j];
                            nxt.a[i] -= need;

                            int id = encode(nxt);

                            if(!dist.count(id))
                            {
                                dist[id] = d + 1;
                                q.push(nxt);
                            }
                        }
                    }
                }
            }
        }

        if(!ok)
            cout << "NO\n";
    }
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    if (fopen("input.txt","r"))
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }

    read();
    solve();
}