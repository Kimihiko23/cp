#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
int n, m, k;
int par[N];
int find(int x)
{
    if(par[x]==x) return x;
    return par[x]=find(par[x]);
}
vector<pair<int, pair<int, int>>> g;
void join(int x, int y)
{
    x = find(x);
    y = find(y);
    if(x != y)
    {
        par[x] = y;
    }
}
void read()
{
   cin >> n >>  m >> k;
   for(int i = 1; i <= k ; i++)
   {
        int x;
        cin >> x;
        g.pb({0,{0, x}});
   }
   for(int i = 1; i <= m; i++)
   {
        int u, v, w;
        cin >> u >> v >> w;
        g.pb({w,{u, v}});
   }
}
void solve()
{
   sort(g.begin(), g.end());
   for(int i = 1; i <= n; i++)
   {
        par[i] = i;
   }
   int ans = 0;
   for(auto i : g)
   {
        int w = i.fi;
        int u = i.se.fi;
        int v = i.se.se;
        if(find(u) != find(v))
        {
            join(u, v);
            ans += w;
        }
   }
   set<int> s;
   for(int i = 1; i <= n; i++)
   {
        s.insert(find(i));
   }
   if(s.size() > 1)
   {
        cout << -1;
   }
   else
   {
        cout << ans;
   }
   
}
