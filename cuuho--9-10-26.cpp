int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
pair<int, int> a[N];
int n, m;
pair<int, pair<int, int>> que[N];
int ans[N];
int par[N];
int sz[N];
int mxsz = 0;
bool dd[N];
int find(int x)
{
    if(par[x] != x)
        par[x] = find(par[x]);
    return par[x];
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(sz[v] > sz[u])
        swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].fi;
        par[i] = i;
        sz[i] = 1;
        a[i].se = i;
        dd[i] = 0;
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> que[i].fi >> que[i].se.fi;
        que[i].se.se = i;
    }
    if(n == 1)
    {
        for(int i = 1; i <= m; i++)
        {
            cout << 1 << "\n";
        }
        exit(0);
    }
}
void solve()
{
    sort(que + 1, que + 1 + m);
    sort(a + 1, a + 1 + n, greater());
    int vt = 1;
    for(int i = m; i >= 1; i--)
    {
        // cout << que[i].fi << " " << que[i].se.fi << "\n";
        while(a[vt].fi > que[i].fi && vt <= n)
        {
            // cout << "gei";
            dd[a[vt].se] = 1;
            mxsz = max(mxsz, (int)1);
            int nx = min(a[vt].se + 1, n);
            int pre = max(a[vt].se - 1, (int)1);
            // cout << a[vt].se << " " << nx << " " << pre << "\n";
            if(dd[nx])
            {
                join(nx, a[vt].se);
            }
            if(dd[pre])
            {
                join(pre, a[vt].se);
            }
            int u = a[vt].se;
            u = find(u);
            mxsz = max(mxsz, sz[u]);
            vt++;
        }
        // cout << mxsz << "\n";
        // cout << vt << "\n";
        if(mxsz < que[i].se.fi)
        {
            // cout << "gei";
            // cout << que[i].se.se << "\n";
            ans[que[i].se.se] = 1;
        }
    }
    for(int i = 1; i <= m; i++)
        cout << ans[i] << "\n";
}
