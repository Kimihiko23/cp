const int N = 2e5 + 23;
int n, m, q;
vector<pair<int, int>> g[N];
vector<int> g2[N];
vector<pair<int, int>> edg;
int ndfs[N], low[N], cnt = 0;
stack<int> sta;
int partarjan[N];
int tplt = 0;
int heavy[N], head[N], pos[N], sz[N], st[N * 4], par[N];
int lazy[N * 4];

void tarjan(int u, int p)
{
    ndfs[u] = low[u] = ++cnt;
    sta.push(u);
    for(auto [v, id] : g[u])
    {
        if(id == p)
            continue;
        if(ndfs[v] == 0)
        {
            tarjan(v, id);
            low[u] = min(low[u], low[v]);
        }
        else
            low[u] = min(low[u], ndfs[v]);
    }
    if(low[u] == ndfs[u])
    {
        tplt++;
        while(sta.top() != u)
        {
            partarjan[sta.top()] = tplt;
            sta.pop();
        }
        partarjan[sta.top()] = tplt;
        sta.pop();
    }
    
}

void dfs(int u)
{
    sz[u] = 1;
    for(auto v : g2[u])
    {
        if(v != par[u])
        {
            par[v] = u;
            dfs(v);
            sz[u] += sz[v];
            if(sz[heavy[u]] < sz[v])
                heavy[u] = v;
        }
    }
}

void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    if(heavy[u] > 0)
        hld(heavy[u], hd);
    for(auto v : g2[u])
    {
        if(v != par[u] && v != heavy[u])
        {
            hld(v, v);
        }
    }
}

int lca(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            v = par[head[v]];
        else
            u = par[head[u]];
    }
    return (pos[u] < pos[v]) ? u : v;
}


void down(int id, int l, int r, int mid)
{
    if(lazy[id] != -1)
    {
        st[id * 2] = lazy[id] * (mid - l + 1);
        st[id * 2 + 1] = lazy[id] * (r - mid);
        lazy[id * 2] = lazy[id];
        lazy[id * 2 + 1] = lazy[id];
        lazy[id] = -1;
    }
}

void updatep(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    updatep(id * 2, l, mid, pos, val);
    updatep(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

void updater(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id] = val * (r - l + 1);
        lazy[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    updater(id * 2, l, mid, u, v, val);
    updater(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
void updatepath(int u, int v, int val)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
        {
            swap(u, v);
        }
        updater(1, 1, tplt, pos[head[u]], pos[u], val);
        u = par[head[u]];
    }
    if(pos[v] > pos[u])
    {
        swap(u, v);
    }
    if(u != v)
    {
        updater(1, 1, tplt, pos[v] + 1, pos[u], val);
    }
}
int getpath(int u, int v)
{
    int res = 0;
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
        {
            swap(u, v);
        }
        res += get(1, 1, tplt, pos[head[u]], pos[u]);
        u = par[head[u]];
    }
    if(pos[v] > pos[u])
    {
        swap(u, v);
    }
    if(u != v)
    {
        res += get(1, 1, tplt, pos[v] + 1, pos[u]);
    }
    return res;
}
void read()
{
    cin >> n >> m >> q;
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb({v, i});
        g[v].pb({u, i});
        edg.pb({u, v});
    }
}

void solve()
{
    memset(lazy, -1, sizeof(lazy));
    tarjan(1, 0);
    for(auto [u, v] : edg)
    {
        if(partarjan[u] != partarjan[v])
        {
            g2[partarjan[u]].pb(partarjan[v]);
            g2[partarjan[v]].pb(partarjan[u]);
        }
    }
    for(int i = 1; i <= tplt; i++)
    {
        sort(g2[i].begin(), g2[i].end());
        g2[i].erase(unique(g2[i].begin(), g2[i].end()), g2[i].end());
    }
    par[1] = 0;
    dfs(1);
    cnt = 0;
    hld(1, 1);
    for(int i = 2; i <= tplt; i++)
    {
        updatep(1, 1, tplt, pos[i], 1);
    }
    int u, v, x, y;
    while(q--)
    {
        cin >> x >> y >> u >> v;
        x = partarjan[x];
        y = partarjan[y];
        u = partarjan[u];
        v = partarjan[v];
        updatepath(x, y, 0);
        cout << getpath(u, v) << "\n";
        updatepath(x, y, 1);
    }
}
