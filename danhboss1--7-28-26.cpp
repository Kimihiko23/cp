int f, w;
int n;
int s[100 + 23];
int sum = 0;
bitset<N> dp;
void read()
{
    cin >> w >> f;
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> s[i];
        sum += s[i];
    }
}
void solve()
{
    dp[0] = 1;
    for(int i = 1; i <= n; i++)
    {
        dp |= (dp << s[i]);
    }
    int ans = 1e18;
    for(int i = 0; i <= sum ; i++)
    {
        if(dp[i])
        {
            int a = i;
            int b = sum - i;
            int tam1 = (a + f - 1) / f;
            int tam2 = (b + w - 1) / w;
            ans = min(ans, max(tam1, tam2));
        }
    }
    cout << ans;

}
