#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 16 + 1;
const int M = (1 << N) + 23;
int n;
string g[N], w[N];
bool dd[N][N];
int dp[N][M];
void read()
{
    cin >> n;
    for(int i = 0; i < n; i++)
    {
        cin >> g[i] >> w[i];
    }
}
void solve()
{
    int ans = 1e18;
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < n; j++)
        {
            if(g[i] == g[j] || w[i] == w[j])
                dd[i][j] = true;
        }
    }
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < (1 << n); j++)
        {
            dp[i][j] = 0;
        }
    }
    for(int i = 0; i < n ; i++)
    {
        dp[i][(1 << i)] = 1;
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        for(int i = 0; i < n; i++)
        {
            if(mask & (1 << i))
                on.pb(i);
        }
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i != j && dd[i][j])
                {
                    dp[i][mask] = max(dp[i][mask], dp[j][mask ^ (1 << i)]);
                }
            }
            if(dp[i][mask] == 1)
            {
                ans = min(ans, (int)(n - on.size()));
            }
        }
    }
    cout << ans;
}
