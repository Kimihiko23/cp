using namespace std;
const int N =2e3+23;
priority_queue<pair<int, pair<int,int>> , vector< pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>>> pq;
// w, u, ty
int n, m;
vector<pair<int, int>> g[N];
int a[N];
int dist[N][N];
void dijkstra()
{
    pq.push({dist[1][1], {1, 1}});
    while(!pq.empty())
    {
        int w = pq.top().fi;
        int u = pq.top().se.fi;
        int ty = pq.top().se.se;
        pq.pop();
        if(u == n)
        {
            cout << dist[n][ty];
            return;
        }
        if(w > dist[u][ty])
            continue;
        if(dist[u][u] > dist[u][ty])
        {
            dist[u][u] = dist[u][ty];
            pq.push({dist[u][u], {u, u}});
        }
        for(auto i : g[u])
        {
            int v = i.se;
            int w1 = i.fi;
            if(dist[v][ty] > dist[u][ty] + w1 * a[ty])
            {
                dist[v][ty] = dist[u][ty] + w1 * a[ty];
                pq.push({dist[v][ty] ,{v, ty}});
            }
        }
    }
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        g[u].pb({w, v});
        g[v].pb({w, u});
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        for(int j = 1; j <= n; j++)
        {
            dist[i][j] = 1e18;
        }
    }

}
void solve()
{
    dist[1][1] = 0;
    dijkstra();
}

