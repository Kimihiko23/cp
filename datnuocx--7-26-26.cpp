int n;
vector<int> g[N], revg[N];
int dp[N];
int ans[N], sz[N];
void dfs(int u, int p)
{
    sz[u] = 1;
    for(auto v: g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dp[u] += dp[v];
        sz[u] += sz[v];
    }
    for(auto v: revg[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dp[u] += dp[v] + 1;
        sz[u] += sz[v];
    }
}
void reroot(int u, int p)
{
    for(auto v: g[u])
    {
        if(v == p)
            continue;
        // cout << v << "\n";
        int oldu = dp[u];
        int oldv = dp[v];
        int szu = sz[u];
        int szv = sz[v];

        sz[u] -= sz[v];
        sz[v] += sz[u];

        dp[u] -= dp[v];
        dp[v] += dp[u] + 1;
        
        ans[v] = dp[v];
        
        reroot(v, u);

        dp[v] = oldv;
        dp[u] = oldu;
        sz[v] = szv;
        sz[u] = szu;
    }
    for(auto v: revg[u])
    {
        if(v == p)
            continue;
        // cout << v << "\n";
        int oldu = dp[u];
        int oldv = dp[v];
        int szu = sz[u];
        int szv = sz[v];

        sz[u] -= sz[v];
        sz[v] += sz[u];

        dp[u] -= dp[v] + 1;
        dp[v] += dp[u];
 
        ans[v] = dp[v];
        reroot(v, u);

    

        dp[v] = oldv;
        dp[u] = oldu;
        sz[v] = szv;
        sz[u] = szu;
    }
}
