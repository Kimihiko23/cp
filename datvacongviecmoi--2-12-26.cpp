#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =2e5+23;
int par[N];
int sz[N], sum[N];
bool dd[N];
int n, m, q;
struct que
{
    char ty;
    int vt;
    int val;
};
vector<pair<int, int>> edge;
stack<int> ver[N];
vector<que> querry;
multiset<int> ms;
int findpar(int u)
{
    if(par[u] == u)
        return par[u];
    else
        return par[u] = findpar(par[u]);
}
void join(int u, int v)
{
    int x = findpar(u);
    int y = findpar(v);
    if(x != y)
    {
        if(sz[y] > sz[x])
        {
            swap(x,y);
        }
        par[y] = x;
        sz[x] += sz[y];
        sum[x] += sum[y];
    }
}
void read()
{
    querry.pb({' ', -1, -1});
    edge.pb({-1, -1});
    
    cin >> n >> m >> q;
    
    for(int i = 1; i <= n; i++)
    {
        int val;
        cin >> val;
        sum[i] = val;
        par[i] = i;
        sz[i] = 1;
        ver[i].push(val);
    }
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        edge.pb({u, v});
    }
    
    for(int i = 1; i <= q; i++)
    {
        char ty;
        cin >> ty;
        if(ty == 'D')
        {
            int vt;
            cin >> vt;
            dd[vt] = 1;
            querry.pb({ty, vt, -1});
        }
        else
        {
            int vt, val;
            cin >> vt >> val;
            ver[vt].push(val);
            sum[vt] = val;
            querry.pb({ty, vt, val});
        }
    }
}

void solve()
{
    int tam = -1e18;
    vector<int> ans;
    for(int i = 1; i <= n; i++)
    {
        ms.insert(sum[i]);
    }
    for(int i = 1; i <= m; i++)
    {
        if(!dd[i])
        {
            if(ms.find(sum[findpar(edge[i].fi)]) != ms.end())
                ms.erase(ms.find(sum[findpar(edge[i].fi)]));
            if(ms.find(sum[findpar(edge[i].se)]) != ms.end())
                ms.erase(ms.find(sum[findpar(edge[i].se)]));
            join(edge[i].fi, edge[i].se);
            ms.insert(sum[findpar(edge[i].fi)]);
        }
    }
    ans.pb(*ms.rbegin());
    for(int i = q; i >= 1; i--)
    {
        if(querry[i].ty == 'D')
        {
            int vt = querry[i].vt;
            int u = edge[vt].fi;
            int v = edge[vt].se;
            if(findpar(u) == findpar(v))
            {
                ans.pb(*ms.rbegin());
                continue;
            }
            else
            {
                ms.erase(ms.find(sum[findpar(u)]));
                ms.erase(ms.find(sum[findpar(v)]));
                join(u, v);
                tam = sum[findpar(u)];
                ms.insert(tam);
                ans.pb(*ms.rbegin());
            }
        }
        else
        {
            int vt = querry[i].vt;
            int vtpar = findpar(vt);
            int val = querry[i].val;
            ms.erase(ms.find(sum[vtpar]));
            sum[vtpar] -= ver[vt].top();
            ver[vt].pop();
            sum[vtpar] += ver[vt].top();
            ms.insert(sum[vtpar]);
            ans.pb(*ms.rbegin());
            // sum[vtpar] -= ver[vt].top();
            // sum[vt] -= ver[vt].top();
            // ver[vt].pop();
            // sum[vt] = ver[vt].top();
            // sum[vtpar] += val;

        }
        
    }
    reverse(ans.begin(), ans.end());
    for(int i = 1; i < ans.size(); i++)
    {
        cout << ans[i] << "\n";
    }
}

