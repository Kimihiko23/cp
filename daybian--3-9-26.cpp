using namespace std;
const int N =1e5+23;
map<int,int> mp;
int pre[N];
int n, k;

void read()
{
   cin >> n >> k;
   for(int i = 1; i <= n; i++)
   {
       cin >> pre[i];
       pre[i] += pre[i-1];
   }
   mp[0] = 1;
}
void solve()
{
   int ans = 0;
    for(int i = 1; i <= n; i++)
    {
         ans += mp[pre[i]-k];
         mp[pre[i]]++;
    }
    cout << ans;
}
