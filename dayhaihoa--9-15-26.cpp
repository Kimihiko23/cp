void solve()
{
    int ans = 0;
    for(int i = 0; i < n; i++) {
        int mx = a[i];
        int mn = a[i];
        for(int j = i; j < n; j++) 
        {
            mx = max(mx, a[j]);
            mn = min(mn, a[j]);
            if (mx - mn == j - i) 
            {
                ans++;
            }
        }
    }
    cout << ans << '\n';
}

