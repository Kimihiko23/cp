using namespace std;
const int N =1e6+23;
const int MOD = 1000020407;
int n, k;
int a[N];
bool check(int x)
{
    int cnt = 0;
    for(int i = 2; i <= n; i++)
    {
        cnt += (a[i] - a[i-1] - 1) / x;
    }
    return cnt <= k;
}
void read()
{   
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + n + 1);
    int l = 1, r = 1e18, ans = 1e18;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            ans = mid;
            r = mid - 1;
        }
        else l = mid + 1;
    }
    cout << ans;
}   

