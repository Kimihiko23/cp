void solve()
{
    int ans = 0;
    
    for (int j = 1; j <= n; j++) 
    {
        ans += cnt[a[j]];
        

        cnt[a[j]]++;
        

        if (j >= k + 1) 
        {
            cnt[a[j - k]]--;
        }
    }
    
    cout << ans << "\n";
}

