const int MOD = 1000020409;
const int N = 1e6 + 23;
struct que
{
    int l, r, id;
};
que Q[N];
int n, q;
int a[N];
int cnt[N];
int L = 1, R = 0;
int mo;
int ans[N];
int sum = 0;
void MO(int i)
{
    while(R < Q[i].r)
    {
        R++;
        sum -= cnt[a[R]] * cnt[a[R]] * a[R];
        cnt[a[R]]++;
        sum += cnt[a[R]] * cnt[a[R]] * a[R];
    }
    while(R > Q[i].r)
    {
        sum -= cnt[a[R]] * cnt[a[R]] * a[R];
        cnt[a[R]]--;
        sum += cnt[a[R]] * cnt[a[R]] * a[R];
        R--;
    }
    while(L < Q[i].l)
    {
        sum -= cnt[a[L]] * cnt[a[L]] * a[L];
        cnt[a[L]]--;
        sum += cnt[a[L]] * cnt[a[L]] * a[L];
        L++;
    }
    while(L > Q[i].l)
    {
        L--;
        sum -= cnt[a[L]] * cnt[a[L]] * a[L];
        cnt[a[L]]++;
        sum += cnt[a[L]] * cnt[a[L]] * a[L];
    }
    ans[Q[i].id] = sum;
}
bool cmp(que a, que b)
{
    if(a.l / mo != b.l / mo) return a.l < b.l;
    return a.r < b.r;
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> Q[i].l >> Q[i].r;
        Q[i].id = i;
    }
    mo = sqrt(n);
}
void solve()
{
    sort(Q + 1, Q + q + 1, cmp);
    for(int i = 1; i <= q; i++)
    {
        MO(i);
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
