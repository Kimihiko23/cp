#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =50+23;
int n, m;
int a[N][N];
bool dd[N][N];
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
void bfs(int x, int y)
{
    queue<pair<int, int>> q;
    q.push({x, y});
    dd[x][y] = true;
    vector<int> dx{0, 0, 1, 1, 1, -1, -1, -1};
    vector<int> dy{1, -1, 0, 1, -1, 0, 1, -1};
    while(!q.empty())
    {
        int xx = q.front().fi;
        int yy = q.front().se;
        q.pop();
        for(int i = 0; i < dx.size(); i++)
        {
            int xxx = xx + dx[i];
            int yyy = yy + dy[i];
            if(check(xxx, yyy) && a[xxx][yyy] == a[x][y] && !dd[xxx][yyy])
            {
                q.push({xxx, yyy});
                dd[xxx][yyy] = true;
            }
        }
    }
    
}
void read()
{
    if(n == 0 && m == 0)
    {
        exit(0);
    }
    swap(n, m);
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dd[i][j] = false;
        }
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(!dd[i][j])
            {
                bfs(i, j);
                if(a[i][j] == 1)
                {
                    ans++;
                    // cout << i << " " << j << "\n";
                }
            }
        }
    }
    cout << ans << "\n";
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    while(cin >> n >> m)
    {
        read();
        solve();
    }
} 
