void solve()
{
    int ans = 0;
    int dem = 0;
    for(auto i : mp)
    {
        if(i.se > ans)
        {
            ans = i.se;
            dem = 1;
        }
        else
        if(i.se == ans)
        {
            dem++;
        }
    }
    cout << ans << " " << dem;
}
