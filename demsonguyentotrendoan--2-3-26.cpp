using namespace std;
const int N =1e7+23;
int dd[N];
int q;
int pre[N];
void sieve()
{
    dd[0] = dd[1] = 1;
    for(int i = 2; i < N; i++)
    {
        if(!dd[i])
        for(int j = i * i; j < N; j+=i)
        {
            dd[j] = 1;
        }
    }
}

void read()
{
   cin >> q;
}

void solve()
{
   sieve();
   pre[0] = 1;
   for(int i = 1; i < N; i++)
   {
        pre[i] = pre[i-1];
        if(!dd[i])
            pre[i]++;
   }

   for(int i = 1; i <= q; i++)
   {
        int l, r;
        cin >> l >> r;
        cout << pre[r] - pre[l - 1] << "\n";
   }

}

