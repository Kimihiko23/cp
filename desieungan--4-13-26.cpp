#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
const int M = 30;
const int MOD = 1000020409;
vector<pair<int, int>> g[N];
vector<pair<int, int>> fg[N];
vector<pair<int, pair<int, int>>> edg;
int par[N];
int n, m;
int dp[N][30 + 23];
int h[N];
vector<int> special_nodes;
int d_special[45][N];
int dis[N];
set<int> s_nodes;
void dijkstra(int start_node, int idx) 
{
    for (int i = 1; i <= n; i++) d_special[idx][i] = 1e18;
    d_special[idx][start_node] = 0;
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    pq.push({0, start_node});

    while (!pq.empty()) {
        int d = pq.top().fi;
        int u = pq.top().se;
        pq.pop();
        if (d > d_special[idx][u]) continue;
        for (auto edge : fg[u]) 
        {
            if (d_special[idx][edge.fi] > d + edge.se) {
                d_special[idx][edge.fi] = d + edge.se;
                pq.push({d_special[idx][edge.fi], edge.fi});
            }
        }
    }
}
void dfs(int u, int p)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        int w = i.se;
        if (v == p) continue;
        h[v] = h[u] + 1;
        dis[v] = dis[u] + w;
        dp[v][0] = u;
        dfs(v, u);
    }
}
void init()
{
    for(int j = 1; j <= 30; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[i][j] = dp[dp[i][j-1]][j-1];
        }
    }
}
int lca(int u, int v)
{
    if (h[u] < h[v]) swap(u, v);
    for(int i = 30; i >= 0; i--)
    {
        if (h[dp[u][i]] >= h[v]) u = dp[u][i];
    }
    if (u == v) return u;
    for(int i = 30; i >= 0; i--)
    {
        if (dp[u][i] != dp[v][i])
        {
            u = dp[u][i];
            v = dp[v][i];
        }
    }
    return dp[u][0];
}
int dist(int u, int v)
{
    int w = lca(u, v);
    return dis[u] + dis[v] - 2*dis[w];
}
int find(int u)
{
    if (par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    par[u] = v;
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        fg[u].pb({v, w});
        fg[v].pb({u, w});
        edg.pb({w, {u, v}});

    }
}
void solve()
{
    sort(edg.begin(), edg.end());
    for(int i = 1; i <= n; i++) 
        par[i] = i;
    for(auto i : edg)
    {
        int w = i.fi;
        int u = i.se.fi;
        int v = i.se.se;
        if (find(u) != find(v))
        {
            join(u, v);
            g[u].pb({v, w});
            g[v].pb({u, w});
        }
        else
        {
            s_nodes.insert(u);
            s_nodes.insert(v);
        }
    }
    for (int node : s_nodes) special_nodes.pb(node);
    for (int i = 0; i < special_nodes.size(); i++)
        dijkstra(special_nodes[i], i);
    dp[1][0] = 0;
    dfs(1, 0);
    init();
    int q;
    cin >> q;
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        int ans = dist(u, v);
        for (int i = 0; i < special_nodes.size(); i++) 
            ans = min(ans, d_special[i][u] + d_special[i][v]);
        cout << ans << "\n";
    }
}   

