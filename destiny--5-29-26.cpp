const int MOD = 1000020409;
const int N = 3e5 + 23;
mt19937_64 rd(chrono::steady_clock::now().time_since_epoch().count());


ll rand(ll l, ll r)
{
    return uniform_int_distribution <int> (l, r) (rd);
}
struct que
{
    int l, r, id, k;
};
que Q[N];
int n, q;
int a[N];
int cnt[N];
int L = 1, R = 0;
int mo;
int ans[N];
void MO(int i)
{
    while(R < Q[i].r)
    {
        R++;
        // s.erase(s.find(cnt[a[R]]));
        cnt[a[R]]++;
        // s.insert(cnt[a[R]]);
    }
    while(R > Q[i].r)
    {
        // s.erase(s.find(cnt[a[R]]));
        cnt[a[R]]--;
        // s.insert(cnt[a[R]]);
        R--;
    }
    while(L < Q[i].l)
    {
        // s.erase(s.find(cnt[a[L]]));
        cnt[a[L]]--;
        // s.insert(cnt[a[L]]);
        L++;
    }
    while(L > Q[i].l)
    {
        L--;
        // s.erase(s.find(cnt[a[L]]));
        cnt[a[L]]++;
        // s.insert(cnt[a[L]]);
    }
    
}
bool cmp(que a, que b)
{
    if(a.l / mo != b.l / mo) return a.l < b.l;
    int id = a.l / mo;
    if(id & 1) return a.r < b.r;
    return a.r > b.r;
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> Q[i].l >> Q[i].r >> Q[i].k;
        Q[i].id = i;
    }
    mo = sqrt(n);
}
void solve()
{
    sort(Q + 1, Q + q + 1, cmp);
    for(int i = 1; i <= q; i++)
    {
        MO(i);
        int res = 1e18;
        for(int j = 1; j <= 100; j++)
        {
            int vt = rand(Q[i].l, Q[i].r);
            if(cnt[a[vt]] > ((Q[i].r - Q[i].l + 1)/ Q[i].k))
            {
                res = min(res, a[vt]);
            }
        }
        ans[Q[i].id] = res;
    }
    for(int i = 1; i <= q; i++)
    {
        if(ans[i] != 1e18)
            cout << ans[i] << "\n";
        else
            cout << -1 << "\n";
    }
}
