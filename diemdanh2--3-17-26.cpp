#define siesta main
using namespace std;
const int N =1e5+23;
int n, k1, k2;
int dp[N][11][11];
// ngay, sui, tre
const int MOD = 1e9+7;
void read()
{
    cin >> n >> k1 >> k2;
    dp[0][0][0] = 1;
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= k1; j++)
        {
            for(int x = 0; x < k2; x++)
            {
                dp[i][j][0] += dp[i - 1][j][x];
                dp[i][j][0] %= MOD;
            }       
        }
        for(int j = 1; j <= k1; j++)
        {
            for(int x = 0; x < k2; x++)
            {
                dp[i][j][0] += dp[i - 1][j - 1][x];
                dp[i][j][0] %= MOD;
            }
        }
        for(int j = 0; j <= k1; j++)
        {
            for(int x = 1; x < k2; x++)
            {
                dp[i][j][x] += dp[i - 1][j][x - 1];
                dp[i][j][x] %= MOD;
            }
        }
    }
    int ans = 0;
    for(int i = 0; i <= k1; i++)
    {
        for(int j = 0; j <= k2; j++)
        {
            ans += dp[n][i][j];
            ans %= MOD;
            // cout << dp[n][i][j] << " " << i << " " << j << "\n";
        }
    }
    cout << ans;
}
