int n, m, s;
vector<vector<pair<int, int>>> adj;

void read()
{
    cin >> n >> m >> s;
    adj.resize(n + 1);
    for (int i = 0; i < m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }
}
void solve()
{
    vector<int> dist(n + 1, INF);
    dist[s] = 0;
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    pq.push({0, s});
    while (pq.size())
    {
        int d = pq.top().fi;
        int u = pq.top().se;
        pq.pop();
        if (d > dist[u])
        {
            continue;
        }
        for (auto e : adj[u])
        {
            int v = e.fi;
            int w = e.se;
            if (dist[v] > dist[u] + w)
            {
                dist[v] = dist[u] + w;
                pq.push({dist[v], v});
            }
        }
    }
    for (int i = 1; i <= n; i++)
    {
        if (dist[i] == INF)
        {
            cout << -1 << " ";
        }
        else
        {
            cout << dist[i] << " ";
        }
    }
}
