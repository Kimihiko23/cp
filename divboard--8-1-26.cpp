int pre[N][N];
int n, m;
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}
void read()
{
    cin >> n >> m;
    int x;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> x;
            pre[i][j] = pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1] + x;
        }
    }
}
vector<int> good(int stx, int edx)
{
    vector<int> res;
    int vt = 1;
    int l = 1, r = m;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        int lef = cal(stx, 1, edx, mid);
        int rig = cal(stx, mid + 1, edx, m);
        if(lef <= rig)
        {
            vt = mid;
            l = mid + 1;
        }
        else r = mid - 1;
    }
    res.pb(vt);
    if(vt + 1 <= m)
        res.pb(vt + 1);
    return res;
}
void solve()
{
    int ans = 1e18;
    for(int i = 1; i <= n; i++)
    {
        vector<int> test1, test2;
        test1 = good(1, i);
        test2 = good(i + 1, n);
        for(auto x : test1)
        {
            for(auto y : test2)
            {
                int upl = cal(1, 1, i, x);
                int upr = cal(1, x + 1, i, m);
                int downl = cal(i + 1, 1, n, y);
                int downr = cal(i + 1, y + 1, n, m);
                int mn = min({upl, upr, downl, downr});
                int mx = max({upl, upr, downl, downr});
                ans = min(ans, mx - mn);
            }
        }
    }
    cout << ans;
}
