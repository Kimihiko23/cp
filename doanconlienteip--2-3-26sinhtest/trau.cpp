const int N =1e6+23;
int a[N];
int q, n;
void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
}

void solve()
{
   while(q--)
   {
        int ty;
        cin >> ty;
        if(ty == 1)
        {
            int l, r, x;
            cin >> l >> r >> x;
            for(int i = l; i <= r; i++)
            {
                a[i] = x;
            }
        }
        else
        {
            int l, r;
            cin >> l >> r;
            int tem = 0;
            int ans = 0;
            for(int i = l; i <= r; i++)
            {
                tem += a[i];
                ans = max(ans, tem);
                if(tem < 0)
                    tem = 0;
            }
            cout << ans << "\n";
        }
   }
}

