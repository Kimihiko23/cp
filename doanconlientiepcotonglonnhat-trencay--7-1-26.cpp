int head[N], pos[N], heavy[N];
vector<int> g[N];
int n, q;
int par[N];
int a[N];
struct node
{
    int pre = 0, suf = 0, sum = 0, ans = 0;
};
node st[N * 4];
int sz[N];
int lz[N * 4];
int change[N * 4];
int cnt = 0;
void dfs(int u)
{
    sz[u] = 1;
    int mx = 0;
    for(auto v : g[u])
    {
        if(v == par[u])
            continue;
        par[v] = u;
        dfs(v);
        sz[u] += sz[v];
        if(sz[v] > mx)
        {
            mx = sz[v];
            heavy[u] = v;
        }

    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    if(heavy[u])
        hld(heavy[u], hd);
    for(auto v : g[u])
    {
        if(v == par[u] || v == heavy[u])
            continue;
        hld(v, v);
    }
}
void down(int id, int l, int r)
{
    if(!change[id])
        return;
    int x = lz[id];
    lz[id] = 0;
    int mid = (l + r) / 2;
    st[id * 2].sum = (mid - l + 1) * x;
    st[id * 2 + 1].sum = (r - mid) * x;
    st[id * 2].pre = max(st[id * 2].sum, 0LL);
    st[id * 2 + 1].pre = max(st[id * 2 + 1].sum, 0LL);
    st[id * 2].suf = max(st[id * 2].sum, 0LL);
    st[id * 2 + 1].suf = max(st[id * 2 + 1].sum, 0LL);
    st[id * 2].ans = max(st[id * 2].sum, 0LL);
    st[id * 2 + 1].ans = max(st[id * 2 + 1].sum, 0LL);
    lz[id * 2] = x;
    lz[id * 2 + 1] = x;
    change[id * 2] = 1;
    change[id * 2 + 1] = 1;
    change[id] = 0;
}
void update(int id, int l, int r, int u, int v, int x)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id].sum = (r - l + 1) * x;
        st[id].pre = max(st[id].sum, 0LL);
        st[id].suf = max(st[id].sum, 0LL);
        st[id].ans = max(st[id].sum, 0LL);
        lz[id] = x;
        change[id] = 1;
        return;
    }
    down(id, l, r);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, x);
    update(id * 2 + 1, mid + 1, r, u, v, x);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum;
    st[id].pre = max(st[id * 2].pre, st[id * 2].sum + st[id * 2 + 1].pre);
    st[id].suf = max(st[id * 2 + 1].suf, st[id * 2 + 1].sum + st[id * 2].suf);
    st[id].ans = max({st[id * 2].ans, st[id * 2 + 1].ans, st[id * 2].suf + st[id * 2 + 1].pre});
}
node get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return {0, 0, 0, 0};
    if(l >= u && r <= v)
        return st[id];
    down(id, l, r);
    int mid = (l + r) / 2;
    node L = get(id * 2, l, mid, u, v);
    node R = get(id * 2 + 1, mid + 1, r, u, v);
    node res;
    res.sum = L.sum + R.sum;
    res.pre = max(L.pre, L.sum + R.pre);
    res.suf = max(R.suf, R.sum + L.suf);
    res.ans = max({L.ans, R.ans, L.suf + R.pre});
    return res;
}
void updatepath(int u, int v, int x)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            swap(u, v);
        update(1, 1, n, pos[head[u]], pos[u], x);
        u = par[head[u]];
    }
    if(pos[u] > pos[v])
        swap(u, v);
    update(1, 1, n, pos[u], pos[v], x);
}
int lca(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            swap(u, v);
        u = par[head[u]];
    }
    if(pos[u] > pos[v])
        swap(u, v);
    return u;
}
node merge(node L, node R)
{
    node res;
    res.sum = L.sum + R.sum;
    res.pre = max(L.pre, L.sum + R.pre);
    res.suf = max(R.suf, R.sum + L.suf);
    res.ans = max({L.ans, R.ans, L.suf + R.pre});
    return res;
}
node rev(node L)
{
    node res;
    res.sum = L.sum;
    res.pre = L.suf;
    res.suf = L.pre;
    res.ans = L.ans;
    return res;
}
void getpath(int u, int v)
{
    int tar = lca(u, v);
    node res1 = {0, 0, 0, 0}, res2 = {0, 0, 0, 0};
    while(head[u] != head[tar])
    {
        res1 = merge(res1, rev(get(1, 1, n, pos[head[u]], pos[u])));
        u = par[head[u]];
    }
    while(head[v] != head[tar])
    {
        res2 = merge(res2, rev(get(1, 1, n, pos[head[v]], pos[v])));
        v = par[head[v]];
    }
    res1 = merge(res1, rev(get(1, 1, n, pos[tar], pos[u])));
    if(pos[tar] + 1 <= pos[v])
    {
        res2 = merge(res2,
                     rev(get(1,1,n,pos[tar] + 1,pos[v])));
    }
    res2 = rev(res2);
    node res = merge(res1, res2);
    cout << res.ans << '\n';
}
