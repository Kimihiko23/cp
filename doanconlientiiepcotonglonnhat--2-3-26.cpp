using namespace std;
const int N =1e6+23;
struct ar
{
    int lr, lnor, nolr, nolnor, sz;
};
ar st[N * 4];
int lazy[N * 4];
ar emp = {0,(int) -1e18,(int) -1e18,(int) -1e18, 0};

ar combine(ar x, ar y)
{
    ar res;
    if (x.sz == 0)
        return y;
    if (y.sz == 0)
        return x;
    if(x.sz > 1 && y.sz > 1)
    {
    res.lr = x.lr + y.lr;
    res.lnor = max({x.lr + y.lnor, x.lr, x.lnor});
    res.nolr = max({x.nolr + y.lr, y.lr, y.nolr});
    res.nolnor = max({x.nolnor, y.nolnor, x.nolr, y.lnor, x.nolr + y.lnor});
    }
    else
    {
        if(x.sz == 1 && y.sz == 1)
        {
            res.lr = x.lr + y.lr;
            res.lnor = x.lr;
            res.nolr = y.lr;
            res.nolnor = -1e18;
        }
        else
        if(x.sz == 1)
        {
            res.lr = x.lr + y.lr;
            res.lnor = max(x.lr + y.lnor, x.lr);
            res.nolr = max(y.lr, y.nolr);
            res.nolnor = max(y.lnor, y.nolnor);
        }
        else
        if(y.sz == 1)
        {
            res.lr = x.lr + y.lr;
            res.lnor = max(x.lnor, x.lr);
            res.nolr = max(x.nolr + y.lr, y.lr);
            res.nolnor = max(x.nolr, x.nolnor);
        }
    }
    res.sz = x.sz + y.sz;
    return res;
}
void equa(int id, int val)
{
    st[id].lr = val;
    st[id].nolnor = -1e18;
    st[id].lnor = -1e18;
    st[id].nolr = -1e18;
    st[id].sz= 1;
}
int n, q;
int a[N];
void push(int id, int mid, int l, int r)
{
    if(lazy[id] == -1e18)
    {
        return;
    }
    int val = lazy[id];
    int deml = mid - l + 1;
    int demr = r - mid;
    st[id * 2].lr = deml * lazy[id];
    st[id * 2].lnor = (deml >= 3 ? (deml - 1) * val : -1e18);
    st[id * 2].nolnor = (deml >= 3 ? (deml - 2)*val : -1e18);
    st[id * 2].nolr = (deml >= 2 ? (deml - 1) * val : -1e18);
    lazy[id * 2] = lazy[id];


    st[id * 2 + 1].lr = demr * lazy[id];
    st[id * 2 + 1].lnor = (demr >= 2 ? (demr - 1) * val : -1e18);
    st[id * 2 + 1].nolnor = (demr >= 3 ? (demr - 2) * val : -1e18);    
    st[id * 2 + 1].nolr = (demr >= 2 ? (demr - 1) * val : -1e18);
    lazy[id * 2 + 1] = lazy[id];
    lazy[id] = -1e18;

}
void build(int l, int r, int id)
{
    if(l == r)
    {
        equa(id, a[l]);
        return;
    }
    int mid = (l + r)/2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
ar get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
            return emp;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l+r)/2;
    push(id, mid, l, r);
    return combine(get(l, mid, id * 2, u, v), get(mid + 1, r, id * 2 + 1, u, v));
}

void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u)
    {
        return;
    }
    if(l >= u && r <= v)
    {
        int dem = (r-l) + 1;
        st[id].lr = dem * val;
        st[id].lnor = (dem - 1) * val;
        st[id].nolnor = (dem - 2) * val;
        st[id].nolr = (dem - 1) * val;
        lazy[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    push(id, mid, l, r);
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1, u, v, val);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);

}
void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
   for(int i = 1; i <= n*4; i++)
   {
        lazy[i] = -1e18;
   }
}

void solve()
{
   build(1, n, 1);
 
   while(q--)
   {
        int type;
        cin >> type;
        if(type == 1)
        {
            int l, r, val;
            cin >> l >> r >> val;
            update(1, n, 1, l, r, val);
        }
        else
        {
            int l, r;
            cin >> l >> r;
            ar ans = get(1, n, 1, l, r);
            cout << max({ans.lnor, ans.lr, ans.nolnor, ans.nolr, (int)0}) << "\n";
        }
   }
   
}

