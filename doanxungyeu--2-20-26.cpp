#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m;
vector<int> g2[N];
int ndfs[N], low[N];
int dem = 0;
int tplt = 0;
stack<int> st;
int nen[N];
int leaf;
bool dd[N];
vector<pair<int, int>> edge, g1[N];
void dfs2(int u, int par)
{
    if(g2[u].size() == 1)
    {
        leaf++;
    }
    dd[u] = true;
    for(auto i : g2[u])
    {
        if(i != par)
        {
            dfs2(i, u);
        }
    }
}
void dfs(int u, int par)
{
    ndfs[u] = low[u] = ++dem;
    st.push(u);
    for(auto i : g1[u])
    {
        int v = i.fi;
        int id = i.se;
        if(id != par)
        {
            if(ndfs[v] == 0)
            {
                dfs(v, id);
                low[u] = min(low[u], low[v]);
            }
            else
            {
                low[u] = min(low[u], ndfs[v]);
            }
        }
    }
    if(ndfs[u] == low[u])
    {
        tplt++;
        while(!st.empty())
        {
            nen[st.top()] = tplt;
            // cout << st.top() << " ";
            if(st.top() == u)
            {
                st.pop();
                break;
            }
            st.pop();
        }
    }
}
void read()
{
   cin >> n >> m;
   for(int i = 1; i <= m; i++)
   {
        int u, v;
        cin >> u >> v;
        g1[u].pb({v, i});
        g1[v].pb({u, i});
        edge.pb({u, v});
   }
}
int ans = 0;
void solve()
{
   for(int i = 1; i <= n; i++)
   {
        if(ndfs[i] == 0)
        {
            dfs(i, -1);
        } 
   }
   for(auto i : edge)
   {
        if(nen[i.fi] != nen[i.se])
        {
            g2[nen[i.fi]].pb(nen[i.se]);
            g2[nen[i.se]].pb(nen[i.fi]);
        }
   }
   for(int i = 1; i <= tplt; i++)
   {
        if(dd[i] == true)
            continue;
        leaf = 0;
        dfs2(i, -1);
        ans += (leaf + 1)/2;
   }
   cout << ans;
   
}
