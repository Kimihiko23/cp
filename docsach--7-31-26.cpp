int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, k;
int a[N];
int check(int x)
{
    int cnt = 1;
    int ex = 1;
    for(int i = 2; i <= n; i++)
    {
        if(a[i] - a[ex] >= x)
        {
            cnt++;
            ex = i;
        }
    }
    return cnt;
}
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    int l = 0, r = 1e18;
    int ans = 0;
    // cout << check(3) << "\n";
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid) >= k)
        {
            l = mid + 1;
            ans = max(ans, mid);
        }
        else
            r = mid - 1;
    }
    cout << a[1] << " ";
    int cnt = 1;
    int ex = 1;
    for(int i = 2; i <= n; i++)
    {
        if(a[i] - a[ex] >= ans)
        {
            cout << a[i] << " ";
            cnt++;
            ex = i;
        }
        if(cnt == k)
            break;
    }
    

}
