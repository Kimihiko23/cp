const int N =2e6+23;
int dem[N];
int n, mx = 0;
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        int x;
        cin >> x;
        mx = max(mx, x);
        dem[x]++;
   }
}

void solve()
{
    int ans =0;
    for(int i = 1; i <= mx; i++)
    {
        int de = 0;
        for(int j = i; j <= mx; j+=i)
        {
            de += dem[j];
        }
        ans = max(ans, de * i);
    }
    cout << ans;
    
}

