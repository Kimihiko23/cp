void solve()
{
    int ans = 0;
    int l = 0, r = s.size() - 1;
    while (l < r)
    {
        // cout << "gay";
        if(s[l] != s[r])
        {
            // cout << "gay";
            if(s[l] != s[r] && s[l] != 'm' && s[r] != 'm'   )
            {
                cout << -1;
                return;
            }
            if(s[r] == 'm')
            {
                r--;
                ans++;
            }
            else
            {
                l++;
                ans++;
            }
        }
        else
        {
            l++;
            r--;
        }
    }
    cout << ans;
}

