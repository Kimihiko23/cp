using namespace std;
#define name "DOUBLEPENETRATION"
const int MOD = 1000020409;
const int N = 15000 + 23;
int n;
int pre[N];

int cal(int l, int r)
{
    return pre[r] - pre[l - 1];
}

void read()
{
    int x;
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        pre[i] = pre[i - 1] + x;
    }
}

void solve()
{
    int ans = 0;
    
    
    for (int l = 1; l <= n - 1; l++)
    {
        int k = l; 
        for (int r = l + 1; r <= n; r++)
        {
          
            while (k < r - 1 && cal(l, k) < cal(k + 1, r))
            {
                k++;
            }
            
    
            if (cal(l, k) == cal(k + 1, r))
            {
                ans = max(ans, r - l + 1);
            }
        }
    }
    cout << ans;
}

