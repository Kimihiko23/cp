int dp[N][N];
string s;
int n;
void read()
{
    cin >> s;
    n = s.length();
}
void solve()
{
    s = " " + s;
    dp[0][0] = 0;
    for(int i = 1; i <= n; i++)
        dp[i][i] = 1;
    for(int len = 2; len <= n; len++)
    {
        for(int i = 1; i + len - 1 <= n; i++)
        {
            int j = i + len - 1;
            dp[i][j] += dp[i + 1][j] + dp[i][j - 1] - dp[i + 1][j - 1];
            if(s[i] == s[j])
                dp[i][j] += dp[i + 1][j - 1] + 1;
            dp[i][j] = (dp[i][j] % MOD + MOD) % MOD;
            
        }
    }
    cout << dp[1][n];
}
