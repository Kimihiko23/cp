using namespace std;
const int MOD = 1000020409;
const int N =1e5+23;
int n, w;
int dp[N];
int a[N], b[N];
void read()
{
    cin >> n >> w;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i] >> b[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = w; j >= a[i]; j--)
        {
            dp[j] = max(dp[j], dp[j - a[i]] + b[i]);
        }
    }
    int ans = 0;
    for(int i = 0; i <= w; i++)
    {
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
