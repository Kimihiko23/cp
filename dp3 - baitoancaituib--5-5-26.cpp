{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> w[i] >> p[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= k; j++)
        {
            int tam = j - w[i];
            if(tam < 0)
                continue;
            dp[j] = max(dp[tam] + p[i], dp[j]);

        }
    }
    int ans = 0;
    for(int i = 0; i <= k; i++)
    {   
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
