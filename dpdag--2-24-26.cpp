using namespace std;
const int N =1e5+23;

vector<int> g[N];
int n, m;
int dp[N];
bool vis[N];
int ans = 0;
void dfs(int u)
{
    vis[u] = 1;
    for(auto v : g[u])
    {
        if(!vis[v])
        {
            dfs(v);
        }
        dp[u] = max(dp[u], dp[v]+1);
    }
    ans = max(ans, dp[u]);
}
void read()
{
   cin >> n >> m;
   for(int i = 1; i <= m; i++)
   {
       int u, v;
       cin >> u >> v;
       g[u].pb(v);
   }
}
void solve()
{
   for(int i = 1; i <= n; i++)
   {
       if(!vis[i])
       {
           dfs(i);
       }
   }
   cout << ans;
}
