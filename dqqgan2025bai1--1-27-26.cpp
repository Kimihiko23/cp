#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
using namespace std;
const int INF = 1e18;
const int N = 3e5+25; 

int n, q;
int a[N];

struct Node {
    int mx[3]; 
    int mn[3]; 
};

Node st[N * 4];


Node combine(Node x, Node y) {
    Node res;
    int vmx[6], vmn[6];

  
    for (int i = 0; i < 3; i++) {
        vmx[i] = x.mx[i];
        vmx[i + 3] = y.mx[i];
        vmn[i] = x.mn[i];
        vmn[i + 3] = y.mn[i];
    }

    
    sort(vmx, vmx + 6, greater<int>());
    
    sort(vmn, vmn + 6);

    for (int i = 0; i < 3; i++) {
        res.mx[i] = vmx[i];
        res.mn[i] = vmn[i];
    }
    return res;
}

void build(int id, int l, int r) {
    if (l == r) {
        st[id].mx[0] = a[l];
        st[id].mx[1] = -INF;
        st[id].mx[2] = -INF;

        st[id].mn[0] = a[l];
        st[id].mn[1] = INF;
        st[id].mn[2] = INF;
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}

Node query(int id, int l, int r, int u, int v) {
    if (v < l || r < u) {
        Node null_node;
        for (int i = 0; i < 3; i++) {
            null_node.mx[i] = -INF;
            null_node.mn[i] = INF;
        }
        return null_node;
    }
    if (u <= l && r <= v) return st[id];

    int mid = (l + r) / 2;
    return combine(query(id * 2, l, mid, u, v), query(id * 2 + 1, mid + 1, r, u, v));
}

void read() {
    cin >> n >> q;
    for (int i = 1; i <= n; i++) cin >> a[i];
}

void solve() {
    build(1, 1, n);
    while (q--) 
    {
        int ans=-INF;
        int l, r;
        cin >> l >> r;
        if(r - l + 1 < 5)
        {
            for(int i = l; i <= r; i++)
            {
                for(int j = i + 1; j <= r; j++)
                {
                    for(int k = j + 1; k <= r; k++)
                    {
                        ans = max(ans, a[i] * a[j] * a[k]);
                    }
                }
            }
        }
        else
        {
            int d[6];
            Node res = query(1, 1, n, l, r);
            for(int i = 0; i < 3; i++)
            {
                d[i] = res.mx[i];
                d[i + 3] = res.mn[i];
            }
            for(int i = 0; i <= 5; i++)
            {
                for(int j = i + 1; j <= 5; j++)
                {
                    for(int k = j + 1; k <= 5; k++)
                    {
                        ans = max(ans, d[i] * d[j] * d[k]);
                    }
                }
            }
            
        }
        cout << ans << "\n";
        
    }    
}

main() {
    ios::sync_with_stdio(false);
    cin.tie(0);
     freopen("input.txt","r",stdin);
     freopen("output.txt","w",stdout);
    read();
    solve();
}