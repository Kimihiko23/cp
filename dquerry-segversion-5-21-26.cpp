using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 2e5 + 23;
vector<pair<int, pair<int, int>>> b;
int a[N];
int n;
int st[N * 4];
int q;
map<int, int> last;
int ans[N];
void update(int l, int r, int id, int val, int pos)
{
    if (l > pos || r < pos)
    {
        return;
    }
    if (l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(l, mid, id * 2, val, pos);
    update(mid + 1, r, id * 2 + 1, val, pos);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int l, int r, int id, int u, int v)
{
    if (l > v || r < u)
    {
        return 0;
    }
    if (l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return get(l, mid, id * 2, u, v) + get(mid + 1, r, id * 2 + 1, u, v);
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    cin >> q;
    for(int i = 1; i <= q; i++)
    {
        int l, r;
        cin >> l >> r;
        b.pb({l, {r, i}});
    }
}
void solve()
{
    sort(b.begin(), b.end(), [](pair<int, pair<int, int>> a, pair<int, pair<int, int>> b)
    {
        return a.se.fi < b.se.fi;
    });
    int r = b[0].se.fi;
    for(int i = 1; i <= r; i++)
    {
        if (last[a[i]] != 0)
        {
            update(1, n, 1, 0, last[a[i]]);
        }
        last[a[i]] = i;
        update(1, n, 1, 1, i);
    }
    for(int i = 0; i < q; i++)
    {
        int l = b[i].fi;
        int r = b[i].se.fi;
        ans[b[i].se.se] = get(1, n, 1, l, r);
        if (i + 1 < q && b[i + 1].se.fi > r)
        {
            for(int j = r + 1; j <= b[i + 1].se.fi; j++)
            {
                if (last[a[j]] != 0)
                {
                    update(1, n, 1, 0, last[a[j]]);
                }
                last[a[j]] = j;
                update(1, n, 1, 1, j);
            }
        }
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
