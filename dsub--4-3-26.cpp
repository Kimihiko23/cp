const int N =1e6+23;
const int MOD = 1000020407;
const int base = 256;
int p[N] , pre[N];
string a , b;
int n, k;
int x = 0;
map<int, int> mp;
int add(int a , int b)
{
    return (a + b) % MOD;
}
int mul(int a , int b)
{
    return (a * b) % MOD;
}
int sub(int a , int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int f(int l , int r)
{
    return sub(pre[r] , mul(p[r - l + 1] , pre[l - 1]));
}
bool check(int mid)
{
    mp.clear();
    for(int i = 1; i + mid - 1 <= n; i++)
    {
        int h = f(i , i + mid - 1);
        mp[h]++;
        if(mp[h] >= k)
            return 1;
    }
    return 0;
}
void read()
{   
    cin >> n >> k >> a;
}
void solve()
{
    p[0] = 1;
    for(int i = 1; i <= n; i++)
    {
        p[i] = mul(p[i - 1] , base);
        pre[i] = add(mul(pre[i - 1] , base) , a[i - 1]);
    }
    int l = 1 , r = n , ans = 0;
    while(l <= r)
    {
        int mid = (l + r) >> 1;
        if(check(mid))
            ans = mid , l = mid + 1;
        else
            r = mid - 1;
    }
    cout << ans;
}   

