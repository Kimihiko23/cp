int m, n;
vector<int> a, b;

void read()
{
    cin >> m >> n;

    a.resize(m);
    b.resize(n);

    for (int i = 0; i < m; i++)
        cin >> a[i];

    for (int i = 0; i < n; i++)
        cin >> b[i];
}

bool ok(vector<int> &v)
{
    if (v.size() < 3)
        return false;

    for (int i = 1; i + 1 < (int)v.size(); i++)
        if ((v[i] - v[i - 1]) * (v[i] - v[i + 1]) <= 0)
            return false;

    return true;
}

bool check(vector<int> &v)
{
    int j = 0;

    for (int x : b)
    {
        if (j < (int)v.size() && x == v[j])
            j++;
    }

    return j == (int)v.size();
}

void solve()
{
    int ans = 0;

    for (int mask = 0; mask < (1 << m); mask++)
    {
        vector<int> cur;

        for (int i = 0; i < m; i++)
            if (mask >> i & 1)
                cur.pb(a[i]);

        if (!ok(cur))
            continue;

        if (!check(cur))
            continue;

        ans = max(ans, (int)cur.size());
    }

    cout << ans;
}

