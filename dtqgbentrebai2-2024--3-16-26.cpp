void read()
{
   cin >> d >> k >> a >> b >> t;
}
void solve()
{
   int ans = d * b;
   for(int i = 1; i <= d; i++)
   {
        int tam = d * b;
        tam = i * a + (i - 1)/k * t + (d - i) * b;
        
        ans = min(ans, tam);
   }
   cout << ans;
}
