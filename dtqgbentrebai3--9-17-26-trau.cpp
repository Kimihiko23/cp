set<int> s[N];
int n, m;
int own[N];
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        own[i] = i;
        s[i].insert(i);
    }
}
void solve()
{
    int u, v;
    while(m--)
    {
        cin >> u >> v;
        if(own[u] == own[v]) continue;
        // cout << own[u] << " " << own[v] << "\n";
        if(*s[own[u]].begin() > *s[own[v]].begin())
        {
            // cout << "gei1\n";
            int old = own[u];
            for(auto x : s[own[u]])
            {
                s[own[v]].insert(x);
                own[x] = own[v];
            }
            s[old].clear();
        }
        else
        {
            // cout << "gei2\n";
            // cout << own[u] << " " << own[v] << "\n";
            int old = own[v];
            for(auto x : s[own[v]])
            {
                s[own[u]].insert(x);
                own[x] = own[u];
            }
            s[old].clear();
        }
        // cout << own[u] << " " << own[v] << "\n";
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        if(s[i].size() > 0)
        {
            // cout << "set " << i << ": " << "\n";
            ans++;
        }
    }
    cout << ans << "\n";
}
