int par[N], sz[N], mn[N];
int findpar(int u)
{
    if (par[u] == u) return u;
    return par[u] = findpar(par[u]);
}
void join(int u, int v)
{
    u = findpar(u);
    v = findpar(v);
    if (u == v) return;
    if (sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    mn[u] = min(mn[u], mn[v]);
}
int n, m;
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
        mn[i] = i;
    }
}
void solve()
{
    int u, v;
    while(m--)
    {
        cin >> u >> v;
        join(u, v);
    }
    set<int> st;
    for(int i = 1; i <= n; i++)
    {
        st.insert(findpar(i));
    }
    cout << st.size() << "\n";
}
