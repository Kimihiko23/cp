int dis[N];
priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
void dijkstra()
{
    memset(dis, 0x3f, sizeof(dis));
    int s = lower_bound(id.begin(), id.end(), make_pair(st, sth)) - id.begin();
    dis[s] = 0;
    pq.push({0, s});
    while(!pq.empty())
    {
        int u = pq.top().se;
        int w = pq.top().fi;
        pq.pop();
        if(w > dis[u])
        {
            continue;
        }
        for(auto i: g[u])
        {
            int v = i.fi;
            int ww = i.se;
            if(dis[v] > dis[u] + ww)
            {
                dis[v] = dis[u] + ww;
                pq.push({dis[v], v});
            }
        }
    }
}
void read()
{
    cin >> n >> m >> st >> ed >> sth >> edh;
    id.pb({st, sth});
    difh[st].pb(sth);
    id.pb({ed, edh});
    difh[ed].pb(edh);
    for (int i = 1; i <= m; i++)
    {
        int u, v, h;
        cin >> u >> v >> h;
        edg.pb({h, {u, v}});
        id.pb({u, h});
        id.pb({v, h});
        difh[u].pb(h);
        difh[v].pb(h);
    }
}
void solve()
{
    sort(id.begin(), id.end());
    id.erase(unique(id.begin(), id.end()), id.end());
    for(int i = 1; i <= n; i++)
    {
        sort(difh[i].begin(), difh[i].end());
        difh[i].erase(unique(difh[i].begin(), difh[i].end()), difh[i].end());
        for(int j = 0; j < (int)difh[i].size() - 1; j++)
        {
            int u = lower_bound(id.begin(), id.end(), make_pair(i, difh[i][j])) - id.begin();
            int v = lower_bound(id.begin(), id.end(), make_pair(i, difh[i][j + 1])) - id.begin();
            int w = difh[i][j + 1] - difh[i][j];
            g[u].pb({v, w});
            g[v].pb({u, w});
        }
    }
    for(auto x : edg)
    {
        int u = lower_bound(id.begin(), id.end(), make_pair(x.se.fi, x.fi)) - id.begin();
        int v = lower_bound(id.begin(), id.end(), make_pair(x.se.se, x.fi)) - id.begin();
        g[u].pb({v, 0});
        g[v].pb({u, 0});
    }
    dijkstra();
    int e = lower_bound(id.begin(), id.end(), make_pair(ed, edh)) - id.begin();
    cout << dis[e];

}
