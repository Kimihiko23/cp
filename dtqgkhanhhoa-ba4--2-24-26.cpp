const int N = 500 + 23;
int pre[N][N];
int n, m, a, b;
int pre1[N];

int cal(int x1, int y1, int x2, int y2)
{
    return pre[x2][y2] - pre[x1-1][y2] - pre[x2][y1-1] + pre[x1-1][y1-1];
}
void read()
{
   cin >> n >> m >> a >> b;
   if(a > b) swap(a, b);
   int x;
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            cin >> x;
            pre[i][j] = pre[i-1][j] + pre[i][j-1] - pre[i-1][j-1] + x;
        }
   }
}
void solve()
{
   int ans = 1e18;
   int tam = 0;
   vector<int> tem;
   for(int i = 1; i <= n; i++)
   {
        for(int j = i; j <= n; j++)
        {
            memset(pre1, 0, sizeof(pre1));
            for(int z = 1; z <= m; z++)
            {
                int tam1 = cal(i, z, j, z);
                pre1[z] = pre1[z-1] + tam1;
            }
            for(int r = 1; r <= m; r++)
            {
                int left = 1, right = r, res = -1;
                while(left <= right)
                {
                    int mid = (left + right) >> 1;
                    if(pre1[mid - 1] <= pre1[r] -a)
                    {
                        res = mid;
                        left = mid + 1;
                    }
                    else
                    {
                        right = mid - 1;
                    }
                }
                if(res != -1)
                {
                    int s = pre1[r] - pre1[res - 1];
                    if(s <= b)
                    {
                        ans = abs(s - a) + abs(s - b);
                        cout << ans;
                        exit(0);
                    }
                    else
                    {
                        ans = min(ans, abs(s - a) + abs(s - b));
                    }

                }
                left = 1;
                right = r;
                res = -1;
                while(left <= right)
                {
                    int mid = (left + right) >> 1;
                    if(pre1[mid - 1] > pre1[r] -a)
                    {
                        res = mid;
                        right = mid - 1;
                    }
                    else
                    {
                        left = mid + 1;
                    }
                }
                if(res != -1)
                {
                    int s = pre1[r] - pre1[res - 1];
                    ans = min(ans, abs(s - a) + abs(s - b));
                }
               
            }
        }
   }
   cout << ans;
}
