int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1, 1, 1, -1, -1}, dy{-1, 1, 0, 0, 1, -1, 1, -1};
bool dd[N][N];
int n, m;
int a[N][N];
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
int ans = 0;
void bfs(int stx, int sty)
{
    int tam = 0;
    int ty = (a[stx][sty] > 0 ? 1 : -1);
    queue<pair<int, int>> q;
    q.push({stx, sty});
    dd[stx][sty] = 1;
    while(!q.empty())
    {
        int x = q.front().fi, y = q.front().se;
        tam += a[x][y];
        q.pop();
        for(int i = 0; i < 8; i++)
        {
            int xx = x + dx[i], yy = y + dy[i];
            if(ty == 1)
            {
                if(check(xx, yy) && !dd[xx][yy] && a[xx][yy] > 0)
                {
                    dd[xx][yy] = 1;
                    q.push({xx, yy});
                }
            }
            else
            {
                if(check(xx, yy) && !dd[xx][yy] && a[xx][yy] <= 0)
                {
                    dd[xx][yy] = 1;
                    q.push({xx, yy});
                }
            }
        }
    }
    ans = max(ans, tam);
}
void read()
{
    cin >> n >> m;
    // swap(n, m);
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(!dd[i][j])
            {
                bfs(i, j);
            }
        }
    }
    cout << ans;
}
