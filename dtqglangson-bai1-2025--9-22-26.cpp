vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int st[N * 4][3], a[N], n, q;
string s;
void update(int l, int r, int id, int vt, int val, int ty)
{
    if(l > vt || r < vt)
        return;
    if(l == r)
    {
        st[id][ty] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(l, mid, id * 2, vt, val, ty);
    update(mid + 1, r, id * 2 + 1, vt, val, ty);
    st[id][ty] = st[id * 2][ty] + st[id * 2 + 1][ty];
}
int get(int l, int r, int id, int u, int v, int ty)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
        return st[id][ty];
    int mid = (l + r) / 2;
    return get(l, mid, id * 2, u, v, ty) + get(mid + 1, r, id * 2 + 1, u, v, ty);
}
