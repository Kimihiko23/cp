int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> 
    dxp{0, 0, 1, -1, 1, 1, -1, -1}, 
    dyp{-1, 1, 0, 0, 1, -1, 1, -1}, 
    dxk{1, 1, -1, -1, 2, 2, -2, -2}, 
    dyk{2, -2, 2, -2, 1, -1, 1, -1};
char a[N][N];
int n, m;
int dis[N][N][2];
int ans[N][N][2];
int cnt[N][N][2];
int sum = 0;
bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
void read()
{
    bool onlyone = true;
    int cnt = 0;
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            // dis[i][j][0] = dis[i][j][1] = INF;
            if(a[i][j] == 'M' || a[i][j] == 'T')
            {
                sum++;
                cnt++;
                if(cnt > 1)
                {
                    onlyone = false;
                }
            }
        }
    }
    if(onlyone)
    {
        cout << 0;
        exit(0);
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(a[i][j] == 'M' || a[i][j] == 'T')
            {
                // cout << i << " " << j << endl;
                for(int k = 1; k <= n; k++)
                {
                    for(int l = 1; l <= m; l++)
                    {
                        dis[k][l][0] = dis[k][l][1] = INF;
                    }
                }
                dis[i][j][0] = 0;
                vector<int> dx, dy;
                if(a[i][j] == 'T')
                {

                    dx = dxp;
                    dy = dyp;
                }
                else if(a[i][j] == 'M')
                {
                    // cout << 1;
                    dx = dxk;
                    dy = dyk;
                }
                queue<pair<int, pair<int, int>>> q;
                q.push({0, {i, j}});
                while(!q.empty())
                {
                    auto tam = q.front();
                    q.pop();
                    int ty = tam.fi;
                    int x = tam.se.fi;
                    int y = tam.se.se;
                    for(int k = 0; k < dx.size(); k++)
                    {
                        int xx = x + dx[k];
                        int yy = y + dy[k];
                        if(check(xx, yy) && 
                            dis[xx][yy][(ty + 1) % 2] > dis[x][y][ty] + 1 &&
                            a[xx][yy] != '#')
                        {
                            dis[xx][yy][(ty + 1) % 2] = dis[x][y][ty] + 1;
                            q.push({(ty + 1) % 2, {xx, yy}});
                        }
                    }
                }
                bool bad = true;
                for(int k = 1; k <= n; k++)
                {
                    for(int l = 1; l <= m; l++)
                    {
                        if(dis[k][l][0] != INF)
                        {
                            cnt[k][l][0]++;
                            ans[k][l][0] = max(ans[k][l][0], dis[k][l][0]);
                            if(k != i || l != j)
                            {
                                bad = false;
                            }
                        }
                        if(dis[k][l][1] != INF)
                        {
                            cnt[k][l][1]++;
                            ans[k][l][1] = max(ans[k][l][1], dis[k][l][1]);
                            if(k != i || l != j)
                            {
                                bad = false;
                            }
                        }
                    }
                }
                if(bad)
                {
                    cout << -1;
                    exit(0);
                }
            }
        }
    }
    int res = 1e18;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            if(ans[i][j][0] != 0 && cnt[i][j][0] == sum)
            {
                res = min(res, ans[i][j][0]);
            }
            if(ans[i][j][1] != 0 && cnt[i][j][1] == sum)
            {
                res = min(res, ans[i][j][1]);
            }
        }
    }
    if(res == 1e18)
    {
        cout << -1;
        exit(0);
    }
    cout << res;
}
