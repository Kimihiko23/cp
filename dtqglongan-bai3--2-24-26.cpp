using namespace std;
const int N = 500 + 23;
int pre[N][N];
int n, m;


int cal(int x1, int y1, int x2, int y2)
{
    return pre[x2][y2] - pre[x1-1][y2] - pre[x2][y1-1] + pre[x1-1][y1-1];
}
void read()
{
   cin >> n >> m;
   int x;
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            cin >> x;
            pre[i][j] = pre[i-1][j] + pre[i][j-1] - pre[i-1][j-1] + x;
        }
   }
}
void solve()
{
   int ans = 0;
   int tam = 0;
   vector<int> tem;
   for(int i = 1; i <= n; i++)
   {
        for(int j = i; j <= n; j++)
        {
            tem.clear();
            for(int z = 1; z <= m; z++)
            {
                int tam1 = cal(i, z, j, z);
                tem.pb(tam1);
            }
            tam = 0;
            for(auto z : tem)
            {
                tam += z;
                ans = max(ans, tam);
                if(tam < 0)
                {
                    tam = 0;
                }
            }
        }
   }
   cout << ans;
}
