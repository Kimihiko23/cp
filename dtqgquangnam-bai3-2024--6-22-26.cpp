const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
int n, m, k;
vector<pair<int, int>> edg;
vector<int> g[N];
int f[N];
int L[N], R[N];
int cnt = 0;
int par[N][64];
int h[N];
void dfs(int u, int p)
{
    L[u] = ++ cnt;
    for(auto v : g[u])
    {
        if(v == p) continue;
        par[v][0] = u;
        h[v] = h[u] + 1;    
        dfs(v, u);
    }
    R[u] = cnt;
}
void init()
{
    for(int j = 1; j <= 60; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);
    while(x > 0)
    {
        for(int i = tam; i >= 0; i--)
        {
            if((1 << i) <= x)
            {
                x -= 1 << i;
                u = par[u][i];
            }
        }
    }
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
void read()
{
    cin >> n >> m >> k;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        edg.pb({u, v});
        g[u].pb(v);
        g[v].pb(u);
    }
}
void dfs2(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs2(v, u);
        f[u] += f[v];
    }
}
bool cmp(int a, int b)
{
    return L[a] < L[b];
}
void solve()
{
    dfs(1, -1);
    init();
    while(m--)
    {
        int x;
        cin >> x;
        int vt;
        // cout << x;
        vector<int> a;
        for(int i = 1; i <= x; i++)
        {
            cin >> vt;
            a.pb(vt);
        }
        sort(a.begin(), a.end(), cmp);
        for(auto i : a)
        {
            f[i]++;
        }
        for(int i = 1; i < x; i++)
        {
            int u = a[i - 1];
            int v = a[i];
            int w = lca(u, v);
            f[w]--;
        }
        f[lca(a[0], a[x - 1])]--;
    }
    vector<int> ans;
    // cout << n;
    
    dfs2(1, -1);
    // for(int i = 1; i <= n; i++)
    // {
    //     cout << f[i] << " ";
    // }
    for(int i = 0; i < n - 1; i++)
    {
        int u = edg[i].fi;
        int v = edg[i].se;
        // cout << u << " " << v << "\n";
        int x = u;
        if(par[v][0] == u)
        {
            x = v;
        }
        if(f[x] >= k)
        {
            ans.pb(i + 1);
        }
    }
    cout << ans.size() << "\n";
    for(auto i : ans)
    {
        cout << i << " ";
    }
}
