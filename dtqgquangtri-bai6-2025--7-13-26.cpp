mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int sz[N];
int par[N];
int mx[N];
int n, m, q;
struct edge
{
    int u, v, w;
};
struct query
{
    int st, need;
};
query a[N];
vector<edge> g;
int L[N], R[N], ans[N];
vector<int> check[N];
bool cmp(edge a, edge b)
{
    return a.w < b.w;
}
int find(int u)
{
    if (par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v, int id)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    if (sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    mx[u] = max({mx[u], mx[v], g[id].w});
}

void read()
{
    cin >> n >> m >> q;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        g.pb({u, v, w});
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> a[i].st >> a[i].need;
        L[i] = 0;
        R[i] = m;
        ans[i] = -1;
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
        mx[i] = 0;
    }
    sort(g.begin(), g.end(), cmp);
    while(1)
    {
        bool stop = true;
        for(int i = 1; i <= q; i++)
        {
            if(L[i] > R[i]) continue;
            stop = false;
            int mid = (L[i] + R[i]) / 2;
            check[mid].pb(i);
        }
        if(stop) break;
        for(int i = 0; i <= m; i++)
        {
            if(i > 0)
            {
                join(g[i - 1].u, g[i - 1].v, i - 1);
            }
            for(auto id : check[i])
            {
                int st = a[id].st;
                int need = a[id].need;
                int root = find(st);
                if(sz[root] >= need + 1)
                {
                    if(i == 0) ans[id] = 0;
                    else ans[id] = mx[root];
                    R[id] = i - 1;
                }
                else
                {
                    L[id] = i + 1;
                }
            }
            check[i].clear();
        }
        for(int i = 1; i <= n; i++)
        {
            par[i] = i;
            sz[i] = 1;
            mx[i] = 0;
        }
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
