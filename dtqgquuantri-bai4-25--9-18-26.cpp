int binpow(int x, int pw)
{
    int ans = 1;
    while (pw) 
    {
        if (pw & 1) ans *= x;
        ans %= MOD;
        x *= x;
        x %= MOD;
        pw >>= 1;
        
    }
    return ans;
}
int fact[N], invfact[N], d[N];
void precompute()
{
    fact[0] = 1;
    for(int i = 1; i < N; i++)
    {
        fact[i] = fact[i - 1] * i % MOD;
    }
    invfact[N - 1] = binpow(fact[N - 1], MOD - 2);
    for(int i = N - 2; i >= 0; i--)
    {
        invfact[i] = invfact[i + 1] * (i + 1) % MOD;
    }
    d[0] = 1;
    d[1] = 0;
    for(int i = 2; i < N; i++)
    {
        d[i] = (i - 1) * (d[i - 1] + d[i - 2]);
        d[i] %= MOD;
    }
}
int cnk(int n, int k)
{
    if(k < 0 || k > n) return 0;
    return fact[n] * invfact[k] % MOD * invfact[n - k] % MOD;
}
int n, a, b;
void read()
{
    cin >> n >> a >> b;
}
void solve()
{
    precompute();
    int ans = 0;
    for(int i = a; i <= b; i++)
    {
        ans += cnk(n, i) * d[n - i];
        ans %= MOD;
    }
    cout << ans;
}
