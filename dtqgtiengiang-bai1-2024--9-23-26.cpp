string s;
int n;
int t = 1e18;
void read()
{
    cin >> n >> s;
    int cnt = 0;
    int start_idx = -1;
    
    for(int i = 0; i < n; i++)
    {
        if(s[i] == '1')
        {
            if(cnt == 0) start_idx = i;
            cnt++;
        }
        if(s[i] == '0' || i == n - 1)
        {
            if(cnt > 0)
            {
                bool is_prefix = (start_idx == 0);
                bool is_suffix = (i == n - 1 && s[i] == '1');

                if(is_prefix && is_suffix)
                {
                    continue;
                }
                else if(is_prefix || is_suffix)
                {
                    t = min(t, cnt - 1);
                }
                else
                {
                    t = min(t, (cnt - 1) / 2);
                }
            }
            cnt = 0;
        }
    }
}
void solve()
{
    int ans = 0;
    int cnt = 0;
    // t--;
    // cout << t << "\n";
    for(int i = 0; i < n; i++)
    {
        if(s[i] == '1') cnt++;
        if(s[i] == '0' || i == n - 1)
        {
            ans += (cnt + 2 * t) / (2 * t + 1);
            cnt = 0;
        }
    }
    cout << ans;
}
