#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=200+23;
int n, m, k;
int pre[N][N];
int a[N][N];
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx-1][edy] - pre[edx][sty - 1] + pre[stx-1][sty-1];
}
void read()
{
   cin >> n >> m >> k;
   for(int i = 1; i <= n ; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            pre[i][j]= pre[i-1][j] + pre[i][j-1] + a[i][j] - pre[i-1][j-1];
        }
   }
}
void solve()
{
    int ans=0;
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= i ; j++)
        {
            int pre1[N];
            memset(pre1, 0, sizeof(pre1));
            for(int z = 1; z <= m; z++)
            {
                pre1[z]=pre1[z-1]+cal(j,z,i,z);
                int l=0, r = z;
                while(l <= r)
                {
                    int mid = (l+r)/2;
                    int tam=pre1[z]-pre1[mid];
                    if(tam<=k)
                    {
                        ans=max(ans,(z-mid)*(i-j+1));
                        r=mid-1;
                    }
                    else
                    {
                        l=mid+1;
                    }
                }
            }
            
            
        }
   }
   cout << ans;
   
   
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
