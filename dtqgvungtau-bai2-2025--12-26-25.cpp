#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=1e6+23;
vector<int> g0[N],g1[N];
int dist[N];
int n,m;
bool dd[N];
// duong di ngan nhat trong do thi thi khong can danh dau da tham
void bfs01()
{
    deque<pair<int,int>> dq;
    dist[1]=0;
    dq.push_front({1,0});
    dd[1]=true;
    while(!dq.empty())
    {
        int u,w;
        u=dq.front().fi;
        w=dq.front().se;
        dq.pop_front();
        for(auto i: g0[u])
        {
            if(dist[i]>w)
            {
             
                dist[i]=w;
                dq.push_front({i,w});
            }
        }
        for(auto i: g1[u])
        {
            if(dist[i]>w+1)
            {
                
                dist[i]=w+1;
                dq.push_back({i,dist[i]});
            }
        }
    }
    if(dist[n]!=1e18)
    {
        cout << dist[n];
    }
    else
    cout << -1;

}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u,v;
        cin >> u >> v;
        g0[u].pb(v);
        g1[v].pb(u);
    }
    for(int i = 1; i <= n; i++)
    {
     
        dist[i]=1e18;
    }

}

void solve()
{
    bfs01();
}

