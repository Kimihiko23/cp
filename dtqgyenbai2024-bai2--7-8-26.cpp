mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}


long long fac[N], invfac[N];

long long pw(long long a, long long b)
{
    long long res = 1;
    while (b)
    {
        if (b & 1) res = res * a % MOD;
        a = a * a % MOD;
        b >>= 1;
    }
    return res;
}

void init()
{
    fac[0] = 1;
    for (int i = 1; i < N; i++)
        fac[i] = fac[i - 1] * i % MOD;

    invfac[N - 1] = pw(fac[N - 1], MOD - 2);

    for (int i = N - 2; i >= 0; i--)
        invfac[i] = invfac[i + 1] * (i + 1) % MOD;
}

long long C(int n, int k)
{
    if (k < 0 || k > n) return 0;
    return fac[n] * invfac[k] % MOD * invfac[n - k] % MOD;
}
map<int, int> mp;
int n, q;
int ans[N];
int k[N];
void read()
{
    cin >> n >> q;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        mp[x]++;
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> k[i];
    }
}
void solve()
{
    init();
    for(auto it : mp)
    {
        int cnt = it.se;
        for(int i = 1; i <= q; i++)
        {
            if(cnt >= k[i])
            {
                ans[i] += C(cnt, k[i]);
                ans[i] %= MOD;
            }
        }
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
