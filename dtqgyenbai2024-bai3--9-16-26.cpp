int dp[5][N][N];
int a[N][N], ans[N];
int n, q;
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            cin >> a[i][j];
        }
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        dp[0][i][1] = a[i][1];
        dp[1][1][i] = a[1][i];
    }
    for(int j = 2; j <= n; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[0][i][j] = max({dp[0][i - 1][j - 1], dp[0][i][j - 1], dp[0][i + 1][j - 1]}) + a[i][j];
        }
    }
    for(int i = 2; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[1][i][j] = max({dp[1][i - 1][j], dp[1][i - 1][j - 1], dp[1][i - 1][j + 1]}) + a[i][j];
        }
    }
    for(int i = 1; i <= n; i++)
    {
        ans[0] = max(ans[0], dp[0][i][n]);
        ans[1] = max(ans[1], dp[1][n][i]);
    }
    // cout << ans[0];

    int side = 0;
    while(q--)
    {
        char x; int mv;
        cin >> x >> mv;
        if(x == 'R')
            side += mv;
        if(x == 'L')
            side -= mv;
        side = (side % 2 + 2) % 2;
        if(x == '3')
            cout << ans[side] << "\n";
    }
}
