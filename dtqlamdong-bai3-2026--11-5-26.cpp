int add(int a , int b)
{
    return (a + b) % MOD;
}
int mul(int a , int b)
{
    return (a * b) % MOD;
}
void dfs(int u, int p)
{
    in[u] = out[u] = ++timer;
    for(auto v : g[u])
    {
        if(v == p) continue;
        h[v] = h[u] + 1;
        par[0][v] = u;
        dfs(v, u);
    }
    out[u] = timer;
}
bool isancs(int u, int v)
{
    return in[u] <= in[v] && out[v] <= out[u];
}
bool cmp(int u, int v)
{
    return in[u] < in[v];
}
void init()
{
    for(int i = 1; i < 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            par[i][j] = par[i - 1][par[i - 1][j]];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    for(int i = 19; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v]) u = par[i][u];
    }
    if(u == v) return u;
    for(int i = 19; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            u = par[i][u];
            v = par[i][v];
        }
    }
    return par[0][u];
}
int dis(int u, int v)
{
    return h[u] + h[v] - 2 * h[lca(u, v)];
}
vector<int> vertex;
void dfs2(int u, int p, int typ)
{
    sum1[u] = cnt1[u];
    sum2[u] = cnt2[u];
    for(auto i : gvt[u])
    {
        int v = i.fi;
        int ww = i.se;
        if(v == p) continue;
        dfs2(v, u, typ);
        sum1[u] += sum1[v];
        sum2[u] += sum2[v];
        ans = add(ans, mul( add(mul(sum1[v], ty[typ + 1].size() - sum2[v]),
        mul(sum2[v], ty[typ].size() - sum1[v])), ww));
    }
}
int buildvt()
{
    vector<int> v;
    for(auto u : vertex)
    {
        while(v.size() >= 2 && !isancs(v.back(), u))
        {
            int x = v[v.size() - 2];
            int y = v.back();
            int w = dis(x, y);
            w %= MOD;
            // gvt[y].pb({x, w});
            gvt[x].pb({y, w});
            v.pop_back();
        }
        v.pb(u);
    }
    while(v.size() >= 2)
    {
        int u = v.back();
        int x = v[v.size() - 2];
        int w = dis(x, u);
        w %= MOD;
        gvt[x].pb({u, w});
        v.pop_back();
    }
    return v[0];
}
void virtualtree()
{
    sort(vertex.begin(), vertex.end(), cmp);
    int szvt = vertex.size();
    for(int i = 0; i < szvt - 1; i++)
    {
        vertex.pb(lca(vertex[i], vertex[i + 1]));
    }
    sort(vertex.begin(), vertex.end(), cmp);
    vertex.erase(unique(vertex.begin(), vertex.end()), vertex.end());
    int root = buildvt();
}
