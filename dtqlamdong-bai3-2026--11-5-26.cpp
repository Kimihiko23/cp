void solve()
{
    dfs(1, 0);
    init();

    vector<int> pre(m + 2, 1), suf(m + 2, 1);
    for (int i = 1; i <= m; i++) pre[i] = mul(pre[i - 1], ty[i].size());
    for (int i = m; i >= 1; i--) suf[i] = mul(suf[i + 1], ty[i].size());

    int final_res = 0;

    for (int i = 1; i < m; i++)
    {
        for (auto u : ty[i])
        {
            cnt1[u] = 1;
            vertex.pb(u);
        }
        for (auto u : ty[i + 1])
        {
            cnt2[u] = 1;
            vertex.pb(u);
        }
        sort(vertex.begin(), vertex.end(), cmp);
        int szvt = vertex.size();
        for (int j = 0; j < szvt - 1; j++)
        {
            vertex.pb(lca(vertex[j], vertex[j + 1]));
        }
        sort(vertex.begin(), vertex.end(), cmp);
        vertex.erase(unique(vertex.begin(), vertex.end()), vertex.end());
        int root = buildvt();
        ans = 0;
        dfs2(root, 0, i);
        int ways_other = mul(pre[i - 1], suf[i + 2]);
        final_res = add(final_res, mul(ans, ways_other));
        for (auto u : vertex)
        {
            cnt1[u] = cnt2[u] = 0;
            sum1[u] = sum2[u] = 0;
            gvt[u].clear();
        }
        vertex.clear();
    }

    cout << final_res << "\n";
}
