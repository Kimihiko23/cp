#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
int n, m;
int dp[N];
vector<pair<int, int>> g[N];
bool dd[N];
void dfs(int u)
{
    int mx = 0;
    dd[u] = true;
    for(auto i : g[u])
    {
        int v = i.se;
        int w = i.fi;
        if(!dd[v])
        {
            dfs(v);
        }
        mx = max(mx, w + dp[v]);
    }
    dp[u] = mx;
    
}
void read()
{
   cin >> n >> m;
   int u, v, w;
   for(int i = 1; i <= m; i++)
   {
        cin >> u >> v >> w;
        g[u].pb({w, v});
   }
}
void solve()
{
   int ans = 0;
   for(int i = 1; i <= n; i++)
   {
        if(!dd[i])
        {
            dfs(i);
        }
   }
   for(int i = 1; i <= n; i++)
   {
        ans = max(ans, dp[i]);
   }
   cout << ans;
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
} 
