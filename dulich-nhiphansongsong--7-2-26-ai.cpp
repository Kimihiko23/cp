#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;

#define name "TOURIST"

const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 100000 + 23;
const int INF = 1e18;
const int NINF = -1e18;

mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l,int r)
{
    return uniform_int_distribution<int>(l,r)(rng);
}

struct Edge
{
    int u,v,w;
} edge[N];

struct Query
{
    int u,v,k;
} qr[N];

vector<int> adj[N];
vector<int> mid[N];

int n,m;

int st[N],en[N];
int dep[N];
int pos[N];

int timer=0;
int tour=0;

int rmq[20][2*N];

int bitCnt[N];
int L[N],R[N],ans[N];
ll bitSum[N];

void dfs(int u)
{
    st[u]=++timer;

    pos[u]=++tour;
    rmq[0][tour]=u;

    for(auto v:adj[u])
    {
        if(st[v]) continue;
        dep[v]=dep[u]+1;
        dfs(v);

        rmq[0][++tour]=u;
    }

    en[u]=timer;
}

bool cmp(Edge a,Edge b)
{
    return a.w<b.w;
}

int MinDepth(int a,int b)
{
    if(dep[a]<dep[b]) return a;
    return b;
}

void build()
{
    dfs(1);

    sort(edge+1,edge+n,cmp);

    for(int i=1;i<n;i++)
    {
        if(dep[edge[i].u]<dep[edge[i].v])
            swap(edge[i].u,edge[i].v);
    }

    int LG=__lg(tour);

    for(int k=1;k<=LG;k++)
    {
        for(int i=1;i+(1<<k)-1<=tour;i++)
        {
            rmq[k][i]=MinDepth(rmq[k-1][i],rmq[k-1][i+(1<<(k-1))]);
        }
    }
}

int lca(int u,int v)
{
    int l=pos[u];
    int r=pos[v];

    if(l>r) swap(l,r);

    int k=__lg(r-l+1);

    return MinDepth(rmq[k][l],rmq[k][r-(1<<k)+1]);
}

void update(int i,ll val,int cnt)
{
    while(i<=n)
    {
        bitSum[i]+=val;
        bitCnt[i]+=cnt;
        i+=i&-i;
    }
}

void rangeUpdate(int l,int r,ll val,int cnt)
{
    update(l,val,cnt);
    update(r+1,-val,-cnt);
}

pair<ll,int> get(int i)
{
    pair<ll,int> res={0,0};

    while(i)
    {
        res.fi+=bitSum[i];
        res.se+=bitCnt[i];
        i-=i&-i;
    }

    return res;
}

int dist(int u,int v,int p)
{
    return dep[u]+dep[v]-2*dep[p];
}

pair<ll,int> calc(int u,int v)
{
    int p=lca(u,v);

    auto A=get(st[u]);
    auto B=get(st[v]);
    auto C=get(st[p]);

    pair<ll,int> res;

    res.fi=A.fi+B.fi-2*C.fi;
    res.se=dist(u,v,p)-(A.se+B.se-2*C.se);

    return res;
}

void read()
{
    cin>>n>>m;

    for(int i=1;i<n;i++)
    {
        cin>>edge[i].u>>edge[i].v>>edge[i].w;

        adj[edge[i].u].pb(edge[i].v);
        adj[edge[i].v].pb(edge[i].u);
    }

    build();

    for(int i=1;i<=m;i++)
    {
        cin>>qr[i].u>>qr[i].v>>qr[i].k;
        R[i]=n-1;
    }
}

void solve()
{
    while(true)
    {
        bool ok=false;

        for(int i=1;i<=m;i++)
        {
            if(L[i]>R[i]) continue;

            ok=true;

            mid[(L[i]+R[i])>>1].pb(i);
        }

        if(!ok) break;

        memset(bitSum,0,sizeof(bitSum));
        memset(bitCnt,0,sizeof(bitCnt));

        for(int i=0;i<n;i++)
        {
            if(i)
            {
                rangeUpdate(st[edge[i].u],en[edge[i].u],edge[i].w,1);
            }

            for(auto id:mid[i])
            {
                auto cur=calc(qr[id].u,qr[id].v);

                if(cur.fi<=qr[id].k)
                {
                    ans[id]=cur.se;
                    L[id]=i+1;
                }
                else
                {
                    R[id]=i-1;
                }
            }

            mid[i].clear();
        }
    }

    for(int i=1;i<=m;i++)
        cout<<ans[i]<<"\n";
}

