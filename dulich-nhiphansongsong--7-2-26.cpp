int n, q;
vector<pair<int, int>> g[N];
int pos[N], head[N], par[N], heavy[N], sz[N], cnt = 0;
int L[N], R[N], ans[N];
vector<int> query[N];
struct query1
{
    int u, v, w;
};
query1 queries[N];
struct node
{
    int w1 = 0, w2 = 0;
};
node st[N * 4];
struct edg
{
    int u, v, w;
};
vector<edg> edges;
void dfs(int u)
{
    // cout << u << "\n";
    sz[u] = 1;
    for(auto [v, w] : g[u])
    {
        if(v == par[u]) continue;
        par[v] = u;
        dfs(v);
        sz[u] += sz[v];
        if(sz[v] > sz[heavy[u]]) heavy[u] = v;
    }
}
void hld(int u, int h)
{
    pos[u] = ++cnt;
    head[u] = h;
    if(heavy[u]) hld(heavy[u], h);
    for(auto [v, w] : g[u])
    {
        if(v == par[u] || v == heavy[u]) continue;
        hld(v, v);
    }
}
void update(int id, int l, int r, int pos, int w1, int w2)
{
    if(l > pos || r < pos) return;
    if(l == r)
    {
        st[id].w1 = w1;
        st[id].w2 = w2;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, w1, w2);
    update(id * 2 + 1, mid + 1, r, pos, w1, w2);
    st[id].w1 = (st[id * 2].w1 + st[id * 2 + 1].w1);
    st[id].w2 = (st[id * 2].w2 + st[id * 2 + 1].w2);
}
node get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return {0, 0};
    if(l >= u && r <= v) return st[id];
    int mid = (l + r) / 2;
    node L = get(id * 2, l, mid, u, v);
    node R = get(id * 2 + 1, mid + 1, r, u, v);
    return {L.w1 + R.w1, L.w2 + R.w2};
}
node getpath(int u, int v)
{
    node res = {0, 0};
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]]) swap(u, v);
        node tmp = get(1, 1, n, pos[head[u]], pos[u]);
        res.w1 += tmp.w1;
        res.w2 += tmp.w2;
        u = par[head[u]];
    }
    if(pos[u] < pos[v]) swap(u, v);
    // if
    node tmp = {0, 0};
    if(v != u) 
        tmp = get(1, 1, n, pos[v] + 1, pos[u]);
    res.w1 += tmp.w1;
    res.w2 += tmp.w2;
    return res;
}
bool cmp(edg &a, edg &b)
{
    return a.w < b.w;
}
void read()
{
    cin >> n >> q;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
        edges.pb({u, v, w});
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> u >> v >> w;
        queries[i] = {u, v, w};
        L[i] = 0;
        R[i] = n - 1;
        ans[i] = -1;
    }
}
void solve()
{
    dfs(1);
    hld(1, 1);

    sort(edges.begin(), edges.end(), cmp);
    for(auto i : edges)
    {
        if(par[i.u] == i.v) swap(i.u, i.v);
        update(1, 1, n, pos[i.v], 0, 1);
    }
    // cout << getpath(1, 3).w2 << "\n";
    
    while(true)
    {
        bool stop = true;
        for(int i = 1; i <= q; i++)
        {
            if(L[i] > R[i]) continue;
            stop = false;
            int mid = (L[i] + R[i]) / 2;
            query[mid].pb(i);
        }
        if(stop)
            break;
        for(int i = 0; i < n; i++)
        {
            if(i > 0)
            {
                if(par[edges[i - 1].u] == edges[i - 1].v) 
                    swap(edges[i - 1].u, edges[i - 1].v);
                update(1, 1, n, pos[edges[i - 1].v], edges[i - 1].w, 0);
            }
            for(auto j : query[i])
            {
                node tmp = getpath(queries[j].u, queries[j].v);
                if(tmp.w1 <= queries[j].w)
                {
                    ans[j] = tmp.w2;
                    // R[j] = i - 1;
                    L[j] = i + 1;
                }
                else
                {
                    // L[j] = i + 1;
                    R[j] = i - 1;
                }
            }
        }
        for(int i = 0; i < n; i++)
        {
            if(i > 0)
            {
                if(par[edges[i - 1].u] == edges[i - 1].v) 
                    swap(edges[i - 1].u, edges[i - 1].v);
                update(1, 1, n, pos[edges[i - 1].v], 0, 1);
            }
            query[i].clear();
        }

    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
    
}
