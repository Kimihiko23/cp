#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
int n, q;
int L[N], R[N];
int dp[N][64];
int f[N];
int h[N];
vector<pair<int, int>> g[N];
int cnt = 0;
int st[N * 4];
int lz[N * 4];
int W[N];
pair<int, int> edge[N];
void down(int id)
{
    if(lz[id] != 0)
    {
        st[id * 2] += lz[id];
        st[id * 2 + 1] += lz[id];

        lz[id * 2] += lz[id];
        lz[id * 2 + 1] += lz[id];

        lz[id] = 0;

        
    }
}
void dfs(int u, int p)
{
    L[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v.fi == p) continue;
        dp[v.fi][0] = u;
        h[v.fi] = h[u] + 1;
        f[v.fi] = f[u] + v.se;
        dfs(v.fi, u);
    }
    R[u] = cnt;
}
void init()
{
    for(int j = 1; j < 64; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[i][j] = dp[dp[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    int k = h[u] - h[v];
    for(int i = 0; i < 64; i++)
    {
        if(k & (1LL << i))
        {
            u = dp[u][i];
        }
    }
    if(u == v) return u;
    for(int i = 63; i >= 0; i--)
    {
        if(dp[u][i] != dp[v][i])
        {
            u = dp[u][i];
            v = dp[v][i];
        }
    }
    return dp[u][0];
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u) return;
    if(l >= u && r <= v)
    {
        st[id] += val;
        lz[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    down(id);
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = max(st[id * 2], st[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return 0;
    if(l >= u && r <= v)
    {
        return st[id];
        // return;
    }
    int mid = (l + r) / 2;
    down(id);
    int left = get(id * 2, l, mid, u, v);
    int right = get(id * 2 + 1, mid + 1, r, u, v);
    // st[id] = max(st[id * 2], st[id * 2 + 1]);
    return max(left, right);
}

void read()
{
    cin >> n;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
        edge[i] = {u, v};
        W[i] = w;
    }
}
void solve()
{
    dfs(1, 0);
    init();
    for(int i = 1; i <= n; i++)
    {
        update(1, 1, n, L[i], L[i], f[i]);
    }
    int ty, val, pos1, pos2;
    cin >> q;
    while(q--)
    {
        cin >> ty >> pos1;
        if(ty == 1)
        {
            cin >> val;
            int u = edge[pos1].fi;
            int v = edge[pos1].se;
            if(h[u] > h[v]) swap(u, v);
            update(1, 1, n, L[v], R[v], val - W[pos1]);
            W[pos1] = val;
        }
        else
        {
            cin >> pos2;
            int tem = lca(pos1, pos2);  
            int tam = get(1, 1, n, L[pos1], L[pos1]) + 
            get(1, 1, n, L[pos2], L[pos2]) - 
            2 * get(1, 1, n, L[tem], L[tem]); 
            cout << tam << endl;
        }
    }
}
