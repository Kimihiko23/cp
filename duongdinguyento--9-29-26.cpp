mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r)
{
    return uniform_int_distribution<int>(l, r)(rng);
}

int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}

vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};

int n, m, s, t;
int d[N];
vector<pair<int,int>> a[N];
vector<int> prime;
bool eras[M];

void read()
{
    cin >> n >> m >> s >> t;
    for (int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        int idx = lower_bound(prime.begin(), prime.end(), w) - prime.begin();
        int x = prime[idx];
        a[u].pb({v, x - w});
        a[v].pb({u, x - w});
    }
}

void solve()
{
    fill(d + 1, d + n + 1, INF);
    priority_queue<pair<int,int>,
                   vector<pair<int,int>>,
                   greater<pair<int,int>>> pq;

    d[s] = 0;
    pq.push({0, s});
    while (!pq.empty())
    {
        auto [du, u] = pq.top();
        pq.pop();
        if (du > d[u])
            continue;
        for (auto [v, w] : a[u])
        {
            if (d[v] > du + w)
            {
                d[v] = du + w;
                pq.push({d[v], v});
            }
        }
    }
    cout << d[t];
}
void pre()
{
    for (int i = 2; i < M; i++)
    {
        if (eras[i])
            continue;

        prime.pb(i);
        if (i * i < M)
        {
            for (int j = i * i; j < M; j += i)
                eras[j] = true;
        }
    }
}

