#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int ndfs[N], low[N];
bool out[N];
stack<int> st;
vector<pair<int, int>> adj;
vector<int> g[N];
map<pair<int, int>, int> mp;
int par[N];
int sz[N];
int scc = 0, dem = 0;
int n, m;
void dfs(int u)
{
    low[u] = ndfs[u] = ++dem;
    st.push(u);
    for(auto i : g[u])
    {
        if(!out[i])
        {
            if(!ndfs[i])
            {
                dfs(i);
                low[u] = min(low[u], low[i]);
            }
            else low[u] = min(low[u], ndfs[i]);
        }
    }
    if(low[u] == ndfs[u])
    {
        scc++;
        while(1)
        {
            int v = st.top();
            par[v] = scc;
            sz[scc]++;
            st.pop();
            out[v] = 1;
            if(v == u) break;
        }
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        if(mp[{u, v}] == 0 && u != v)
        {
            mp[{u, v}] = 1;
            adj.pb({u, v});
            g[u].pb(v);

        }   
    }
}

void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        if(!ndfs[i]) dfs(i);
    }
    for(int i = 0; i < adj.size(); i++)
    {
        int u = adj[i].fi;
        int v = adj[i].se;
        if(par[u] == par[v])
        {
            ans--;
        }
    }
    for(int i = 1; i <= scc; i++)
    {
        ans += sz[i] * (sz[i] - 1);
    }
    cout << ans;
}

