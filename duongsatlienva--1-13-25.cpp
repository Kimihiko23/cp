#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
using namespace std;
const int N =3e5+23;
int st[N*4];
int lazy[N*4];
int n, m, z;
void push(int id)
{
    int x = lazy[id];
    if(x == 0) return;
    lazy[id] = 0;
    lazy[id*2] += x;
    st[id*2] += x;
    lazy[id * 2 + 1] += x;
    st[id * 2 + 1] += x;
}
void update (int id, int l, int r, int u, int v, int val) {
    if (l > v || r < u) return;
    else 
    if (l >= u && v >= r) 
    {
        st[id] += val;
        lazy[id] += val;
        
        return;
    }
    push(id);
    int mid = (l+r)/2;
    update (id*2, l, mid, u, v, val);
    update (id*2+1, mid+1, r, u, v, val);
    st[id] = min(st[id*2], st[id*2+1]);
}

int get (int id, int l, int r, int u, int v)
 {
    if (l > v || r < u) return 1e18;
    else if (l >= u && r <= v)
    { 
        return st[id];
    }
    int mid = (l+r)/2;
    push(id);
    return min(get(id*2, l, mid, u, v), get(id*2+1, mid+1, r, u, v));
}
void read()
{
   cin >> n >> m >> z;
}
void solve()
{
    update(1, 1, n, 1, n, m);
    while(z--)
    {
        int l, r, x;
        cin >> l >> r >> x;
        if (get(1, 1, n, l, r) >= x)
        {
            cout << "YES\n";
            update(1, 1, n, l, r, -x);
        }
        else
        {
            cout << "NO\n";
        }
    }
    
}
main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();

   
    
}
