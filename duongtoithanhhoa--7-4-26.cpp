int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int pre[N][1023];
int dis[N][N];
int n, m, k;


bool check(int x1, int y1, int r, int x2, int y2)
{
    int dx = x1 - x2;
    int dy = y1 - y2;
    return dx * dx + dy * dy <= r * r;
}
bool insi(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
vector<int> dx{0, 0, 1, -1};
vector<int> dy{1, -1, 0, 0};
void read()
{
   cin >> n >> m >> k;
}
void bfs(int stx, int sty)
{
    queue<pair<int, int>> q;
    dis[stx][sty] = 0;
    q.push({stx, sty});
    while(!q.empty())
    {
        auto u = q.front();
        // cout << u.fi << " " << u.se << "\n";
        q.pop();
        for(int i = 0; i < 4; i++)
        {
            int vx = u.fi + dx[i];
            int vy = u.se + dy[i];
            if(insi(vx, vy) && pre[vx][vy] == 0 && dis[vx][vy] == 1e18)
            {
                dis[vx][vy] = dis[u.fi][u.se] + 1;
                q.push({vx, vy});
            }
        }
    }
    
}
void solve()
{
   int x, y, R;
   for(int i = 1; i <= k; i++)
   {
        cin >> x >> y >> R;
        for (int i = max(1LL, x - R); i <= min(n, x + R); i++) 
        {
            long long dx = i - x;
            long long rem = R*R - dx*dx;
            if (rem < 0) continue;

            long long dy = sqrt(rem);

            int l = max(1LL, y - dy);
            int r = min(m, y + dy);

            pre[i][l]++;
            pre[i][r + 1]--;
        }
   }
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            pre[i][j] += pre[i][j - 1];
            // cout << pre[i][j] << " ";
            dis[i][j] = 1e18;
        }
        // cout << "\n";
   }
   if(pre[1][1] == 0)
   {
    // cout << "gei";
        bfs(1, 1);
        
        if(dis[n][m] != 1e18)
            cout << dis[n][m];
        else
            cout << -1;
   }
   else
   {
        cout << -1;
   }
}
