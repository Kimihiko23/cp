struct fen
{
    int n;
    vector<int> bit;

    fen(int _n)
    {
        n = _n;
        bit.assign(n + 5, 0);
    }

    void upd(int i, int val)
    {
        for (; i <= n; i += i & -i) bit[i] += val;
    }

    int get(int i)
    {
        int res = 0;
        for (; i > 0; i -= i & -i) res += bit[i];
        return res;
    }
};

int n;
vector<int> a, comp;

void read()
{
    cin >> n;
    a.resize(n + 1);

    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        comp.pb(a[i]);
    }

    sort(comp.begin(), comp.end());
    comp.erase(unique(comp.begin(), comp.end()), comp.end());

    for (int i = 1; i <= n; i++)
        a[i] = lower_bound(comp.begin(), comp.end(), a[i]) - comp.begin() + 1;
}

void solve()
{
    fen BIT1(comp.size()), BIT2(comp.size());

    for (int i = 1; i <= n; i++)
        BIT2.upd(a[i], 1);

    int ans = 0;

    for (int i = 1; i <= n; i++)
    {
        BIT2.upd(a[i], -1);

        int tmp1 = BIT1.get(a[i] - 1);
        int left1 = BIT1.get(a[i]);
        int left2 = (i - 1) - tmp1;

        int tmp2 = BIT2.get(a[i] - 1);
        int right1 = BIT2.get(a[i]);
        int right2 = (n - i) - tmp2;

        ans += left1 * right1 + left2 * right2 - (left1 - tmp1) * (right1 - tmp2);

        BIT1.upd(a[i], 1);
    }

    cout << ans;
}

