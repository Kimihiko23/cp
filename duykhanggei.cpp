const int N = 3e5 + 23;
const int INF = 0x3f3f3f3f3f3f3f3f;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, m, q;
int ndfs[N], low[N];
vector<int> g[N], g2[N];
int dis[N];
vector<pair<int, int>> edg;
stack<int> st;
int tt = 0;
int nen[N], par[20][N];
int tplt = 0;
void dfs(int u, int p)
{
    ndfs[u] = low[u] = tt++;
    st.push(u);
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        if(ndfs[v] == INF)
        {
            dfs(v, u);
            low[u] = min(low[u], low[v]);
        }
        else
            low[u] = min(low[u], ndfs[v]);
    }
    if(low[u] == ndfs[u])
    {
        tplt++;
        while(1)
        {
            int tam = st.top();
            nen[tam] = tplt;
            st.pop();
            if(tam == u)
                break;
        }
    }
}
void dfs2(int u, int p)
{
    for(auto v : g2[u])
    {
        if(v == p)
            continue;
        par[0][v] = u;
        dis[v] = dis[u] + 1;
        dfs2(v, u);
    }
}
void init()
{
    for(int i = 1; i < 20; i++)
        for(int j = 1; j <= tplt; j++)
            par[i][j] = par[i - 1][par[i - 1][j]];
}
int lca(int u, int v)
{
    if(dis[u] < dis[v])
        swap(u, v);
    for(int i = 19; i >= 0; i--)
        if(dis[par[i][u]] >= dis[v])
            u = par[i][u];
    if(u == v)
        return u;
    for(int i = 19; i >= 0; i--)
        if(par[i][u] != par[i][v])
            u = par[i][u], v = par[i][v];
    return par[0][u];
}
int disance(int u, int v)
{
    return dis[u] + dis[v] - 2 * dis[lca(u, v)];
}
void read()
{
    cin >> n >> m >> q;
    int u, v;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
        edg.pb({u, v});
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
        ndfs[i] = INF;
    dfs(1, 0);
    for(auto i : edg)
    {
        int u = i.fi, v = i.se;
        if(nen[u] != nen[v])
        {
            g2[nen[u]].pb(nen[v]);
            g2[nen[v]].pb(nen[u]);
        }
    }
    for(int i = 1; i <= tplt; i++)
    {
        sort(g2[i].begin(), g2[i].end());
        g2[i].erase(unique(g2[i].begin(), g2[i].end()), g2[i].end());
    }
    dfs2(1, 0);
    int u, v;
    while(q--)
    {
        cin >> u >> v;
        u = nen[u];
        v = nen[v];
        cout << disance(u, v) << '\n';
    }

    
}
