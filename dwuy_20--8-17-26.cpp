vector<int> ans;
int n, m;
int a[N][N];
void read()
{
    ans.clear();
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            ans.pb(a[i][j]);
        }
    }
}
void solve()
{
    sort(ans.begin(), ans.end(), greater());
    int res = 0;
    for(int i = 0; i < n; i++)
    {
        res += ans[i];
    }
    cout << res << "\n";
}
