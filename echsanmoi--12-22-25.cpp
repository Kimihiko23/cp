#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=2000+23;
int n, m, k;
int a[N][N];
int dp[N][N];
deque<int> dq;
void push(int vt, int line)
{
    while (!dq.empty() && dp[line-1][vt] >= dp[line-1][dq.back()])
        dq.pop_back();
    dq.push_back(vt);
}
void pop(int vt)
{
    if (!dq.empty() && dq.front() == vt)
        dq.pop_front();
}
void read()
{
    cin >> n >> m >> k;
    for(int i = 1; i <= n ; i++)
        for(int j = 1; j <= m ; j++)
            cin >> a[i][j];
}

void solve()
{
    k=min(k,m);
    for(int i = 1; i <= m ; i++)
    {
        dp[1][i] = a[1][i];
    }
    for(int i = 2; i <= n; i++)
    {
        dq.clear();
        for(int j = 1; j <= k ; j++)
        {
            push(j , i);
        }
        for(int j=1; j <= m; j++)
        {
            if (j + k <= m)
                push(j + k, i);
            if (!dq.empty() && abs(dq.front()-j) > k)
                dq.pop_front();
            
            dp[i][j] = dp[i-1][dq.front()] + a[i][j];
        }
    }
    int ans=0;
    for(int i = 1; i <= m ; i++)
        ans = max(ans, dp[n][i]);
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
