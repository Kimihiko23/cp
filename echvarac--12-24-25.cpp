#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=2e6+23;
deque<int> dq;
int h[N], j[N];
int n;
vector<int> ans;
void push(int i)
{
    while(!dq.empty() && h[dq.back()] <= h[i])
        dq.pop_back();
    dq.push_back(i);
}
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        cin >> h[i];
   }
   for(int i = 1; i <= n; i++)
   {
        cin >> j[i];
   }
}

void solve()
{
    for(int i = n; i >= 1; i--)
    {
        push(i);
        if(j[i] >= dq.size())
        {
            ans.push_back(-1);
        }
        else
        {
            
            ans.push_back(h[dq[dq.size()-j[i]-1]]);
        }
        
    }
    reverse(ans.begin(),ans.end());
    for(auto i: ans)
    {
        cout << i << " ";
    } 
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
