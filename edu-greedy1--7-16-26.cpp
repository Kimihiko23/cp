mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n;
int a[N];
int b[N];
int wa[N];
int wb[N];
int mna, mnb;
void read()
{
    mna = 1e18;
    mnb = 1e18;
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mna = min(mna, a[i]);
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> b[i];
        mnb = min(mnb, b[i]);
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        wa[i] = a[i] - mna;
        wb[i] = b[i] - mnb;
        if(wa[i] >= wb[i])
        {
            ans += wb[i] + (wa[i] - wb[i]);
        }
        else
        {
            ans += wa[i] + (wb[i] - wa[i]);
        }
    }
    cout << ans << "\n";
}
