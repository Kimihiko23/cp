int n, k;
int a[N];
int b[N];
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= k; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    int ans = 0;
    sort(b + 1, b + k + 1);
    sort(a + 1, a + n + 1, greater<int>());
    for(int i = 1; i <= k; i++)
    {
        ans += a[i];
        if(b[i] == 1)
        {
            ans += a[i];
        }
        b[i]--;
    }
    int vt = k;
    for(int i = 1; i <= k; i++)
    {
        if(b[i] != 0)
        {
            ans += a[vt + b[i]];
            vt += b[i];
        }
    }
    cout << ans << "\n";
}
