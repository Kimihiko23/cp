#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int dp[N][3];
int n;
vector<pair<int, int>> a;
void read()
{
    cin >> n;
    int x, h;
    a.pb({0, 0});
    for(int i = 1; i <= n; i++)
    {
        cin >> x >> h;
        a.pb({x, h});
    }
}
void solve()
{
    //0 = not thing
    //1 = fall foward
    //2 = fall backward
    sort(a.begin(), a.end());
    dp[1][0] = 0;
    dp[1][1] = 1;
    dp[1][2] = 1;
    for(int i = 2; i <= n; i++)
    {
        for(int j = 0; j < 3; j++)
        {
            for(int z = 0; z < 3; z++)
            {
                if(j == 0)
                {
                    if(z == 0)
                    {
                        dp[i][j] = max(dp[i][j], dp[i - 1][z]);
                    }
                    if(z == 1)
                    {
                        if(a[i - 1].fi + a[i - 1].se < a[i].fi)
                            dp[i][j] = max(dp[i][j], dp[i - 1][z]);
                    }
                    if(z == 2)
                    {
                        // if(a[i - 1].fi - a[i - 1].se < a[i].fi);
                            dp[i][j] = max(dp[i][j], dp[i - 1][z]);
                    }
                }
                if(j == 1)
                {
                    if(z == 0)
                    {
                        dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                    if(z == 1)
                    {
                        if(a[i - 1].fi + a[i - 1].se < a[i].fi)
                            dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                    if(z == 2)
                    {
                        // if(a[i - 1].fi - a[i - 1].se < a[i].fi);
                            dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                }
                if(j == 2)
                {
                    if(z == 0)
                    {
                        if(a[i - 1].fi < a[i].fi - a[i].se)
                            dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                    if(z == 1)
                    {
                        if(a[i - 1].fi + a[i - 1].se < a[i].fi - a[i].se)
                            dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                    if(z == 2)
                    {
                        if(a[i - 1].fi < a[i].fi - a[i].se)
                            dp[i][j] = max(dp[i][j], dp[i - 1][z] + 1);
                    }
                }
            }
        }
    }
    int ans = 0;
    for(int i = 0; i < 3; i++)
    {
        ans = max(ans, dp[n][i]);
    }
    cout << ans;
}
