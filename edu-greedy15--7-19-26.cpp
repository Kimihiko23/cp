mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, k;
vector<int> a;
vector<int> b;
vector<int> c;
int prea[N], preb[N], prec[N];
//a = 2 of them like, b = the first like, c = the second like
void read()
{
    cin >> n >> k;
    int cost, ty1, ty2;
    for (int i = 1; i <= n; i++)
    {
        cin >> cost >> ty1 >> ty2;
        if (ty1 == 1 && ty2 == 1)
            a.pb(cost);
        else if (ty1 == 1)
            b.pb(cost);
        else if (ty2 == 1)
            c.pb(cost);
    }
}
void solve()
{
    sort(a.begin(), a.end());
    sort(b.begin(), b.end());
    sort(c.begin(), c.end());
    int ans = 1e18;
    for(int i = 1; i <= a.size(); i++)
    {
        prea[i] = prea[i - 1] + a[i - 1];
    }
    for(int i = 1; i <= b.size(); i++)
    {
        preb[i] = preb[i - 1] + b[i - 1];
    }
    for(int i = 1; i <= c.size(); i++)
    {
        prec[i] = prec[i - 1] + c[i - 1];
    }
    for(int i = 1; i <= min(k, (int)a.size()); i++)
    {
        int need = k - i;
        if(need <= b.size() && need <= c.size())
        {
            ans = min(ans, prea[i] + preb[need] + prec[need]);
        }
    }
    if(ans != 1e18)
    cout << ans << "\n";
    else cout << -1 << "\n";
}
