int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int k, n;
int a[N];
int sum = 0;
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        sum += a[i];
    }
}
void solve()
{
    int ned = sum / k;
    if(sum % k != 0)
    {
        cout << "No";
        return;
    }
    int tam = 0;
    int dem = 0;
    vector<int> ord;
    bool ok = true;
    for(int i = 1; i <= n; i++)
    {
        tam += a[i];
        dem++;
        if(tam == ned)
        {
            ord.pb(dem);
            dem = 0;
            tam = 0;   
        }
        else
        if(tam > ned)
        {
            ok = false;
            break;
        }
    }
    if(!ok)
    {
        cout << "No";
        return;
    }
    else
    {
        cout << "Yes\n";
        for(auto i : ord)
        {
            cout << i << " ";
        }
    }
}
