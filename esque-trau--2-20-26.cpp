void solve()
{
   int ans = 0;
   for(int i = l ;i <= r; i++)
   {
        string s = to_string(i);
        int dem = 0;
        bool dd = true;
        for(int j = 0; j < s.size(); j++)
        {
            if(s[j] == '6' || s[j] == '8')
            {
                dem++;
            }
            if(s[j] == '4')
            {
                dd = false;
                break;
            }
        }
        if(s.size() % 2 == 0 && dem == s.size() / 2 && dd)
        {
            ans++;
            ans %= mod;
        }
   }
   cout << ans;
}
