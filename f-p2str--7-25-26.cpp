bool good[N][N];
int dp[3][N][N];
string s;
int n = 0;
void read()
{
    cin >> s;
    n = s.size();
}
void solve()
{
    s = " " + s;
    for(int i = 1; i <= n; i++)
    {
        good[i][i] = 1;
        dp[0][i][i] = 1;
        dp[1][i][i] = 1;
    }
    ll ans = 0;
    for(int len = 2; len <= n; len++)
    {
        for(int i = 1; i <= n - len + 1; i++)
        {
            int j = i + len - 1;
            if(len == 2)
            {
                if(s[i] == s[j])
                {
                    good[i][j] = 1;
                }
            }
            else
            {
                if(s[i] == s[j])
                {
                    good[i][j] = good[i + 1][j - 1];
                }
            }
            dp[0][i][j] = dp[0][i][j - 1] + good[i][j];
            dp[1][i][j] = dp[1][i + 1][j] + good[i][j];

            if(s[i] != s[j])
            {
                dp[2][i][j] = 0;
            }
            else
            {
                dp[2][i][j] = dp[2][i + 1][j - 1] + dp[1][i + 1][j - 1] + dp[0][i + 1][j - 1] + 1;
            }
            ans += dp[2][i][j];
        }
    }
    cout << ans;
    
}
