void solve()
{
    for(int i = 0; i < N; i++)
    {
        cnk[0][i] = 1;
        cnk[i][i] = 1;
    }
    for(int n = 1; n < N; n++)
    {
        for(int k = 1; k <= n; k++)
        {
            cnk[k][n] = cnk[k][n - 1] + cnk[k - 1][n - 1];
            cnk[k][n] %= MOD;
        }
    }
    dp[1] = 1;
    dp[2] = 1;
    dp[0] = 1;
    for(int i = 3; i < N; i++)
    {
        for(int j = 2; j <= i; j++)
        {
            if(j % 2 == 0)
            {
                dp[i] += ((dp[j - 1] * dp[i - j]) % MOD) * cnk[j - 1][i-1];
                dp[i] %= MOD;
            }
        }
    }
    int q;
    int x;
    cin >> q;
    for(int i = 1; i <= q; i++)
    {
        cin >> x;
        cout << setw(9) << setfill('0') << dp[x] << "\n";
    }
}
