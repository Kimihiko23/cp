const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int a[N];
vector<int> g[N];
int n, m, k;
int ndfs[N], low[N], cnt = 0;
stack<int> st;
int tplt = 0;
int mxsz = 0;
int limit = 0;
bool out[N];
vector<int> ord;
void dfs(int u)
{
    ndfs[u] = low[u] = ++cnt;
    st.push(u);
    for(auto v: g[u])
    {
        if(!out[v] && a[v] >= limit)
        {
            if(ndfs[v] == 0)
            {
                dfs(v);
                low[u] = min(low[u], low[v]);

            }
            else
            {
                low[u] = min(low[u], ndfs[v]);
            }
        }
    }
    if(ndfs[u] == low[u])
    {
        tplt++;
        int sz = 0;
        while(1)
        {
            sz++;
            int x = st.top();
            st.pop();
            out[x] = 1;
            if(x == u)
                break;
        }
        mxsz = max(mxsz, sz);  
    }
}
void read()
{
    cin >> n >> m >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        ord.pb(a[i]);
    }
    int u, v;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
    }
}
void solve()
{
    int ans = -1e18;
    sort(ord.begin(), ord.end());
    int l = 0, r = n - 1;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        limit = ord[mid];
        mxsz = 0;
        tplt = 0;
        cnt = 0;
        memset(out, 0, sizeof(out));
        memset(ndfs, 0, sizeof(ndfs));
        while(!st.empty())
            st.pop();
        for(int i = 1; i <= n; i++)
        {
            if(!ndfs[i] && a[i] >= limit)
            {
                dfs(i);
            }
        }
        if(mxsz >= k)
        {
            ans = ord[mid];
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }
    cout << ans;
}
