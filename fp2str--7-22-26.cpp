bool check(int l1, int r1, int l2, int r2)
{
    string t = "";

    for(int i = l1; i <= r1; i++)
        t += s[i];

    for(int i = l2; i <= r2; i++)
        t += s[i];

    int l = 0, r = (int)t.size() - 1;

    while(l < r)
    {
        if(t[l] != t[r])
            return false;
        l++;
        r--;
    }

    return true;
}
