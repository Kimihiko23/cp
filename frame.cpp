int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int a[N][N], pre[N][N];
int n, m;
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}
int cnt1 = 0;
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        string s;
        cin >> s;
        for(int j = 1; j <= m; j++)
        {
            a[i][j] = s[j - 1] - '0';
            if(a[i][j] == 1) cnt1++;
            pre[i][j] = pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1] + a[i][j];
        }
    }
}
void solve()
{
    int ans = n * m - cnt1;
    for(int sz = 2; sz <= min(n, m); sz++)
    {
        for(int i = 1; i + sz - 1 <= n; i++)
        {
            for(int j = 1; j + sz - 1 <= m; j++)
            {
                int sum = cal(i, j, i + sz - 1, j + sz - 1);
                if(sum == 0) ans++;
            }
        }
    }
    cout << ans;
}
