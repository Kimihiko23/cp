#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =2e5+23;
int h[N];
int n, m;
vector<int> g[N];
int par[N][60];
vector<int> k[N];
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        if(i != old)
        {
            h[i] = h[u] + 1;
            par[i][0] = u;
            dfs(i, u);
        }
    }
}
void init()
{
    for(int j = 1; (1 << j) <= n; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);
    while(x > 0)
    {
        for(int i = tam; i >= 0; i--)
        {
            if((1 << i) <= x)
            {
                x -= 1 << i;
                u = par[u][i];
            }
        }
    }
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        int u, v;
        cin >> u >> v;
        if(v != 0)
        {
            g[i].pb(v);
            g[v].pb(i);
        }
        k[u].pb(i);
    }
}
void solve()
{
    dfs(1, -1);
    init();
    for(int i = 1; i <= m; i++)
    {
        int mx = 0;
        int vtmx = 0;
        for(auto j : k[i])
        {
            if(h[j] > mx)
            {
                mx = h[j];
                vtmx = j;
            }
        }
        int ans = 0;
        for(auto j : k[i])
        {
            ans = max(ans, h[vtmx] + h[j] - 2 * h[lca(vtmx, j)]);
        }
        cout << ans << "\n";
    }
    // cout << k[2].size();
    

}
