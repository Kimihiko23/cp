#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, k;
struct edge
{
    int u, v, w;
};
vector<edge> edg;
vector<edge> edgrm;
vector<pair<int, int>> g[N], g2[N];
int f[N];
bool dd[N];
vector<int> famous;
int dep[N];
void dfs(int u, int p)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        if(v == p)
            continue;
        dep[v] = dep[u] + 1;
        dfs(v, u);
        f[u] += f[v];
    }
}
void read()
{
    cin >> n >> k;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
        edg.pb({u, v, w});
    }
    for(int i = 1; i <= k; i++)
    {
        cin >> u;
        dd[u] = 1;
        famous.pb(u);
        f[u] = 1;
    }
}
void solve()
{
    dfs(1, 0);
    for(auto i : edg)
    {
        int u = i.u;
        int v = i.v;
        if(dep[v] < dep[u])
            swap(u, v);
        if(f[v] == 0 || f[v] == k)
            continue;
        g2[u].pb({v, i.w});
        g2[v].pb({u, i.w});
        edgrm.pb({u, v, i.w});
    }
    for(auto i : edgrm)
    {
        cout << i.u << " " << i.v << "\n";
    }
}
