mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, q;
vector<int> g[N];
int head[N], pos[N], sz[N], par[N], heavy[N], cnt = 0;
int mxsub[N];
struct node
{
    int sum = 0, mx = 0, lz = 0;
};
node st[N * 4];
void dfs(int u)
{
    sz[u] = 1;
    int mxsz = 0;
    for(auto v : g[u])
    {
        if(v == par[u]) continue;
        par[v] = u;
        dfs(v);
        sz[u] += sz[v];
        if(sz[v] > mxsz)
        {
            mxsz = sz[v];
            heavy[u] = v;
        }
    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    if(heavy[u]) hld(heavy[u], hd);
    for(auto v : g[u])
    {
        if(v == par[u] || v == heavy[u]) continue;
        hld(v, v);
    }
    mxsub[u] = cnt;
}
void down(int id, int l, int r)
{
    if(st[id].lz)
    {
        int mid = l + (r - l) / 2;
        int x = st[id].lz;
        st[id * 2].sum += x * (mid - l + 1);
        st[id * 2 + 1].sum += x * (r - mid);
        st[id * 2].mx += x;
        st[id * 2 + 1].mx += x;
        st[id * 2].lz += x;
        st[id * 2 + 1].lz += x;
        st[id].lz = 0;
    }
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u) 
        return;
    if(l >= u && r <= v)
    {
        st[id].sum += val * (r - l + 1);
        st[id].mx += val;
        st[id].lz += val;
        return;
    }
    down(id, l, r);
    int mid = l + (r - l) / 2;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum;
    st[id].mx = max(st[id * 2].mx, st[id * 2 + 1].mx);
}
void updatepath(int u, int v, int val)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]]) swap(u, v);
        update(1, 1, n, pos[head[u]], pos[u], val);
        u = par[head[u]];
    }
    if(pos[u] > pos[v]) swap(u, v);
    update(1, 1, n, pos[u], pos[v], val);
}
void updatesub(int u, int val)
{
    update(1, 1, n, pos[u], mxsub[u], val);
}
node get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) 
        return {0, 0, 0};
    if(l >= u && r <= v)
        return st[id];
    down(id, l, r);
    int mid = l + (r - l) / 2;
    node x = get(id * 2, l, mid, u, v);
    node y = get(id * 2 + 1, mid + 1, r, u, v);
    return {x.sum + y.sum, max(x.mx, y.mx), 0};
}
void getmxsub(int u)
{
    node res = get(1, 1, n, pos[u], mxsub[u]);
    cout << res.mx << '\n';
}
void getpathmx(int u, int v)
{
    int res = 0;
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]]) swap(u, v);
        node tmp = get(1, 1, n, pos[head[u]], pos[u]);
        res = max(res, tmp.mx);
        u = par[head[u]];
    }
    if(pos[u] > pos[v]) swap(u, v);
    node tmp = get(1, 1, n, pos[u], pos[v]);
    res = max(res, tmp.mx);
    cout << res << '\n';
}
void read()
{
    cin >> n >> q;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1);
    hld(1, 1);
    int type, u, v, val;
    while(q--)
    {
        cin >> type >> u;
        if(type == 1)
        {
            cin >> v >> val;
            updatepath(u, v, val);
        }
        else if(type == 2)
        {
            cin >> val;
            updatesub(u, val);
        }
        else if(type == 4)
        {
            getmxsub(u);
        }
        else
        {
            cin >> v;
            getpathmx(u, v);
        }
    }
}
