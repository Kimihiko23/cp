int n, m;
vector<int> adj[N];
int c[N];

int tin[N], low[N], vis[N], timer;
stack<int> st;

int cici[N], id[N];
int scc;

vector<int> gadj[N];

int vis2[N];
vector<int> topo;

int gcd2[N];

void dfs(int u)
{
    vis[u] = 1;
    tin[u] = low[u] = ++timer;
    st.push(u);

    for (auto v : adj[u])
    {
        if (!vis[v])
        {
            dfs(v);
            low[u] = min(low[u], low[v]);
        }
        else if (vis[v] == 1)
        {
            low[u] = min(low[u], tin[v]);
        }
    }

    if (tin[u] == low[u])
    {
        ++scc;

        while (true)
        {
            int v = st.top();
            st.pop();

            vis[v] = 2;
            id[v] = scc;

            cici[scc] = gcd(cici[scc], c[v]);

            if (u == v)
                break;
        }
    }
}

void hina(int u)
{
    vis2[u] = 1;

    for (auto v : gadj[u])
    {
        if (!vis2[v])
            hina(v);
    }

    topo.pb(u);
}

void read()
{
    cin >> n >> m;

    for (int i = 1; i <= n; ++i)
        cin >> c[i];

    for (int i = 1; i <= m; ++i)
    {
        int u, v;
        cin >> u >> v;

        adj[u].pb(v);
    }
}

void solve()
{
    for (int i = 1; i <= n; ++i)
    {
        if (!vis[i])
            dfs(i);
    }

    for (int u = 1; u <= n; ++u)
    {
        for (auto v : adj[u])
        {
            if (id[u] != id[v])
                gadj[id[u]].pb(id[v]);
        }
    }
    for (int i = 1; i <= scc; ++i)
    {
        if (!vis2[i])
            hina(i);
    }
    int ans = INF;
    for (auto u : topo)
    {
        gcd2[u] = cici[u];

        for (auto v : gadj[u])
        {
            gcd2[u] = min(
                gcd2[u],
                gcd(gcd2[v], cici[u])
            );
        }

        ans = min(ans, gcd2[u]);
    }

    cout << ans << '\n';
}

