int n, m, k;
int a[N], b[N];
bool check(int x)
{
    int sum = 0;
    for(int i = 1; i <= n; i++)
    {
        int vt = 0;
        int l = 1, r = m;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(b[mid] + a[i] <= x)
            {
                vt = max(vt, mid);
                l = mid + 1;
            }
            else
            {
                r = mid - 1;
            }
        }
        sum += vt;
    }
    return sum >= k;
}
void read()
{
    cin >> n >> m >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    sort(b + 1, b + 1 + m);
    int L = a[1] + b[1];
    int R = a[n] + b[m];
    int ans = 1;
    while(L <= R)
    {
        int mid = (L + R)/2;
        if(check(mid))
        {
            ans = mid;
            R = mid - 1;
        }
        else
        {
            L = mid + 1;
        }
    }
    cout << ans;
}
