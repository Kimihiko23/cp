#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N = 1e5+23;
int st1[N*4];
int st2[N*4];
int a[N],b[N];
int get1(int l, int r, int id, int u, int v)
{
    if ( v < l || u > r ) return 1e18;
    if ( u <= l && r <= v )
    {
        return st1[id];
    }
    int mid=(l+r)/2;
    return min(get1(l, mid, id*2, u, v), get1( mid+1, r, id*2+1, u, v)) ;
}
void build1(int l, int r, int id)
{
    if ( l == r )
    {
        st1[id] = a[l];
        return;
    }
    int mid=(l+r)/2;
    build1(mid+1, r, id*2+1);
    build1(l , mid, id*2);
    st1[id] = min(st1[id*2], st1[id*2+1]);
}
void update1(int l, int r, int id, int pos, int val)
{
    if ( pos < l || pos > r ) return;
    if ( l == r )
    {
        st1[id] = val;
        return;
    }
    int mid=(l+r)/2;
    update1(l, mid, id*2, pos, val);
    update1(mid+1, r, id*2+1, pos, val);
    st1[id] = min(st1[id*2], st1[id*2+1]);
}


int get2(int l, int r, int id, int u, int v)
{
    if ( v < l || u > r ) return 1e18;
    if ( u <= l && r <= v )
    {
        return st2[id];
    }
    int mid=(l+r)/2;
    return min(get2(l, mid, id*2, u, v), get2( mid+1, r, id*2+1, u, v)) ;
}
void build2(int l, int r, int id)
{
    if ( l == r )
    {
        st2[id] = b[l];
        return;
    }
    int mid=(l+r)/2;
    build2(mid+1, r, id*2+1);
    build2(l , mid, id*2);
    st2[id] = min(st2[id*2], st2[id*2+1]);
}
void update2(int l, int r, int id, int pos, int val)
{
    if ( pos < l || pos > r ) return;
    if ( l == r )
    {
        st2[id] = val;
        return;
    }
    int mid=(l+r)/2;
    update2(l, mid, id*2, pos, val);
    update2(mid+1, r, id*2+1, pos, val);
    st2[id] = min(st2[id*2], st2[id*2+1]);
}

int n, q;
int p[N];

void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
      cin >> p[i];
      a[i] = p[i] - i;
      b[i] = p[i] + i;
   }
}

void solve()
{
   build1(1, n, 1);
   build2(1, n, 1);
   
   while(q--)
   {
      int t;
      cin >> t;
      if(t == 1)
      {
         int k,x;
         cin >> k >> x;
         p[k] = x;
         a[k] = p[k] - k;
         b[k] = p[k] + k;
         update1(1, n, 1, k, a[k]);
         update2(1, n, 1, k, b[k]);
      }
      else
      {
         int k;
         cin >> k;
         int tam1 = get1(1, n, 1, 1, k) + k;
         int tam2 = get2(1, n, 1 , k+1, n) - k;
         cout << min(tam1,tam2) << "\n";
      }
   }
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
