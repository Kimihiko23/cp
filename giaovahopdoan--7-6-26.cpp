mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<pair<int, int>> ord;
int n;
int dd[N];
void read()
{
    ord.clear();
    cin >> n;
    int l, r, a, b;
    for(int i = 1; i <= n; i++)
    {
        cin >> l >> r >> a >> b;
        ord.pb({l, i});
        ord.pb({r + 1, -i});
        ord.pb({a, i});
        ord.pb({b + 1, -i});
      
    }
}
void solve()
{
    memset(dd, 0, sizeof(dd));
    sort(ord.begin(), ord.end());
    // int sum = 0;
    int ans = -1;
    int cnt = 0;
    for(int i = 0; i < ord.size(); i++)
    {
        int vt = ord[i].fi;
        int w = ord[i].se;
        if(w > 0)
        {
            if(dd[w] == 0)
            {
                cnt++;
            }
            dd[w]++;
        }
        else
        {
            dd[abs(w)]--;
            if(dd[abs(w)] == 0)
            {
                cnt--;
            }
        }
        if(cnt == n)
        {
            ans = vt;
            break;
        }
    }
    cout << ans << " ";
}
