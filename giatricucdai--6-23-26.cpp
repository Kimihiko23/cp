const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
int n, q;
vector<int> g[N];
int a[N], heavy[N], sz[N], pos[N],
head[N], par[N], st[N * 4];
int curc = 0, curp = 0;
void dfs(int u)
{
    sz[u] = 1;
    for(auto v : g[u])
    {
        if(v != par[u])
        {
            par[v] = u;
            dfs(v);
            sz[u] += sz[v];
            if(sz[heavy[u]] < sz[v])
                heavy[u] = v;
        }
    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++ curp;
    if(heavy[u] > 0)
        hld(heavy[u], hd);
    for(auto v : g[u])
    {
        if(v != par[u] && v != heavy[u])
        {
            hld(v, v);
        }
    }
}
int lca(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[u] > pos[v])
        {
            u = par[head[u]];
        }
        else
            v = par[head[v]];
    }
    if(pos[u] > pos[v])
    {
        return v;
    }
    return u;
}
void update(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = max(st[id * 2], st[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
    {
        return -1e18;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return max(get(id * 2, l, mid, u, v), get(id * 2 + 1, mid + 1, r, u, v));
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1);
    hld(1, 1);
    for(int i = 1; i <= n; i++)
    {
        update(1, 1, n, pos[i], a[i]);
    }
    while(q--)
    {
        int ty, x, y;
        cin >> ty >> x >> y;
        if(ty == 1)
        {
            update(1, 1, n, pos[x], y);
        }
        else
        {
            int p = lca(x, y);
            int ans = -1e18;
            while(head[x] != head[p])
            {
                ans = max(ans, get(1, 1, n, pos[head[x]], pos[x]));
                x = par[head[x]];
            }
            while(head[y] != head[p]) 
            {
                ans = max(ans, get(1, 1, n, pos[head[y]], pos[y]));
                y = par[head[y]];
            }
            if (pos[x] > pos[y]) swap(x, y);
            ans = max(ans, get(1, 1, n, pos[x], pos[y]));
            cout << ans << ' ';
        }
    }
}
