int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, k, a[N];
int mx = 0;
int check(int x)
{
    // if(mx / x < k)
    //     return 1e18;
    int cnt = 1;
    int sum = a[1];
    if(sum > x)
        return 1e18;
    int sz = 1;
    for(int i = 2; i <= n; i++)
    {
        if(sum + a[i] > x)
        {
            sum = a[i];
            cnt++;
            sz = 1;
        }
        if(sz == 1 && sum > x)
            return 1e18;
    }
    return cnt;
}
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mx += a[i];
    }
}
void solve()
{
    int ans = -1;
    int l = 1, r = mx;
    cout << check(10) << "\n";
    while(l <= r)
    {
        int mid = (l + r) / 2;
        int tam = check(mid);
        if(tam <= k)
        {
            ans = max(ans, mid);
            l = mid + 1;
        }
        else
            r = mid -  1;
    }
    cout << ans;
}
