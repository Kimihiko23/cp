#include <bits/stdc++.h>
#define fi first
#define se second
#define siesta main
using namespace std;


const int N = 5005; 
int stx, sty, edx, edy;
int n;
int mxX = 0, mxY = 0;
int dis[N][N];
map<int, int> mpx, mpy;
int x[N], y[N];


bool check(int xx, int yy) 
{
    return (xx >= 1 && xx <= mxX && yy >= 1 && yy <= mxY && dis[xx][yy] < 1e9);
}

vector<int> dx{1, -1, 0, 0};
vector<int> dy{0, 0, 1, -1};

void bfs(int sx, int sy) 
{
    queue<pair<int, int>> qe;
    qe.push({sx, sy});
    dis[sx][sy] = 0;

    while(!qe.empty()) 
    {
        int xx = qe.front().fi;
        int yy = qe.front().se;
        qe.pop();

        for(int i = 0; i < 4; i++) 
        {
            int afx = xx + dx[i];
            int afy = yy + dy[i];

           
            if(check(afx, afy)) 
            {
                while(check(afx + dx[i], afy + dy[i])) 
                {
                    afx += dx[i];
                    afy += dy[i];
                }
                
           
                if(dis[afx][afy] > dis[xx][yy] + 1) 
                {
                    dis[afx][afy] = dis[xx][yy] + 1;
                    qe.push({afx, afy});
                }
            }
        }
    }
}

void read() 
{
    if (!(cin >> n >> stx >> sty >> edx >> edy)) return;
    mpx[stx]; mpy[sty];
    mpx[edx]; mpy[edy];
    for(int i = 1; i <= n; i++) 
    {
        cin >> x[i] >> y[i];
        mpx[x[i]]; mpy[y[i]];
    }
}

void solve() 
{
    int demX = 0;
    for(auto &i : mpx) i.second = ++demX;
    mxX = demX;

    int demY = 0;
    for(auto &i : mpy) i.second = ++demY;
    mxY = demY;

    for(int i = 1; i <= mxX; i++) 
    {
        for(int j = 1; j <= mxY; j++) 
        {
            dis[i][j] = 1e8;
        }
    }


    for(int i = 1; i <= n; i++) 
    {
        dis[mpx[x[i]]][mpy[y[i]]] = 1e9;
    }

    bfs(mpx[stx], mpy[sty]);

    int res = dis[mpx[edx]][mpy[edy]];
    if(res >= 1e8) cout << -1;
    else cout << res;
}

siesta() 
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
    return 0;
}