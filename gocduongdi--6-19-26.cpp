const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
int n, q;
int a[N];
int L[N], R[N];
int dp[N][64];
int f[N];
int h[N];
vector<int> g[N];
int cnt = 0;
int st[N * 4];
int lz[N * 4];
void down(int id)
{
    if(lz[id] != 0)
    {
        st[id * 2] += lz[id];
        st[id * 2 + 1] += lz[id];

        lz[id * 2] += lz[id];
        lz[id * 2 + 1] += lz[id];

        lz[id] = 0;

        
    }
}
void dfs(int u, int p)
{
    f[u] += a[u];
    L[u] = ++cnt;
    for(int v : g[u])
    {
        if(v == p) continue;
        dp[v][0] = u;
        h[v] = h[u] + 1;
        f[v] += f[u];
        dfs(v, u);
    }
    R[u] = cnt;
}
void init()
{
    for(int j = 1; j < 64; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            dp[i][j] = dp[dp[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    int k = h[u] - h[v];
    for(int i = 0; i < 64; i++)
    {
        if(k & (1LL << i))
        {
            u = dp[u][i];
        }
    }
    if(u == v) return u;
    for(int i = 63; i >= 0; i--)
    {
        if(dp[u][i] != dp[v][i])
        {
            u = dp[u][i];
            v = dp[v][i];
        }
    }
    return dp[u][0];
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u) return;
    if(l >= u && r <= v)
    {
        st[id] += val;
        lz[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    down(id);
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = max(st[id * 2], st[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) return 0;
    if(l >= u && r <= v)
    {
        return st[id];
        // return;
    }
    int mid = (l + r) / 2;
    down(id);
    int left = get(id * 2, l, mid, u, v);
    int right = get(id * 2 + 1, mid + 1, r, u, v);
    // st[id] = max(st[id * 2], st[id * 2 + 1]);
    return max(left, right);
}

void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, 0);
    init();
    for(int i = 1; i <= n; i++)
    {
        update(1, 1, n, L[i], L[i], f[i]);
    }
    int ty, val, pos;
    while(q--)
    {
        cin >> ty >> pos;
        if(ty == 1)
        {
            cin >> val;
            update(1, 1, n, L[pos], R[pos], val - a[pos]);
            a[pos] = val;
        }
        else
        {
            int tem = lca(pos, 1);
            int tam = get(1, 1, n, L[pos], L[pos]) + 
            get(1, 1, n, L[1], L[1]) - 
            2 * get(1, 1, n, L[tem], L[tem]) + a[tem]; 
            cout << tam << endl;
        }
    }
}
