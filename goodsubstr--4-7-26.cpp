#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
const int MOD1 = 1000040201;
const int MOD2 = 1e9 + 7;
vector<pair<int, int>> ans;
pair<int, int> base = {256, 256}, pre[N], p[N];
bool dd[N];
int k;
string s;
pair<int, int> add(pair<int, int> a, pair<int, int> b)
{
    int tam1 = (a.fi + b.fi) % MOD1;
    int tam2 = (a.se + b.se) % MOD2;
    return {tam1, tam2};
}
pair<int, int> mul(pair<int, int> a, pair<int, int> b)
{
    int tam1 = a.fi * b.fi % MOD1;
    int tam2 = a.se * b.se % MOD2;
    return {tam1, tam2};
}
pair<int, int> sub(pair<int, int> a, pair<int, int> b)
{
    int tam1 = ((a.fi - b.fi % MOD1) + MOD1) % MOD1;
    int tam2 = ((a.se - b.se % MOD2) + MOD2) % MOD2;
    return {tam1, tam2};
}
pair<int, int> f(int l, int r)
{
    return sub(pre[r], mul(p[r - l + 1], pre[l - 1]));
}
void read()
{
    cin >> s;
    for(int i = 1; i <= 26; i++)
    {
        char x;
        cin >> x;
        if(x == '0')
            dd[i] = true;
    }
    cin >> k;
}
void solve()
{
    p[0] = {1, 1};
    for(int i = 1; i <= s.size(); i++)
    {
        p[i] = mul(p[i - 1], base);
        pre[i] = add(mul(pre[i - 1], base), {s[i - 1] - 'a' + 1, s[i - 1] - 'a' + 1});
    }
    for(int l = 1; l <= s.size(); l++)
    {
        int bad = 0;
        for(int r = l; r <= s.size(); r++)
        {
            bad += dd[s[r-1] - 'a' + 1];
            if(bad > k)
                break;
            ans.pb(f(l, r));
        }
    }
    sort(ans.begin(), ans.end());
    ans.erase(unique(ans.begin(), ans.end()), ans.end());
    cout << ans.size() << "\n";

}
