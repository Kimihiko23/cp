int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, q;
char a[N];
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        a[i] = 'A';
    }
    a[0] = ' ';
    a[n + 1] = ' ';
}
void solve()
{
    int ty, l, r;
    char x;
    while(q--)
    {
        cin >> ty >> l;
        if(ty == 1)
        {
            cin >> r >> x;
            l++;
            r++;
            for(int i = l; i <= r; i++)
            {
                a[i] = x;
            }
        }
        else
        {   int ans = 0;
            int dem = 0;
            for(int i = 1; i <= n + 1; i++)
            {
                if(a[i] != a[i - 1])
                {
                    ans += max((int)0, dem - l);
                    dem = 1;
                }
                else
                {
                    dem++;
                }
            }
            // ans += max((int)0, dem - l);
            cout << ans << "\n";
        }
    }
}
