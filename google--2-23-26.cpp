using namespace std;
const int N = 3e4+23;
int pre[N][1023];
int n, m, k;


bool check(int x1, int y1, int r, int x2, int y2)
{
    int dx = x1 - x2;
    int dy = y1 - y2;
    return dx * dx + dy * dy <= r * r;
}
void read()
{
   cin >> n >> m >> k;
}
void solve()
{
   int x, y, R, z;
   for(int i = 1; i <= k; i++)
   {
        cin >> y >> x >> R >> z;
        for(int j = max(y - R, 1LL); j <= min(y + R, m); j++)
        {
            int l, r, mid;
            l = 1;
            r = x;
            int tam;
            while(l <= r)
            {
                mid = (l + r) / 2;
                if(check(x, y, R, mid, j))
                {
                    tam = mid;
                    r = mid - 1;
                }
                else
                {
                    l = mid + 1;
                }
            }
            pre[tam][j] += z;
            l = x;
            r = n;
            while(l <= r)
            {
                mid = (l + r) / 2;
                if(check(x, y, R, mid, j))
                {
                    tam = mid;
                    l = mid + 1;
                }
                else
                {
                    r = mid - 1;
                }
            }
            pre[tam + 1][j] -= z;
        }
        
   }
//    for(int i = 1; i <= n; i++)
//    {
//         for(int j = 1; j <= m; j++)
//         {
//             pre[i][j] += pre[i - 1][j];
//             cout << pre[i][j] << " ";
//         }
//         cout << "\n";
//    }
   int ans = 0;
   int dem = 0;
   for(int i = 1; i <= m; i++)
   {
        for(int j = 1; j <= n; j++)
        {
            pre[j][i] += pre[j - 1][i];
            if(pre[j][i] > ans)
            {
                ans = pre[j][i];
                dem = 1;
            }
            else if(pre[j][i] == ans)
            {
                dem++;
            }
        }
   }
   cout << ans << "\n" << dem;
}
