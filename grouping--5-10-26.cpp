#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N =16 + 1;
const int M =(1 << N) + 2;
int n;
int a[N][N];
int f[M];
int dp[M];
void read()
{
    cin >> n;
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < n; j++)
        {
            cin >> a[i][j];
        }
    }
}
void solve()
{
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        for(int i = 0; i < n; i++)
        {
            if((mask >> i) & 1)
                on.pb(i);
        }
        for(int i = 0; i < on.size(); i++)
        {
            for(int j = i + 1; j < on.size(); j++)
            {
                f[mask] += a[on[i]][on[j]];
            }
        }
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        for(int submask = mask; submask > 0; submask = (submask - 1) & mask)
        {
            dp[mask] = max(dp[mask], dp[mask ^ submask] + f[submask]);
        }
    }
    cout << dp[(1 << n) - 1];
}
