#define name "triprime"
const int MOD = 1000020409;
const int N =1e7 + 9 + 23;
bool dd[N];
vector<int> prime;
int n;
void sang()
{
    for(int i = 2; i < N; i++)
    {
        if(dd[i])
            continue;
        for(int j = i * i; j < N; j += i)
        {
            dd[j] = true;
        }
    }
}
void read()
{
    cin >> n;
}
void solve()
{
    sang();
    for(int i = 2; i < N; i++)
    {
        if(!dd[i])
            prime.pb(i);
    }
    vector<int> ans;
    int tt = 0;
    // cout << prime[tt];
    while(n != 1 && tt < prime.size())
    {
        int dem = 0;
        while(n % prime[tt] == 0)
        {
            n /= prime[tt];
            dem++;
            if(dem > 1)
            {
                cout << "NO";
                exit(0);
            }
            if(dem == 1)
            {
                ans.pb(1);
            }
            // exit(0);
        }
        tt++;
    }
    int tam = ans.size();
    if(n != 1)
        tam++;
    if(tam == 3)
    {
        cout << "YES";
    }
    else
    {
        cout << "NO";
    }
}
