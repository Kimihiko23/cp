void solve()
{
    s = " " + s;
    dp[1] = 1;
    dp[0] = 1;
    int n = s.size() - 1;
    for(int i = 2; i <= n; i++)
    {
        dp[i] = dp[i - 1];
        string tam = s.substr(i - 1, 2);
        // cout << tam << "\n";
        for(auto j : a)
        {
            if(j == tam)
            {
                dp[i]+= dp[i - 2];
            }
        }
        dp[i] %= MOD;
    }
    cout << dp[n];
}
