void solve()
{
    
    int vt1, vt2;
    for(int i = 0; i < ans.size(); i++)
    {
        if(ans[i] == s1)
        {
            vt1 = i;
            break;
        }
    }
    for(int i = 0; i < ans.size(); i++)
    {
        if(ans[i] == s2)
        {
            vt2 = i;
            break;
        }
    }
    // cin >> vt1 >> vt2;
    if(vt2 < vt1)
    {
        swap(vt1, vt2);
    }
    if(vt1 == vt2)
    {
        cout << "Same";
        exit(0);
    }
    if(abs(vt1 - vt2) == 1 || (vt1 == 0 && vt2 == 5))
    {
        cout << "Adjacent";
        exit(0);
    }
    if(abs(vt1 - vt2) == 2)
    {
        vt1++;
        cout << ans[vt1];
        exit(0);
    }
    if(abs(vt1 - vt2) == 4)
    {
        vt2++;
        if(vt2 == 6)
        {
            vt2 = 0;
        }
        cout << ans[vt2];
        exit(0);
    }
    if(abs(vt1 - vt2) == 3)
    {
        cout << "Complementary";
        exit(0);
    }
    // cout << "None";

}
