void solve()
{
    vector<string> ans;
    for(int i = 1; i <= n; i++)
    {
        // cout << s[i] << "\n";
        string so;
        for(int j = s[i].size() - 1; j >= 0; j--)
        {
            if(s[i][j] == ' ')
                break;
            so += s[i][j];
        }
        reverse(so.begin(), so.end());
        int vt = stoll(so);
        string tam;
        int dem = 0;
        for(auto j : s[i])
        {
            auto it = j;
            // it++;
            if(j == ' ')
            {
                if(tam.size() == 0)
                    continue;
                dem++;
                if(dem == vt)
                {
                    ans.pb(tam);
                    break;
                }
                tam.clear();
            }
            else
                tam += j;
        }
    }
    for(auto i : ans)
    {
        cout << i << " ";
    }
}
