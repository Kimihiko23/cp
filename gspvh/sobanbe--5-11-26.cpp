string riels(string s)
{
    sort(s.begin(), s.end());
    s.erase(unique(s.begin(), s.end()), s.end());
    return s;
}

bool hope(string s, string tar)
{
    int n = s.size();
    for (int i = 0; i < n - 1; i++)
    {
        int a = s[i] - '0';
        int b = s[i + 1] - '0';

        if (a > 0 && b < 9)
        {
            string tam = s;
            tam[i]--;
            tam[i + 1]++;
            if (!(i == 0 && tam[i] == '0'))
            {
                if (riels(tam) == tar)
                {
                    return true;
                }
            }
        }

        if (a < 9 && b > 0)
        {
            string tam = s;
            tam[i]++;
            tam[i + 1]--;
            if (riels(tam) == tar)
            {
                return true;
            }
        }
    }
    return false;
}
