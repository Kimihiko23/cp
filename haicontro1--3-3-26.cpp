using namespace std;
const int N =1e5+23;
int l = 1, r = 1;
int n, m;
int a[N], b[N];


void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++) cin >> a[i];
    for(int i = 1; i <= m; i++) cin >> b[i];
}
void solve()
{
    vector<int> ans;
    while(l <= n && r <= m)
    {
        if(a[l] < b[r]) 
        {
            ans.pb(a[l]);
            l++;
        }
        else
        {
            ans.pb(b[r]);
            r++;
        }
    }
    while(l <= n) ans.pb(a[l++]);
    while(r <= m) ans.pb(b[r++]);
    for(int i = 0; i < ans.size() - 1; i++)
            cout << ans[i] << " ";
    cout << ans[ans.size() - 1];
}
