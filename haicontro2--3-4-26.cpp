using namespace std;
const int N =1e6+23;
int n, k;
int a[N];
void read()
{
    cin >> n >> k;
    for (int i = 1; i <= n; i++)
        cin >> a[i];
}
void solve()
{
    int l = 1, r = 1, sum = 0, ans = 0;
    while (r <= n)
    {
        sum += a[r];
        r++;
        while (sum > k)
        {
            sum -= a[l];
            l++;
        }
        if (sum == k)
            ans++;
        
    }
    cout << ans;
}

