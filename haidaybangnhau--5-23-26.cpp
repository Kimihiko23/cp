#define name "input"
const int MOD = 1000020409;
const int N = 1e6 + 23;
int RA = 1, RB = 1;
int n, m;
int a[N], b[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    cin >> m;
    for(int i = 1; i <= m; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    int ans = n;
    while(RA <= n && RB <= m)
    {
        if(a[RA] == b[RB])
        {
            RA++;
            RB++;
        }
        else
        if(a[RA] < b[RB])
        {
            RA++;
            ans--;
            a[RA] += a[RA - 1];
        }
        else
        {
            RB++;
            b[RB] += b[RB - 1];
        }
    }
    cout << ans << "\n";
}
