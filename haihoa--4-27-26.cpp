#define siesta main
using namespace std;
const int MOD = 1000020409;
const int N = 1e5 + 23;

int n, k, a[N], f[N], best[N];

void read()
{
    cin >> n >> k;
    for (int i = 1; i <= n; i++) cin >> a[i];
}

void solve()
{
    deque<int> mx, mn;
    int l = 1;

    for (int r = 1; r <= n; r++)
    {
        while (!mx.empty() && a[mx.back()] <= a[r]) mx.pop_back();
        mx.push_back(r);

        while (!mn.empty() && a[mn.back()] >= a[r]) mn.pop_back();
        mn.push_back(r);

        while (a[mx.front()] - a[mn.front()] > k)
        {
            if (mx.front() == l) mx.pop_front();
            if (mn.front() == l) mn.pop_front();
            l++;
        }

        f[r] = r - l + 1;
    }

    for (int i = 1; i <= n; i++)
        best[i] = max(best[i - 1], f[i]);

    int ans = 0;

    for (int i = 1; i < n; i++)
        ans = max(ans, best[i] + f[i + 1]);

    ans = max(ans, best[n]);

    cout << ans;
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt", "r"))
    {
        freopen("input.txt", "r", stdin);
        freopen("output.txt", "w", stdout);
    }
    read();
    solve();
}