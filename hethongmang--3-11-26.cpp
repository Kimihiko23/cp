using namespace std;
const int N =1e5+23;
int a[N];
int b[N];
int n, m, k, l;
int nen[N];
int tplt = 0;
vector<pair<int, int>> edge;
vector<pair<int, int>> g[N][3];
stack<int> st;
int ndfs[N], ndfs2[N];
int low[N], low2[N];
int dem = 0;
int ans = 0;
void dfs(int u, int id, int ty)
{
    st.push(u);
    ndfs[u] = low[u] = ++dem;
    for(auto i : g[u][ty])
    {
        int idd = i.se;
        int v = i.fi;
        if(idd != id)
        {
            if(ndfs[v] == 0)
            {
                dfs(v, idd, ty);
                low[u] = min(low[u], low[v]);
            }
            else
            {
                low[u] = min(low[u], ndfs[v]);
            }
        }
    }
    if(low[u] == ndfs[u])
    {
        tplt++;
        while(1)
        {
            int x = st.top();
            st.pop();
            nen[x] = tplt;
            if(x == u)
                break;
        }
    }
}
int powera[N], powerb[N];
void read()
{
   cin >> n >> m >> k >> l;
   int tt = 0;
   for(int i = 1; i <= k; i++)
   {
        int x;
        cin >> x;
        g[0][0].pb({x, ++tt});
        g[x][0].pb({0, tt});
   }
   for(int i = 1; i <= l; i++)
   {
        int x;
        cin >> x;
        g[0][1].pb({x, ++tt});
        g[x][1].pb({0, tt});
   }
   int u, v;
   for(int i = 1; i <= m; i++)
   {
        cin >> u >> v;
        edge.pb({u, v});
        g[u][0].pb({v, ++tt});
        g[v][0].pb({u, tt});
        g[u][1].pb({v, tt});
        g[v][1].pb({u, tt});
   }
}
void solve()
{
   for(int i = 0; i <= n; i++)
   {
        if(ndfs[i] == 0)
        {
            dfs(i, -1, 1);
        }
   }
   cout << tplt;
}
