#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m, k, l;
vector<pair<int, int>> g[N], g2[N];

int low[N];
stack<int> st;
int dd[N];
//int in[N];
int out[N];
int ans = 0;
int dem = 0;
int nen[N];
int suma[N], sumb[N];
int a[N], b[N];
vector<pair<int, int>> edges, edges2;
int dpa[N], dpb[N];
bool dd1[N];
void dfs(int u, int idpar)
{
    st.push(u);
    dd[u] = low[u] = ++dem;
    for(auto i : g[u])
    {
        int v = i.fi;
        int id = i.se;
        if(id == idpar)
            continue;
        if(dd[v] == 0)
        {
            dfs(v, id);
            low[u] = min(low[u], low[v]);
        }
        else
            low[u] = min(low[u], dd[v]);
    }
    if(low[u] == dd[u])
    {
        ans++;
        int tam = 0;
        while(1)
        {
            int x = st.top();
            st.pop();
            out[x] = ans;
            nen[x] = ans;
            if(x == u) break;
        }
    }
    
}
int res = 0;
void dfs2(int u, int p)
{
    dd1[u] = true;
    for(auto i : g2[u])
    {
        int v = i.fi;
        int id = i.se;
        if(p == id)
            continue;
        dd1[v] = true;
        dfs2(v, id);
        dpa[u] += dpa[v];
        dpb[u] += dpb[v];
        if (dpa[v] == 0 || dpb[v] == 0 || (k - dpa[v]) == 0 || (l - dpb[v]) == 0) 
        {
            res++;
        }
    }
}
void read()
{
   cin >> n >> m >> k >> l;
   for(int i = 1; i <= k; i++)
   {
        cin >> a[i];
   }
   for(int i = 1; i <= l; i++)
   {
        cin >> b[i];
   }
    for(int i = 1; i <= m; i++)
    {
         int u, v;
         cin >> u >> v;
         g[u].pb({v, i});
         g[v].pb({u, i});
         edges.pb({u, v});
    }
}

void solve()
{
   for(int i = 1; i <= n; i++)
   {
       if(dd[i] == 0)
       {
           dfs(i, -1);
       }
   }
   for(auto i : edges)
   {
       if(nen[i.fi] != nen[i.se])
       {
           edges2.pb({nen[i.fi], nen[i.se]});
       }
   }
   sort(edges2.begin(), edges2.end());
   edges2.erase(unique(edges2.begin(), edges2.end()), edges2.end());
   dem = 0;
   for(auto i : edges2)
   {
        dem++;
        int u = i.fi;
        int v = i.se;
        g2[u].pb({v, dem});
        g2[v].pb({u, dem});
   }
   for(int i = 1; i <= k; i++)
   {
        dpa[nen[a[i]]]++;
   }
   for(int i = 1; i <= l; i++)
   {
        dpb[nen[b[i]]]++;
   }
   for(int i = 1; i <= ans; i++)
   {
        if(!dd1[i])
            dfs2(i, -1);
   }
   cout << res;

}

