void sieve(int r)
{
    pre1[1]=1;
    
    for(int i = 1; i <= r; i++)
        sum[i] = 1;   
    for(int i = 2; i <= r; i++)
    {
        if(mnp[i] == 0)
        {
            mnp[i] = i;
            for(int j = i * i; j <= r; j += i)
            {
                if(mnp[j] == 0)
                    mnp[j] = i;
            }
        }
    }
    for(int i = 2; i <= r; i++)
    {
        int tmp = i;
        int pow = 1;
        int sum1 = 1;
        int mn = mnp[i];
        while(tmp % mn == 0)
        {
            pow *= mn;
            sum1 += pow;
            tmp /= mn;
        }
        sum[i] = sum1 * sum[tmp];
        pre1[i] = pre1[i-1] + abs(i-(sum[i]-i));
    }
}

