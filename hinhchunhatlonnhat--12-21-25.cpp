#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=3e6+23;
int l[N],r[N], a[N];
int n;
void read()
{
    cin >> n;
    for(int i=1;i <= n; i++)
    {
        cin >> a[i];
  
    }
}

void solve()
{
    int ans=0;
    for(int i=1; i <= n; i++)
    {
        l[i]=i;
        while(l[i]-1 >= 1 && a[l[i]-1] >= a[i])
            l[i]=l[l[i]-1];
    }
    for(int i=n; i >= 1; i--)
    {
        r[i]=i;
        while(r[i]+1 <= n && a[i] <= a[r[i]+1])
            r[i]=r[r[i]+1];
    }
    for(int i=1;i <=  n; i++)
    {
        ans=max(ans,(r[i]-l[i]+1)*a[i]);
    }
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
