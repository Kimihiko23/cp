#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=1e3+23;
int n,m,k;
int a[N][N];
deque<pair<int,int>> dq[N];
deque<pair<int,int>> f;
void push(int x,int y)
{
    while(!f.empty() && a[f.back().fi][f.back().se] >= a[x][y])
        f.pop_back();
    f.push_back({x,y});
}
void read()
{
    cin >> n >> m >> k;
    for(int i = 1; i <= n ; i++)
    {
        for(int j = 1; j <= m ; j++)
        {
            cin >> a[i][j];
        }
    }
}

void solve()
{
    int ans=0;
    for(int i = 1; i <= m; i++)
    {
        for(int j = 1; j <= k; j++)
        {
            while(!dq[i].empty() && a[j][i] <= a[dq[i].back().fi][dq[i].back().se])
                dq[i].pop_back();
            dq[i].push_back({j,i});
        }
    }
    for(int i = 1; i <= m; i++)
    {
        push(dq[i].front().fi, dq[i].front().se);
        if (i>=k)
        {
            while(!f.empty() && f.front().se+k<=i)
                f.pop_front();
            ans=max(ans,a[f.front().fi][f.front().se]);
        }
        //cout << f.size() << " ";
        
    }
    //cout << ans;
    for(int i = k+1; i <= n; i++)
    {
        f.clear();
        for(int j = 1; j <= m; j++)
        {
            while(!dq[j].empty() && a[i][j] <= a[dq[j].back().fi][dq[j].back().se])
                dq[j].pop_back();
            dq[j].push_back({i,j});
            while(!dq[j].empty() && dq[j].front().fi+k<=i)
                dq[j].pop_front();
        }
        for(int j = 1; j <= m; j++)
        {
            push(dq[j].front().fi, dq[j].front().se);
            if (j>=k)
            {
                while(!f.empty() && f.front().se+k<=j)
                    f.pop_front();
                ans=max(ans,a[f.front().fi][f.front().se]);
            }
            
        }
    }
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
    
   
}