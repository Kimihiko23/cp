#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=2000+23;
int pre1[N][N], a[N][N],n,m, pre2[N][N];
void read()
{
    cin >> n >> m;
    for(int i=1; i <= m; i++)
    {
        a[0][i]=0;
    }
    for(int i=1; i <= n; i++)
    {
        for(int j=1; j <= m; j++)
        {
            cin >> a[i][j];
            if(a[i][j] == 1)
            {
                pre1[i][j]= pre1[i-1][j]+1;
            }
            else
                pre2[i][j]= pre2[i-1][j]+1;
        }
    }
}

void solve()
{
    int ans=0;
    int l1[N],r1[N], l2[N], r2[N];
    
    for(int i=1; i <= n; i++)
    {
        for(int j=1; j <= m; j++)
        {
            l1[j] = j;
            l2[j] = j;
            while(l1[j]-1 >= 1 && 
                pre1[i][j] <= pre1[i][l1[j]-1])
                l1[j]=l1[l1[j]-1];
            while(l2[j]-1 >= 1 && 
            pre2[i][j] <= pre2[i][l2[j]-1])
                l2[j]=l2[l2[j]-1];
        }
        for(int j=m; j >= 1; j--)
        {
            r1[j]=j;
            r2[j] = j;
            while(r1[j]+1 <= m && 
                pre1[i][j] <= pre1[i][r1[j]+1])
                r1[j]=r1[r1[j]+1];
            while(r2[j]+1 <= m && 
            pre2[i][j] <= pre2[i][r2[j]+1])
                r2[j]=r2[r2[j]+1];
        }
        for(int j=1; j <= m; j++)
        {
            int tam1 = min(pre1[i][j], r1[j] - l1[j]+1);
            int tam2 = min(pre2[i][j], r2[j] - l2[j]+1);
            ans=max({ans, tam1, tam2});
        }
        
        
    }
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
