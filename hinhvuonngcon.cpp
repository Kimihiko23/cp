#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N=1e3+23;
int n,m,k;
int a[N][N];
deque<pair<int,int>> dq;
void push(int x, int y)
{
    while(!dq.empty() && a[x][y] <= a[dq.back().fi][dq.back().se])
        dq.pop_back();
    dq.push_back({x,y});
}
void read()
{
    cin >> n >> m >> k;
    for(int i = 1; i <= n ; i++)
    {
        for(int j = 1; j <= m ; j++)
        {
            cin >> a[i][j];
        }
    }
}

void solve()
{
    int ans=0;
    for(int i = 1; i <= (n-k+1) ; i++)
    {
        
        dq.clear();
        for(int z = 1; z <= (1+k-1); z++) // Cột chạy từ 1 -> k
        {
            for(int j = i; j <= (i+k-1) ; j++) // Hàng chạy từ i -> i+k-1
            {
                push(j,z);
            }
        }
        //cout << "\n";
        ans=max(ans,a[dq.front().fi][dq.front().se]);
        for(int j = k+1; j <= m ; j++)
        {
            //j la cot moi them vao
            for(int z = i; z <= (i+k-1) ; z++)
            {
                //cout << a[z][j] << " ";
                push(z,j);
                // chay tung dong
            }
            while(!dq.empty() && dq.front().se+k <= j)
            {
                dq.pop_front();
            }
            if(!dq.empty())
                ans=max(ans,a[dq.front().fi][dq.front().se]);
        }
        
    }
    cout << ans;
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
