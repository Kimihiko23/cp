void solve()
{
    stack<int> st;
    for(char c : s)
    {
        if(c == 'C') st.push(12);
        else if(c == 'H') st.push(1);
        else if(c == 'O') st.push(16);
        else if(c == '(') st.push(-1);
        else if(c == ')')
        {
            int sum = 0;
            while(st.top() != -1)
            {
                sum += st.top();
                st.pop();
            }
            st.pop();
            st.push(sum);
        }
        else
        {
            int k = c - '0';
            int x = st.top(); st.pop();
            st.push(x * k);
        }
    }

    int res = 0;
    while(!st.empty())
    {
        res += st.top();
        st.pop();
    }
    cout << res;
}

