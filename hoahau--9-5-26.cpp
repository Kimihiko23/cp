struct hoahau
{
    int a, b, c, d;
};

int n;
hoahau e[N];

bool cmp(hoahau a, hoahau b)
{
    return a.a < b.a;
}

void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
        cin >> e[i].a >> e[i].b >> e[i].c >> e[i].d;
}

void solve()
{
    sort(e + 1, e + 1 + n, cmp);

    int ans = 0;

    for (int i = 1; i <= n; i++)
    {
        bool check = false;

        for (int j = i + 1; j <= n; j++)
        {
            if (e[j].b > e[i].b &&
                e[j].c > e[i].c &&
                e[j].d > e[i].d)
            {
                check = true;
                break;
            }
        }

        if (check)
            ans++;
    }

    cout << ans;
}

