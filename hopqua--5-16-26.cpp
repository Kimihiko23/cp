int a[N];
int n, d;

void read()
{
    cin >> n >> d;

    for (int i = 1; i <= n; i++)
        cin >> a[i];
}

void solve()
{
    sort(a + 1, a + n + 1);

    int l = 1;
    int ans = 0;

    for (int r = 1; r <= n; r++)
    {
        while (a[r] - a[l] > d)
            l++;

        int len = r - l;

        if (len >= 2)
            ans += len * (len - 1) / 2;
    }

    cout << ans;
}

