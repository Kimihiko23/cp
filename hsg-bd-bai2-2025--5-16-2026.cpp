void read()
{
    cin >> n >> m;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        s1.insert(x);
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> x;
        s2.insert(x);
    }
}
void solve()
{
    int ans = 0;
    for(auto i : s2)
    {
        auto it = s1.lower_bound(i);
        if(it == s1.end())
        {
            cout << -1;
            exit(0);
        }
        ans += *it;
        s1.erase(it);
    }
    cout << ans;
}
