using namespace std;
const int N =1e5+23;

bool dd[N];
int a[N];
void sieve()
{
    dd[1] = false;
    for(int i = 2; i <= N; i++)
    {
        int tam = 0;
        for(int j = 2; j <= sqrt(i) + 1; j++)
        {
            if(i % j == 0)
            {
                tam+=2;
            }
        }
        if(tam == 0)
        {
            dd[i] = true;
        }
    }
}
int dem = 0;
void read()
{
   sieve();
   int x;
   while(cin >> x)
   {
        dem++;
        a[dem] = x;
   }
}
void solve()
{
   for(int i = dem - 1; i >= 2; i--)
   {
        if(a[i - 1] >= 0 && a[i + 1] >= 0 && dd[a[i - 1]] && dd[a[i + 1]])
        {
            cout <<i;
            return;
        }
   }
   cout << 0;
}
