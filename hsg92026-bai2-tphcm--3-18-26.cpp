using namespace std;
const int N =1e3+23;
int n, m;
int a[N];
int dp[N][N];
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j < m; j++)
        {
            int tam = dp[i - 1][j] + a[i];
            int mod = tam % m;
            dp[i][mod] = max(dp[i][mod], tam);
        }
        for(int j = 0; j < m; j++)
        {
            dp[i][j] = max(dp[i][j], dp[i - 1][j]);
        }
    }
    cout << dp[n][0];
}

