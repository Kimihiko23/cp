const int N = 1e5 + 23;
int n, m, p, c;
int a[N];
int s[N];
int dp[N][64 + 23];
void read()
{
    cin >> n >> m >> p >> c;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    for(int i = 0; i < m; i++)
    {
        cin >> s[i];
    }
}
void solve()
{
    /*
    dp[i][mask] xét tới thằng thứ y;


    dp[7][1010] = max

    dp[7 - S1][1010] + sum;
    dp[7 - S1][0010] + sum;

    dp[7 - S3][1010] + sum;
    dp[7 - S3][1000] + sum;
    */
    sort(a + 1, a + n + 1);
    dp[0][0] = 0;
    for(int mask = 1; mask < (1 << m); mask++)
    {
        dp[0][mask] = -1e18;
    }
    for(int i = 1; i <= n; i++)
    {
        for(int mask = 0; mask < (1 << m); mask++)
        {
            dp[i][mask] = dp[i - 1][mask];
            for(int x = 0; x < m; x++)
            {
                if(mask && (1 << x) && i >= s[x])
                {
                    int sum = p - (a[i] - a[i - s[x] + 1]) * (a[i] - a[i - s[x] + 1]) * c;
                    dp[i][mask] = max({dp[i][mask], 
                        dp[i - s[x]][mask] + sum, 
                        dp[i - s[x]][mask ^ (1 << x)] + sum});
                }
            }
        }
    }
    cout << dp[n][(1 << m) - 1];

}
