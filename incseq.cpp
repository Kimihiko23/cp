using namespace std;
const int N = 1005;
int dp[N][N]; 
string s;
int n;

bool check(int p, int q, int i, int j) 
{
    while (p < q && s[p] == '0') p++;
    while (i < j && s[i] == '0') i++;

    int len1 = q - p + 1;
    int len2 = j - i + 1;

    if (len1 != len2) return len1 < len2;
    for (int k = 0; k < len1; k++) 
    {
        if (s[p + k] != s[i + k]) return s[p + k] < s[i + k];
    }
    return false;
}
void read()
{
    cin >> n >> s;
}

void solve() 
{
    s = " " + s;
    int ans = 1;
    for (int j = 1; j <= n; j++) 
    {
        for (int i = 1; i <= j; i++) 
        {
            dp[i][j] = 1;
            for (int q = 1; q < i; q++) 
            {
                for (int p = 1; p <= q; p++)
                {
                    if (check(p, q, i, j)) {
                        dp[i][j] = max(dp[i][j], dp[p][q] + 1);
                    }
                }
            }
            ans = max(ans, dp[i][j]);
        }
    }
    cout << ans;
}

