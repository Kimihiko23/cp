using namespace std;
const int N =1e5+23;
int n, l, r, a[N];
int pre[N];
deque<int> dq;
void push(int vt)
{
    while(!dq.empty() && pre[vt] < pre[dq.back()])
        dq.pop_back();
    dq.push_back(vt);

}
void read()
{
   cin >> n >> l >> r;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
   }
}
void solve()
{
   int ans = -1e18;
   push(0);
   for(int i = l; i <= n; i++)
   {
        while(!dq.empty() && dq.front() < i - r)
            dq.pop_front();
        int tam = pre[i] - pre[dq.front()];
        ans = max(ans, tam);
        push(i - l + 1);
   }
   cout << ans;
}
