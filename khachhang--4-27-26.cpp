const int MOD = 1000020409;
const int N =1e5+23;
multiset<pair<int, int>> s;
int n;
int b[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        s.insert({x, i});
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> b[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        auto it = s.lower_bound({b[i], 0});
        if(it == s.end())
        {
            it = min_element(s.begin(), s.end(), [](auto a, auto b)
                {return a.second < b.second;});
        }
        cout << (*it).se << " ";
        s.erase(it);
    }
}
