void solve()
{
    long double ans = 1e18;
    long double l = 0, r = 1;
    for(int i = 0; i < 100; i++)
    {
        long double m1 = l + (r - l) / 3;
        long double m2 = r - (r - l) / 3;
        long double d1 = dist(m1);
        long double d2 = dist(m2);
        if(d1 <= d2)
        {
            r = m2;
            ans = min(ans, d1);
        }
        else
        {
            l = m1;
            ans = min(ans, d2);
        }
    }
    cout << fixed << setprecision(6) << ans << "\n";
}
