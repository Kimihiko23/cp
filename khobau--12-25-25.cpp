#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
using namespace std;
const int N =9;
int n=3, m=3;
bool dd[N][N];
char a[N][N];
int q;
vector<int> ans;
void dequy(int x,int y, string s, int dem)
{
    if (dem==9)
    {
        ans.pb(stoi(s));
        return;
    }
    if(x < 1 || x >n || y < 1 || y > m)
    {
        return;
    }
    vector<int> dx = {0, 0, 1, -1};
    vector<int> dy = {1, -1, 0, 0};
    for(auto i=0;i<4;i++)
    {
        int xx = x + dx[i];
        int yy = y + dy[i];
        if(xx >= 1 && xx <= n && yy >= 1 && yy <= m && dd[xx][yy]==false)
        {
            dd[xx][yy]=true;
            dequy(xx, yy, s + a[xx][yy], dem + 1);
            dd[xx][yy]=false;
        }
    }
}
void read()
{
    cin >> q;
}
void solve()
{
    ans.clear();
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dd[i][j]=false;
        }
    }
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            dd[i][j]=true;
            dequy(i, j, string(1, a[i][j]), 1);
            dd[i][j]=false;
        }
    }
    sort(ans.begin(), ans.end());
    cout << ans[ans.size()-1] << "\n";
    
}
main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    while(q--)
            solve();    
}
