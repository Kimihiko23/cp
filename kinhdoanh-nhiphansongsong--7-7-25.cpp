int n, m, q;
int dema[N];
int L[N], R[N], ans[N];
int in[N], out[N];
int cnt = 0;
int st[N * 4][2];
int lz[N * 4][2];
int h[N];
struct query
{
    int f, x, d;
};
query qe[N];
void down(int id, int l, int r, int mid, int ty)
{
    if(lz[id][ty] == 0)
        return;
    int x = lz[id][ty];
    st[id * 2][ty] += (mid - l + 1) * x;
    st[id * 2 + 1][ty] += (r - l) * x;
    lz[id * 2][ty] += x;
    lz[id * 2 + 1][ty] += x;
    
    lz[id][ty] = 0;
}
void update(int id, int l, int r, int u, int v, int val, int ty)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id][ty] += (r - l + 1) * val;
        lz[id][ty] += val;
        return;
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid, ty);
    update(id * 2, l, mid, u, v, val, ty);
    update(id * 2 + 1, mid + 1, r, u, v, val, ty);
    st[id][ty] = st[id * 2][ty] + st[id * 2 + 1][ty];
}
int get(int id, int l, int r, int u, int v, int ty)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
    {
        return st[id][ty];
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid, ty);
    int l = get(id * 2, l, mid, u, v, ty);
    int r = get(id * 2 + 1, mid + 1, r, u, v, ty);
    return l + r;
}
void dfs(int u, int p)
{
    in[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        h[v] = h[u] + 1;
        dfs(v, u);
    }
    out[u] = cnt;
}
