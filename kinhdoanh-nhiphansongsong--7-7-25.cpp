mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<int> g[N];
vector<int> ow[N];
int n, m, q;
int dema[N];
int L[N], R[N], ans[N];
int in[N], out[N];
int cnt = 0;

int h[N];
vector<int> check[N];
struct query
{
    int f, x, d;
};
query qe[N];
int bit[N][2];


void add(int idx, int val, int ty)
{
    for (; idx <= n; idx += idx & -idx)
        bit[idx][ty] += val;
}


void update_range(int l, int r, int val, int ty)
{
    if (l > r) return;
    add(l, val, ty);
    add(r + 1, -val, ty);
}


int get_point(int idx, int ty)
{
    int sum = 0;
    for (; idx > 0; idx -= idx & -idx)
        sum += bit[idx][ty];
    return sum;
}
void dfs(int u, int p)
{
    in[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        h[v] = h[u] + 1;
        dfs(v, u);
    }
    out[u] = cnt;
}
