void solve()
{
    dfs(1, 0);
    while(1)
    {
        bool stop = true;
        memset(bit, 0, sizeof(bit));
        for(int i = 1; i <= m; i++)
        {
            if(L[i] > R[i])
                continue;
            stop = false;
            int tam = (L[i] + R[i]) / 2;
            check[tam].pb(i);
        }
        if(stop)
            break;
        for(int i = 0; i <= q; i++)
        {
            if(i > 0)
            {
                int u = qe[i].f;
                int x = qe[i].x;
                int d = qe[i].d;
                update_range(in[u], out[u], x - h[u] * d, 0);
                update_range(in[u], out[u], d, 1);
            }
            for(auto id : check[i])
            {
                int who = id;
                int need = dema[who];
                int have = 0;
                for(auto u : ow[who])
                {
                    have += get_point(in[u], 0) + h[u] * get_point(in[u], 1);
                }
                if(have >= need)
                {
                    ans[who] = i;
                    R[who] = i - 1;
                }
                else
                {
                    L[who] = i + 1;
                }
            }
            check[i].clear();
        }
    }
    for(int i = 1; i <= m; i++)
    {
        cout << ans[i] << "\n";
    }
}
