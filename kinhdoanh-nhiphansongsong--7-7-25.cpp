void solve()
{
    while(1)
    {
        bool stop = true;
        vector<int> check[N];
    
        for(int i = 1; i <= m; i++)
        {
            if(L[i] > R[i])
                continue;
            stop = false;
            int tam = L[i] + R[i] / 2;
            check[tam].pb(i);
        }
        
    }
}
