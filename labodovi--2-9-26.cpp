using namespace std;
const int N =1e3 + 523;
int n, m;
char a[N][N];
bool dd[N][N];
int par[N * N];
vector<pair<int, int>> st;
queue<pair<int, int>> que[3];

int conve(int x, int y)
{
    return (x-1) * m + y;
}

int findpar(int u)
{
    if(par[u] == u)
    return par[u];
    else
    return par[u] = findpar(par[u]);
}
void join(int u, int v)
{
    int x = findpar(u);
    int y = findpar(v);
    if(x == y)
    {
        return;
    }
    else
    par[y] = par[x];
}
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
void loang(int stx, int sty)
{
    queue<pair<int, int>> tt;
    tt.push({stx, sty});
    dd[stx][sty] = true;
    int id1 = conve(stx, sty);
    vector<int> dx = {0, 0, -1, 1};
    vector<int> dy = {1, -1, 0, 0};
    while(!tt.empty())
    {
        auto tam = tt.front();
        tt.pop();
        int ux = tam.fi;
        int uy = tam.se;
        for(int i = 0; i < 4; i++)
        {
            int vx = ux + dx[i];
            int vy = uy + dy[i];
            if(check(vx, vy) && !dd[vx][vy] && a[vx][vy] != 'X')
            {
                int id2 = conve(vx, vy);
                dd[vx][vy] = true;
                join(id1, id2);
                tt.push({vx, vy});
            }
        }
    }

}
