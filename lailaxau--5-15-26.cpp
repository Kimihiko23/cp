const int N = (1 << 20) + 23;
int n;
string s;
string in;
int a;
int dis[N];
void bfs(int u)
{
    for(int i = 0; i < (1 << n); i++)
    {
        dis[i] =1e18;
    }
    dis[u] = 0;
    queue<int> q;
    q.push(u);
    while(!q.empty())
    {
        int u = q.front();
        q.pop();
        if(u == 0 || u == (1 << n) - 1)
        {
            cout << dis[u];
            break;
        }
        for(int i = 1; i < n; i++)
        {
            int v = (u ^ (1 << i) ^ (1 << (i - 1)));
            if(dis[v] > dis[u] + 1)
            {
                dis[v] = dis[u] + 1;
                q.push(v);
            }
        }
        for(int i = 2; i < n; i++)
        {
            int v = (u ^ (1 << i) ^ (1 << (i - 1)) ^ (1 << (i - 2)));
            if(dis[v] > dis[u] + 1)
            {
                dis[v] = dis[u] + 1;
                q.push(v);
            }
        }
    }
}
void read()
{
    cin >> n >> s;
    int dem = 0;
    for(int i = s.size() - 1; i >= 0; i--)
    {
        int tam = s[i] - 'A';
        int val = (1 << dem);
        dem++;
        a += val * tam;
    }
}
void solve()
{
    bfs(a);
}
