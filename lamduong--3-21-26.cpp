#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
#define siesta main
using namespace std;

struct E { int u, v; };
int m, s, t;
vector<E> e;
vector<int> p;

int get(int x) 
{
    return lower_bound(p.begin(), p.end(), x) - p.begin();
}

bool check(int k) 
{
    int n = p.size();
    vector<vector<int>> g(n);
    for (int i = 0; i < k; i++) g[get(e[i].u)].pb(get(e[i].v));
    
    vector<bool> vs(n, 0);
    queue<int> q;
    int st = get(s), en = get(t);
    q.push(st); vs[st] = 1;
    
    while (!q.empty()) 
    {
        int u = q.front(); q.pop();
        if (u == en) return 1;
        for (int v : g[u]) if (!vs[v]) { vs[v] = 1; q.push(v); }
    }
    return 0;
}

void read() 
{
    cin >> m >> s >> t;
    p.pb(s); p.pb(t);
    for (int i = 0, u, v; i < m; i++) 
    {
        cin >> u >> v;
        e.pb({u, v});
        p.pb(u); p.pb(v);
    }
    sort(p.begin(), p.end());
    p.erase(unique(p.begin(), p.end()), p.end());
}

void solve() 
{
    int l = 1, r = m, res = 0;
    while (l <= r) {
        int mid = (l + r) / 2;
        if (check(mid)) { res = mid; r = mid - 1; }
        else l = mid + 1;
    }
    cout << res;
}

siesta() {
    ios::sync_with_stdio(0);
    cin.tie(0); cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();

}