void solve()
{
    s.insert({1, n, 'A'});
    add1(n, n);
    add2(n, 1);
    int ty, l, r;
    char x;
    while(q--)
    {
        cin >> ty >> l;
        if(ty == 1)
        {
            cin >> r >> x;
            l++;
            r++;
            auto le = s.lower_bound({l, 0, 0});
            auto prele = le;
            
            bool atStart = (prele != s.end() && prele->idx == l);
            if(!atStart) prele--; 
            int left = prele->idx;
            int right = prele->idx + prele->len - 1;
            if(left <= l && right >= r)
            {
                if(prele->ty == x)
                {
                    l = left;
                    r = right;
                    del(prele);
                    s.erase(prele);
                }
                else
                {
                    char old = prele->ty;
                    del(prele);
                    s.erase(prele);

                    if(l - left > 0)
                    {
                        int len1 = l - left;
                        s.insert({left, len1, old});
                        add1(len1, len1);
                        add2(len1, 1);
                    }
                    if(right - r > 0)
                    {
                        int len2 = right - r;
                        s.insert({r + 1, len2, old});
                        add1(len2, len2);
                        add2(len2, 1);
                    }
                }
                // add1(r - l + 1, r - l + 1);
                // add2(r - l + 1, 1);
                s.insert({l, r - l + 1, x});
                auto it = s.lower_bound({l, r - l + 1, x});
                auto lef = it;
                auto rig = it;
                if(it != s.begin())
                {
                    lef--;
                    if(lef->ty == x)
                    {
                        l = lef->idx;
                        del(lef);
                        s.erase(lef);
                    }
                }
                if(it != prev(s.end()))
                {
                    rig++;
                    {
                        if(rig->ty == x)
                        {
                            r = rig->idx + rig->len - 1;
                            del(rig);
                            s.erase(rig);
                        }
                    }
                }
                s.erase(it);
                add1(r - l + 1, r - l + 1);
                add2(r - l + 1, 1);
                s.insert({l, r - l + 1, x});
            }
            else
            {
                bool cutl = !atStart;
                bool cutr = true;

                while(le != s.end() && (le->idx + le->len - 1) <= r)
                {
                    del(le);
                    le = s.erase(le);
                }

                if(le == s.end()) cutr = false;
                else if(le->idx > r) cutr = false;

                if(cutl)
                {
                    if(prele->ty == x)
                    {
                        l = prele->idx;
                        del(prele);
                        s.erase(prele);
                    }
                    else
                    {
                        int nxlen = l - prele->idx;
                        int nxidx = prele->idx;
                        char nxty = prele->ty;
                        del(prele);
                        s.erase(prele);
                        add1(nxlen, nxlen);
                        add2(nxlen, 1);
                        s.insert({nxidx, nxlen, nxty});
                    }
                }
                if(cutr)
                {
                    if(le->ty == x)
                    {
                        r = le->idx + le->len - 1;
                        del(le);
                        s.erase(le);
                    }
                    else
                    {
                        int nxidx = r + 1;
                        int nxlen = le->idx + le->len - 1 - r;
                        char nxty = le->ty;
                        del(le);
                        s.erase(le);
                        add1(nxlen, nxlen);
                        add2(nxlen, 1);
                        s.insert({nxidx, nxlen, nxty});
                    }
                }
                
                s.insert({l, r - l + 1, x});
                auto it = s.lower_bound({l, r - l + 1, x});
                auto lef = it;
                auto rig = it;
                if(it != s.begin())
                {
                    lef--;
                    if(lef->ty == x)
                    {
                        l = lef->idx;
                        del(lef);
                        s.erase(lef);
                    }
                }
                if(it != prev(s.end()))
                {
                    rig++;
                    {
                        if(rig->ty == x)
                        {
                            r = rig->idx + rig->len - 1;
                            del(rig);
                            s.erase(rig);
                        }
                    }
                }
                s.erase(it);
                add1(r - l + 1, r - l + 1);
                add2(r - l + 1, 1);
                s.insert({l, r - l + 1, x});
            }
        }
        else
        {
            int ans = get1(l + 1, n) - l * get2(l + 1, n);
            cout << ans << "\n";
        }
    }
}
