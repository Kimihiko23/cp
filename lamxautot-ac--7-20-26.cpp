mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int bit1[N];
int bit2[N];
int n , q;
struct node
{
    int idx, len;
    char ty;
    bool operator<(const node &other) const
    {
        return idx  < other.idx;
    }
};
set<node> s;
void add1(int id, int val)
{
    while(id <= n)
    {
        bit1[id] += val;
        id += id & (-id);
    }
}
int sum1(int id)
{
    int res = 0;
    while(id > 0)
    {
        res += bit1[id];
        id -= id & (-id);
    }
    return res;
}
int get1(int l, int r)
{
    return sum1(r) - sum1(l - 1);
}
void add2(int id, int val)
{
    while(id <= n)
    {
        bit2[id] += val;
        id += id & (-id);
    }
}
int sum2(int id)
{
    int res = 0;
    while(id > 0)
    {
        res += bit2[id];
        id -= id & (-id);
    }
    return res;
}
int get2(int l, int r)
{
    return sum2(r) - sum2(l - 1);
}
void del(set<node>::iterator it)
{
    int leng = (*it).len;
    add1(leng, -leng);
    add2(leng, -1);
}
