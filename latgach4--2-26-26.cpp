void solve()
{
   dp[1] = 1;
   dp[2] = 5;
   dp[3] = 11;
   dp[4] = 33;
   ans[1] = 0;
   ans[2] = 12;
   ans[3] = 36;
   ans[4] = 156;
   for(int i = 5; i <= n; i++)
   {
      dp[i] = dp[i - 1] + 4 * dp[i - 2] + 2 * dp[i - 3];
      ans[i] = ans[i - 1] + 4 * ans[i - 2] + 2 * ans[i - 3] + 12 * (dp[i - 2] + dp[i - 3]);
      dp[i] %= mod;
      ans[i] %= mod;
      // dp[i]=dp[i-1]*2+dp[i-2]+12;
   }
   cout << ans[n];
}
