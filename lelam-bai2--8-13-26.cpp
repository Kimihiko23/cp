mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, c, d;
int a[N];
int prec[N];
int pred[N];
int cal(int cop)
{
    return pred[n] - pred[n - cop] + prec[n - cop] - prec[cop];
}
void read()
{
    cin >> n >> c >> d;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    for(int i = 1; i <= n; i++)
    {
        prec[i] = prec[i - 1] + a[i] - c;
        pred[i] = pred[i - 1] + a[i] - d;
    }
    int ans = prec[n];
    for(int i = 1; i <= n / 2; i++)
    {
        ans = max(ans, cal(i));
    }
    cout << ans << "\n";
}
