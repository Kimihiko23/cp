struct thing
{
    int a, t;
};
vector<thing> item;
int cnt[11][11];
int n, T;
int dp[N];
void read()
{
    cin >> n >> T;
    int a, t;
    for(int i = 1; i <= n; i++) 
    {
        cin >> a >> t;
        cnt[a][t]++;
    }
}
void solve()
{
    for(int i = 1; i <= 10; i++)
    {
        for(int j = 1; j <= 10; j++)
        {
            if(cnt[i][j] == 0)
                continue;
            int mul = 1;
            while(mul <= cnt[i][j])
            {
                int a = i * mul;
                int t = j * mul;
                item.pb({a, t});
                cnt[i][j] -= mul;
                mul *= 2;
            }
            if(cnt[i][j] > 0)
            {
                int a = i * cnt[i][j];
                int t = j * cnt[i][j];
                item.pb({a, t});
            }
            
        }
    }
    for(int i = 1; i <= T; i++)
    {
        dp[i] = -1e18;
    }
    for(auto i : item)
    {
        for(int j = T; j >= 1; j--)
        {
            if(j - i.t >= 0)
            {
                dp[j] = max(dp[j], dp[j - i.t] + i.a);
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= T; i++)
    {
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
