char a[N][N];
vector<pair<int, int>> g[N];
int n, m;
int dis[N][N];
vector<int> dx{0, 0, -1, 1};
vector<int> dy{1, -1, 0, 0};
bool dd[N][N];
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
void bfs(int stx, int sty)
{
    queue<pair<int, int>> q;
    q.push({stx, sty});
    dd[stx][sty] = 1;
    while(!q.empty())
    {
        auto vt = q.front();
        auto u = a[vt.fi][vt.se];
        q.pop();
        if(u == '#')
            continue;
        for(int i = 0; i < 4; i++)
        {
            int vx = vt.fi + dx[i];
            int vy = vt.se + dy[i];
            if(check(vx, vy) && a[vx][vy] != '#' && dd[vx][vy] == 0)
            {
                dd[vx][vy] = 1;
                dis[vx][vy] = dis[vt.fi][vt.se] + 1;
                q.push({vx, vy});
            }
        }
        if(u == '.')
            continue;
        for(auto i : g[u - 'a'])
        {
            if(!dd[i.fi][i.se])
            {
                dd[i.fi][i.se] = 1;
                dis[i.fi][i.se] = dis[vt.fi][vt.se] + 1;
                q.push({i.fi, i.se});
            }
        }

    }
    
}
