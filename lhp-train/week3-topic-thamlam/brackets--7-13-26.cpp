mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n;
pair<int, int> a[N];
bool dd[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].fi;
        a[i].se = i;
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    int sum = 0;
    int l = 1, r = n;
    while(l < r)
    {
        sum += a[r].fi - a[l].fi;
        dd[a[r].se] = 1;
        dd[a[l].se] = 0;
        l++;
        r--;
    }
    cout << sum << "\n";
    int opencout = 1;
    int curval = dd[1];
    cout << "(";
    for(int i = 2; i <= n; i++)
    {
        if(dd[i] == curval)
        {
            opencout++;
            cout << "(";
        }
        else
        {
            opencout--;
            if(opencout == 0)
            {
                curval = dd[i + 1];
            }
            cout << ")";
        }
        
    }
    cout << "\n";

}
