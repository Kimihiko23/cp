int n;
int a[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    int ans = 0;
    int l = 1, r = n;
    while(l < r)
    {
        ans += abs(a[l] - a[r]);
        l++;
        r--;
    }
    cout << ans;
}
