const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n;
pair<int, int> a[N], b[N];
bool prime[N];
int dp[N];
bool dd[N];
int truyvet[N];
vector<int> res;
void who(int vt)
{
    if(vt == truyvet[vt]) 
    {
        res.pb(vt);
        return;
    }
    res.pb({vt});
    who(truyvet[vt]);
}
void sang()
{
    prime[0] = 1;
    prime[1] = 1;
    for(int i = 2; i < N; i++)
    {
        if(prime[i]) continue;
        for(int j = i * i; j < N; j += i)
        {
            prime[j] = 1;
        }
    }

}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].fi;
        a[i].se = i;
        b[i].fi = a[i].fi;
        b[i].se = i;
    }
}
void solve()
{
    sort(a + 1, a + n + 1);
    sang();
    for(int i = 1; i <= n; i++)
    {
        int idx = a[i].se;
        dd[idx] = 1;
        dp[idx] = 1;
        truyvet[idx] = idx;
        for(int j = max(idx - 5, (int)1); j <= min(n, idx + 5); j++)
        {
            if(j == idx || !dd[j]) continue;
            int dif = b[idx].fi - b[j].fi;
            if(dif < 0)
                continue;
            if(prime[dif] == 0)
            {
                if(dp[j] + 1 > dp[idx])
                {
                    dp[idx] = dp[j] + 1;
                    truyvet[idx] = j;
                }
            }
        }
    }
    int ans = 0;
    int vt = -1;
    for(int i = 1; i <= n; i++)
    {
        if(dp[i] > ans)
        {
            ans = dp[i];
            vt = i;
        }
        // cout << truyvet[i] << " " << dp[i] << "\n";
    }
    // cout << vt << "\n";
    // cout << "\n";
    who(vt);
    reverse(res.begin(), res.end());
    cout << ans << "\n";
    for(auto i : res)
    {
        cout << b[i].se << " ";
    }
}
