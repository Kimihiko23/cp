using namespace std;
const int N =2e3+23;
int pre[N][N];
int n, m, k;
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}
void read()
{   
    cin >> n >> m >> k;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            int x;
            cin >> x;
            pre[i][j] = x + pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1];
        }
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int x1 = 1;
        int y1 = i;
        int x2 = x1;
        int y2 = y1;
        while(y2 <= m && x2 <= n)
        {
            int tam = cal(x1, y1, x2, y2);
            if(tam == k)
            {
                ans = max(ans, (x2 - x1 + 1)* (y2 - y1 + 1));
                x2++;
                y2++;
            }
            else
            {
                if(tam >= k)
                {
                    if(x1 < x2 && y1 < y2)
                    {
                        x1++;
                        y1++;
                    }
                    else
                    {
                        x2++;
                        y2++;
                    }
                }
                else
                {
                    x2++;
                    y2++;
                }
            }
        }
    }
    for(int i = 1; i <= m; i++)
    {
        int x1 = i;
        int y1 = 1;
        int x2 = x1;
        int y2 = y1;
        while(y2 <= m && x2 <= n)
        {
            int tam = cal(x1, y1, x2, y2);
            if(tam == k)
            {
                ans = max(ans, (x2 - x1 + 1)* (y2 - y1 + 1));
                x2++;
                y2++;
            }
            else
            {
                if(tam >= k)
                {
                    if(x1 < x2 && y1 < y2)
                    {
                        x1++;
                        y1++;
                    }
                    else
                    {
                        x2++;
                        y2++;
                    }
                }
                else
                {
                    x2++;
                    y2++;
                }
            }
        }
    }
    cout << ans;
}

