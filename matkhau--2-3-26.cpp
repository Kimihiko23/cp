#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =   31624;
bool dd[N];
vector<int> prime;
void sieve()
{
    dd[0]=dd[1]=1;
    for(int i = 2;i <= N; i++)
    {
        if(!dd[i])
        {
            prime.pb(i);
            for(int j = i*i;j <= N; j += i)
            {
                dd[j]=1;
            }
        }
    }
}
int n;
int check(int x)
{
    if(x < N)
    {
        return (dd[x] == 0) ? 1 : 0;
    }
    for(auto i : prime)
    {
        if(i*i > x)
            break;
        if (x % i == 0)
        {
            return 0;
        }
        
    }
    return 1;
}
void read()
{
   cin >> n;
   sieve();

}

void solve()
{
   while(n--)
   {
        int x;
        cin >> x;
        cout << check(x) << "\n";
   }
}

