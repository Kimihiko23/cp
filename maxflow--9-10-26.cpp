vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
vector<int> g[N];
int n, q;
int par[22][N];
int h[N];
int diff[N];
void dfs(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        par[0][v] = u;
        h[v] = h[u] + 1;
        dfs(v, u);
    }
}
void init()
{
    for(int j = 1; j < 21; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[j][i] = par[j - 1][par[j - 1][i]];
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v])
        swap(u, v);
    for(int i  = 20; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
            u = par[i][u];
    }
    if(u == v)
        return u;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            u = par[i][u];
            v = par[i][v];
        }
    }
    return par[0][u];
}
void dfs2(int u, int p)
{
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dfs2(v, u);
        diff[u] += diff[v];
    }
}
void read()
{
    cin >> n >> q;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    par[0][1] = 1;
    dfs(1, 0);
    init();
    int u, v;
    vector<pair<int, int>> queries;
    vector<int> gut;
    while(q--)
    {
        cin >> u >> v;
        queries.pb({u, v});
        int l = lca(u, v);
        // cout << l << "\n";
        diff[u]++;
        diff[v]++;
        diff[l] -= 2;
        gut.pb(l);
    }
    dfs2(1, 0);
    for(auto i : gut)
    {
        diff[i]++;
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        // cout << diff[i] << " ";
        ans = max(ans, diff[i]);
    }
    cout << ans;
}
