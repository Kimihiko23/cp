using namespace std;
const int N =500+23;
int pre[N][N];
int n, m;
int cal(int stx, int sty, int edx, int edy)
{
    return pre[edx][edy] - pre[stx - 1][edy] - pre[edx][sty - 1] + pre[stx - 1][sty - 1];
}


void read()
{
    cin >> n >> m;
    for(int i = 1;  i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            int x;
            cin >> x;
            pre[i][j] = x + pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1];
        }
    }
}
void solve()
{
    int ans = -1e18;
    int pre1[N];
    pre1[0] = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = i + 1; j <= n; j++)
        {
            fill(pre1, pre1 + 1 + m, 0);
            int tam = -1e18;
            for(int z = 1; z <= m; z++)
            {
                int tam1 = cal(i , z, j , z);
                pre1[z] = pre1[z - 1] + cal(i, z, i, z) + cal(j, z, j, z);
                // cout << cal(i + 1, z, j - 1, z) << " ";
                // cout << pre1[z] << " ";
                if(z >= 2)
                {
                    int sum = tam1 + pre1[z - 1];
                    ans = max(ans, sum + tam);
                }
                tam = max(tam, tam1 - pre1[z]);
            }
        }
    }
    cout << ans;
    // cout << cal(2, 1, 1, 1);
}
