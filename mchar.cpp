#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, h[N], vt[N];
int linc[N], rdec[N];
int pkl[N], pkr[N];
int st[4 * N];


void nen() {
    vector<int> cordi;
    for (int i = 1; i <= n; i++) cordi.pb(h[i]);
    sort(cordi.begin(), cordi.end());
    cordi.erase(unique(cordi.begin(), cordi.end()), cordi.end());
    for (int i = 1; i <= n; i++) 
    {
        vt[i] = lower_bound(cordi.begin(), cordi.end(), h[i]) - cordi.begin() + 1;
    }
}

void lis() 
{
    vector<int> v;
    for (int i = 1; i <= n; i++) 
    {
        auto it = lower_bound(v.begin(), v.end(), h[i]);
        if (it == v.end()) v.pb(h[i]);
        else *it = h[i];
        linc[i] = lower_bound(v.begin(), v.end(), h[i]) - v.begin() + 1;
    }
    v.clear();

    for (int i = n; i >= 1; i--) 
    {
        auto it = lower_bound(v.begin(), v.end(), h[i]);
        if (it == v.end()) v.pb(h[i]);
        else *it = h[i];
        rdec[i] = lower_bound(v.begin(), v.end(), h[i]) - v.begin() + 1;
    }
}

void update(int id, int start, int end, int idx, int val) 
{
    if (start == end) 
    {
        st[id] = max(st[id], val);
        return;
    }
    int mid = (start + end) / 2;
    if (idx <= mid) update(2 * id, start, mid, idx, val);
    else update(2 * id + 1, mid + 1, end, idx, val);
    st[id] = max(st[2 * id], st[2 * id + 1]);
}

int get(int id, int start, int end, int l, int r) {
    if (r < start || end < l) return 0;
    if (l <= start && end <= r) return st[id];
    int mid = (start + end) / 2;
    return max(get(2 * id, start, mid, l, r), get(2 * id + 1, mid + 1, end, l, r));
}

void read()
{
    cin >> n;
    for (int i = 1; i <= n; i++) cin >> h[i];
}

void solve()
{
    nen();
    lis();
    int mxh = n;

    for (int i = 1; i <= n; i++) 
    {
        //cout << get(1, 1, mxh, vt[i] + 1, mxh) << " ";
        int best_prev = get(1, 1, mxh, vt[i] + 1, mxh);
        if (best_prev > 0) pkl[i] = best_prev + 1;
        if (linc[i] >= 2) update(1, 1, mxh, vt[i], linc[i]);
        if (pkl[i] > 0) update(1, 1, mxh, vt[i], pkl[i]);
    }

    for (int i = 0; i < 4 * N; i++) 
        st[i] = 0;

    for (int i = n; i >= 1; i--) 
    {
        
        int tam = get(1, 1, mxh, vt[i] + 1, mxh);
        if (tam > 0) pkr[i] = tam + 1;
        if (rdec[i] >= 2) update(1, 1, mxh, vt[i], rdec[i]);
        if (pkr[i] > 0) update(1, 1, mxh, vt[i], pkr[i]);
    }

    int ans = 0;
    for (int i = 1; i <= n; i++) 
    {
        if (pkl[i] >= 1 && pkr[i] >= 1) 
        {
            ans = max(ans, pkl[i] + pkr[i] - 1);
        }
    }

    cout << ans;
}
