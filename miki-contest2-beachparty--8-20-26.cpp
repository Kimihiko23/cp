void dfs(int u)
{
    sz[u] = 1;
    for(auto v : g2[u])
    {
        if(v != par[u])
        {
            depth[v] = depth[u] + 1;
            up[v][0] = u;
            par[v] = u;
            dfs(v);
            sz[u] += sz[v];
            if(sz[heavy[u]] < sz[v])
                heavy[u] = v;
        }
    }
}
void init()
{
    for(int i = 1; i < 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            up[j][i] = up[up[j - 1][i]][i - 1];
        }
    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    if(heavy[u] > 0)
        hld(heavy[u], hd);
    for(auto v : g2[u])
    {
        if(v != par[u] && v != heavy[u])
        {
            hld(v, v);
        }
    }
    tout[u] = cnt;
}

int lca(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            v = par[head[v]];
        else
            u = par[head[u]];
    }
    return (pos[u] < pos[v]) ? u : v;
}


void down(int id, int l, int r, int mid)
{
    if(lazy[id] != 0)
    {
        st[id * 2] += lazy[id] * (mid - l + 1);
        st[id * 2 + 1] += lazy[id] * (r - mid);
        lazy[id * 2] += lazy[id];
        lazy[id * 2 + 1] += lazy[id];
        lazy[id] = 0;
    }
}


void updater(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id] += val * (r - l + 1);
        lazy[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    updater(id * 2, l, mid, u, v, val);
    updater(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
void updatepath(int u, int v, int val)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
        {
            swap(u, v);
        }
        updater(1, 1, tplt, pos[head[u]], pos[u], val);
        u = par[head[u]];
    }
    if(pos[v] > pos[u])
        swap(u, v);

    updater(1, 1, tplt, pos[v], pos[u], val);
}
int getpath(int u, int v)
{
    int res = 0;
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
        {
            swap(u, v);
        }
        res += get(1, 1, tplt, pos[head[u]], pos[u]);
        u = par[head[u]];
    }
    if(pos[v] > pos[u])
    {
        swap(u, v);
    }
        res += get(1, 1, tplt, pos[v], pos[u]);
    return res;
}
bool isancestor(int u, int v)
{ 
    return pos[u] <= pos[v] && tout[v] <= tout[u];
}
int directchild(int u, int x) 
{
  for (int i = 19; i >= 0; --i) 
  {
    if (up[u][i] != 0 && depth[up[u][i]] > depth[x]) 
        u = up[u][i];
  }
  return u;
}
