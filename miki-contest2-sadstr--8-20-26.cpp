void solve()
{
    priority_queue<int> pq[2];

    int tmp1 = 0, tmp2 = 0;

    for (int i = 0; i < (int)s.size(); ++i)
    {
        if (s[i] == 'D')
            pq[0].push(-i);
        else if (s[i] == 'S')
            pq[1].push(-i);
    }

    if (pq[0].empty() && pq[1].empty())
    {
        cout << s << '\n';
        return;
    }

    for (int i = 0; i < q; ++i)
    {
        char c1, c2;
        cin >> c1 >> c2;

        if (c1 == 'D' && c2 == 'S')
            ++tmp1;

        if (c1 == 'S' && c2 == 'D')
            ++tmp2;

        if (c1 == 'D' && c2 == 'A')
        {
            if (!pq[0].empty() &&
                (pq[1].empty() ||
                 -pq[0].top() < -pq[1].top() ||
                 tmp2 == 0))
            {
                s[-pq[0].top()] = 'A';
                pq[0].pop();
            }
            else
            {
                s[-pq[1].top()] = 'A';
                pq[1].pop();
                --tmp2;
            }
        }

        if (c1 == 'S' && c2 == 'A')
        {
            if (!pq[1].empty() &&
                (pq[0].empty() ||
                 -pq[1].top() < -pq[0].top() ||
                 tmp1 == 0))
            {
                s[-pq[1].top()] = 'A';
                pq[1].pop();
            }
            else
            {
                s[-pq[0].top()] = 'A';
                pq[0].pop();
                --tmp1;
            }
        }

        if (pq[0].empty() && pq[1].empty())
            break;
    }

    while (tmp2 && !pq[1].empty())
    {
        s[-pq[1].top()] = 'D';
        --tmp2;
        pq[1].pop();
    }

    cout << s << '\n';
}

