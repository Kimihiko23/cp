vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
struct way
{
    int x, y, t;
};
int n, m, k;
way ways[N];
vector<vector<int>> dis;
priority_queue<pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>> > pq;
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
void dijkstra()
{
    dis[1][1] = 0;
    pq.push({0,{1, 1}});
    while(!pq.empty())
    {
        auto u = pq.top();
        pq.pop();
        int w = u.fi;
        int x = u.se.fi;
        int y = u.se.se;
        // cout << x << " " << y << " " << w << "\n";
        if(dis[x][y] < w)
            continue;
            // cout << x << " " << y << " " << w << "\n";
        for(int i = 1; i <= k; i++)
        {
            int xx = x + ways[i].x;
            int yy = y + ways[i].y;
            // cout << xx << " " << yy << "\n";
            // cout << check(xx, yy) << "\n";
            // cout << dis[xx][yy] << "\n";
            if(check(xx, yy) && dis[xx][yy] > (w + ways[i].t))
            {
                // cout << "gei\n";
                dis[xx][yy] = w + ways[i].t;
                pq.push({dis[xx][yy], {xx, yy}});
            }
        }
    }
}
void read()
{
    cin >> n >> m >> k;
    dis.resize(n + 1, vector<int>(m +1));
    for(int i = 1; i <= k; i++)
    {
        cin >> ways[i].x >> ways[i].y >> ways[i].t;
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            dis[i][j] = 1e18;
        }
    }
    dijkstra();
    cout << dis[n][m];
}
