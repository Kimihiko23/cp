mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int st[N * 4], stmx[N * 4];
int a[N];
int n, q;
int cnt[N];
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id] = a[l];
        stmx[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = st[id * 2] + st[id * 2 + 1];
    stmx[id] = max(stmx[id * 2], stmx[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    // down(id, l, r, mid);
    int lef = get(l, mid, id * 2, u, v);
    int rig = get(mid + 1, r, id * 2 + 1, u, v);
    return lef + rig;
}
int getmx(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return stmx[id];
    }
    int mid = (l + r) / 2;
    // down(id, l, r, mid);
    int lef = getmx(l, mid, id * 2, u, v);
    int rig = getmx(mid + 1, r, id * 2 + 1, u, v);
    return max(lef, rig);
}
void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u || stmx[id] <= 2)
    {
        return;
    }
    if(l == r)
    {
        st[id] = cnt[st[id]];
        stmx[id] = cnt[stmx[id]];
        return;
    }
    int mid = (l + r) / 2;
    // down(id, l, r, mid);
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
    stmx[id] = max(stmx[id * 2], stmx[id * 2 + 1]);
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    build(1, n, 1);
    for(int i = 1; i < N; i++)
    {
        for(int j = i; j < N; j += i)
        {
            cnt[j]++;
        }
    }
    int ty, vt, val;
    while(q--)
    {
        cin >> ty >> vt >> val;
        if(ty == 1)
        {
            update(1, n, 1, vt, val, 1);
        }
        else
        {
            cout << get(1, n, 1, vt, val) << "\n";
        }
    }

}
