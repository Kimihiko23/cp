int n, q;
int a[N][3];
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= (1 << n); i++)
    {
        cin >> a[i][0];
        // cout << i << "\n";
    }
}
void solve()
{
    q = q % n;
    for(int time = 0; time < q; time++)
    {
        int old = 0;
        int nx = 0;
        if(time % 2 == 0)
        {
            old = 0;
            nx = 1;
        }
        else
        {
            old = 1;
            nx = 0;
        }
        if(time == q)
        {
            for(int i = 1; i <= (1 << n); i++)
            {
                cout << a[i][old] << " ";
            }
            return;
        }
        int vt = 1;
        for(int i = 1; i <= (1 << n); i += 2)
        {
            a[i][nx] = a[vt][old];
            vt++;
        }
        for(int i = 2; i <= (1 << n); i += 2)
        {
            a[i][nx] = a[vt][old];
            vt++;
        }
        if(time == (q - 1))
        {
            for(int i = 1; i <= (1 << n); i++)
            {
                cout << a[i][nx] << " ";
            }
        }
    }  
    if(q == 0)
    {
        for(int i = 1; i <= (1 << n); i++)
        {
            cout << a[i][0] << " ";
        }
    } 
}
