#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N=105, INF=1e18;
int n,m;
int S[N],H[N],C[N];
int dp[12][105];
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt","r")) 
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }
    // freopen(name ".inp", "r", stdin);
    // freopen(name ".out", "w", stdout);
    cin >> n >> m;
    for(int i = 1; i <= n;  i++) 
        cin >> S[i];
    for(int i = 1; i <= m; i++) 
        cin >> H[i];
    for(int i = 1; i <= m; i++) 
        cin >> C[i];
    for(int i = 1; i <= n;  i++)
        for(int s = 0; s <= S[i]; s++)
            dp[i][s] = -INF;
    dp[1][0] = 0;
    for(int i = 1; i <= m; i++)
    {
        for(int j = n-1; j >= 1; j--)
        {
            int best = -INF;
            for(int s = 0; s <= S[j]; s++)
                best = max(best, dp[j][s]);
            dp[j+1][0] = max(dp[j+1][0], best);
        }
        int ndp[12][105];
        for(int j = 1; j <= n;  j++)
            for(int s = 0; s <= S[j]; s++)
                ndp[j][s] = dp[j][s];
        for(int j = 1; j <= n;  j++)
        {
            for(int s = 0; s <= S[j]; s++)
            {
                if(dp[j][s] == INF) continue;
                if(s+H[i] <= S[j])
                {
                    ndp[j][s+H[i]] = max(ndp[j][s+H[i]], dp[j][s]+C[i]);
                }
            }
        }
        for(int j = 1; j <= n;  j++)
            for(int s = 0; s <= S[j]; s++)
                dp[j][s] = ndp[j][s];
    }
    int ans = 0;
    for(int j = 1; j <= n;  j++)
        for(int s = 0; s <= S[j]; s++)
            ans = max(ans, dp[j][s]);
    cout << ans << "\n";
}