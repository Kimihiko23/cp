int st[N * 4];
int lz[N * 4];
void push(int id, int l, int r, int mid)
{
    if(lz[id] == 0)
        return;
    int x = lz[id];
    lz[id] = 0;
    lz[id * 2] += x;
    lz[id * 2 + 1] += x;

    st[id * 2] += (mid - l + 1) * x;
    st[id * 2 + 1] += (r - mid) * x;
}
void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id] += (r - l + 1) * val;
        lz[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return 0;
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    return get(l, mid, id * 2, u, v) + get(mid + 1, r, id * 2 + 1, u, v);
}

int binpow(int x, int pw)
{
    int ans = 1;
    while (pw) 
    {
        if (pw & 1) ans *= x;
        ans %= MOD;
        x *= x;
        x %= MOD;
        pw >>= 1;
        
    }
    return ans;
}
int cnt = 0;
void dfs(int u, int p)
{
    L[u] = R[u] = ++cnt;
    who[cnt] = u;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dep[v] = dep[u] + 1;
        dfs(v, u);
    }
    R[u] = cnt;
}
