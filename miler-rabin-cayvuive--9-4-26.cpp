u64 binpower(u64 base, u64 e, u64 mod) {
    u64 result = 1;
    base %= mod;
    while (e) {
        if (e & 1)
            result = (u128)result * base % mod;
        base = (u128)base * base % mod;
        e >>= 1;
    }
    return result;
}

bool check_composite(u64 n, u64 a, u64 d, int s) {
    u64 x = binpower(a, d, n);
    if (x == 1 || x == n - 1)
        return false;
    for (int r = 1; r < s; r++) {
        x = (u128)x * x % n;
        if (x == n - 1)
            return false;
    }
    return true;
};

bool MillerRabin(u64 n, int iter=5) { // returns true if n is probably prime, else returns false.
    if (n < 4)
        return n == 2 || n == 3;

    int s = 0;
    u64 d = n - 1;
    while ((d & 1) == 0) {
        d >>= 1;
        s++;
    }

    for (int i = 0; i < iter; i++) {
        int a = 2 + rand() % (n - 3);
        if (check_composite(n, a, d, s))
            return false;
    }
    return true;
}

void push(int l, int r, int id, int mid)
{
    if(lz[id] == 0)
        return;
    int x= lz[id];
    lz[id] = 0;
    st[id * 2] = (mid - l + 1) * x;
    lz[id * 2] = x;
    st[id * 2 + 1] = (r - mid) * x;
    lz[id * 2 + 1] = x;
}
void update(int l, int r, int id, int val, int u, int v)
{
    if(l > v || r < u) return;
    if(l >= u && r <= v)
    {
        st[id] = (r - l + 1) * val;
        lz[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    push(l, r, id, mid);
    update(l, mid, id * 2, val, u, v);
    update(mid + 1, r, id * 2 + 1, val, u, v);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u) return 0;
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    push(l, r, id, mid);
    return get(l, mid, id * 2, u, v) + get(mid + 1, r, id * 2 + 1, u, v);
}
