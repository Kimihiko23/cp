int f(string &s, int pos, int th, int sx, int ni, int tight)
{
    if(pos == 0)
    {
        if(th == sx && sx == ni && th > 0) 
            return 1;
        return 0;
    }
    if(th > 35 || sx > 35 || ni > 35) 
        return 0;
    if(dp[pos][th][sx][ni] != -1 && tight == 0) 
        return dp[pos][th][sx][ni];
    int limit = 9;
    int ans = 0;
    if(tight) 
        limit = s[s.size() - pos] - '0';
    for(int i = 0; i <= limit; i++)
    {
        if(i == 3) 
            ans += f(s, pos - 1, th + 1, sx, ni, tight && i == limit);
        else if(i == 6) 
            ans += f(s, pos - 1, th, sx + 1, ni, tight && i == limit);
        else if(i == 9) 
            ans += f(s, pos - 1, th, sx, ni + 1, tight && i == limit);
        else 
            ans += f(s, pos - 1, th, sx, ni, tight && i == limit);
    }
    ans %= MOD;
    if(tight == 0)
        dp[pos][th][sx][ni] = ans;
    return ans;
}
int g(string &num)
{
    int dem3 = 0, dem6 = 0, dem9 = 0;
    for(char c : num)
    {
        if(c == '3') 
            dem3++;
        else if(c == '6') 
            dem6++;
        else if(c == '9') 
            dem9++;
    }
    if(dem3 == dem6 && dem6 == dem9 && dem3 > 0) 
        return 1;
    return 0;
}
