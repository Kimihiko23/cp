#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int a[N];
int n, m;
vector<pair<int, pair<int, int>>> edg;
int sz[N];
int par[N];
int mn[N];
int ans[N];
int mx = 1;
int anc(int u)
{
    if(par[u] != u)
    {
        par[u] = anc(par[u]);
    }
    return par[u];
}
void join(int x, int y, int w)
{
    x = anc(x);
    y = anc(y);
    if(x == y)
        return;
    if(sz[x] > sz[y])
        swap(x, y);
    sz[y] += sz[x];
    mn[y] = min(mn[y], mn[x]);
    par[x] = par[y];
    if(sz[y] > mx)
    {
        for(int i = mx + 1; i <= sz[y]; i++)
            ans[i] = w;
        mx = sz[y];
    }
}
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        sz[i] = 1;
        par[i] = i;
        mn[i] = a[i];
        ans[1] = max(a[i], ans[1]);
    }
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        edg.pb({min(a[u], a[v]), {u, v}});
    }
}
void solve()
{
    sort(edg.begin(), edg.end(), greater());
    for(auto i : edg)
    {
        int u = i.se.fi;
        int v = i.se.se;
        join(u, v, i.fi);
        // cout << i.fi << " " << u << " " << v << "\n";

    }
    for(int i = 1; i <= n; i++)
    {
        if(ans[i] == 0)
        {
            cout << -1 << " ";
        }
        else
        cout << ans[i] << " ";
    }
}

