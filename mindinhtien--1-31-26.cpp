using namespace std;
const int N =1e6+23;
deque<int> dq;
int n, k;
int a[N];
void push(int vt)
{
    while(!dq.empty() && a[dq.back()] > a[vt])
    {
        dq.pop_back();
    }
    dq.push_back(vt);
    return;
}
void read()
{
   cin >> n >> k;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
}
void solve()
{
    for(int i = 1; i <= k; i++)
    {
        push(i);
    }
    cout << a[dq.front()] << "\n";
    for(int i = k + 1; i <= n; i++)
    {
        push(i);
        while(!dq.empty() && dq.front() <= i - k)
        {
            dq.pop_front();
        }
        
        cout << a[dq.front()] << "\n";
    }
}
