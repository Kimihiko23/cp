void solve()
{
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < (1 << n); j++)
        {
            dp[i][j] = 0;
        }
    }
    for(int i = 0; i < n; i++)
    {
        dp[i][(1 << i)] = 1;
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        // on.clear();
        for(int x = 0; x < n; x++)
        {
            if(mask & (1 << x))
            {
                on.pb(x);
            }
        }
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i != j && abs(a[i] - a[j]) > k)
                {
                    dp[i][mask] += dp[j][mask ^ (1 << i)];
                    // dp[i][mask] = (dp[i][mask] + dp[j][mask ^ (1 << i)]);
                }
            }
        }
        
    }
    int ans = 0;
    for(int i = 0; i < n; i++)
    {
        ans += dp[i][(1 << n) - 1];
    }
    cout << ans;
}
