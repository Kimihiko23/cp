int dp[105][455][455][2];
bool check(int x)
{
    if(x < 2)
        return false;
    for(int i = 2; i * i <= x; i++)
    {
        if(x % i == 0)
            return false;
    }
    return true;
}
int f(string &s, int pos, int odd, int even, int tight)
{
    int ans = 0;
    if(pos == 0)
    {
        int sum = even - odd;
        if(check(sum))
            return 1;
        else
            return 0;
    }
    if(dp[pos][odd][even][tight] != -1)
        return dp[pos][odd][even][tight];
    int limit = 9;
    if(tight)
        limit = s[s.size() - pos] - '0';
    int res = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(pos % 2 == 0)
            res += f(s, pos - 1, odd, even + i, tight && (i == limit));
        else
            res += f(s, pos - 1, odd + i, even, tight && (i == limit));
    }
    return dp[pos][odd][even][tight] = res % MOD;

}
int g(string &s)
{
    int odd = 0, even = 0;
    for(int i = 0; i < s.size(); i++)
    {
        if((s.size() - i) % 2 == 0)
            even += s[i] - '0';
        else
            odd += s[i] - '0';
    }
    return check(even - odd);
}
