int n, m;
vector<vector<pair<int, int>>> adj;

void read()
{
    cin >> n >> m;
    adj.resize(n + 1);
    for (int i = 0; i < m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }
}
void solve()
{
    vector<bool> vis(n + 1, false);
    priority_queue<pair<int, pair<int, int>>, vector<pair<int, pair<int, int>>>, greater<pair<int, pair<int, int>>>> pq;
    vis[1] = true;
    for (auto e : adj[1])
    {
        pq.push({e.se, {1, e.fi}});
    }
    int ans = 0;
    vector<pair<int, int>> edges;
    while (pq.size())
    {
        int w = pq.top().fi;
        int u = pq.top().se.fi;
        int v = pq.top().se.se;
        pq.pop();
        if (vis[v])
        {
            continue;
        }
        vis[v] = true;
        ans += w;
        edges.pb({u, v});
        for (auto e : adj[v])
        {
            if (!vis[e.fi])
            {
                pq.push({e.se, {v, e.fi}});
            }
        }
    }
    cout << ans << "\n";
    for (auto e : edges)
    {
        cout << e.fi << " " << e.se << "\n";
    }
}
