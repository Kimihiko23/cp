#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
vector<pair<int, int>> g[N];
int n;
int ans = 0;
int dist[N];
bool dd[N];
void dfs(int u)
{
    dd[u] = true;
    for(auto i : g[u])
    {
        int v = i.se;
        int w = i.fi;
        if(dd[v] == 0)
        {
            dist[v] = dist[u] + w;
            dfs(v);
            // dist[v] = dist[u] + w;
        }
    }
}
void read()
{   
    cin >> n;
    for(int i = 1; i <= n - 1; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        g[u].pb({w, v});
        g[v].pb({w, u});
        ans += w;
    }
}
void solve()
{
    int tam = 0;
    ans *= 2;
    int vttam;
    dfs(1);
    for(int i = 1; i <= n; i++)
    {
        if(dist[i] > tam)
        {
            tam = dist[i];
            vttam = i;
        }
        dist[i] = 0;
        dd[i] = 0;
    }
    dfs(vttam);
    for(int i = 1; i <= n; i++)
    {
        if(dist[i] > tam)
        {
            tam = dist[i];
            vttam = i;
        }
    }
    cout << ans - tam;
}

