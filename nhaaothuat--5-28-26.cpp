const int MOD = 1000020409;
const int N = 2e5 + 23;
int n, m;
map<int, int> mp;
int b[N], c[N], d[N];
struct query
{
    int l, r, id;
};
query q[N];
int a[N];
int S1;
int di = 0;
int cnt[N];
int L = 1, R = 0;
int ans = 0;
int res[N];
int sum = 0;
void MO(int i)
{
    while(R < q[i].r)
    {
        R++;
        if(c[b[R]] >= ans)
        {
            sum++;
        }
        cnt[b[R]]++;
        if(sum - cnt[d[ans]] >= ans + 1)
        {
            sum -= cnt[d[ans]];
            ans++;
        }
        
    }
    while(L > q[i].l)
    {
        L--;
        if(c[b[L]] >= ans)
        {
            sum++;
        }
        cnt[b[L]]++;
        if(sum - cnt[d[ans]] >= ans + 1)
        {
            sum -= cnt[d[ans]];
            ans++;
        }
    }





    while(R > q[i].r)
    {
        if(c[b[R]] >= ans)
        {
            sum--;
        }
        cnt[b[R]]--;
        if(sum < ans)
        {
            ans--;
            sum += cnt[d[ans]];
        }
        R--;
    }
    while(L < q[i].l)
    {
        if(c[b[L]] >= ans)
        {
            sum--;
        }
        cnt[b[L]]--;
        if(sum < ans)
        {
            ans--;
            sum += cnt[d[ans]];
        }
        L++;
    }
    
}
bool cmp(query a , query b)
{
    if(a.l / S1 != b.l / S1)
        return a.l < b.l;
    return (a.l / S1 & 1) ? (a.r < b.r) : (a.r > b.r);
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mp[a[i]] = 1;
    }
    S1 = sqrt(n);
    for(int i = 1 ; i <= m; i++)
    {
        cin >> q[i].l >> q[i].r;
        q[i].id = i;
    }
}
void solve()
{
    for(auto i : mp)
    {
        mp[i.fi] = ++di;
    }
    for(int i = 1; i <= n; i++)
    {
        b[i] = mp[a[i]];
        c[b[i]] = a[i];
        d[i] = mp[i];
    }
    sort(q + 1, q + m + 1, cmp);
    for(int i = 1; i <= m; i++)
    {
        MO(i);
        res[q[i].id] = ans;
    }
    for(int i = 1; i <= m; i++)
    {
        cout << res[i] << "\n";
    }
}
