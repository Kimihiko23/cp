#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 30;
int g[N][N];
bool dd[N][N];
int n, m, k;
int a[N];
int dp[N][300000];
void read()
{
    cin >> n >> m >> k;
    for(int i = 0; i < n; i++)
    {
        cin >> a[i];
    }
    for(int i = 1; i <= k; i++)
    {
        int u, v, x;
        cin >> u >> v >> x;
        u--;
        v--;
        g[u][v] += x;
    }
}
void solve()
{
    int ans = 0;
    for(int i = 0 ; i < n ; i++)
        for(int mask = 0 ; mask < (1 << n) ; mask++)
            dp[i][mask] = -1e18;
    for(int i = 0; i < n; i++)
    {
        dp[i][(1 << i)] = a[i];
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        for(int i = 0; i < n; i++)
        {
            if(mask & (1 << i))
                on.pb(i);
        }
        if(on.size() > m)
            continue;
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i != j)
                {
                    dp[i][mask] = max(dp[i][mask], dp[j][mask ^ (1 << i)] + a[i] + g[j][i]);
                }
            }
            if(on.size() == m)
            {
                ans = max(ans, dp[i][mask]);
            }
        }
        
    }
    cout << ans;
}
