mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, l;
struct query
{
    int r, ord[10];
};
query q[N];
int dp[N];
int f(int x1[10], int x2[10])
{
    int id[10];
    for(int i = 1; i <= l; i++)
    {
        id[x1[i]] = i;
    }
    int ans = 0;
    for(int i = 1; i <= l; i++)
    {
        for(int j = 1; j < i; j++)
        {
            if(id[x2[j]] > id[x2[i]])
                ans++;
        }
    }
    return ans;
}
void read()
{
    cin >> n >> l;
    for(int i = 1; i <= n; i++)
    {
        dp[i] = -1e18;
        cin >> q[i].r;
        for(int j = 1; j <= l; j++)
        {
            cin >> q[i].ord[j];
        }
    }
}
void solve()
{
    dp[0] = 0;
    q[0].r = 0;
    for(int i = 1; i <= l; i++)
    {
        q[0].ord[i] = i;
    }
    int mx = 0;
    for(int i = 1; i <= n; i++)
    {
        if(i - 50 >= 0)
        {
            mx = max(mx, dp[i - 50]);
            dp[i] = q[i].r + mx;
        }
        // dp[i] = q[i].r + mx;
        for(int j = max((int)0, i - 50); j < i; j++)
        {
            if(j == 0)
            {
                if(f(q[i].ord, q[j].ord) <= i - j)
                {
                    dp[i] = max(dp[i], dp[j] + q[i].r);
                }
            }
            else
            if(dp[j] != 0)
                if(f(q[i].ord, q[j].ord) <= i - j)
                {
                    dp[i] = max(dp[i], dp[j] + q[i].r);
                }
            
        }
    }
    int ans = 0;
    // cout << f(q[0].ord, q[1].ord);
    for(int i = 1; i <= n; i++)
    {
        // cout << dp[i] << "\n";
        ans = max(ans, dp[i]);
    }
    cout << ans;
}
