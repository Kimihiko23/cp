#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 1e5 + 23;
struct Q
{
    int l, r, id;
};
Q que[N];
int n, q;
int a[N], ans[N];
int L = 1, R = 0;
deque<int> cnt[N];
int s;
multiset<int> se;
bool cmp(Q a, Q b)
{
    if(a.l / s == b.l / s) return a.r < b.r;
    return a.l / s < b.l / s;
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    cin >> q;
    for(int i = 1; i <= q; i++)
    {
        cin >> que[i].l >> que[i].r;
        que[i].id = i;
    }
    s = sqrt(n);
}
void MO(int x)
{
    while(R < que[x].r)
    {
        R++;
        if(cnt[a[R]].size() > 0)
        {
            int tam = cnt[a[R]].back() - cnt[a[R]].front();
            se.erase(se.find(tam));
        }
        cnt[a[R]].push_back(R);
        int tam = cnt[a[R]].back() - cnt[a[R]].front();
        se.insert(tam);
    }
    while(R > que[x].r)
    {
        if(cnt[a[R]].size() > 0)
        {
            int tam = cnt[a[R]].back() - cnt[a[R]].front();
            se.erase(se.find(tam));
        }
        cnt[a[R]].pop_back();
        if(cnt[a[R]].size() > 0)
        {
            int tam = cnt[a[R]].back() - cnt[a[R]].front();
            se.insert(tam);
        }
        R--;
    }
    while(L < que[x].l)
    {
        if(cnt[a[L]].size() > 0)
        {
            int tam = cnt[a[L]].back() - cnt[a[L]].front();
            se.erase(se.find(tam));
        }
        cnt[a[L]].pop_front();
        if(cnt[a[L]].size() > 0)
        {
            int tam = cnt[a[L]].back() - cnt[a[L]].front();
            se.insert(tam);
        }
        L++;
    }
    while(L > que[x].l)
    {
        L--;
        if(cnt[a[L]].size() > 0)
        {
            int tam = cnt[a[L]].back() - cnt[a[L]].front();
            se.erase(se.find(tam));
        }
        cnt[a[L]].push_front(L);
        int tam = cnt[a[L]].back() - cnt[a[L]].front();
        se.insert(tam);
    }
}
void solve()
{
    sort(que + 1, que + q + 1, cmp);
    for(int i = 1; i <= q; i++)
    {
        MO(i);
        ans[que[i].id] = *(--se.end());
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
