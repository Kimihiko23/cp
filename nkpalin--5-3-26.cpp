const int N =2000 + 23;
int dp[N][N];
string s;
void read()
{
    cin >> s;
}
void solve()
{
    s = " " + s;
    int n = s.size() - 1;
    for(int i = 1; i <= n; i++)
    {
        dp[i][i] = 1;
    }
    for(int len = 2; len <= n; len++)
    {
        for(int i = 1; i + len - 1 <= n; i++)
        {
            int j = i + len - 1;
            if(s[i] == s[j])
            {
                dp[i][j] = dp[i + 1][j - 1] + 2;
            }
            else
            {
                dp[i][j] = max(dp[i + 1][j], dp[i][j - 1]);
            }
        }
    }
    string ans = "";
    int i = 1, j = n;
    while(i <= j)
    {
        if(s[i] == s[j])
        {
            ans += s[i];
            i++;
            j--;
        }
        else
        if(dp[i][j] == dp[i + 1][j])
        {
            i++;
        }
        else 
        if(dp[i][j] == dp[i][j - 1])
        {
            j--;
        }
        else
        {
            i++;
            j--;
        }
    }
    if(dp[1][n] % 2 == 0)
    {
        string tmp = ans;
        reverse(tmp.begin(), tmp.end());
        ans += tmp;
    }
    else
    {
        string tmp = ans.substr(0, ans.size() - 1);
        reverse(tmp.begin(), tmp.end());
        ans += tmp;
    }
    cout << ans;
}
