int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    for(int i = 20; i >= 0; i--)
        if(h[par[i][u]] >= h[v])
            u = par[i][u];
    // cout << u << " " << v;
    if(u == v)
        return u;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            u = par[i][u];
            v = par[i][v];
        }
    }
    return par[0][u];
}
int distance(int u, int v)
{
    return h[u] + h[v] - 2 * h[lca(u, v)];
}
void bfsmulti(int ty)
{
    queue<int> que;
    // cout << ty << "\n";
    for(auto i : st[ty])
    {
        que.push(i);
        // cout << i << " ";
        dis[ty][i] = 0;
    }
    // cout << "\n";
    while(!que.empty())
    {
        auto u = que.front();
        que.pop();
        for(auto v : g[u])
        {
            if(dis[ty][v] == 1e18)
            {
                dis[ty][v] = dis[ty][u] + 1;
                que.push(v);
            }
        }
    }
}
