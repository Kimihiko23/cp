struct DSU
{
    vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 1);
        sz.assign(n + 1, 1);
        iota(par.begin(), par.end(), 0);
    }

    int find(int u)
    {
        if (par[u] == u)
            return u;
        return par[u] = find(par[u]);
    }

    bool unite(int u, int v)
    {
        u = find(u);
        v = find(v);

        if (u == v)
            return false;

        if (sz[u] < sz[v])
            swap(u, v);

        par[v] = u;
        sz[u] += sz[v];

        return true;
    }
};

struct Edge
{
    int u, v, w;

    bool operator < (const Edge &other) const
    {
        return w > other.w;
    }
};

int n, m;
vector<Edge> edges;
int ans;

void read()
{
    cin >> n >> m;

    ans = 0;

    for (int i = 1; i <= m; ++i)
    {
        int u, v, w;
        cin >> u >> v >> w;

        edges.pb({u, v, w});
        ans += w;
    }
}

void solve()
{
    sort(edges.begin(), edges.end());

    DSU dsu(n);

    for (auto e : edges)
    {
        if (dsu.unite(e.u, e.v))
            ans -= e.w;
    }

    cout << ans << '\n';
}

