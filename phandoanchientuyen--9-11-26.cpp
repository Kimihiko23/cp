pair<int, int> get (int id, int l, int r, int u, int v) 
{
    if (l > v || r < u) return {(int)-1e18, (int)1e18};
    else if (l >= u && r <= v) return st[id];
    int mid = (l+r)/2;
    auto le = get(id * 2, l, mid, u, v);
    auto ri = get(id * 2 + 1, mid + 1, r, u, v);
    return {max(ri.fi, le.fi), min(le.se, ri.se)};
}
