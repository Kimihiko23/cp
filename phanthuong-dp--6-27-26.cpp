const int N = 300 + 23;
int dp[N][N][N / 2];
int n, k;
int a[N];
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    memset(dp, -1, sizeof(dp));
    dp[1][n][0] = 0;
    for(int c = 0; c <= k; c++)
    {
        for(int i = 1; i <= n; i++)
        {
            for(int j = n; j > i; j--)
            {
                if(dp[i][j][c] == -1)
                    continue;
                dp[i + 1][j][c] = max(dp[i + 1][j][c], dp[i][j][c]);
                dp[i][j - 1][c] = max(dp[i][j - 1][c], dp[i][j][c]);
                if(j - i + 1 >= 2)
                {
                    dp[i + 2][j][c + 1] = max(dp[i + 2][j][c + 1], dp[i][j][c] + abs(a[i + 1] - a[i]));
                    dp[i][j - 2][c + 1] = max(dp[i][j - 2][c + 1], dp[i][j][c] + abs(a[j] - a[j - 1]));
                    dp[i + 1][j - 1][c + 1] = max(dp[i + 1][j - 1][c + 1], dp[i][j][c] + abs(a[i] - a[j]));
                }
            }
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            ans = max(ans, dp[i][j][k]);
        }
    }
    cout << ans;
}
