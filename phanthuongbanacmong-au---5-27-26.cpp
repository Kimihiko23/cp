const int N = 3e5 + 23;
const int BLOCK_MO = 750;
const int BLOCK_VAL = 550;

int n, m;
int a[N];
vector<int> vals;
int b[N], c[N];
int cnt[N];
int b_cnt[BLOCK_VAL + 5];
int b_sum[BLOCK_VAL + 5];
int di = 0;
int L = 1, R = 0;

struct Query
{
    int l, r, t, id;
};
Query q[N];

bool cmp(Query A, Query B)
{
    int blk_A = A.l / BLOCK_MO;
    int blk_B = B.l / BLOCK_MO;
    if (blk_A != blk_B) return blk_A < blk_B;
    return blk_A & 1 ? A.r < B.r : A.r > B.r;
}

int ans[N];

inline void add(int idx)
{
    int p = b[idx];
    cnt[p]++;
    int blk = p / BLOCK_VAL;
    b_cnt[blk]++;
    b_sum[blk] += c[p];
}

inline void remove(int idx)
{
    int p = b[idx];
    cnt[p]--;
    int blk = p / BLOCK_VAL;
    b_cnt[blk]--;
    b_sum[blk] -= c[p];
}

void MO(int i)
{
    while(R < q[i].r) add(++R);
    while(L > q[i].l) add(--L);
    while(R > q[i].r) remove(R--);
    while(L < q[i].l) remove(L++);
}

void read()
{
    cin >> n >> m;
    vals.reserve(n);
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        vals.pb(a[i]);
    }
    for (int i = 1; i <= m; i++)
    {
        cin >> q[i].l >> q[i].r >> q[i].t;
        q[i].id = i;
    }
}

void solve()
{
    sort(vals.begin(), vals.end());
    vals.erase(unique(vals.begin(), vals.end()), vals.end());
    di = vals.size();

    for(int i = 1; i <= di; i++)
    {
        c[i] = vals[i - 1];
    }
    for(int i = 1; i <= n; i++)
    {
        b[i] = lower_bound(vals.begin(), vals.end(), a[i]) - vals.begin() + 1;
    }

    sort(q + 1, q + m + 1, cmp);

    for(int i = 1; i <= m; i++)
    {
        MO(i);
        int t = q[i].t;
        int sum = 0;
        int max_blk = di / BLOCK_VAL;

        for(int j = 0; j <= max_blk; j++)
        {
            if(b_cnt[j] == 0) continue;
            if(t >= b_sum[j])
            {
                t -= b_sum[j];
                sum += b_cnt[j];
            }
            else
            {
                int start_k = j * BLOCK_VAL;
                int end_k = min(di, start_k + BLOCK_VAL - 1);
                if (start_k == 0) start_k = 1;

                for(int k = start_k; k <= end_k; k++)
                {
                    if(cnt[k] == 0) continue;
                    int cost = cnt[k] * c[k];
                    if(t >= cost)
                    {
                        t -= cost;
                        sum += cnt[k];
                    }
                    else
                    {
                        sum += t / c[k];
                        break;
                    }
                }
                break;
            }
        }
        ans[q[i].id] = sum;
    }

    for(int i = 1; i <= m; i++)
    {
        cout << ans[i] << "\n";
    }
}

