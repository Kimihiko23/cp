const int MOD = 1000020409;
const int N = 3e5 + 23;
int n, m;
int a[N];
const int S1 = 750, S2 = 550;
map<int, int> mp;
int b[N], c[N];
int cnt[N];
int b_cnt[600];
int b_sum[600];
int di = 0;
int L = 1, R = 0;
//di = distint
struct Query
{
    int l, r, t, id;
};
Query q[N];
bool cmp(Query A, Query B)
{
    if(A.l / S1 != B.l / S1) return A.l < B.l;
    return (A.l / S1) & 1 ? A.r < B.r : A.r > B.r;
}
int ans[N];
inline void add(int idx)
{
    int p = b[idx];
    cnt[p]++;
    b_cnt[p / S2]++;
    b_sum[p / S2] += c[p];
}

inline void remove(int idx)
{
    int p = b[idx];
    cnt[p]--;
    b_cnt[p / S2]--;
    b_sum[p / S2] -= c[p];
}

void MO(int i)
{
    while(R < q[i].r) add(++R);
    while(L > q[i].l) add(--L);
    while(R > q[i].r) remove(R--);
    while(L < q[i].l) remove(L++);
}
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        mp[a[i]] = 1;
    }
    for (int i = 1; i <= m; i++)
    {
        cin >> q[i].l >> q[i].r >> q[i].t;
        q[i].id = i;
    }
}
void solve()
{
    sort(q + 1, q + m + 1, cmp);
    for(auto i : mp)
    {
        mp[i.fi] = ++di;
    }
    for(int i = 1; i <= n; i++)
    {
        b[i] = mp[a[i]];
        c[b[i]] = a[i];
    }
    for(int i = 1; i <= m; i++)
    {
        MO(i);
        int t = q[i].t;
        int sum = 0;
        for(int j = 0; j <= di / S2; j++)
        {
            if (b_cnt[j] == 0) continue;
            if(t >= b_sum[j])
            {
                t -= b_sum[j];
                sum += b_cnt[j];
            }
            else
            {
                int st = j * S2;
                if(st == 0) st = 1;
                int ed = min(di, j * S2 + S2 - 1);
                for(int k = st; k <= ed; k++)
                {
                    if (cnt[k] == 0) continue;
                    if(t >= cnt[k] * c[k])
                    {
                        t -= cnt[k] * c[k];
                        sum += cnt[k];
                    }
                    else
                    {
                        sum += t / c[k];
                        break;
                    }
                }
                break;
            }
        }
        ans[q[i].id] = sum;
    }
    for(int i = 1; i <= m; i++)
    {
        cout << ans[i] << "\n";
    }
}
