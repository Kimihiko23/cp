int n, q;
int pre1[N][N], pre2[N][N];
void read()
{
    cin >> n >> q;
    int a, b, x;
    while(q--)
    {
        cin >> a >> b >> x;
        pre1[a][b]++;
        pre1[a + 1 + x][b]--;
        pre2[a + 1 + x][b + 1]--;
        pre2[a + 1 + x][b + x + 2]++;
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= i; j++)
        {
            pre1[i][j] += pre1[i - 1][j];
            pre2[i][j] += pre2[i][j - 1];
        }
    }
    int res = 0;
    for(int i = 1; i <= n; i++)
    {
        int ii = i;
        int j = 1;
        // int old = 0;
        int now = 0;
        while(j <= (n - i + 1))
        {
            // cout << ii << " " << j << "\n";
            // now += old;
            now += pre1[ii][j] + pre2[ii][j];
            // old = now;

            // ans[ii][j] += ans[ii - 1][j - 1];
            // ans[ii][j] += pre1[ii][j] + pre2[ii][j];
    
            if(now)
                res++;
            ii++;
            j++;
        }
    }
    cout << res;
}
