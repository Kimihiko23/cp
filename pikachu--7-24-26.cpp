const int N = 1e2 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int a[N][N];
int n, m;
int stx, sty, edx, edy;
int dis[N][N][4];
// bool dd[N][N][4];
struct vt
{
    int x, y, ch, dir;
};
// 0 = up, 1 = right, 2 = down, 3 = left
deque<vt> q;
vector<int> dx = {-1, 0, 1, 0};
vector<int> dy = {0, 1, 0, -1};
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
void bfs01()
{
    while(!q.empty())
    {
        vt u = q.front();
        q.pop_front();
        if(u.ch != dis[u.x][u.y][u.dir]) continue;
        for(int i = 0; i < 4; i++)
        {
            int xx = u.x + dx[i];
            int yy = u.y + dy[i];
            int sum = dis[u.x][u.y][u.dir] + (i != u.dir);
            if(check(xx, yy) && dis[xx][yy][i] > sum)
            {
                if(i == u.dir)
                {
                        dis[xx][yy][i] = dis[u.x][u.y][u.dir];
                        if(a[xx][yy] == 1) continue;
                        q.push_front({xx, yy, dis[xx][yy][i], i});
                    
                }
                else
                {
                        dis[xx][yy][i] = dis[u.x][u.y][u.dir] + 1;
                        if(a[xx][yy] == 1) continue;
                        q.push_back({xx, yy, dis[xx][yy][i], i});
                    
                }
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dis[i][j][0] = INF;
            dis[i][j][1] = INF;
            dis[i][j][2] = INF;
            dis[i][j][3] = INF;
        }
    }
    cin >> stx >> sty >> edx >> edy;
}
void solve()
{
    q.push_back({stx, sty, 0, 0});
    q.push_back({stx, sty, 0, 1});
    q.push_back({stx, sty, 0, 2});
    q.push_back({stx, sty, 0, 3});
    dis[stx][sty][0] = 0;
    dis[stx][sty][1] = 0;
    dis[stx][sty][2] = 0;
    dis[stx][sty][3] = 0;
    bfs01();
    int tam1 = INF;
    int tam2 = INF;
    int tam3 = INF;
    int tam4 = INF;
    if(dis[edx][edy][0] < INF) tam1 = dis[edx][edy][0];
    if(dis[edx][edy][1] < INF) tam2 = dis[edx][edy][1];
    if(dis[edx][edy][2] < INF) tam3 = dis[edx][edy][2];
    if(dis[edx][edy][3] < INF) tam4 = dis[edx][edy][3];
    int ans = min({tam1, tam2, tam3, tam4});
    if(ans == INF) cout << -1;
    else cout << ans;
}
