struct Job 
{
    int t, p, w, id;
    bool operator<(const Job& o) const 
    {
        if (w != o.w)
        {
            return w < o.w;
        }
        if (t != o.t)
        {
            return t > o.t;
        }
        return id > o.id;
    }
};

int n;
vector<Job> a;

void read()
{
    cin >> n;
    a.resize(n);
    for (int i = 0; i < n; i++)
    {
        cin >> a[i].t >> a[i].p >> a[i].w;
        a[i].id = i + 1;
    }
}
bool cmp(Job x, Job y)
{
    if (x.t != y.t)
    {
        return x.t < y.t;
    }
    return x.id < y.id;
}
void solve()
{
    sort(a.begin(), a.end(), cmp);
    priority_queue<Job> pq;
    int idx = 0;
    int cur = 0;
    vector<int> res;
    while (idx < n || pq.size())
    {
        if (pq.empty() && cur < a[idx].t)
        {
            cur = a[idx].t;
        }
        while (idx < n && a[idx].t <= cur)
        {
            pq.push(a[idx++]);
        }
        Job j = pq.top();
        pq.pop();
        res.pb(j.id);
        cur += j.p;
    }
    for (int v : res)
    {
        cout << v << " ";
    }
}
