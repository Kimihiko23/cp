vector<int> G;
vector<int> L;
int ans1[N], ans2[N];
int n;
void read()
{
    cin >> n;
    char x;
    int vt;
    for(int i = 1; i <= n; i++)
    {
        cin >> x >> vt;
        if(x == 'G')
        {
            G.pb(vt);
        }
        else
        {
            L.pb(vt);
        }
    }
}
void solve()
{
    int szg = G.size();
    int szl = L.size();
    G.pb(-1e18);
    L.pb(-1e18);
    sort(G.begin(), G.end());
    sort(L.begin(), L.end());
    int ans = min(szl, szg);
    for(int i = 1; i <= szg; i++)
    {
        int l = 1, r = szl;
        int vt = - 1;
        int gli = szg - i;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(L[mid] >= G[i])
            {
                vt = mid;
                r = mid - 1;
            }
            else
            {
                l = mid + 1;
            }
        }
        int lli = szl;
        if(vt != -1)
        {
            lli = vt - 1;
        }
        ans1[i] = lli + gli;
        ans = min(ans, ans1[i]);
        // cout << ans1[i] << " ";
    }
    for(int i = 1; i <= szl; i++)
    {
        ans2[i] = szg;
        int l = 1, r = szg;
        int vt = -1;
        int lli = i - 1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(G[mid] <= L[i])
            {
                l = mid + 1;
                vt = mid;
            }
            else
            {
                r = mid - 1;
            }
        }
        int gli = szg;
        if(vt != -1)
        {
            gli = szg - vt;
        }
        ans2[i] = gli + lli;
        ans = min(ans, ans2[i]);
        
    }
    cout << ans;
    
    

}
