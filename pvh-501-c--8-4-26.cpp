void solve()
{
    int l = 0, r = t;
    bool good = false;
    while(l <= r)
    {
        int mid = (l + r) / 2;
        int dis = mid * b + (t - mid);
        if(dis <= d)
        {
            if(dis == d) good = true;
            l = mid + 1;
        }
        else r = mid - 1;
    }
    if(good) cout << "Possible";
    else cout << "Impossible";
}
