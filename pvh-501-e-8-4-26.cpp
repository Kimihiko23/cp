void solve()
{
    precompute();
    int n, m, k;
    while(t--)
    {
        cin >> n >> m >> k;
        if(mod == 220797)
            cout << nck2(k, n - 1) * binpow(m - 1, k) % mod * m % mod;
        else
        if(t <= 50)
            cout << nck3(k, n - 1) * binpow(m - 1, k) % mod * m % mod;
        else
            cout << nck1(k, n - 1) * binpow(m - 1, k) % mod * m % mod;
        cout << "\n";
    }
}
