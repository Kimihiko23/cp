mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int mod, t;
int fact[N];
int inv[N];
int binpow(int x, int pw)
{
    int res = 1;
    while(pw)
    {
        if(pw & 1)
        {
            res *= x;
        }
        pw >>= 1;
        x *= x;
        x %= mod;
        res %= mod;
    }
    return res;
}
vector<pair<int, int>> factorize[N];
int lpf[N];
void precompute()
{
    fact[0] = 1;
    for(int i = 1; i < N; i++)
    {
        fact[i] = (fact[i - 1] * i) % mod;
    }
    inv[1000001] = binpow(fact[1000001], mod - 2);
    for(int i = 1000000; i >= 0; i--)
    {
        inv[i] = (inv[i + 1] * (i + 1)) % mod;
    }
    iota(lpf, lpf + 1 + 1000000, 0);
    for(int i = 2; i * i <= 1000000; i++)
    {
        if(lpf[i] == i)
        {
            for(int j = i * i; j <= 1000000; j += i)
            {
                if (lpf[j] == j) lpf[j] = i;
            }
        }
    }
    for(int i = 1; i <= 1000000; i++)
    {
        int prev = 0, cnt = 0;
        int tam = i;
        while(tam > 1)
        {
            if(lpf[tam] != prev)
            {
                if(prev != 0)
                    factorize[i].pb({prev, cnt});
                prev = lpf[tam];
                cnt = 0;
            }
            cnt++;
            tam /= lpf[tam];
        }
        if(prev != 0)
            factorize[i].pb({prev, cnt});
    }
}
int nck1(int k, int n)
{
    int tam = (fact[n] * inv[k]) % mod * inv[n - k] % mod;
    return tam;
}
int nck3(int k, int n)
{
    if(n < k)
        return 0;
    int res = 1;
    for(int i = 1; i <= k; i++)
    {
        res *= (n - i + 1);
        res %= mod;
    }
    res *= inv[k];
    res %= mod;
    return res;
}
int nck2(int k, int n)
{
    if(n < k)
        return 0;
    int ans = 1;
    vector<int> primes(1000005, 0);
    for (int i = 1; i <= n; ++i) 
    {
        for (auto j : factorize[i]) 
        {
        primes[j.fi] += j.se;             
        if (i <= k) primes[j.fi] -= j.se;   
        if (i <= n-k) primes[j.fi] -= j.se; 
        }
    }
    for (int i = 2; i <= 1000000; ++i) 
        if (primes[i] != 0) 
        ans = (1LL * ans * binpow(i, primes[i])) % mod;
    return ans;
}
