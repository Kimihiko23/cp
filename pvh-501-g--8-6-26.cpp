mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int op[N], cl[N];
string s;
int fact[N], inv[N];
int n;
int binpow(int x, int pw)
{
    int res = 1;
    while(pw)
    {
        if(pw & 1) res *= x;
        pw >>= 1;
        x *= x;
        res %= MOD;
        x %= MOD;
    }
    return res;
}
void precompute()
{
    fact[0] = fact[1] = 1;
    for(int i = 2; i < N; i++)
    {
        fact[i] = fact[i - 1] * i;
        fact[i] %= MOD;
    }
    inv[1000000] = binpow(fact[1000000], MOD - 2);
    for(int i = 1000000 - 1; i >= 0; i--)
    {
        inv[i] = inv[i + 1] * (i + 1) % MOD;
    }
}
int cnk(int k, int n)
{
    return  (fact[n] * inv[k] % MOD * inv[n - k]) % MOD;
}
void read()
{
    cin >> s;
    n = s.size();
    s = " " + s;
}
void solve()
{
    precompute();
    // cout << inv[1] << "\n";
    for(int i = 1; i <= n; i++)
    {
        op[i] += op[i - 1];
        cl[i] += cl[i - 1];
        if(s[i] == '(')
        {
            op[i]++;
        }
        else
        {
            cl[i]++;
        }
    }
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int cntcl = cl[n] - cl[i];
        if(s[i] == '(')
        {
            int cntop = op[i - 1];
            ans += cnk(cntcl - 1, cntcl + cntop);
            ans %= MOD;
        }
    }
    cout << ans;
}
