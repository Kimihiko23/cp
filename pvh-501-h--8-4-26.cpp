void solve()
{
    int ans = 0;
    int sum = 1;
    int r = 1;
    cnt[s[1] - 'a']++;
    for(int l = 1; l <= n; l++)
    {
        int chl = s[l] - 'a';
        while(sum < k && r < n)
        {
            r++;
            int ch = s[r] - 'a';
            if(cnt[ch] == 0)
            {
                sum++;
            }
            cnt[ch]++;
            // cout << r << " " << sum << "\n";
        }
        // cout << l << " " << r << "\n";
        if(sum == k)
        ans += n - r + 1;
        cnt[chl]--;
        if(cnt[chl] == 0)
        {
            sum--;
        }

    }
    cout << ans;
}
