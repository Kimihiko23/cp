void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= k; j++)
        {
            dis[i][j] = 1e18;
        }
    }
    dis[1][0] = 0; 
    // nx.push_back({dis[1][0], {0, 1}});
    for(int i = 0; i <= k; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            if(dis[j][i] != 1e18)
            pq.push({dis[j][i], {i, j}});
        }
        dijkstra(i);
    }
    ll ans = 1e18;
    for(int i = 0; i <= k; i++)
    {
        ans = min(ans, dis[n][i]);
    }
    cout << ans;
}
