vector<pair<int, int>> g[N];
ll dis[N][223];
int n, m, k;
priority_queue<pair<ll, pair<int, int>>, vector<pair<ll, pair<int, int>>>, greater<pair<ll, pair<int, int>>> > pq;
// vector<pair<int, pair<int, int>>> nx;
void dijkstra(int x)
{
    while(!pq.empty())
    {
        auto tam = pq.top();
        pq.pop();
        int u = tam.se.se;
        int use = tam.se.fi;
        ll dist = tam.fi;
        if(dist > dis[u][use])
            continue;
        for (const auto &i : g[u])
        {
            int w = i.se;
            int v = i.fi;
            if(use + 1 <= k)
            {
                if(dis[v][use + 1] > dis[u][use] - w)
                {
                    dis[v][use + 1] = dis[u][use] - w;
                    // nx.pb({dis[v][use + 1], {use + 1, v}});

                }
            }
            if(dis[v][use] > dis[u][use] + w)
            {
                dis[v][use] = dis[u][use] + w;
                pq.push({dis[v][use], {use, v}});
            }
        }
    }
} 
