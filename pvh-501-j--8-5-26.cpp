pair<int, int> st[N * 4];
int lz[N * 4];
int n, q;
int a[N];
int sur[N];
set<int> alive;
pair<int, int> merg(int l, int r)
{
    if(st[l].fi < st[r].fi)
    {
        return {st[l].fi, st[l].se};
    }
    else
        return {st[r].fi, st[r].se};
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].fi = a[l];
        st[id].se = l;
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = merg(id * 2, id * 2 + 1);
}
void down(int id)
{
    int x = lz[id];
    if(x == 0)
        return;
    if(st[id * 2].fi <= (int)1e9)
    {
        st[id * 2].fi -= x;
        lz[id * 2] += x;
    }
    if(st[id * 2 + 1].fi <= (int)1e9)
    {
        st[id * 2 + 1].fi -= x;
        lz[id * 2 + 1] += x;
    }
    lz[id] = 0;
}
void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u || st[id].fi > 1e9)
        return;
    if(l >= u && r <= v)
    {
        st[id].fi -= val;
        lz[id] += val;
        return;
    }
    int mid =(l + r) / 2;
    down(id);
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1, u, v, val);
    st[id] = merg(id * 2, id * 2 + 1);
}
pair<int, int> get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
    {
        return {2e9, 0};
    }
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    down(id);
    auto le = get(l, mid, id * 2, u, v);
    auto ri = get(mid + 1, r, id * 2 + 1, u, v);
    if(le.fi < ri.fi)
    {
        return le;
    }
    else
    {
        return ri;
    }
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        // a[i] *= i;
        alive.insert(i);
        sur[i] = -1;
    }
    // memset(lz, -1, sizeof(lz));

}
void solve()
{
    build(1, n, 1);
    int l, r, val;
    int cnt = 0;
    while(q--)
    {
        cnt++;
        cin >> l >> r >> val;
        update(1, n, 1, l, r, val);
        bool change = 0;
        while(true)
        {
            auto tam = get(1, n, 1, l, r);
            if(tam.fi > 0)
                break;
            change = 1;
            int vt = tam.se;
            if (sur[vt] == -1) 
            {
                sur[vt] = cnt;
            }
            update(1, n, 1, vt, vt, -2e9);
        }
    }
    for(int i = 1; i <= n; i++)
    {
        int mx = 0;
        bool good = true;
        for(int j = i; j <= n; j += i)
        {
            mx = max(mx, sur[j]);
            if(sur[j] == -1)
            {
                good = false;
                cout << -1 << " ";
                break;
            }
        }
        if(good)
        {
            cout << mx << " ";
        }
    }
}
