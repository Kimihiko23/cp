const int MOD = 998244353;
const int OFF = 2000;
int stx, sty, edx, edy;
int dp[6005][6005];
// bool dd[6005][6005];
vector<int> dy{1, -1, -2, -2};
vector<int> dx{-2, -2, -1, 1};
bool check(int x, int y)
{
    return(x >= 0 && x <= 6000 && y >= 0 && y <= 6000);
}
void read()
{
    cin >> stx >> sty >> edx >> edy;
    edx -= stx;
    edy -= sty;
    edx += OFF;
    edy += OFF;
    cout << dp[edx][edy] << "\n";   
}
void solve()
{
    // memset(dp, 0, sizeof(dp));
    dp[OFF][OFF] = 1;
    int i = 0, j = 0;
    while(true && i != 6001)
    {
        int ii = i;
        int jj = j;
        while(check(ii, jj))
        {
            for(int z = 0; z < 4; z++)
            {
                int ui = ii + dx[z];
                int uj = jj + dy[z];
                if(check(ui, uj))
                {
                        dp[ii][jj] += dp[ui][uj];
                        if(dp[ii][jj] > MOD)
                        dp[ii][jj] -= MOD;
                }
            }
            ii++;
            jj--;
        }
        if(j != 6000)
            j++;
        else
            i++;
    }
}
