int a1, a2, b1, b2;
vector<pair<int, int>> in;
void read()
{
    cin >> a1 >> a2 >> b1 >> b2;
    if(a1 > a2)
        swap(a1, a2);
    if(b1 > b2)
        swap(b1, b2);   
    in.pb({a1, 1});
    in.pb({a2, -1});
    in.pb({b1, 1});
    in.pb({b2, -1});
}
void solve()
{
    int ans = 0;
    sort(in.begin(), in.end());
    int cur = 0;
    for(int i = 0; i < 4; i++)
    {
        if(i >= 1)
        {
            int vt = in[i].fi;
            int old = in[i - 1].fi;
            if(cur)
                ans += vt - old;
        }
        cur += in[i].se;
        // cur = max(0LL, min(cur, 1LL));
    }
    cout << ans;
}
