void solve()
{
    while(true)
    {
        cin >> s;
        if(s == "$")
            break;
        // cout << s << "\n";
        int n = s.size();
        memset(dp, 0, sizeof(ll) * (n + 1) * 6);
        for(int i = 0; i < n; i++)
        {
            if(i >= 1)
            {
                dp[i][1] = dp[i - 1][1];
                dp[i][2] = dp[i - 1][2];
                dp[i][3] = dp[i - 1][3];
                dp[i][4] = dp[i - 1][4];
            }
            if(s[i] == 'C' && i >= 2)
            {
                dp[i][4] += dp[i - 2][3];
                dp[i][2] += dp[i - 2][1];
            }
            if(s[i] == 'I')
            {
                dp[i][1]++;
            }
            if(s[i] == 'P' && i >= 2)
            {
                dp[i][3] += dp[i - 2][2];
            }
        
            // cout << dp[i][3] << "\n";
        }
        cout << dp[n - 1][4] << "\n";
    }
}
