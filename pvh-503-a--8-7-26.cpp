int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int idd[N];
vector<int> g[N];
int n;
int root;
int bit[N];
int ans = 0;
void add(int id, int val)
{
    while(id <= n)
    {
        bit[id] += val;
        id += id & (-id);
    }
}
int sum(int id)
{
    int res = 0;
    while(id > 0)
    {
        res += bit[id];
        id -= id & (-id);
    }
    return res;
}
int get(int l, int r)
{
    return sum(r) - sum(l - 1);
}
void dfs(int u, int p)
{
    if(u != n)
        ans += get(u + 1, n);
    add(u, 1);
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        dfs(v, u);
    }
    add(u, -1);
}
void read()
{
    cin >> n >> root;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(root, -1);
    cout << ans;
}
