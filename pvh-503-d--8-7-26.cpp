mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int n, q;
struct edge
{
    int u, v, w;
};
vector<edge> edg;
int par[N];
int sz[N];
int find(int u)
{
    if(par[u] != u)
        par[u] = find(par[u]);
    return par[u];
}
void joinset(int a,int b)
{
    a = find(a);
    b = find(b);
    if (a != b)
    {
        if (sz[a] < sz[b])
        {
            swap(a,b);
        }
        sz[a] += sz[b];
        par[b] = a;
    }
}
vector<pair<int, int>> wcnt, que;
pair<int, int> pre[N];
//wcnt = how many paht had that weight
int ans[N];
bool cmp(edge &a, edge &b)
{
    return a.w < b.w;
}
void read()
{
    cin >> n >> q;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        edg.pb({u, v, w});
    }
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
}
void solve()
{
    sort(edg.begin(), edg.end(), cmp);
    int sum = 1;
    int ty = edg[0].w;
    joinset(edg[0].u, edg[0].v);
    int cnt = 0;
    for(int i = 1; i < n - 1; i++)
    {
        if(edg[i].w != ty)
        {
            wcnt.pb({sum, ty});
            sum = 0;
            ty = edg[i].w;
            cnt++;
        }
        int u = find(edg[i].u);
        int v = find(edg[i].v);
        sum += sz[v] * sz[u];
        // cout << edg[i].u << " " << edg[i].v << "\n";
        joinset(u, v);
    }
    wcnt.pb({sum, ty});
    cnt++;
    pre[0].fi = wcnt[0].fi;
    pre[0].se = wcnt[0].se;
    for(int i = 1; i < cnt; i++)
    {
        pre[i].fi = pre[i - 1].fi + wcnt[i].fi;
        pre[i].se = wcnt[i].se;
    }
    while(q--)
    {
        int le, ri;
        cin >> le >> ri;
        int vt1 = -1, vt2 = -1;
        int l = 0, r = cnt - 1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(pre[mid].se <= ri)
            {
                vt2 = mid;
                l = mid + 1;
            }
            else
                r = mid - 1;
        }
        l = 0, r = cnt - 1;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(pre[mid].se >= le)
            {
                vt1 = mid;
                r = mid - 1;
            }
            else
                l = mid + 1;
        }
        if(vt1 > vt2)
            cout << 0 << " ";
        else
        {
            if(vt1 == -1 || vt2 == -1)
            {
                cout << 0 << " ";
            }
            else
            if(vt1 == 0)
            {
                cout << pre[vt2].fi << " ";
            }
            else
            {
                cout << pre[vt2].fi - pre[vt1 - 1].fi << " ";
            }
        }
    }
}
