int dp[N];
bool dd[N];
int n, k;
vector<int> g[N];
int ans = 0;
bool good = true;
void dfs(int u, int p)
{
    if(good == false)
        return;
    for(auto v: g[u])
    {
        if(v == p)
            continue;
        if(dd[u] && dd[v])
        {
            cout << "-1";
            good = false;
            return;
        }
        dfs(v, u);
        dp[u] += dp[v];
        if(dp[u] >= 2 && !dd[v] && dd[u])
        {
            dp[u] -= dp[v];
            ans++;
        }
    }
    if(!dd[u] && dp[u] >= 2)
    {
        dp[u] = 0;
        ans++;
    }
}
void read()
{
    for(int i = 1; i <= k; i++)
    {
        int x;
        cin >> x;
        dp[x] = 1;
        dd[x] = true;
    }
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, -1);
    if(good)
    cout << ans << "\n";
    for(int i = 1; i <= n; i++)
    {
        g[i].clear();
        dd[i] = 0;
        dp[i] = 0;
    }
    good = true;
    ans = 0;
}
