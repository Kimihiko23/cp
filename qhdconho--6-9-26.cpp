const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;

const int N = 30;
int dp[N][N];
int n, k, x, y;
map<int, int> mp1, mp2;
int f(int xx, int yy)
{
    int u = mp1[xx];
    int v = mp2[yy];
    if(dp[u][v] != -1) return dp[u][v];
    int w = (xx * yy + 2 * xx + 3 * yy) % k;
    if(xx == 1 && yy == 1) return w;
    if(xx > 1) dp[u][v] = max(dp[u][v], f(xx / 2, yy) + w);
    if(yy > 1) dp[u][v] = max(dp[u][v], f(xx, yy / 2) + w);
    return dp[u][v];
}
void read()
{
    cin >> n >> k >> x >> y;
}
void solve()
{
    int cnt = 0;
    int tem = x;
    while(tem >= 1)
    {
        mp1[tem] = ++cnt;
        tem /= 2;
    }
    cnt = 0;
    tem = y;
    while(tem >= 1)
    {
        mp2[tem] = ++cnt;
        tem /= 2;
    }
    memset(dp, -1, sizeof(dp));
    cout << f(x, y);
}
