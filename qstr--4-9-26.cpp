using namespace std;
const int MOD = 1000020407;
const int MOD2 = 1e9 + 7;
const int N =1e6+23;
pair<int, int> p[N], pre[N][3];
string s1, s2;
int n, m;
pair<int, int> base{256, 256};
pair<int, int> sum(pair<int, int> a, pair<int, int> b)
{
    int tam1 = (a.fi + b.fi) % MOD;
    int tam2 = (a.se + b.se) % MOD2;
    return {tam1, tam2};
}
pair<int, int> sub(pair<int, int> a, pair<int, int> b)
{
    int tam1 = ((a.fi - b.fi) % MOD + MOD) % MOD;
    int tam2 = ((a.se - b.se) % MOD2 + MOD2) % MOD2;
    return {tam1, tam2};
}
pair<int, int> mul(pair<int, int> a, pair<int, int> b)
{
    int tam1 = (a.fi * b.fi) % MOD;
    int tam2 = (a.se * b.se) % MOD2;
    return {tam1, tam2};
}
pair<int, int> f(int l, int r, int ty)
{
    // int x = r - l + 1;
    return sub(pre[r][ty], mul(pre[l - 1][ty], p[r - l + 1]));

}
void read()
{
    cin >> n >> m >> s1 >> s2;
}
void solve()
{
    s1 = " " + s1;
    s2 = " " + s2;
    p[0] = {1, 1};
    for(int i = 1; i <= max(n, m); i++)
    {
        p[i].fi = p[i-1].fi * base.fi % MOD;
        p[i].se = p[i-1].se * base.se % MOD2;
    }
    for(int i = 1; i <= n; i++)
    {
        pre[i][1] = sum(mul(pre[i-1][1], base), {s1[i], s1[i]});
    }
    for(int i = 1; i <= m; i++)
    {
        pre[i][2] = sum(mul(pre[i-1][2], base), {s2[i], s2[i]});
    }
    int q;
    cin >> q;
    while(q--)
    {
        int l1, r1, l2, r2;
        cin >> l1 >> r1 >> l2 >> r2;
        int l = 0 , r = min(r2 - l2 + 1 , r1 - l1 + 1) , ans = 0;
        while(l <= r)
        {
            int mid = (l + r) / 2;
            if(f(l1, l1 + mid - 1, 1) == f(l2, l2 + mid - 1, 2))
            {
                ans = mid;
                l = mid + 1;
            }
            else
            {
                r = mid - 1;
            }
        }
        if(l1 + ans > r1 && l2 + ans > r2)
            cout << "=";
            else if(l1 + ans > r1)
            cout << "<";
            else if(l2 + ans > r2)
            cout << ">";
        else
        {
            if(s1[l1 + ans] > s2[l2 + ans])
                cout << ">";
            else
                cout << "<";
        }
        
    }

}
