using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N = 5e5 + 23;
int n;
vector<int> g[N];
int a[N];
int pre[N];
set<int> s;
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        g[a[i]].pb(i);
        pre[i] = pre[i - 1] + a[i];
        s.insert(a[i]);
    }
}
void solve()
{
    int ans = 0;
    for(auto i : s)
    {
        int l = *g[i].begin();
        int r = *prev(g[i].end());
        ans = max(pre[r] - pre[l - 1], ans);
    }
    cout << ans;
}
