{
    cin >> n >> q;
    for (int i = 1; i <= n; i++) cin >> a[i];
    for (int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }
}
void solve()
{
    dfs();
    for (int i = 1; i <= n; i++) val[tin[i]] = a[i];
    build(1, 1, n);
    while (q--)
    {
        int type;
        cin >> type;
        if (type == 1)
        {
            int u, x;
            cin >> u >> x;
            a[u] = x;
            update(1, 1, n, tin[u], x);
        }
        else
        {
            int u;
            cin >> u;
            Node res = query(1, 1, n, tin[u], tout[u]);
            cout << res.mx << " " << res.cnt << "\n";
        }
    }
}
