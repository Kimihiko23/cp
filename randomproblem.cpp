int n, k;
int a[N];
int ans = 1e18;
void sinh(string s)
{
    if(s.size() == n)
    {
        int cur = 0, sum = 0, vis = 0;
        for(int i = 0; i < n; i++)
        {
            if(s[i] == '1')
            {
                int target = max(a[i + 1], cur + 1);
                sum += target - a[i + 1];
                cur = target;
                vis++;
            }
            else if(a[i + 1] > cur)
            {
                cur = a[i + 1];
                vis++;
            }
        }
        if(vis >= k) ans = min(ans, sum);
        return;
    }
    sinh(s + "0");
    sinh(s + "1");
}
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
