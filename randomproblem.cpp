int n, q;
int a[N];
vector<int> adj[N];
int tin[N], tout[N], par[N], timer_ = 0;

struct Node
{
    int mx, cnt;
};
Node st[4 * N];

Node merge(const Node &L, const Node &R)
{
    if (L.mx > R.mx) return L;
    if (L.mx < R.mx) return R;
    return {L.mx, L.cnt + R.cnt};
}

int val[N];

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = {val[l], 1};
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void update(int id, int l, int r, int pos, int x)
{
    if (l == r)
    {
        st[id] = {x, 1};
        return;
    }
    int mid = (l + r) / 2;
    if (pos <= mid) update(id * 2, l, mid, pos, x);
    else update(id * 2 + 1, mid + 1, r, pos, x);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

Node query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u) return {NINF, 0};
    if (u <= l && r <= v) return st[id];
    int mid = (l + r) / 2;
    return merge(query(id * 2, l, mid, u, v),
                 query(id * 2 + 1, mid + 1, r, u, v));
}

void dfs()
{
    vector<int> stk, it(n + 1, 0);
    stk.pb(1);
    par[1] = 0;
    tin[1] = ++timer_;
    while (!stk.empty())
    {
        int u = stk.back();
        if (it[u] < (int)adj[u].size())
        {
            int v = adj[u][it[u]++];
            if (v == par[u]) continue;
            par[v] = u;
            tin[v] = ++timer_;
            stk.pb(v);
        }
        else
        {
            tout[u] = timer_;
            stk.pop_back();
        }
    }
}

