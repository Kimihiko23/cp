#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;

#define name "input"

const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e2 + 23;

bool dd[N][N];
int n, m;
int a[N][N];

vector<int> dx = {-1, -1, -1, 0, 0, 1, 1, 1};
vector<int> dy = {-1, 0, 1, -1, 1, -1, 0, 1};

vector<pair<int, int>> ed;
int ans = 0;

void dfs(int x, int y)
{
    dd[x][y] = true;
    ans++;

    bool leaf = true;

    for(int i = 0; i < 8; i++)
    {
        int nx = x + dx[i];
        int ny = y + dy[i];

        if(nx < 1 || nx > n || ny < 1 || ny > m)
            continue;

        if(a[nx][ny] == 1 || dd[nx][ny])
            continue;

        leaf = false;
        dfs(nx, ny);
    }

    if(leaf)
        ed.pb({x, y});
}

void read()
{
    cin >> n >> m;

    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
        }
    }
}

void solve()
{
    dfs(1, 1);

    sort(ed.begin(), ed.end());

    cout << ans << "\n";

    for(auto x : ed)
    {
        cout << x.fi << " " << x.se << "\n";
    }
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);

    if (fopen("input.txt","r"))
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }

    read();
    solve();
}