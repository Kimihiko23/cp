using namespace std;
const int N =1e3+23;
int dp[N][N];
int n, m;
int a[N][N];

bool check(int x, int y)
{
    return (x >= 1 && x <= n && y >= 1 && y <= m);
}
void read()
{
   cin >> n >> m;
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            dp[i][j] = -1e18;
        }
   }
}
void solve()
{
   for(int i = 1; i <= n; i++)
   {
        dp[i][1] = a[i][1];
   }
   for(int i = 2; i <= m; i++)
   {
        for(int j = 1; j <= n; j++)
        {
            vector<int> xx {-1, 0, 1};
            for(int i1 = 0; i1 < xx.size(); i1++)
            {
                int x1 = j + xx[i1];
                int y1 = i - 1;
                if(check(x1, y1))
                {
                    dp[j][i] = max(dp[j][i], dp[x1][y1] + a[j][i]);
                }

            }
        }
   }
   
   int ans=-1e18;
   for(int i = 1; i <= n; i++)
   {
        ans = max(ans, dp[i][m]);
   }
   cout << ans;
}
