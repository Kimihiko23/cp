#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1000020409;
const int N =16 + 1;
const int M = (1 << N) + 23;
int n, m;
int dist[N][N];
vector<int> dx{0, 0, -1, 1};
vector<int> dy{1, -1, 0, 0};
char a[N][N];
int d = 0;
pair<int, int> q[N * N];
int c[N][N];
int dp[N][M];
bool check(int x, int y)
{
    return x >= 0 && x < n && y >= 0 && y < m;
}
void bfs(int i)
{
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < m; j++)
        {
            dist[i][j] = 1e18;
        }
    }
    queue<pair<int, int>> que;
    dist[q[i].fi][q[i].se] = 0;
    que.push({q[i].fi, q[i].se});
    while(!que.empty())
    {
        int ux = que.front().fi;
        int uy = que.front().se;
        que.pop();
        for(int j = 0; j < 4; j++)
        {
            int vx = ux + dx[j];
            int vy = uy + dy[j];
            if(check(vx, vy) && dist[vx][vy] == 1e18 && a[vx][vy] != 'x')
            {
                dist[vx][vy] = dist[ux][uy] + 1;
                que.push({vx, vy});
            }
        }
    }
    for(int j = 0; j <= d; j++)
    {
        c[i][j] = dist[q[j].fi][q[j].se];
    }

}
void read()
{
    d = 0;
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < m; j++)
        {
            cin >> a[i][j];
            if(a[i][j] == 'o')
            {
                q[0] = {i, j};
            }
            if(a[i][j] == '*')
            {
                d++;
                q[d] = {i, j};
            }
        }
    }
}
void solve()
{
    for(int i = 0; i <= d; i++)
    {
        bfs(i);
    }
    // for(int i = 0; i <= d; i++)
    // {
    //     for(int j = 0; j <= d; j++)
    //     {
    //         cout << c[i][j] << " ";
    //     }
    //     cout << "\n";
    // }
    n = d + 1;
    for(int i = 0; i < n; i++)
    {
        for(int j = 0; j < (1 << n); j++)
        {
            dp[i][j] = 1e18;
        }
    }
    dp[0][(1 << 0)] = 0;
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        on.clear();
        for(int x = 0; x < n; x++)
        {
            if(mask & (1 << x))
            {
                on.pb(x);
            }
        }
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i != j)
                {
                    dp[i][mask] = min(dp[i][mask], dp[j][mask ^ (1 << i)] + c[j][i]);
                }
            }
        }
        
    }
    int ans = 1e18;
    for(int i = 0; i < n; i++)
    {
        ans = min(ans, dp[i][(1 << n) - 1]);
    }
    if(ans != 1e18)
        cout << ans << "\n";
    else
        cout << "-1\n";
}
