void dfs(int u)
{
    sz[u] = 1;
    for(auto v : g2[u])
    {
        if(v != par[u])
        {
            par[v] = u;
            dfs(v);
            sz[u] += sz[v];
            if(sz[heavy[u]] < sz[v])
                heavy[u] = v;
        }
    }
}

void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    if(heavy[u] > 0)
        hld(heavy[u], hd);
    for(auto v : g2[u])
    {
        if(v != par[u] && v != heavy[u])
        {
            hld(v, v);
        }
    }
}

