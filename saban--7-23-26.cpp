#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define se second
#define ll long long
#define siesta main
using namespace std;

const int MOD = 1e9 + 7;
const int N = 2e5 + 23;

int n, m;
int low[N], ndfs[N], tt;
int par[N], sz[N];
bool bridge[N];

vector<pair<int, int>> g[N];
vector<pair<int, int>> edg;

void tarjan(int u, int old)
{
    ndfs[u] = low[u] = ++tt;
    for(auto i : g[u])
    {
        int v = i.fi;
        int id = i.se;

        if(id == old)
            continue;

        if(!ndfs[v])
        {
            tarjan(v, id);
            low[u] = min(low[u], low[v]);

            if(low[v] > ndfs[u])
                bridge[id] = 1;
        }
        else
            low[u] = min(low[u], ndfs[v]);
    }
}

int tplt;

void dfs(int u)
{
    par[u] = tplt;
    sz[tplt]++;

    for(auto i : g[u])
    {
        int v = i.fi;
        int id = i.se;

        if(par[v] || bridge[id])
            continue;

        dfs(v);
    }
}

void read()
{
    cin >> n >> m;

    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;

        g[u].pb({v, i});
        g[v].pb({u, i});
    }
}

void solve()
{
    for(int i = 1; i <= n; i++)
        if(!ndfs[i])
            tarjan(i, 0);

    for(int i = 1; i <= n; i++)
    {
        if(!par[i])
        {
            ++tplt;
            dfs(i);
        }
    }

    int ans = 0;
    for(int i = 1; i <= tplt; i++)
        ans = max(ans, sz[i]);

    cout << ans;
}

