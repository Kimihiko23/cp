struct Node 
{
    int s;
    int i;
    bool operator<(const Node& o) const {
        return s != o.s ? s < o.s : i > o.i;
    }
};

siesta() 
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    int n; 
    cin >> n;
    vector<int> s(n + 2);
    vector<int> L(n + 2), R(n + 2);
    vector<bool> dead(n + 2, false);
    priority_queue<Node> pq;

    for (int i = 1; i <= n; i++) 
    {
        cin >> s[i];
        L[i] = i - 1;
        R[i] = i + 1;
        pq.push({s[i], i});
    }
    L[1] = R[n] = -1;

    int ans = 0;

    while (!pq.empty()) 
    {
        int u = pq.top().i;
        pq.pop();
        if (dead[u]) continue;
        ans += s[u];
        if (L[u] != -1) ans += s[L[u]], R[L[u]] = R[u];
        if (R[u] != -1) ans += s[R[u]], L[R[u]] = L[u];
        dead[u] = true;
    }

    cout << ans;
}
