#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 3e5 + 23;
int n, m, q;
vector<int> que[N], color[N];
int a[N], l[N], r[N], ans[N];
int b[N];
struct edge
{
    int l, r, w;
};
edge e[N];

int bit[N];

void add(int x, int val)
{
    while (x <= n)
    {
      
            bit[x] += val;
        x += x & -x;
    }
}

void update(int l, int r, int val)
{
    add(l, val);
    if (r < n) add(r + 1, -val);
}

int get(int x)
{
    int res = 0;
    while (x)
    {
        res += bit[x];
        x -= x & -x;
    }
    return res;
}
void read()
{
    cin >> m >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        color[a[i]].pb(i);
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> b[i];
    }
    cin >> q;
    for(int i = 1; i <= q; i++)
    {
        cin >> e[i].l >> e[i].r >> e[i].w;
    }
}
void solve()
{
    for(int i = 1; i <= m; i++)
    {
        l[i] = 0;
        r[i] = q;
        ans[i] = -1;
    }
    while(true)
    {
        memset(bit, 0, sizeof(bit));

        for (int i = 0; i <= q; i++)
            que[i].clear();
        bool stop = true;
        for(int i = 1; i <= m; i++)
        {
            if(l[i] > r[i])
                continue;
            stop = false;
            int mid = (l[i] + r[i]) / 2;
            que[mid].pb(i);
        }
        if(stop) break;
        for(int i = 0; i <= q; i++)
        {
            if(i > 0)
            {
                int u = e[i].l;
                int v = e[i].r;
                int w = e[i].w;
                if(u > v)
                {
                    update(1, v, w);
                    update(u, n, w);
                }
                else
                    update(u, v, w);
                }

            for(auto id : que[i])
            {
                int sum = 0;
                for(auto x : color[id])
                {
                    sum += get(x);
                    if(sum >= b[id])
                        break;
                }
                if(sum >= b[id])
                {
                    ans[id] = i;
                    r[id] = i - 1;
                }
                else
                {
                    l[id] = i + 1;
                }
            }
        }
    }
    for(int i = 1; i <= m; i++)
    {
        cout << ans[i] << "\n";
    }
}
