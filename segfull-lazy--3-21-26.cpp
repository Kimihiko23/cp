using namespace std;
const int N=1e5 + 23;
int n, m;
int stmx[N * 4];
int stmn[N * 4];
int st[N * 4];
int lazy[N * 4];
const int minn = -1e18;
int a[N];
void push(int id, int l, int r)
{
    if (lazy[id] == 0) return;
    int mid = (l + r) / 2;
    int x = lazy[id];
    st[id*2] += x * (mid - l + 1);
    stmx[id*2] += x;
    stmn[id*2] += x;
    lazy[id*2] += x;
    st[id*2+1] += x * (r - mid);
    stmx[id*2+1] += x;
    stmn[id*2+1] += x;
    lazy[id*2+1] += x;
    lazy[id] = 0;
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        stmx[id] = a[l];
        stmn[id] = a[l];
        st[id] = a[l];
        return;
    }
    int mid = (l+r)>>1;
    build(l, mid, (id << 1));
    build(mid+1, r, (id << 1) | 1);
    /*
    int mid = (l+r)/2;
    build(l, mid, (id*2));
    build(mid+1, r, (id*2) | 1);
    
    */
    stmx[id] = max( stmx[id*2], stmx[id*2+1]);
    stmn[id] = min( stmn[id*2], stmn[id*2+1]);
    st[id] = st[id * 2] + st[id * 2 + 1];

}
void update (int id, int l, int r, int u, int v, int val) {
    if (l > v || r < u) return;
    if (l >= u && r <= v) 
    {
        stmx[id] += val;
        stmn[id] += val;
        st[id] += val * (r - l + 1);
        lazy[id] += val;
        return;
    }
    push(id, l, r);
    int mid = (l+r)/2;
    update (id*2, l, mid, u, v, val);
    update (id*2+1, mid+1, r, u, v, val);
    stmx[id] = max( stmx[id*2], stmx[id*2+1]);
    stmn[id] = min( stmn[id*2], stmn[id*2+1]);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

int getmx (int id, int l, int r, int u, int v) {
    if (l > v || r < u) return minn;
    else if (l >= u && r <= v) return stmx[id];
    push(id, l, r);
    int mid = (l+r)/2;
    return max(getmx(id*2, l, mid, u, v), getmx(id*2+1, mid+1, r, u, v));
}
int getmn (int id, int l, int r, int u, int v) {
    if (l > v || r < u) return 1e18;
    else if (l >= u && r <= v) return stmn[id];
    push(id, l, r);
    int mid = (l+r)/2;
    return min(getmn(id*2, l, mid, u, v), getmn(id*2+1, mid+1, r, u, v));
}
int get (int id, int l, int r, int u, int v) {
    if (l > v || r < u) return 0;
    else if (l >= u && r <= v) return st[id];
    push(id, l, r);
    int mid = (l+r)/2;
    return get(id*2, l, mid, u, v) + get(id*2+1, mid+1, r, u, v);
}
