int n, k;
int a[N];
long double b[N];
long double pre[N];
bool check(long double x)
{
    for(int i = 1; i <= n; i++)
    {
        b[i] = a[i] - x;
        pre[i] = pre[i - 1] + b[i];
    }
    deque<int> dq;
    auto push = [&](int x)
    {
        while(!dq.empty() && pre[dq.back()] >= pre[x])
            dq.pop_back();
        dq.push_back(x);
    };
    push(0);
    for(int i = k; i <= n; i++)
    {
        if(pre[i] - pre[dq.front()] >= 0) return true;
        push(i - k + 1);
    }
    return false;
}
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    long double l = -1e9, r = 1e9;
    long double ans = 0;
    for(int i = 1; i <= 100; i++)
    {
        long double mid = (l + r) / 2;
        if(check(mid)) 
        {
            ans = mid;
            l = mid;
        }
        else r = mid;
    }
    cout << fixed << setprecision(5) << ans;
}
