const int N =1e6+23;
const int MOD = 1000020409;
int st[N*4];
int a[N];
int n,q;
void build(int l, int r, int id)
{
    if ( l == r )
    {
        st[id] = a[l];
        return;
    }
    int mid=(l+r)/2;
    build(mid+1, r, id*2+1);
    build(l , mid, id*2);
    st[id]= st[id*2] + st[id*2+1];
}
void update(int l, int r, int id, int pos, int val)
{
    if ( pos < l || pos > r ) return;
    if ( l == r )
    {
        st[id] = val;
        return;
    }
    int mid=(l+r)/2;
    update(l, mid, id*2, pos, val);
    update(mid+1, r, id*2+1, pos, val);
    st[id] = st[id*2] + st[id*2+1];
}
int get(int l, int r, int id, int u, int v)
{
    if ( v < l || u > r ) return 0;
    if ( u <= l && r <= v )
    {
        return st[id];
    }
    int mid=(l+r)/2;
    return get(l, mid, id*2, u, v) + get( mid+1, r, id*2+1, u, v);
}
void read()
{
   cin >> n >> q;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
}

void solve()
{
    build(1, n, 1);
    while(q--)
    {
        int t;
        cin >> t;
        if(t==2)
        {
            int l,r;
            cin >> l >> r;
            cout << get(1,n,1,l,r) << "\n";
        }
        else
        {
            int pos,val;
            cin >> pos >> val;
            update(1,n,1,pos,val);
        }
    }
   
}

