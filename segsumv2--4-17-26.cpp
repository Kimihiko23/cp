using namespace std;
const int N =1e6+23;
const int MOD = 1000020409;
int bit[N];
int a[N];
int n, q;


void update(int idx, int val) {
    for (; idx <= n; idx += idx & -idx) {
        bit[idx] += val;
    }
}


int query(int idx) {
    int sum = 0;
    for (; idx > 0; idx -= idx & -idx) {
        sum += bit[idx];
    }
    return sum;
}


int get_sum(int l, int r) {
    if (l > r) return 0;
    return query(r) - query(l - 1);
}

void read() 
{
    cin >> n >> q;
    for (int i = 1; i <= n; i++) 
    {
        cin >> a[i];
        update(i, a[i]);
    }
}

void solve() 
{
    while (q--) 
    {
        int t;
        cin >> t;
        if (t == 1) {
            int i, v;
            cin >> i >> v;
            int diff = v - a[i];
            update(i, diff);     
            a[i] = v;            
        } else {
            int l, r;
            cin >> l >> r;
            cout << get_sum(l, r) << "\n";
        }
    }
}

