#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
int st[N * 4][30];
int lazy[N * 4][30];
int n, q;
string s;
void push(int l, int r, int id, int mid, int ty)
{
    if (lazy[id][ty] == -1)
        return;
    int val = lazy[id][ty];

    st[id * 2][ty] = val * (mid - l + 1);
    lazy[id * 2][ty] = val;

    st[id * 2 + 1][ty] = val * (r - mid);
    lazy[id * 2 + 1][ty] = val;

    lazy[id][ty] = -1;

}
void update(int l, int r, int id, int u, int v, int val, int ty)
{
    if(l > v || r < u)
    {
        return; 
    }
    if(l >= u && r <= v)
    {
        st[id][ty] = val * (r - l + 1);
        lazy[id][ty] = val;
        return;
    }
    int mid = (l + r)/2;
    push(l, r, id, mid, ty);
    update(l , mid, id * 2, u, v, val, ty);
    update(mid + 1 , r, id * 2 + 1, u, v, val, ty);
    st[id][ty] = st[id * 2][ty] + st[id * 2 + 1][ty];
}
void build(int id , int l , int r)
{
    if(l == r)
    {
        st[id][s[l] - 'a'] = 1;
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2 , l , mid);
    build(id * 2 + 1 , mid + 1 , r);

    for(int i = 0 ; i <= 25 ; i++)
        st[id][i] = (st[id * 2][i] + st[id * 2 + 1][i]);
}
int get(int l, int r, int id, int u, int v, int ty)
{
    if(l > v || r < u)
    {
        return 0; 
    }
    if(l >= u && r <= v)
    {
        return st[id][ty];
    }
    int mid = (l + r)/2;
    push(l, r, id, mid, ty);
    return get(l, mid, id * 2, u, v, ty) + get(mid + 1, r, id * 2 + 1, u, v, ty);
}

void read()
{
    cin >> n >> q >> s;
    s = " " + s;
}

void solve()
{
    for(int i = 1; i <= n * 4; i++)
    {
        for(int j = 0; j < 26; j++)
        {
            lazy[i][j] = -1;
        }
    }
    build(1, 1, n);
    while(q--)
    {
        int l, r, x;
        int cnt[26] = {0}; 
        cin >> l >> r >> x;
        if(x == 1)
        {
            for(int j = 0; j < 26; j++)
            {
                cnt[j] = get(1, n, 1, l, r, j);
                update(1, n, 1, l, r, 0, j);
            }
            for(int j = 0; j < 26; j++)
            {
                if(cnt[j])
                {
                    update(1, n, 1, l, l + cnt[j] - 1, 1, j);
                    l += cnt[j];
                }
            }
        }
        else
        {
            for(int j = 0; j < 26; j++)
            {
                cnt[j] = get(1, n, 1, l, r, j);
                update(1, n, 1, l, r, 0, j);
            }
            for(int j = 25; j >= 0; j--)
            {
                if(cnt[j])
                {
                    update(1, n, 1, l, l + cnt[j] - 1, 1, j);
                    l += cnt[j];
                }
            }
        }
    }
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j < 26; j++)
        {
            int cnt = get(1, n, 1, i, i, j);
            if(cnt)
            {
                cout << char(j + 'a');
                break;
            }
        }
    }
}

