void solve()
{
    int tam = a[1];
    pre[1] = a[1];
    int dem = 1;
    for(int i = 2; i <= n; i++)
    {
        tam += a[i];
        dem++;
        if(tam < 0)
        {
            tam = 0;
            dem = 0;
        }
        pre[i] = pre[i - 1];
        if(dem > 0)
        {
            pre[i] = max(pre[i], tam);
        }
    }
    tam = a[n];
    suf[n] = a[n];
    dem = 1;
    for(int i = n - 1; i >= 1; i--)
    {
        tam += a[i];
        dem++;
        if(tam < 0)
        {
            tam = 0;
            dem = 0;
        }
        suf[i] = suf[i + 1];
        if(dem > 0)
        {
            suf[i] = max(suf[i], tam);
        }
    }
    int ans = -1e18;
    for(int i = 1; i < n; i++)
    {
        ans = max(ans, pre[i] + suf[i + 1]);
    }
    if(n == 1)
    cout << a[1];
    else
    cout << ans;
}
