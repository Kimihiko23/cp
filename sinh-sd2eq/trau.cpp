int n;
int a[N];
int pre[N];
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
}
void solve()
{
    int ans = -1e18;
    for(int l1 = 1; l1 <= n - 1; l1++)
    {
        for(int r1 = l1; r1 <= n - 1; r1++)
        {
            for(int l2 = r1 + 1; l2 <= n; l2++)
            {
                for(int r2 = l2; r2 <= n; r2++)
                {
                    int sum = pre[r1] - pre[l1 - 1] + pre[r2] - pre[l2 - 1];
                    ans = max(ans, sum);
                }
            }
        }
    }
    cout << ans;
}
