#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD = 1e9 + 7;
const int N = 16 + 1;
const int M = (1 << N) + 23;
int dp[60][M];
int n, m;
bool dd[60][60];
void read()
{
    cin >> n >> m;
    for(int i = 0 ; i < n; i++)
    {
        int x;
        cin >> x;
        for(int j = 0; j < x; j++)
        {
            int y;
            cin >> y;
            dd[i][y] = true;
        }
    }
}
void solve()
{
    dp[0][0] = 1;
    for(int i = 1; i <= m; i++)
    {
        for(int mask = 0; mask < (1 << n); mask++)
        {
            dp[i][mask] = dp[i - 1][mask];
            for(int x = 0; x < n; x++)
            {
                if((mask & (1 << x)) && dd[x][i])
                {
                    dp[i][mask] += dp[i - 1][mask ^ (1 << x)];
                    dp[i][mask] %= MOD;
                }
            }
        }
    }
    cout << dp[m][(1 << n) - 1];
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt","r")) 
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }
    // freopen(name ".inp", "r", stdin);
    // freopen(name ".out", "w", stdout);
    read();
    solve();
} 
