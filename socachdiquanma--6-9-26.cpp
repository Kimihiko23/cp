#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9;

int n, m, k, q;
int dp[1005][1005];
bool f[1005][1005];
bool check(int x, int y)
{
    if (x >= 1 && x <= m && y >= 1 && y <= n)
    {
        return true;
    }
    return false;
}
void read()
{
    cin >> n >> m >> k >> q;
    for (int i = 0; i < k; i++)
    {
        int x, y;
        cin >> x >> y;
        f[x][y] = true;

    }
}

void solve()
{
    dp[m][n] = 1;

    int dx[] = {-1, 1, 2, 2};
    int dy[] = {2, 2, -1, 1};

    int mv = min(m, n);
    for(int i = m; i >= 1; i--)
    {
        int x = n;
        int y = i;
        while(check(x, y))
        {
            if(!f[x][y] && !(x == m && y == n))
            {
                for (int j = 0; j < 4; j++)
                {
                    int xx = x + dx[j];
                    int yy = y + dy[j];
                    if (check(xx, yy) && !f[xx][yy])
                    {
                        dp[x][y] += dp[xx][yy];
                        dp[x][y] %= MOD;
                    }
                }
            }
            x--;
            y++;
        }
    }

    for (int i = 0; i < q; i++)
    {
        int x, y;
        cin >> x >> y;
        cout << dp[x][y] << "\n";
    }
}

