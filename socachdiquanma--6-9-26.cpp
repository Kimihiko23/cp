#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9;

int n, m, k, q;
int dp[1005][1005];
bool f[1005][1005];

void read()
{
    cin >> n >> m >> k >> q;
    for (int i = 0; i < k; i++)
    {
        int x, y;
        cin >> x >> y;
        if (x >= 1 && x <= m && y >= 1 && y <= n)
        {
            f[x][y] = true;
        }
    }
}

void solve()
{
    if (!f[m][n]) 
    {
        dp[m][n] = 1;
    }

    int dx[] = {-1, 1, 2, 2};
    int dy[] = {2, 2, -1, 1};

    for (int x = m; x >= 1; x--)
    {
        for (int y = n; y >= 1; y--)
        {
            if (f[x][y]) 
            {
                continue;
            }
            if (x == m && y == n) 
            {
                continue;
            }

            for (int i = 0; i < 4; i++)
            {
                int nx = x + dx[i];
                int ny = y + dy[i];

                if (nx >= 1 && nx <= m && ny >= 1 && ny <= n)
                {
                    dp[x][y] = (dp[x][y] + dp[nx][ny]) % MOD;
                }
            }
        }
    }

    for (int i = 0; i < q; i++)
    {
        int x, y;
        cin >> x >> y;
        cout << dp[x][y] << "\n";
    }
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt","r")) 
    {
        freopen("input.txt","r",stdin);
        freopen("output.txt","w",stdout);
    }
    read();
    solve();
}