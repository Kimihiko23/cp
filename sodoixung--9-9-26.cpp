bool checktight(const string &num, int cnt0) 
{
    // int cnt0 = 0;
    string s = num.substr(cnt0);
    int len = s.size();
    string p = s;
    int k = (len + 1) / 2;
    for (int i = 0; i < len - k; i++) 
    {
        p[len - 1 - i] = s[i];
    }
    return p <= s; 
}
int f(string &num, int pos, int tight, int lead, int cnt0)
{
    int used = num.size() - pos - cnt0;
    int len = num.size() - cnt0;
    if(len == 0) return 0;
    if(!tight && used == (len + 1) / 2) return 1;
    if(tight && used == (len + 1) / 2)
    {
        if(checktight(num, cnt0)) return 1;
        return 0;
    }
    if(pos == 0) return 0;
    if(dp[pos][tight][lead][cnt0] != -1) return dp[pos][tight][lead][cnt0]  ;
    int limit = 9;
    if(tight) limit = num[num.size() - pos] - '0';
    int res = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(lead)
        {
            if(i == 0)
                res += f(num, pos - 1, 0, 1, cnt0 + 1) % MOD;
            else
                res += f(num, pos - 1, tight && (i == limit), 0, cnt0) % MOD;
        }
        else
        res += f(num, pos - 1, tight && (i == limit), 0, cnt0) % MOD;
    }
    res %= MOD;
    return dp[pos][tight][lead][cnt0] = res;
}
