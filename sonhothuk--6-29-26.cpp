using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
int n, q;
pair<int, int> a[N];
struct qe
{
    int l, r, k;
};
int L[N];
int R[N];
int ans[N];
qe que[N];
int st[N * 4];
vector<int> query[N];
int bit[N];

void update(int pos, int val)
{
    while(pos <= n)
    {
        bit[pos] += val;
        pos += pos & -pos;
    }
}

int get(int pos)
{
    int res = 0;
    while(pos > 0)
    {
        res += bit[pos];
        pos -= pos & -pos;
    }
    return res;
}

int get(int l, int r)
{
    return get(r) - get(l - 1);
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i].fi;
        a[i].se = i;
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> que[i].l >> que[i].r >> que[i].k;
        L[i] = 0;
        R[i] = n;
        ans[i] = -1;
    }
}
void solve()
{
    sort(a + 1, a + 1 + n);
    while(true)
    {
        bool stop = true;
        for(int i = 1; i <= q; i++)
        {
            if(L[i] > R[i])
                continue;
            stop = false;
            int mid = (L[i] + R[i]) / 2;
            query[mid].pb(i);
        }
        if(stop)
        {
            break;
        }
        memset(bit, 0, sizeof(bit));
        for(int i = 0; i <= n; i++)
        {
            if(i > 0)
            {
                // update(1, 1, n, a[i].se, 1);
                update(a[i].se, 1);
            }
            for(auto id : query[i])
            {
                int tam = get(que[id].l, que[id].r);
                if(tam >= que[id].k)
                {
                    R[id] = i - 1;
                    ans[id] = a[i].fi;
                }
                else
                {
                    L[id] = i + 1;
                }
            }
            query[i].clear();
        }

    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
