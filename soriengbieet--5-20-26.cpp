const int N = 1e6 + 23; 

int n, k;
vector<int> a;
int cnt[N];

void read()
{
    if (!(cin >> n >> k)) return;
    a.resize(n);
    for (int i = 0; i < n; i++) {
        cin >> a[i];
    }
}

void solve()
{
    int ans = 0;
    int dem = 0;
    int L = 0;

    for (int R = 0; R < n; R++) {

        if (cnt[a[R]] == 0) {
            dem++;
        }
        cnt[a[R]]++;

        while (dem > k) {
            cnt[a[L]]--;
            if (cnt[a[L]] == 0) {
                dem--;
            }
            L++;
        }

        ans += (R - L + 1);
    }

    cout << ans << "\n";
}

