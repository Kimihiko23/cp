const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
string L, R;
int dp[105][2][2][2];
int g(string &num)
{
    for(int i = 0; i < num.size(); i++)
    {
        if((i + 1) % 2 != (num[i] - '0') % 2)
            return 0;
    }
    return 1;
}
int f(string &num, int pos, int odd, int tight, int lead)
{
    if(pos == 0)
        return 1;
    if(dp[pos][odd][tight][lead] != -1)
        return dp[pos][odd][tight][lead];
    int limit = 9;
    if(tight == 1)
        limit = (num[num.size() - pos] - '0');
    int ans = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(i == 0)
        {
            if(lead == 0)
            {
                if(i % 2 == odd)
                    ans = (ans + f(num, pos - 1, 1 - odd, (tight & (i == limit)), 0)) % MOD;
            }
            else
            {
                ans = (ans + f(num, pos - 1, odd, (tight & (i == limit)), 1)) % MOD;
            }
        }
        else
        {
            if(i % 2 == odd)
                ans = (ans + f(num, pos - 1, 1 - odd, (tight & (i == limit)), 0)) % MOD;
        }
    }
    return dp[pos][odd][tight][lead] = ans;
}
void read()
{
    cin >> L >> R;
}
void solve()
{
    memset(dp, -1, sizeof(dp));
    int ans_r = f(R, R.size(), 1, 1, 1);
    memset(dp, -1, sizeof(dp));
    int ans_l = f(L, L.size(), 1, 1, 1);
    cout << ((ans_r - ans_l + g(L)) % MOD + MOD) % MOD;
}
