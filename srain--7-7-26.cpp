int a[N];
int b[N];
int n, q;
int pre[N];
int stmx[N * 4], stmn[N * 4];
int st[N * 4];
int lzmx[N  * 4], lzmn[N * 4];
int lz[N * 4];
void build(int id, int l, int r)
{
    if(l == r)
    {
        stmx[id] = b[l] - a[l];
        stmn[id] = b[l] - a[l];
        st[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    stmx[id] = max(stmx[id * 2], stmx[id * 2 + 1]);
    stmn[id] = min(stmn[id * 2], stmn[id * 2 + 1]);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
void downmx(int id)
{
    if(lzmx[id] == 0)
        return;
    int x = lzmx[id];
    lzmx[id * 2] += x;
    stmx[id * 2] -= x;
    lzmx[id * 2 + 1] += x;
    stmx[id * 2 + 1] -= x;
    lzmx[id] = 0;
}
void downmn(int id)
{
    if(lzmn[id] == 0)
        return;
    int x = lzmn[id];
    lzmn[id * 2] += x;
    stmn[id * 2] -= x;
    lzmn[id * 2 + 1] += x;
    stmn[id * 2 + 1] -= x;
    lzmn[id] = 0;
    
}
void updatemxmn(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        stmx[id] -= val;
        lzmx[id] += val;
        stmn[id] -= val;
        lzmn[id] += val;
        return;
    }
    downmx(id);
    downmn(id);
    int mid = (l + r) / 2;
    updatemxmn(id * 2, l, mid, u, v, val);
    updatemxmn(id * 2 + 1, mid + 1, r, u, v, val);
    stmx[id] = max(stmx[id * 2], stmx[id * 2 + 1]);
    stmn[id] = min(stmn[id * 2], stmn[id * 2 + 1]);
}
pair<int, int> getmxmn(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return {-1e18, 1e18};
    if(l >= u && r <= v)
    {
        int x1 = max((int)0, stmx[id]);
        int x2 = max((int)0, stmn[id]);
        return {x1,x2};
    }
    downmx(id);
    downmn(id);
    int mid = (l + r) / 2;
    auto x1 = getmxmn(id * 2, l, mid, u, v);
    auto x2 = getmxmn(id * 2 + 1, mid + 1, r, u, v);
    int y1 = max(x1.fi, x2.fi);
    int y2 = min(x1.se, x2.se);
    return {y1, y2};
}
void down(int id, int l, int r, int mid)
{
    if(lz[id] == 0)
        return;
    int x = lz[id];
    lz[id * 2] += x;
    lz[id * 2 + 1] += x;
    st[id * 2] += (mid - l + 1) * x;
    st[id * 2 + 1] += (r - mid) * x;
    lz[id] = 0;
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id] += (r - l + 1) * val;
        lz[id] += val;
        return;
    }
    int mid = (l + r) / 2;
    down(id, l, r, mid);
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return 0;
    // if(l == r)
    // {
    //     return min(b[l], st[id]);
    // }
    if(l >= u && r <= v)
    {
        auto check = getmxmn(1, 1, n, l, r);
        if(check.fi == 0 && check.se == 0)
            return pre[r] - pre[l - 1];
        if(check.fi > 0 && check.se > 0)
            return st[id];
    }
    int mid =(l + r) / 2;
    down(id, l, r, mid);
    int le = get(id * 2, l, mid, u, v);
    int ri = get(id * 2 + 1, mid + 1, r, u, v);
    return le + ri;
}
