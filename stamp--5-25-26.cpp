const int MOD = 1000020409;
const int N = 1e6 + 23;
int n, m, H, W;
vector<vector<int>> a;
vector<vector<int>> pre;
vector<vector<int>> dif;
vector<vector<int>> ans;
int cal(int x1, int y1, int x2, int y2)
{
    return pre[x2][y2] - pre[x1 - 1][y2] - pre[x2][y1 - 1] + pre[x1 - 1][y1 - 1];
}
int cal2(int x1, int y1, int x2, int y2)
{
    return ans[x2][y2] - ans[x1 - 1][y2] - ans[x2][y1 - 1] + ans[x1 - 1][y1 - 1];
}
void update(int x1, int y1, int x2, int y2)
{
    dif[x1][y1]++;
    dif[x1][y2 + 1]--;
    dif[x2 + 1][y1]--;
    dif[x2 + 1][y2 + 1]++;
}
void read()
{
    cin >> n >> m >> H >> W;
    a.clear();
    pre.clear();
    dif.clear();
    ans.clear();
    a.resize(n + 23, vector<int>(m + 23, 0));
    pre.resize(n + 23, vector<int>(m + 23, 0));
    dif.resize(n + 23, vector<int>(m + 23, 0));
    ans.resize(n + 23, vector<int>(m + 23, 0));
    pre[0][0] = 0;
    ans[0][0] = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            pre[i][j] = pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1] + a[i][j];
        }
    }
}
void solve()
{
    bool bad = false;
    for(int i = 1; i <= n - H + 1; i++)
    {
        for(int j = 1; j <= m - W + 1; j++)
        {
            if(cal(i, j, i + H - 1, j + W - 1) == 0)
            {
                update(i, j, i + H - 1, j + W - 1);
            }
        }
    }
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            ans[i][j] = ans[i - 1][j] + ans[i][j - 1] - ans[i - 1][j - 1] + dif[i][j];
            if(ans[i][j] == 0 && a[i][j] != 1)
            {
                bad = true;
            }
        }
    }
    if(bad)
    {
        cout << "NO\n";
    }
    else
    {
        cout << "YES\n";
    }
}
