const int N = 2e5 + 23;
int n, q;
vector<int> g[N];
int L[N], R[N];
int cnt = 0;
int stmx[N * 4];
int lz[N * 4];
void push(int id)
{
    if(lz[id] == 0)
    {
        return;
    }
    int x= lz[id];
    lz[id] = 0;

    lz[id * 2] += x;
    stmx[id * 2] += x;

    lz[id * 2 + 1] += x;
    stmx[id * 2 + 1] += x;
    
}
void dfs(int u, int par)
{
    L[u] = ++cnt;
    for(auto v : g[u])
    {
        if(v == par)
            continue;
        dfs(v, u);
    }
    R[u] = cnt;
}
void update(int id, int l, int r, int u, int v, int val)
{
    if(l > v || r < u)
    {
        return;
    }
    if(l >= u && r <= v)
    {
        stmx[id] += val;
        lz[id] += val;
        // push(id);
        return;
    }
    push(id);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    stmx[id] = max(stmx[id * 2], stmx[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
    {
        return -1e18;
    }
    if(l >= u && r <= v)
    {
        return stmx[id];
    }
    int mid = (l + r) / 2;
    push(id);
    return max(get(id * 2, l, mid, u, v), get(id * 2 + 1, mid + 1, r, u, v));
}
void read()
{
    cin >> n;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, -1);
    cin >> q;
    int ty, pos, val;
    while(q--)
    {
        cin >> ty >> pos;
        if(ty == 1)
        {
            cin >> val;
            update(1, 1, n, L[pos], R[pos], val);
        }
        else
        {
            cout << get(1, 1, n, L[pos], R[pos]) << "\n";
        }
    }
}
