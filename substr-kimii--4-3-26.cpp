using namespace std;
const int N =1e6+23;
const int MOD = 1000020407;
const int base = 256;
int p[N] , pre[N];
string a , b;
int n, m;
int x = 0;
int add(int a , int b)
{
    return (a + b) % MOD;
}
int mul(int a , int b)
{
    return (a * b) % MOD;
}
int sub(int a , int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int f(int l , int r)
{
    return sub(pre[r] , mul(p[r - l + 1] , pre[l - 1]));
}
void read()
{   
    cin >> a >> b;
    n = a.size();
    a = " " + a;
    m = b.size();
    b = " " + b;
    p[0] = 1;
}
void solve()
{
    for(int i = 1; i <= max(n, m); i++)
    {
        p[i] = mul(p[i - 1], base);
    }
    for(int i = 1; i <= n; i++)
    {
        pre[i] = add(mul(pre[i - 1], base), a[i]);
    }
    for(int i = 1; i <= m; i++)
    {
        x = add(mul(x, base), b[i]);
    }
    for(int i = 1; i <= n - m + 1; i++)
    {
        if(f(i, i + m - 1) == x)
        {
            cout << i << " ";
        }
    }
}   

