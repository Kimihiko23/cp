#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e3+23;
int st[N * 4];
deque<pair<int, pair<int, int>>> sum;
deque<pair<int, pair<int, pair<int, int>>>> que;
int pre[N];
int a[N];
int n, q;
int bit[N][N];
void update(int l, int r, long long val) 
{
    int i = n - l + 1; 
    for (; i <= n; i += i & -i) 
    {
        for (int j = r; j <= n; j += j & -j) 
        {
            bit[i][j] = max(bit[i][j], val);
        }
    }
}
long long query(int u, int v) {
    long long res = -1e18;
    int i = n - u + 1;
    for (; i > 0; i -= i & -i) {
        for (int j = v; j > 0; j -= j & -j) 
        {
            res = max(res, bit[i][j]);
        }
    }
    return res;
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
    for(int i = 1; i <= q; i++)
    {
        int k, l, r;
        cin >> l >> r >> k;
        que.pb({k, {l, {r, i}}});
    }
}

void solve()
{
    vector<int> ans(q + 1);
    for(int i = 1; i <= n; i++)
    {
        for(int j = i; j <= n; j++)
        {
            sum.pb({pre[j] - pre[i - 1], {i, j}});
        }
    }
    sort(sum.begin(), sum.end());
    // for(auto i : sum)
    // {
    //     cout << i.fi << " ";
    // }
    sort(que.begin(), que.end());
    for(int i = 1; i <= n; i++)
        for(int j = 1; j <= n; j++)
            bit[i][j] = -1e18;
    while(!que.empty() && sum.front().fi > que.front().fi)
    {
        ans[que.front().se.se.se] = -1e18;
        que.pop_front();
    }
    for(int i = 0; i < que.size(); i++)
    {
        while(!sum.empty() && sum.front().fi <= que[i].fi)
        {
            update(sum.front().se.fi, sum.front().se.se, sum.front().fi);
            sum.pop_front();
        }
        ans[que[i].se.se.se] = query(que[i].se.fi, que[i].se.se.fi);
    }
    for(int i = 1; i <= q; i++)
        if(ans[i] == -1e18)
            cout << "NONE\n";
        else
        cout << ans[i] << "\n";
}

