int dis[N];
void dijkstra()
{
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    pq.push({0, 0});
    while(!pq.empty())
    {
        auto [w, u] = pq.top();
        pq.pop();
        if(w > dis[u])
        {
            continue;
        }
        for(int i = 1; i <= n; i++)
        {
            if(dis[(w + a[i]) % a[1]] > w + a[i])
            {
                dis[(w + a[i]) % a[1]] = w + a[i];
                pq.push({dis[(w + a[i]) % a[1]], (w + a[i]) % a[1]});
            }
        }
    }
}
