int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
vector<pair<int,int>> a;
int n, q;
void read()
{
    cin >> n >> q;
    int l, r;
    for(int i = 1; i <= q; i++)
    {
        cin >> l >> r;
        if(l > r)
        {
            a.pb({r + 1, -1});
            a.pb({l, 1});
            a.pb({1, 1});
        }
        else
        {
            a.pb({l, 1});
            a.pb({r + 1, -1});
        }
    }
    
}
void solve()
{
    int ans = 0;
    sort(a.begin(), a.end());
    int sum = 0;
    int cnt = 0;
    for(int i = 0; i < a.size(); i++)
    {
        sum += a[i].se;
        if(a[i].fi != a[i + 1].fi)
        {
            if(sum > ans)
            {
                ans = sum;
                cnt = a[i + 1].fi - a[i].fi;
            }
            else if(sum == ans)
            {
                cnt += a[i + 1].fi - a[i].fi;
            }
        }
    }
    cout << ans << " " << cnt;
}
