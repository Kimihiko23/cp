mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int BIT[N];
int n;
void add(int pos, int val)
{
    for(int i = pos; i <= n; i += i & (-i))
    {
        BIT[i] += val;
    }
}
int get(int pos)
{
    int res = 0;
    for(int i = pos; i > 0; i -= i & (-i))
    {
        res += BIT[i];
    }
    return res;
}
int getr(int l, int r)
{
    return get(r) - get(l - 1);
}
struct query
{
    
    int ty, x1,x2;
};
bool cmp(const query &a, const query &b)
{
    return a.ty < b.ty;
}
vector<query> evn[N];
void read()
{
    cin >> n;
    int x1, x2, y1, y2;
    for(int i = 1; i <= n; i++)
    {
        cin >> x1 >> y1 >> x2 >> y2;
        if(y1 == y2)
        {
            evn[x1].pb({0, y1, 0});
            evn[x2 + 1].pb({1, y2, 0});
        }
        else
        {
            evn[x1].pb({3, y1, y2});
        }
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= 100000; i++)
    {
        if(evn[i].size() == 0)
            continue;
        sort(evn[i].begin(), evn[i].end(), cmp);
        for(auto j : evn[i])
        {
            if(j.ty == 0)
            {
                add(j.x1, 1);
            }
            else
            if(j.ty == 1)
            {
                add(j.x1, -1);
            }
            else
            {
                ans += getr(j.x1, j.x2);
            }
        }
    }
    cout << ans;
}
