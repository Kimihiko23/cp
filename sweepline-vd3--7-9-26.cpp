vector<int> g[N];
int n;
multiset<int> s;
int ans = 0;
void read()
{
    cin >> n;
    int x, y, h1, h2;
    for(int i = 1; i <= n; i++)
    {
        cin >> x >> h1 >> y >> h2;
        g[x].pb(h1);
        g[y].pb(-h2);
    }
}
void solve()
{

    for(int i = 1; i < 100000; i++)
    {
        for(auto j : g[i])
        {
            if(j > 0)
            {
                s.insert(j);
            }
            else
            {
                s.erase(s.find(-j));
            }
        }
        if(!s.empty())
            ans += *s.rbegin();
    }
    cout << ans;
}
