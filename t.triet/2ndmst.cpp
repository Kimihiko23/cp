int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int par[22][N];
int mx[22][N];
int n, m;
int pardsu[N], h[N];
int sz[N];
vector<pair<int, int>> g[N];
vector<pair<int, pair<int, int>>> edg;
bool dd[N];
int findpar(int v)
{
    if (v==pardsu[v])
    {
        return v;
    }
    else
    {
        pardsu[v]=findpar(pardsu[v]);
    }
    return pardsu[v];
}
void joinset(int a,int b)
{
    a=findpar(a);
    b=findpar(b);
    if (a!=b)
    {
        if (sz[a]<sz[b])
        {
            swap(a,b);
        }
        sz[a]+=sz[b];
        pardsu[b]=a;
    }
}
void dfs(int u, int p)
{
    for(auto i : g[u])
    {
        int v = i.se;
        int w = i.fi;
        if(v == p)
            continue;
        h[v] = h[u] + 1;
        par[0][v] = u;
        mx[0][v] = w;
        dfs(v, u);
    }
}
void init()
{
    for(int i = 1; i <= 19; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            par[i][j] = par[i - 1][par[i - 1][j]];
            mx[i][j] = max(mx[i - 1][j], mx[i - 1][par[i - 1][j]]);
        }
    }
}
int lca(int u, int v)
{
    int res = -1e18;
    if(h[v] > h[u])
    swap(u, v);
    for(int i = 19; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
        {
            res = max(res, mx[i][u]);
            u = par[i][u];
        }
    }
    if(u == v)
        return res;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            res = max(res, mx[i][u]);
            res = max(res, mx[i][v]);
            u = par[i][u];
            v = par[i][v];
        }
    }
    res = max(res, mx[0][u]);
    res = max(res, mx[0][v]);
    return res;

}
void read()
{
    cin >> n >> m;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        edg.pb({w, {u, v}});
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        sz[i] = 1;
        pardsu[i] = i;
    }
    int mn = 0;
    sort(edg.begin(), edg.end());
    for(int i = 0; i < m; i++)
    {
        int u = edg[i].se.fi;
        int v = edg[i].se.se;
        // cout << u << " " << v << "\n";
        int uu = u;
        int vv = v;
        u = findpar(u);
        v = findpar(v);
        // cout << u << " " << v << "\n";
        // cout << "\n";
        int w = edg[i].fi;
        if(u != v)
        {
            mn += edg[i].fi;
            v = vv;
            u = uu;
            joinset(u, v);
            g[u].pb({w, v});
            g[v].pb({w, u});
            dd[i] = 1;
            // cout << u << " " << v << "\n";
        }
    }
    // cout << mn << "\n";
    if(m == n - 1)
    {
        cout << -1;
        return;
    }
    dfs(1, 0);
    init();
    int ans = 1e18;
    for(int i = 0; i < m; i++)
    {
        if(dd[i])
            continue;
        int u = edg[i].se.fi;
        int v = edg[i].se.se;
        // u = findpar(u);
        // v = findpar(v);
        int w = edg[i].fi;
        int tam = lca(u, v);
        // cout << tam << " " << u << " " << v << "\n";
        ans = min(ans, mn - tam + w);
    }
    cout << ans;
}
