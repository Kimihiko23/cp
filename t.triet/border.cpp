void solve()
{
    for(int i = 0; i < n; i++)
    {
        for(int mask = 0; mask < (1 << n); mask++)
        {
            dp[i][mask] = 0;
        }
    }
    for(int mask = 0; mask < (1 << n); mask++)
    {
        vector<int> on;
        for(int x = 0; x < n; x++)
        {
            if((mask >> x) & 1)
                on.pb(x);
        }
        if(on.size() == 1)
            continue;
        // cout << on.size() << "\n";
        for(auto i : on)
        {
            for(auto j : on)
            {
                if(i == j)
                    continue;
                dp[i][mask] = max(dp[i][mask], dp[j][mask ^ (1 << i)] + __gcd(a[i], a[j]));
            }
        }
    }
    int ans = 0;
    for(int i = 0; i < n; i++)
    {
        ans = max(ans, dp[i][(1 << n) - 1]);
    }
    cout << ans;
}
