#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int nen[N];
int ttdfs[N];
int lowdfs[N];
bool out[N];
vector<int> g[N];
vector<int> g2[N];
stack<int> st;
vector<int> res;
vector<pair<int, int>> edges;
int n, m;
int dem = 0;
int cot = 0;
void dsf(int u)
{
    dem++;
    st.push(u);
    ttdfs[u] = dem;
    lowdfs[u] = dem;
    for(auto i : g[u])
    {
        if(out[i]) continue;
        if(ttdfs[i]==0)
        {
            dsf(i);
            lowdfs[u] = min(lowdfs[u], lowdfs[i]);
        }
        else
        {
            lowdfs[u] = min(lowdfs[u], ttdfs[i]);
        }
    }
    if(lowdfs[u]==ttdfs[u])
    {
        int sz = 0;
        int v = -1;
        cot++;
        while(v!=u)
        {
            v = st.top();
            st.pop();
            out[v] = 1;
            sz++;
            nen[v] = cot;
        }
        res.pb(sz);
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        edges.pb({u, v});
    }
}

void solve()
{
    for(int i = 1; i <= n; i++)
    {
        lowdfs[i] = 1e18;
    }
    for(int i = 1; i <= n; i++)
    {
        if(ttdfs[i]==0)
        {
            dsf(i);
        }
    }
    for(int i = 0; i < edges.size(); i++)
    {
        int u = edges[i].fi;
        int v = edges[i].se;
        if(nen[u]!=nen[v])
        {
            g2[nen[u]].pb(nen[v]);
        }
    }
    for(int i = 1; i <= cot; i++)
    {
        g2[i].erase(unique(g2[i].begin(), g2[i].end()), g2[i].end());
    }
    int ans = 1e18;
    for(int i = 1; i <= cot; i++)
    {
        if(g2[i].size()==0)
        {
            ans = min(ans, res[i-1]);
        }
    }
    cout << ans;
}

siesta()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
}
