#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define all(x) x.begin(), x.end()
#define fi first
#define se second
using namespace std;
const int N = 3e5+23;
struct ar
{
    int g;
    int dem;
};
int a[N];
int n, q;
ar st[N*4];
ar emp = {0, 0};
ar combine(ar x, ar y)
{
    if(x.g == 0)
    {
        return y;
    }
    if(y.g == 0)
    {
        return x;
    }
    ar ans;
    ans.g = __gcd(x.g, y.g);
    ans.dem = 0;
    if(x.g == ans.g)
        ans.dem += x.dem;
    if(y.g == ans.g)
        ans.dem += y.dem;
    return ans;
    
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].g = a[l];
        st[id].dem = 1;
        return;
    }
    int mid=(l + r)/ 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = combine(st[id * 2], st[id * 2 + 1]);
}
ar get(int l, int r, int id, int u, int v)
{
    if(l > v || r < u)
        return emp;
    if(l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return combine(get(l, mid, id * 2, u, v),
    get(mid + 1, r, id * 2 + 1, u, v));

}
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
   cin >> q;
}

void solve()
{
   build(1, n, 1);
   while(q--)
   {
        int l, r;
        cin >> l >> r;
        int ans = get(1, n, 1, l, r).dem;
        cout << r - l + 1 - ans << "\n";
   }
}

main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);
    read();
    solve();
    
   
}
