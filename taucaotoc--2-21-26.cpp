#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m;
vector<int> g[N], g2[N];
int in[N], ou[N];
int low[N];
stack<int> st;
int dd[N];
//int in[N];
int out[N];
int ans = 0;
int dem = 0;
int nen[N];
vector<pair<int, int>> edges;
void dfs(int u)
{
    st.push(u);
    dd[u] = low[u] = ++dem;
    for(auto v : g[u])
    {
        if(out[v] == 0)
        {
            if(dd[v] == 0)
            {
                dfs(v);
                low[u] = min(low[u], low[v]);
            }
            else
            {
                low[u] = min(low[u], dd[v]);
            }
        }
    }
    if(low[u] == dd[u])
        {
            ans++;
            while(1)
            {
                
                int x = st.top();
                st.pop();
                out[x] = ans;
                nen[x] = ans;
                if(x == u) break;
            }
        }
    
}

void read()
{
   cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
         int u, v;
         cin >> u >> v;
         g[u].pb(v);
         edges.pb({u, v});
    }
}

void solve()
{
   for(int i = 1; i <= n; i++)
   {
       if(dd[i] == 0)
       {
           dfs(i);
       }
   }
   for(auto i : edges)
   {
       if(nen[i.fi] != nen[i.se])
       {
           g2[nen[i.fi]].pb(nen[i.se]);
           in[nen[i.se]]++;
           ou[nen[i.fi]]++;
       }
   }
   int dem1 = 0, dem2 = 0;
    for(int i = 1; i <= ans; i++)
    {
         if(in[i] == 0) dem1++;
         if(ou[i] == 0) dem2++;
    }
    cout << max(dem1, dem2);
}

