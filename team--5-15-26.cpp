const int MOD = 1e9 + 7;
const int N = 1e6 + 23;


int fact[N], invfact[N];

int pw(int a, int b)
{
    int res = 1;
    while(b)
    {
        if(b & 1) res = res * a % MOD;
        a = a * a % MOD;
        b >>= 1;
    }
    return res;
}

int C(int n, int k)
{
    if(k < 0 || k > n) return 0;
    return fact[n] * invfact[k] % MOD * invfact[n - k] % MOD;
}

