void solve()
{
    fact[0] = 1;
    for(int i = 1; i < N; i++)
        fact[i] = fact[i - 1] * i % MOD;

    invfact[N - 1] = pw(fact[N - 1], MOD - 2);

    for(int i = N - 2; i >= 0; i--)
        invfact[i] = invfact[i + 1] * (i + 1) % MOD;
    int n, a, b, d;
    while(cin >> n >> a >> b >> d)
    {
        cout << C(n, a) * pw(C(b, d), a) % MOD << "\n";
    }
    
}

