int a[N];
int n, k;
bool check(int x)
{
    int vtmid = n / 2 + 1;
    int need = 0;
    // cout << need << "\n";
    for(int i = vtmid; i <= n; i++)
    {
        if(a[i] <= x)
        {
            need += abs(a[i] - x);
        }
        if(need > k)
            return false;
    }
    // cout << need << "\n";
    return need <= k;
}
void read()
{
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }    
}
void solve()
{
    sort(a + 1, a + 1 + n);
    // cout << n / 2 + 1;
    int ans = a[n / 2 + 1];
    int l = a[n / 2 + 1], r = 1e18;
    // check(3);
    while(l <= r)
    {
        int mid = (l + r) / 2;
        if(check(mid))
        {
            ans = max(ans, mid);
            l = mid + 1;
        }
        else
            r = mid - 1;
    }
    cout << ans;
}
