void solve()
{
    par[1] = 0;
    dfs(1, 0);
    hld(1, 1);
    sort(tt.begin(), tt.end());
    tt.erase(unique(tt.begin(), tt.end()), tt.end());
    for(auto x : tt)
    {
        for(auto u : ty[x])
        {
            updatever(u, 1);
        }
        for(auto [id, l, r] : que[x])
        {
            int sum = getpath(l, r);
            if(sum > 0)
                ans[id] = 1;
            else
                ans[id] = 0;
        }
        for(auto u : ty[x])
        {
            updatever(u, 0);
        }
    }
    for(int i = 1; i <= q; i++)
      {
      cout << ans[i] ;
    }

}
