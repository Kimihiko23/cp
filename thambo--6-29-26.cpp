const int N = 1e5 + 23;
struct node
{
    int id, l, r;
};
vector<node> que[N];
int n, q;
int a[N];
int par[N], heavy[N], head[N], pos[N], sz[N];
vector<int> g[N];
int ans[N];
int st[N * 4];
vector<int> ty[N];
void update(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        st[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
        return st[id];
    int mid = (l + r) / 2;
    return get(id * 2, l, mid, u, v) + get(id * 2 + 1, mid + 1, r, u, v);
}
void updatever(int u, int val)
{
    update(1, 1, n, pos[u], val);
}
int getpath(int u, int v)
{
    int res = 0;
    // u > v
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            swap(u, v);
        res += get(1, 1, n, pos[head[u]], pos[u]);
        u = par[head[u]];
    }
    if(pos[u] > pos[v])
        swap(u, v);
    res += get(1, 1, n, pos[u], pos[v]);
    return res;
}
void dfs(int u, int p)
{
    // par[u] = p;
    sz[u] = 1;
    int mx = 0;
    for(auto v : g[u])
    {
        if(v == p)
            continue;
        par[v] = u;
        dfs(v, u); 
        sz[u] += sz[v];
        if(sz[v] > mx)
        {
            mx = sz[v];
            heavy[u] = v;
        }
    }
}
int cnt = 0;
void hld(int u, int he)
{
    head[u] = he;
    pos[u] = ++cnt;
    if(heavy[u])
        hld(heavy[u], he);
    for(auto v : g[u])
    {
        if(v == par[u] || v == heavy[u])
            continue;
        hld(v, v);
    }
}
