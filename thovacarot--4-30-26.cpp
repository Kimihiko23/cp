void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (!dd[i][j] && a[i][j] == 1)
            {
                bfs(i, j);
            }
        }
    }
    int ans = 0;
    queue<pair<int, int>> q;
    int mx = 0;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            dis[i][j] = 1e18;
            dd[i][j] = false;
            if(a[i][j] == 1)
            {
                pair<int, int> p = find(i, j);
                int x = p.fi;
                int y = p.se;
                int val = sz[x][y];
                if(val > mx)
                {
                    q = queue<pair<int, int>>();
                    dd[i][j] = true;
                    dis[i][j] = 0;
                    q.push({i, j});
                    mx = val;
                }
                else if(val == mx)
                {
                    q.push({i, j});
                    dd[i][j] = true;
                    dis[i][j] = 0;
                }

            }
        }
    }
    while(!q.empty())
    {
        pair<int, int> u = q.front();
        q.pop();
        vector<int> dx = {0, 0, 1, -1};
        vector<int> dy = {1, -1, 0, 0};
        for (int i = 0; i < 4; i++)
        {
            int x = u.fi + dx[i];
            int y = u.se + dy[i];
            if (check(x, y) && !dd[x][y])
            {
                dis[x][y] = dis[u.fi][u.se] + 1;
                dd[x][y] = true;
                q.push({x, y});
            }
        }
    }
    cout << mx << " " << dis[vtx][vty];

    
}
