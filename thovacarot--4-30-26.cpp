using namespace std;
const int MOD = 1000020409;
const int N =1e3+23;
int a[N][N];
int n, m;
int sz[N][N];
pair<int, int> par[N][N];
bool dd[N][N];
int dis[N][N];
int vtx, vty;
bool check(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= m;
}
pair<int, int> find(int x, int y)
{
    if (par[x][y] == make_pair(x, y))
        return {x, y};
    return par[x][y] = find(par[x][y].fi, par[x][y].se);
}
void join(int x1, int y1, int x2, int y2)
{
    pair<int, int> p1 = find(x1, y1);
    pair<int, int> p2 = find(x2, y2);
    if (p1 == p2)
        return;
    if (sz[p1.fi][p1.se] < sz[p2.fi][p2.se])
        swap(p1, p2);
    par[p2.fi][p2.se] = p1;
    sz[p1.fi][p1.se] += sz[p2.fi][p2.se];
}
void bfs(int stx, int sty)
{
    queue<pair<int, int>> q;
    q.push({stx, sty});
    dd[stx][sty] = true;
    vector<int> dx = {0, 0, 1, -1};
    vector<int> dy = {1, -1, 0, 0};
    while (!q.empty())
    {
        pair<int, int> u = q.front();
        q.pop();
        for (int i = 0; i < 4; i++)
        {
            int x = u.fi + dx[i];
            int y = u.se + dy[i];
            if (check(x, y) && !dd[x][y] && a[x][y] == a[stx][sty])
            {
                dd[x][y] = true;
                join(stx, sty, x, y);
                q.push({x, y});
            }
        }
    }
}
