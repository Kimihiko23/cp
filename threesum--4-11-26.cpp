{   
    cin >> n >> k;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}
void solve()
{
    sort(a + 1, a + n + 1);
    for(int i = 1; i <= n; i++)
    {
        int tam = k - a[i];
        mp2.clear();
        for(int j = i + 1; j <= n; j++)
        {
            if(mp2.find(tam - a[j]) != mp2.end())
            {
                ans += mp2[tam - a[j]];
                int tem[3];
                tem[0] = a[i];
                tem[1] = a[j];
                tem[2] = tam - a[j];
                sort(tem, tem + 3);
                cout << tem[0] << " " << tem[1] << " " << tem[2] << "\n";
                exit(0);
            }
            mp2[a[j]]++;
        }
        mp1[a[i]]++;
    }
    cout << "IMPOSSIBLE\n";
}   

