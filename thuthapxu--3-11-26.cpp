#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m;
vector<int> g[N], g2[N];
int low[N];
stack<int> st;
int dd[N];
//int in[N];
int out[N];
int ans = 0;
int dem = 0;
int nen[N];
int sum[N];
int a[N];
vector<pair<int, int>> edges;
int dp[N];
bool dd1[N];
void dfs(int u)
{
    st.push(u);
    dd[u] = low[u] = ++dem;
    for(auto v : g[u])
    {
        if(out[v] == 0)
        {
            if(dd[v] == 0)
            {
                dfs(v);
                low[u] = min(low[u], low[v]);
            }
            else
            {
                low[u] = min(low[u], dd[v]);
            }
        }
    }
    if(low[u] == dd[u])
        {
            ans++;
            int tam = 0;
            while(1)
            {
                int x = st.top();
                sum[ans] += a[x];
                st.pop();
                out[x] = ans;
                nen[x] = ans;
                if(x == u) break;
            }
        }
    
}
void dfs2(int u)
{
    dd1[u] = true;
    int tam = 0;
    for(auto i : g2[u])
    {
        if(!dd1[i])
        {
            dfs2(i);
        }
        tam = max(tam, dp[i]); 
    }
    dp[u] = sum[u] + tam;
}
void read()
{
   cin >> n >> m;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
    for(int i = 1; i <= m; i++)
    {
         int u, v;
         cin >> u >> v;
         g[u].pb(v);
         edges.pb({u, v});
    }
}

void solve()
{
   for(int i = 1; i <= n; i++)
   {
       if(dd[i] == 0)
       {
           dfs(i);
       }
   }
   for(auto i : edges)
   {
       if(nen[i.fi] != nen[i.se])
       {
           g2[nen[i.fi]].pb(nen[i.se]);
       }
   }
   for(int i = 1; i <= ans; i++)
   {
        sort(g2[i].begin(), g2[i].end());
        g2[i].erase(unique(g2[i].begin(), g2[i].end()), g2[i].end());
   }
   int res = 0;
   for(int i = 1; i <= ans; i++)
   {
        // cout << sum[i] << " ";
        if(!dd1[i])
        {
            dfs2(i);
        }
   }
   for(int i = 1; i <= ans; i++)
   {
        res = max(res, dp[i]);
   }
   cout << res;
}

