ll c[N], h[N];
ll n;
int prec[N];
int prehc[N];
int preh[N];
int cal(int x, int ed)
{
    if(h[x] * ed > preh[ed])
    {
        return INF;
    }
    int tam1 = h[x] * prec[x] - prehc[x];
    int tam2 = prehc[ed] - prehc[x] - h[x] * (prec[ed] - prec[x]);
    return tam1 + tam2;
}
void write(int x)
{
    if(x == 0)
    {
        cout << 0;
        return;
    }
    vector<ll> v;
    while(x > 0)
    {
        v.pb(x % 10);
        x /= 10;
    }
    reverse(v.begin(), v.end());
    for(int i = 0; i < v.size(); i++)
    {
        cout << v[i];
    }
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> h[i];
    }
    for(int i = 1; i <= n; i++)
    {
        cin >> c[i];
        prec[i] = prec[i - 1] + c[i];
        prehc[i] = prehc[i - 1] + h[i] * c[i];
        preh[i] = preh[i - 1] + h[i];
    }
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        int ans = INF;
        int l = 1, r = i;
        while(l < r)
        {
            int mid1 = l + (r - l) / 3;
            int mid2 = r - (r - l) / 3;
            int le = cal(mid1, i);
            int ri = cal(mid2, i);
            if(le < ri)
            {
                ans = min(ans, le);
                
                r = mid2 - 1;
            }
            else
            {
                ans = min(ans, ri);
                l = mid1 + 1;
            }
        }
        ans = min(ans, cal(l, i));
        write(ans);
        cout << " ";
    }
}
