mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int h[N];
int n, a, b, c;
int f(int x)
{
    int res = 0;
    int ned = 0;
    int rem = 0;
    for (int i = 1; i <= n; i++)
    {
        if(h[i] > x)
        {
            rem += h[i] - x;
        }
        else
        if(h[i] < x)
        {
            ned += x - h[i];
        }
    }
    if(c > a + b)
    {
        res = ned * a + rem * b;
    }
    else
    {
        int tmp = min(ned, rem);
        ned -= tmp;
        rem -= tmp;
        res = tmp * c + ned * a + rem * b;
    }
    return res; 
}
