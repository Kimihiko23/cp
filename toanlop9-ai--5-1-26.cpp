using namespace std;
const int MOD = 1000020409;
const int N =1e5+23;
const double eps = 1e-15;

int n, ans = 0;
vector<double> v;

void read()
{
    cin >> n;
}

void solve()
{
    for (int i = 1; i <= n; i++)
    {
        int a, b, c;
        cin >> a >> b >> c;

        if (ans == -1) continue;

        if (a == 0)
        {
            if (b == 0)
            {
                if (c == 0) ans = -1;
            }
            else
            {
                v.pb((double)(-c) / b);
            }
        }
        else
        {
            int delta = b * b - 4 * a * c;

            if (delta == 0)
            {
                v.pb((double)(-b) / ((double)2 * a));
            }
            else if (delta > 0)
            {
                v.pb((-b + sqrt(delta)) / ((double)2 * a));
                v.pb((-b - sqrt(delta)) / ((double)2 * a));
            }
        }
    }

    if (ans == -1)
    {
        cout << -1 << '\n';
        return;
    }

    sort(v.begin(), v.end());

    for (int i = 0; i < (int)v.size(); i++)
    {
        if ((i + 1 < (int)v.size() && v[i + 1] - v[i] > eps) || i == (int)v.size() - 1)
        {
            ans++;
        }
    }

    cout << ans << '\n';
}

