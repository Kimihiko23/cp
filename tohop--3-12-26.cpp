double logfact(int n) 
{
    double res = 0;
    for (int i = 1; i <= n; i++) {
        res += log(i);
    }
    return res;
}
double logc(int m, int n) 
{
    if (n < 0 || n > m) return -1e18;
    return logfact(m) - logfact(n) - logfact (m - n);
}
