#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
int n, m;
vector<int> g1[N], g2[N];
int nen[N];
int ndfs[N];
int low[N];
int dem = 0;
int tplt = 0;
stack<int> st;
void dfs(int u, int par)
{
    st.push(u);
    ndfs[u] = low[u] = ++dem;
    for(auto i : g1[u])
    {
        if(i != par)
        {
            if(ndfs[i] == 0)
            {
                dfs(i, u);
                low[u] = min(low[u], low[i]);
            }
            else
            {
                low[u] = min(low[u], ndfs[i]);
            }
        }
    }
    if(low[u] == ndfs[u])
    {
        tplt++;
        while(!st.empty())
        {
            nen[st.top()] = tplt;
            // cout << st.top() << " ";
            if(st.top() == u)
            {
                st.pop();
                break;
            }
            st.pop();
        }

    }
}
int dis[N];
void duongkinh(int u)
{
    queue<int> tt;
    tt.push(u);
    dis[u] = 0;
    while(!tt.empty())
    {
        int v = tt.front();
        tt.pop();
        for(auto i : g2[v])
        {
            if(dis[i] > dis[v] + 1)
            {
                dis[i] = dis[v] + 1;
                tt.push(i);
            }
        }
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g1[u].pb(v);
        g1[v].pb(u);
    }
}

void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(ndfs[i] == 0)
        {
            dfs(i, i);
        }
    }
    for(int i = 1; i <= n; i++)
    {
        for(auto j : g1[i])
        {
            if(nen[i] != nen[j])
            {
                int u = nen[i];
                int v = nen[j];
                g2[u].pb(v);
                g2[v].pb(u);
            }
        }
    }
    for(int i = 1; i <= tplt; i++)
    {
        sort(g2[i].begin(), g2[i].end());
        g2[i].erase(unique(g2[i].begin(), g2[i].end()),g2[i].end());
        dis[i] = 1e18;
    }
    for(int i = 1; i <= tplt; i++)
    {
        if(dis[i] == 1e18)
        {
            duongkinh(i);
        }
    }
    int mx = -1e18;
    int vt = -1;
    for(int i = 1; i <= tplt; i++)
    {
        if(dis[i] > mx)
        {
            mx = dis[i];
            vt = i;
        }
    }
    for(int i = 1; i <= tplt; i++)
    {
        dis[i] = 1e18;
    }
    duongkinh(vt);
    mx = 0;
    for(int i = 1; i <= tplt; i++)
    {
        if(dis[i] > mx)
        {
            mx = dis[i];
        }
    }
    cout << mx;

}

