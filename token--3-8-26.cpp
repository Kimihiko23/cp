using namespace std;
const int N =1e6+23;
vector<int> g[N];
int n;
int dp[N], dp1[N];
void dfs(int u, int p)
{
    dp[u] = 1;
    dp1[u] = 1;
    for(auto v : g[u])
    {
        if(v == p) continue;
        dfs(v, u);
        dp[u] += dp[v];
        dp1[u] += dp1[v] + dp[v];
    }
}
void read()
{   
    cin >> n;
    for(int i = 2; i <= n; i++)
    {
        int x;
        cin >> x;
        g[x].pb(i);
    }
}
void solve()
{
    dfs(1, 0);
    for(int i = 1; i <= n; i++)
        cout << dp1[i] << " ";
}

