#define name "input"
const int MOD = 1e9 + 7;
const int N = 1e3 + 23;
int dp[N][3130];
int n;
int pow5[N];
vector<int> g[3130];
vector<int> mask;
vector<int> nguphan(int mask)
{
    vector<int> res;
    for(int i = 5 - 1; i >= 0; i--)
    {
        int digit = mask/ pow5[i];
        res.push_back(digit);
        mask -= digit * pow5[i];
    }
    return res;
}
bool check1(vector<int> in)
{
    for(int i = 1; i < in.size(); i++)
        if(in[i] == in[i - 1])
            return false;
    return true;
}
bool check2(vector<int> in1, vector<int> in2)
{
    for(int i = 0; i < in1.size(); i++)
        if(in1[i] == in2[i])
            return false;
    return true;
}
void read()
{
    cin >> n;
}
void solve()
{
    pow5[0] = 1;
    for(int i = 1; i <= 5; i++)
    {
        pow5[i] = pow5[i - 1] * 5;
    }
    for(int i = 0; i < pow5[5]; i++)
    {
        if(check1(nguphan(i)))
            mask.push_back(i);
    }
    for(auto i : mask)
    {
        dp[1][i] = 1;
    }
    for(auto j : mask)
        {
            for(auto z : mask)
            {
                if(check2(nguphan(j), nguphan(z)))
                {
                    g[j].pb(z);
                }
            }
        }
    for(int i = 2; i <= n; i++)
    {
        for(auto j : mask)
        {
            for(auto z : g[j])
            {
                dp[i][j] += dp[i - 1][z];
                dp[i][j] %= MOD;
            }
        }
    }
    int ans = 0;
    for(auto i : mask)
    {
        ans += dp[n][i];
        ans %= MOD;
    }
    cout << ans;
    
}
