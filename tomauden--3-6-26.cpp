using namespace std;
const int N =1e5+23;

string s;
int n, k;
int pre[N];
void read()
{
   cin >> n >> k >> s;
   s = " " + s;
}
void solve()
{
   for(int i = 1; i <= n; i++)
   {
        if(s[i] == 'B')
            pre[i] = 1;
        pre[i] += pre[i-1];
   }
   int ans = 1e18;
   for(int i = k; i <= n; i++)
   {
        ans = min(ans, k - (pre[i] - pre[i-k]));
   }
   cout << ans << "\n";
}
