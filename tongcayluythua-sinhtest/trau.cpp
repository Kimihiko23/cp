int power(int a, int b, int mod) 
{
    int res = 1;
    a %= mod;
    if(a < 0)
        a += MOD;
    while (b) {
        if (b & 1) res = res * a % mod;
        a = a * a % mod;
        b >>= 1;
    }
    return res;
}
