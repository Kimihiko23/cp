int n, k;
int pre[N];
void read()
{
    cin >> n >> k;
    int x;
    for(int i = 1; i <= n; i++)
    {
        cin >> x;
        pre[i] = pre[i - 1] + x;
    }
}
void solve()
{
    int ans = -1e18;
    for(int i = k; i <= n; i++)
    {
        int l = i - k;
        ans = max(ans, pre[i] - pre[l]);
    }
    cout << ans;
}
