int f(int x)
{
    if(x == 0) return 0;
    int ans = 0;
    int sq = sqrt(x);
    for(int i = 1; i <= (x/sq); i++)
    {
        ans += x / i;
    }
    for(int i = 1; i < sq; i++)
    {
        int r = x / i;
        int l = x / (i + 1) + 1;
        ans += (r - l + 1) * i;
    }
    return ans;

}
