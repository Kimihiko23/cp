using namespace std;
const int N =1e5+23;


int n, t, s;
int p[N], w[N];
int ans = 0;
void sinh(string tam, int vt)
{
    if(vt == n)
    {
        int res = 0;
        int vt = 0;
        int used = 0;
        while(vt < n)
        {
            if(tam[vt] == '1')
            {
                if(used + w[vt + 1] <= s)
                {
                    used += w[vt + 1];
                    res += p[vt + 1];
                    ans = max(ans, res);
                }  
                else
                    break;
            }
            vt++;
        }
        used = s;
        if(used < s)
        {
            used = s - 1;
        }
        for(int i = vt; vt < n; vt++)
        {
             if(tam[vt] == '1')
            {
                if(used + w[vt + 1] <= t)
                {
                    used += w[vt + 1];
                    res += p[vt + 1];
                }  
                else
                    break;
            }
        }
        ans = max(ans, res);
    }
    for(int i = vt + 1; i <= n; i++)
    {
        sinh(tam + '1', vt + 1);
        sinh(tam + '0', vt + 1);
    }
    
}
void read()
{
   cin >> n >> t >> s;
   for(int i = 1; i <= n; i++)
   {
        cin >> p[i] >> w[i];
   }
}
void solve()
{
    sinh("", 0);
    cout << ans;
}
