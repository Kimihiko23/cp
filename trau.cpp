bool dd[N];
void read()
{
   cin >> n;
   for(int i = 1; i <= n; i++)
   {
        cin >> a[i];
   }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        int sum = 0;
        int vt;
        cin >> vt;
        dd[vt] = 1;
        for(int j = 1; j <= n + 1; j++)
        {
            if(dd[j])
            {
                sum += a[j];
            }
            else
            {
                ans = max(ans, sum);
                sum = 0;
            }
        }
        cout << ans << "\n";
    }
}
