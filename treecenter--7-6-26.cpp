int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int h[N];
int n, q;
vector<int> g[N];
int par[N][30];
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        int v = i;
        if(v != old)
        {
            h[v] = h[u] + 1;
            par[v][0] = u;
            dfs(v, u);
        }
    }
}
void init()
{
    for(int j = 1; (1 << j) <= n; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);
    while(x > 0)
    {
        for(int i = tam; i >= 0; i--)
        {
            if((1 << i) <= x)
            {
                x -= 1 << i;
                u = par[u][i];
            }
        }
    }
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
int dis(int u, int v)
{
    int x = lca(u, v);
    return h[u] + h[v] - 2 * h[x];
}
void read()
{
    cin >> n >> q;
    for(int i = 1; i <= n - 1; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1, -1);
    init();
    int m;
    vector<int> que;
    while(q--)
    {
        que.clear();
        cin >> m;
        int x;
        for(int i = 1; i <= n; i++)
        {
            cin >> x;
            que.pb(x);
        }
        int mxvt1 = que[0], mxdis = 0;
        for(auto i : que)
        {
            int tam = dis(1, i);
            if(tam > mxdis)
            {
                mxvt1 = i;
                mxdis = tam;
            }
        }
    }
}
