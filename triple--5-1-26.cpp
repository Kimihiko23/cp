using namespace std;
const int MOD = 1e9 + 7;
const int N =1e4+23;
map<int,int> mp;
int ans = 0;
int n, m;
int a[N];
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
        cin >> a[i];

}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = i + 1; j <= n; j++)
        {
            int tam = m - a[i] - a[j];
            if(mp.find(tam) != mp.end())
            {
                ans += mp[tam];
                ans %= MOD;
            }
        }
        mp[a[i]]++;
    }
    cout << ans;
}
