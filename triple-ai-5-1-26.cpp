using namespace std;
const int MOD = 1e9 + 7;
const int N = 1e4 + 23;
int n, m;
int a[N];
void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
}

void solve()
{
    sort(a + 1, a + n + 1);
    int ans = 0;

    for (int i = 1; i <= n - 2; i++)
    {
        int target = m - a[i];
        if (target < 0) break;

        int L = i + 1, R = n;
        while (L < R)
        {
            int sum = a[L] + a[R];
            if (sum < target)
            {
                L++;
            }
            else if (sum > target)
            {
                R--;
            }
            else
            {
                if (a[L] == a[R])
                {
                    int count = R - L + 1;
                    ans = (ans + (count * (count - 1) / 2)) % MOD;
                    break;
                }
                else
                {
                    int left_val = a[L], right_val = a[R];
                    int cntL = 0, cntR = 0;
                    
                    while (L < R && a[L] == left_val)
                    {
                        cntL++;
                        L++;
                    }
                    while (R >= L && a[R] == right_val)
                    {
                        cntR++;
                        R--;
                    }
                    ans = (ans + (cntL * cntR)) % MOD;
                }
            }
        }
    }
    cout << ans << "\n";
}

