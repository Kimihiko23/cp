const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int a[N], b[N];
int n, m;
int f(int x)
{
    int res = 0;
    for(int i = 1; i <= n; i++)
    {
        if(a[i] <= x) res += x - a[i];
    }
    for(int i = 1; i <= m; i++)
    {
        if(b[i] >= x) res += b[i] - x;
    }
    return res;
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++) cin >> a[i];
    for(int i = 1; i <= m; i++) cin >> b[i];
}
void solve()
{
    int l = 1, r = 1e9;
    int ans = INF;
    while(l < r)
    {
        int mid1 = l + (r - l) / 3;
        int mid2 = r - (r - l) / 3;
        if(f(mid1) < f(mid2))
        {
            ans = min(ans, f(mid1));
            r = mid2 - 1;
        }
        else
        {
            ans = min(ans, f(mid2));
            l = mid1 + 1;
        }
    }
    cout << ans;
}
