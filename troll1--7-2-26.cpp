const int N = 5005;
const long long INF = (long long)4e18;

mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r)
{
    return uniform_int_distribution<int>(l, r)(rng);
}

int n, m, q;

vector<pair<int,int>> adj[N];
long long dista[N];

void read()
{
    cin >> n >> m;
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }
    cin >> q;
}

long long dijkstra(int s, int t)
{
    for(int i = 1; i <= n; i++)
        dista[i] = INF;

    priority_queue<pair<long long,int>,
                   vector<pair<long long,int>>,
                   greater<pair<long long,int>>> pq;

    dista[s] = 0;
    pq.push({0, s});

    while(!pq.empty())
    {
        auto cur = pq.top();
        pq.pop();

        long long d = cur.fi;
        int u = cur.se;

        if(d != dista[u]) continue;

        if(u == t) return d;

        for(auto e : adj[u])
        {
            int v = e.fi;
            long long w = e.se;

            if(dista[v] > d + w)
            {
                dista[v] = d + w;
                pq.push({dista[v], v});
            }
        }
    }

    return -1;
}

void solve()
{
    while(q--)
    {
        int x, y;
        cin >> x >> y;
        cout << dijkstra(x, y) << '\n';
    }
}

