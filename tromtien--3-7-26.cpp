using namespace std;
const int N =1e6+23;
int n, m;
int a[N], h[N];
int dd[N];
int pre1[N], pre2[N];
void read()
{   
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
        cin >> a[i];
    for(int i = 1; i <= n; i++)
        cin >> h[i];
    h[n + 1] = 1;
}
void solve()
{
    for(int i = 1; i <= n; i++)
    {
        if(h[i] % h[i + 1] == 0)
            dd[i] = 1;
        pre1[i] = pre1[i - 1] + a[i];
        pre2[i] = pre2[i - 1] + dd[i];
        // cout << dd[i] << " ";
    }
    // cout << 4 % 4;
    int ans = 0;
    int l = 1, r = 1;
    while(r <= n)
    {
        int tam1 = pre1[r] - pre1[l - 1];
        int tam2 = pre2[r - 1] - pre2[l - 1];
        if(tam2 == r - l && tam1 <= m)
        {
            ans = max(ans, r - l + 1);
            r++;
        }
        else
        if(l < r)
            l++;
        else
            r++;
    }
    cout << ans;
    
}

