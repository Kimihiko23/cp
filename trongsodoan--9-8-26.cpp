int dp[20][2][10][10];
int g(string &x)
{
    int mx1 = 0, mx2 = 0;
    for(auto i : x)
    {
        if(i - '0' > mx1)
        {
            mx2 = mx1;
            mx1 = i - '0';
        }
        else if(i - '0' > mx2)
        {
            mx2 = i - '0';
        }
    }
    return mx1 + mx2;
}
int f(string &x, int pos, int tight, int lead, int mx1, int mx2)
{
    if(pos == 0)
    {
        return mx1 + mx2;
    }
    if(!tight && dp[pos][lead][mx1][mx2] != -1)
    {
        return dp[pos][lead][mx1][mx2];
    }
    int limit = 9;
    if(tight)
        limit = x[x.size() - pos] - '0';
    int res = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(i == 0)
        {
            if(lead)
            {
                int new_mx1 = mx1, new_mx2 = mx2;
                if(i > new_mx1)
                {
                    new_mx2 = new_mx1;
                    new_mx1 = i;
                }
                else if(i > new_mx2)
                {
                    new_mx2 = i;
                }
                res += f(x, pos - 1, tight && (i == limit), lead, new_mx1, new_mx2);
                res %= MOD;
            }
            else
            {
                int new_mx1 = mx1, new_mx2 = mx2;
                if(i > new_mx1)
                {
                    new_mx2 = new_mx1;
                    new_mx1 = i;
                }
                else if(i > new_mx2)
                {
                    new_mx2 = i;
                }
                res += f(x, pos - 1, tight && (i == limit), lead, new_mx1, new_mx2);
                res %= MOD;
            }
        }
        else
        {
            int new_mx1 = mx1, new_mx2 = mx2;
            if(i > new_mx1)
            {
                new_mx2 = new_mx1;
                new_mx1 = i;
            }
            else if(i > new_mx2)
            {
                new_mx2 = i;
            }
            res += f(x, pos - 1, tight && (i == limit), 0, new_mx1, new_mx2);
            res %= MOD;
        }
    }
    res %= MOD;
    if(!tight)
        dp[pos][lead][mx1][mx2] = res;
    return res;
}
