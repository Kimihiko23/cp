void sinh(string s, int len)
{
    if(s.size() == n * 2 - 1)
    {
        if(abs(eval(s) - x) < 1e-9)
        {
            res++;
        }
        return;
    }
    if(len % 2 == 0)
    {
        for(int i = 0; i < nu.size(); i++)
        {
            sinh(s + nu[i], len + 1);
        }
    }
    else
    {
        for(int i = 0; i < op.size(); i++)
        {
            sinh(s + op[i], len + 1);
        }
    }
}
