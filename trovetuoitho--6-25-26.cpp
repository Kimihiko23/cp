long double eval(string s)
{
    long double ans = 0;
    long double cur = s[0] - '0';

    for(int i = 1; i < s.size(); i += 2)
    {
        char op = s[i];
        long double x = s[i + 1] - '0';

        if(op == '*')
        {
            cur *= x;
        }
        else if(op == '/')
        {
            cur /= x;
        }
        else if(op == '+')
        {
            ans += cur;
            cur = x;
        }
        else // '-'
        {
            ans += cur;
            cur = -x;
        }
    }

    return ans + cur;
}
int n, x;
int res = 0;
