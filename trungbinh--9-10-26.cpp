void add(int id, int val)
{
    while(id <= n)
    {
        bit[id] += val;
        id += id & (-id);
    }
}
int sum(int id)
{
    int res = 0;
    while(id > 0)
    {
        res += bit[id];
        id -= id & (-id);
    }
    return res;
}
int get(int l, int r)
{
    return sum(r) - sum(l - 1);
}
