const int MOD = 1e9 + 7;
const int N =2e5+23;
int low[N];
int ndfs[N];
int tplt = 0;
int n, m;
int tt = 1;
int par[N];
vector<pair<int, int>> g[N], edg;
vector<int> g2[N];
int sz[N];
stack<int> st;
int dd[N];
int ans = 0;
int vtans = 1;
void tarjan(int u, int old)
{
    ndfs[u] = low[u] = tt++;
    st.push(u);
    int node = (old != -1);
    for(auto i : g[u])
    {
        int v = i.fi;
        int id = i.se;
        if(id == old)
            continue;
        if(ndfs[v] == 1e18)
        {
            tarjan(v, id);
            low[u] = min(low[u], low[v]);
            if(low[v] >= ndfs[u])
            {
                node++;
            }
        }
        else
            low[u] = min(low[u], ndfs[v]);
    }
    if(node > 1)
    {
        dd[u] = 1;
        if(node > ans)
        {
            ans = node;
            vtans = u;
        }
        if(node == ans)
        {
            vtans = min(vtans, u);
        }
    }
    if(low[u] == ndfs[u])
    {
        tplt++;
        while(1)
        {
            sz[tplt]++;
            int tam = st.top();
            par[tam] = tplt;
            st.pop();
            if(tam == u)
                break;
        }
    }
}
