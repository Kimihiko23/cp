#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e6+23;
bool dd[N];
int par[N];
int n, m;
string s[N];
int mne = 1e18;
vector<pair<int, pair<int, int>>> edges;
int find(int u)
{
    if(par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    int pu = find(u);
    int pv = find(v);
    if(pu != pv)
    {
        par[pu] = pv;
    }
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        cin >> s[i];
    }

}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        edges.pb({m, {i, 0}});
    }
    for(int i = 1; i <= n; i++)
    {
        for(int j = i + 1; j <= n; j++)
        {
            int w = 0;
            for(int z = 0; z < m; z++)
            {
                if (s[i][z] != s[j][z]) w++;
            }
            edges.pb({w * 2, {i, j}});
        }
    }
    sort(edges.begin(), edges.end());
    for(int i = 0; i < edges.size(); i++)
    {
        int u = edges[i].se.fi;
        int v = edges[i].se.se;
        int w = edges[i].fi;
        int pu = find(u);
        int pv = find(v);
        if(pu != pv)
        {
            dd[u] = dd[v] = 1;
            join(u, v); 
            ans += w;
        }
    }
    cout << ans;
    
}

