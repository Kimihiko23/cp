int h[N];
int n;
vector<pair<int, int>> g[N];
int par[N][30];
int dis[N];
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        int w = i.se;
        if(v != old)
        {
            h[v] = h[u] + 1;
            par[v][0] = u;
            dis[v] = dis[u] + w;
            dfs(v, u);
        }
    }
}
void init()
{
    for(int j = 1; (1 << j) <= n; j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
        }
    }
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);
    while(x > 0)
    {
        for(int i = tam; i >= 0; i--)
        {
            if((1 << i) <= x)
            {
                x -= 1 << i;
                u = par[u][i];
            }
        }
    }
    if(u == v)
        return u;
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {
            u = par[u][i];
            v = par[v][i];
        }
    }
    return par[u][0];
}
