#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e6 + 23;
const int INF = 0x3f3f3f3f3f3f3f3f;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int n, q;
int w[N];
int par[N];
vector<pair<int, int>> g[N], gvt[N];
int dp[20][N];
int h[N];
int dis[N], in[N], out[N];
int sz[N];
int k;
int timer = 0;
vector<int> vertex;
int ans = 0;
void dfs(int u, int p)
{
    in[u] = ++timer;
    for(auto i : g[u])
    {
        int v = i.fi;
        int ww = i.se;
        if(v == p)
            continue;
        h[v] = h[u] + 1;
        dis[v] = dis[u] + ww;
        dp[0][v] = u;
        dfs(v, u);
    }
    out[u] = timer;
}
void init()
{
    for(int i = 1; i < 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            dp[i][j] = dp[i - 1][dp[i - 1][j]];
        }
    }
}
int caldis(int u, int v)
{
    return (dis[v] - dis[u]) % MOD;
    // int l = lca(u, v);
    // return dis[u] + dis[v] - 2 * dis[l] % MOD;
}
bool cmp(int u, int v)
{
    return in[u] < in[v];
}
int lca(int u, int v)
{
    if(h[v] > h[u])
        swap(u, v);
    for(int i = 19; i >= 0; i--)
    {
        if(h[dp[i][u]] >= h[v])
            u = dp[i][u];
    }
    if(u == v)
        return u;
    for(int i = 19; i >= 0; i--)
    {
        if(dp[i][u] != dp[i][v])
        {
            u = dp[i][u];
            v = dp[i][v];
        }
    }
    return dp[0][u];
}
bool isancs(int u, int v)
{
    return in[u] <= in[v] && out[v] <= out[u];
}
int buildvt()
{
    vector<int> v;
    for(auto u : vertex)
    {
        while(v.size() >= 2 && isancs(v.back(), u) == false)
        {
            int x = v[v.size() - 2];
            int y = v.back();
            gvt[x].pb({y, caldis(x, y)});
            v.pop_back();
        }
        v.pb(u);
    }
    while(v.size() >= 2)
    {
        int x = v[v.size() - 2];
        int y = v.back();
        gvt[x].pb({y, caldis(x, y)});
        v.pop_back();
    }
    return v[0];
}
void dfs2(int u)
{
    for(auto i : gvt[u])
    {
        int v = i.fi;
        int ww = i.se;
        dfs2(v);
        sz[u] += sz[v];
        ans = ans + sz[v] * (k - sz[v]) % MOD * ww % MOD;
    }
}
void virtualtree()
{
    vector<int> a;
    cin >> k;
    int x;
    
    for(int i = 1; i <= k; i++)
    {
        cin >> x;
        sz[x] = 1;
        a.pb(x);
        vertex.pb(x);
    }
    sort(a.begin(), a.end(), cmp);
    for(int i = 0; i < k - 1; i++)
    {
        vertex.pb(lca(a[i], a[i + 1]));
    }
    sort(vertex.begin(), vertex.end(), cmp);
    vertex.erase(unique(vertex.begin(), vertex.end()), vertex.end());
    ans = 0;
    int root = buildvt();
    dfs2(root);
    cout << ans % MOD << "\n";
    for(auto u : vertex)
    {
        sz[u] = 0;
        gvt[u].clear();
    }
}
