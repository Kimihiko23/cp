mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
int flor(int a, int b)
{
    return a / b - (a % b && (a ^ b) < 0);
}
vector<int> dx{0, 0, 1, -1}, dy{-1, 1, 0, 0};
int p[N];
int w[N];
int par[21][N];
int n, q, k;
vector<pair<int, int>> g[N];
int h[N], dis[N];
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        int ww = i.se;
        if(v == old)
            continue;
        h[v] = h[u] + 1;
        dis[v] = dis[u] + ww;
        par[0][v] = u;
        dfs(v, u);
    }
}
void init()
{
    for(int i = 1; i <= 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            par[i][j] = par[i - 1][par[i - 1][j]];
        }
    }
}
void read()
{
    cin >> n >> q;
    for(int i = 2; i <= n; i++)
    {
        cin >> p[i];
    }
    for(int i = 2; i <= n; i++)
    {
        cin >> w[i];
        g[p[i]].pb({i, w[i]});
        g[i].pb({p[i], w[i]});
    }
}
void solve()
{
    par[0][1] = 1;
    dfs(1, 0);
    init();
}
