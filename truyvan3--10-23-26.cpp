int par[21][N], h[N], mx[21][N];
int n, q, k;
int p[N], w[N];
vector<pair<int, int>> g[N], gvt[N];
vector<int> v;
int pardsu[N], sz[N];
int timer = 0;
int in[N], out[N];
vector<pair<int, pair<int, int>>> edge;
int findpar(int u)
{
    if(pardsu[u] == u) return u;
    return pardsu[u] = findpar(pardsu[u]);
}
void join(int u, int v)
{
    u = findpar(u);
    v = findpar(v);
    if(u == v) return;
    if(sz[u] < sz[v]) swap(u, v);
    pardsu[v] = u;
    sz[u] += sz[v];
}
void dfs(int u, int old)
{
    in[u] = timer++;
    for(auto i : g[u])
    {
        int v = i.fi;
        int ww = i.se;
        if(v == old) continue;
        par[0][v] = u;
        h[v] = h[u] + 1;
        mx[0][v] = ww;
        dfs(v, u);
    }
    out[u] = timer;
}
void init()
{
    for(int i = 1; i <= 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            par[i][j] = par[i - 1][par[i - 1][j]];
            mx[i][j] = max(mx[i - 1][j], mx[i - 1][par[i - 1][j]]);
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    for(int i = 20; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
        {
            u = par[i][u];
        }
    }
    if(u == v) return u;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            u = par[i][u];
            v = par[i][v];
        }
    }
    return par[0][u];
}
int mxw(int u, int v)
{
    int res = 0;
    if(h[u] < h[v]) swap(u, v);
    for(int i = 20; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
        {
            res = max(res, mx[i][u]);
            u = par[i][u];
        }
    }
    if(u == v) return res;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            res = max(res, mx[i][u]);
            res = max(res, mx[i][v]);
            u = par[i][u];
            v = par[i][v];
        }
    }
    res = max(res, mx[0][u]);
    res = max(res, mx[0][v]);
    return res;
}
bool cmp(int a, int b)
{
    return in[a] < in[b];
}
bool isanc(int u, int v)
{
    return in[u] <= in[v] && out[u] >= out[v];
}
int buildvt()
{
    sort(v.begin(), v.end(), cmp);
    int nn = v.size();
    for(int i = 0; i < nn - 1; i++)
    {
        int u = v[i];
        int vv = v[i + 1];
        int l = lca(u, vv);
        v.pb(l);
    }
    sort(v.begin(), v.end(), cmp);
    v.erase(unique(v.begin(), v.end()), v.end());
    vector<int> tam;
    for(auto i : v)
    {
        //bug right here used to !isanc(tam[tam.size() - 2], i)
        //tam.back is right
        while(tam.size() >= 2 && !isanc(tam.back(), i))
        {
            int ww = mxw(tam[tam.size() - 2], tam.back());
            edge.pb({ww, {tam[tam.size() - 2], tam.back()}});
            // gvt[tam[tam.size() - 2]].pb({tam.back(), ww});
            // gvt[tam.back()].pb({tam[tam.size() - 2], ww});
            tam.pop_back();
        }
        tam.pb(i);
    }
    while(tam.size() >= 2)
    {
        int ww = mxw(tam[tam.size() - 2], tam.back());
        edge.pb({ww, {tam[tam.size() - 2], tam.back()}});
        // gvt[tam[tam.size() - 2]].pb({tam.back(), ww});
        // gvt[tam.back()].pb({tam[tam.size() - 2], ww});
        tam.pop_back();
    }
    return tam[0];
}
