int par[21][N], h[N], mx[21][N];
int n, q, k;
int p[N], w[N];
vector<pair<int, int>> g[N], gvt[N];
vector<int> v;
void dfs(int u, int old)
{
    for(auto i : g[u])
    {
        int v = i.fi;
        int ww = i.se;
        par[0][v] = u;
        h[u] = h[v] + 1;
        mx[0][v] = ww;
        dfs(v, u);
    }
}
void init()
{
    for(int i = 1; i <= 20; i++)
    {
        for(int j = 1; j <= n; j++)
        {
            par[i][j] = par[i - 1][par[i - 1][j]];
            mx[i][j] = max(mx[i - 1][j], mx[i - 1][par[i - 1][j]]);
        }
    }
}
int lca(int u, int v)
{
    if(h[u] < h[v]) swap(u, v);
    for(int i = 20; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
        {
            u = par[i][u];
        }
    }
    if(u == v) return u;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            u = par[i][u];
            v = par[i][v];
        }
    }
    return par[0][u];
}
int mxw(int u, int v)
{
    int res = 0;
    if(h[u] < h[v]) swap(u, v);
    for(int i = 20; i >= 0; i--)
    {
        if(h[par[i][u]] >= h[v])
        {
            res = max(res, mx[i][u]);
            u = par[i][u];
        }
    }
    if(u == v) return res;
    for(int i = 20; i >= 0; i--)
    {
        if(par[i][u] != par[i][v])
        {
            res = max(res, mx[i][u]);
            res = max(res, mx[i][v]);
            u = par[i][u];
            v = par[i][v];
        }
    }
    res = max(res, mx[0][u]);
    res = max(res, mx[0][v]);
    return res;
}
