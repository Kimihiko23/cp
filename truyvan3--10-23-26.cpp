void solve()
{
    par[0][1] = 1;
    dfs(1, 0);
    init();
    while(q--)
    {
        cin >> k;
        int x;
        for(int i = 1; i <= k; i++)
        {
            cin >> x;
            v.pb(x);
            sz[x] = 1;
            pardsu[x] = x;
        }
        buildvt();
        //need to put par for the non query vertex bc u also join them so yeah
        for(auto i : v)
        {
            if(pardsu[i] == 0) pardsu[i] = i;
        }
        sort(edge.begin(), edge.end());
        int ans = 0;
        for(auto i : edge)
        {
            int u = i.se.fi;
            int v = i.se.se;
            int ww = i.fi;
            //no mod bc i didnt read the problem statment
            ans += ww * sz[findpar(u)] * sz[findpar(v)];
            join(u, v);
        }
        cout << ans << "\n";
        edge.clear();
        for(auto i : v)
        {
            gvt[i].clear();
            sz[i] = 0;
            pardsu[i] = 0;
        }
        v.clear();
    }
    timer = 0;
    for(int i = 1; i <= n; i++)
    {
        g[i].clear();
        in[i] = 0;
        out[i] = 0;
        for(int j = 0; j <= 20; j++)
        {
            par[j][i] = 0;
            mx[j][i] = 0;
        }
    }
}
