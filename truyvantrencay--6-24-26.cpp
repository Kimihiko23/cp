const int N = 2e5 + 23;
int n, q;
int st[N * 4];
int par[N], heavy[N], sz[N];
int head[N], pos[N];
int idd[N];
int cnt = 0;
vector<int> g[N];
void dfs(int u)
{
    sz[u] = 1;
    for(auto v : g[u])
    {
        if(par[u] != v)
        {
            par[v] = u;
            dfs(v);
            sz[u] += sz[v];
            if(sz[heavy[u]] < sz[v])
                heavy[u] = v;
        }
    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cnt;
    idd[cnt] = u;
    if(heavy[u] > 0)
        hld(heavy[u], hd);
    for(auto v : g[u])
    {
        if(v != par[u] && v != heavy[u])
        {
            hld(v, v);
        }
    }
}
int lca(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]])
            v = par[head[v]];
        else
            u = par[head[u]];
    }
    return (pos[u] < pos[v]) ? u : v;
}
