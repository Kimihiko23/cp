void update(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos)
        return;
    if(l == r)
    {
        if(st[id] != 1e18)
            st[id] = 1e18;
        else
            st[id] = pos;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = min(st[id * 2], st[id * 2 + 1]);
}
int get(int id, int l, int r, int u, int v)
{
    if(l >= u && r <= v)
        return st[id];
    if(l > v || r < u)
        return 1e18;
    int mid = (l + r) / 2;
    return min(get(id * 2, l, mid, u, v), get(id * 2 + 1, mid + 1, r, u, v));
}
void read()
{
    cin >> n >> q;
    int u, v;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v;
        g[u].pb(v);
        g[v].pb(u);
    }
}
void solve()
{
    dfs(1);
    hld(1, 1);
    int ty, x;
    for(int i = 1; i <= n; i++)
    {
        update(1, 1, n, pos[i], 1e18);
    }
    while(q--)
    {
        cin >> ty >> x;
        if(ty == 0)
        {
            update(1, 1, n, pos[x], 0);
        }
        else
        {
            int ans = 1e18;
            while(head[x] != head[1])
            {
                ans = min(ans, get(1, 1, n, pos[head[x]], pos[x]));
                x = par[head[x]];
            }
            ans = min(ans, get(1, 1, n, pos[1], pos[x]));
            if(ans == 1e18)
                cout << -1 << "\n";
            else
                cout << idd[ans] << "\n";
        }
    }
}
