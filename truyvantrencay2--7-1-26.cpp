mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
struct node
{
    int mx = 0, lz = 0, mn = 0;
}; 
node st[N * 4];
int n;
vector<int> g[N];
struct edge
{
    int u, v, w;
};
int head[N], pos[N], sz[N], par[N], heavy[N], cur_pos = 0;
vector<pair<int, int>> edges;
vector<edge> edges2;
void down(int id, int l, int r)
{
    if(st[id].lz % 2 == 1)
    {
        int mid = l + (r - l) / 2;
        int tam1 = st[id * 2].mx;
        int tam2 = st[id * 2 + 1].mx;
        st[id * 2].mx = st[id * 2].mn * -1;
        st[id * 2 + 1].mx = st[id * 2 + 1].mn * -1;
        st[id * 2].mn = tam1 * -1;
        st[id * 2 + 1].mn = tam2 * -1;
        st[id * 2].lz++;
        st[id * 2 + 1].lz++;
        st[id].lz = 0;
    }
}
void update(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) 
        return;
    if(l >= u && r <= v)
    {
        int tam = st[id].mx;
        st[id].mx = st[id].mn * -1;
        st[id].mn = tam * -1;
        st[id].lz++;
        return;
    }
    down(id, l, r);
    int mid = l + (r - l) / 2;
    update(id * 2, l, mid, u, v);
    update(id * 2 + 1, mid + 1, r, u, v);
    st[id].mx = max(st[id * 2].mx, st[id * 2 + 1].mx);
    st[id].mn = min(st[id * 2].mn, st[id * 2 + 1].mn);
}
void updatep(int id, int l, int r, int pos, int val)
{
    if(l > pos || r < pos) 
        return;
    if(l == r && l == pos)
    {
        st[id].mx = val;
        st[id].mn = val;
        return;
    }
    down(id, l, r);
    int mid = l + (r - l) / 2;
    updatep(id * 2, l, mid, pos, val);
    updatep(id * 2 + 1, mid + 1, r, pos, val);
    st[id].mx = max(st[id * 2].mx, st[id * 2 + 1].mx);
    st[id].mn = min(st[id * 2].mn, st[id * 2 + 1].mn);
}
node get(int id, int l, int r, int u, int v)
{
    if(l > v || r < u) 
        return {NINF, 0, INF};
    if(l >= u && r <= v)
        return st[id];
    down(id, l, r);
    int mid = l + (r - l) / 2;
    node x = get(id * 2, l, mid, u, v);
    node y = get(id * 2 + 1, mid + 1, r, u, v);
    return {max(x.mx, y.mx), 0, min(x.mn, y.mn)};
}
void getpath(int u, int v)
{
    int res = NINF;
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]]) swap(u, v);
        node tmp = get(1, 1, n, pos[head[u]], pos[u]);
        res = max(res, tmp.mx);
        u = par[head[u]];
    }
    if(pos[u] > pos[v]) swap(u, v);
    if(u != v)
    {
        node tmp = get(1, 1, n, pos[u] + 1, pos[v]);
        res = max(res, tmp.mx);
    }
    cout << res << "\n";
}
void update_neg_path(int u, int v)
{
    while(head[u] != head[v])
    {
        if(pos[head[u]] < pos[head[v]]) swap(u, v);
        update(1, 1, n, pos[head[u]], pos[u]);
        u = par[head[u]];
    }
    if(pos[u] > pos[v]) swap(u, v);
    if(u != v)
        update(1, 1, n, pos[u] + 1, pos[v]);
}
void dfs(int u)
{
    sz[u] = 1;
    int mxsz = 0;
    for(auto v : g[u])
    {
        if(v == par[u]) continue;
        par[v] = u;
        dfs(v);
        sz[u] += sz[v];
        if(sz[v] > mxsz)
        {
            mxsz = sz[v];
            heavy[u] = v;
        }
    }
}
void hld(int u, int hd)
{
    head[u] = hd;
    pos[u] = ++cur_pos;
    if(heavy[u]) hld(heavy[u], hd);
    for(auto v : g[u])
    {
        if(v == par[u] || v == heavy[u]) continue;
        hld(v, v);
    }
}
void read()
{
    cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        edges.pb({u, v});
        edges2.pb({u, v, w});
        g[u].pb(v);
        g[v].pb(u);
    }
    // cout << n;
}
void solve()
{
    dfs(1);
    hld(1, 1);
    for(int i = 0; i < n - 1; i++)
    {
        int u = edges2[i].u;
        int v = edges2[i].v;
        int w = edges2[i].w;
        if(par[v] == u) swap(u, v);
        updatep(1, 1, n, pos[u], w);
    }
    // getpath(1, 2);
    string ty;
    int u, v;
    while(cin >> ty)
    {
        if(ty == "DONE")
            break;
        cin >> u >> v;
        if(ty == "CHANGE")
        {
            int uu = edges[u - 1].fi;
            int vv = edges[u - 1].se;
            if(par[vv] == uu) swap(uu, vv);
            updatep(1, 1, n, pos[uu], v);
        }
        else
        if(ty == "NEGATE")
        {
            update_neg_path(u, v);
        }
        else 
        if(ty == "QUERY")
        {
            // cout << "gey";
            if(u != v)
                getpath(u, v);
            else
                cout << 0 << "\n";
        }
    }
}
