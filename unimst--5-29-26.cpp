const int MOD = 1000020409;
const int N = 1e5 + 23;
int n, m;
vector<pair<int, pair<int, int>>> edg;
vector<pair<int, int>> g[N];
int par[N], sz[N];
map<int, int> mp;
int find(int u)
{
    if(par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(u == v) return;
    if(sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
}
void read()
{
    cin >> n >> m;
    int u, v, w;
    for(int i = 1; i <= m; i++)
    {
        cin >> u >> v >> w;
        edg.pb({w, {u, v}});
    }
}
void solve()
{
    int ans = 0;
    for(int i = 1; i <= n; i++)
    {
        par[i] = i;
        sz[i] = 1;
    }
    sort(edg.begin(), edg.end());
    int dem1 = 0, dem2 = 0;
    vector<pair<int, pair<int, int>>> edg2;
    int oldw = -1;
    for(int i = 0; i < edg.size(); i++)
    {
        int w = edg[i].fi;
        int u = edg[i].se.fi;
        int v = edg[i].se.se;
        if(w != oldw || i == edg.size() - 1)
        {
            oldw = w;
            dem1 = 0;
            dem2 = 0;
            for(auto j : edg2)
            {
                int u = j.se.fi;
                int v = j.se.se;
                if(find(u) != find(v))
                {
                    dem1++;
                }
            }
            for(auto j : edg2)
            {
                int u = j.se.fi;
                int v = j.se.se;
                if(find(u) != find(v))
                {
                    dem2++;
                    join(u, v);
                }
            }
            ans += abs(dem1 - dem2);
            edg2.clear();
        }
        if(find(u) != find(v))
            edg2.pb({w, {u, v}});
    }
    cout << ans;
}
