#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"

const int MOD = 1000020409;
const int N = 2005;

struct edge
{
    int u , v , w;
};

int n , m;
vector < edge > e;

struct DSU
{
    int par[N];

    void init()
    {
        for (int i = 1 ; i <= n ; i++)
            par[i] = i;
    }

    int find(int u)
    {
        if (par[u] == u) return u;
        return par[u] = find(par[u]);
    }

    bool unite(int u , int v)
    {
        u = find(u);
        v = find(v);

        if (u == v) return false;

        par[u] = v;
        return true;
    }
} dsu;

void read()
{
    cin >> n >> m;

    for (int i = 1 ; i <= m ; i++)
    {
        int u , v , w;
        cin >> u >> v >> w;

        e.pb({u , v , w});
    }
}

void solve()
{
    sort(e.begin() , e.end() , [](edge a , edge b)
    {
        return a.w < b.w;
    });

    dsu.init();

    int ans = 0;

    for (int i = 0 ; i < m ; )
    {
        int j = i;

        while (j < m && e[j].w == e[i].w)
            j++;

        vector < pair<int,int> > cur;
        vector < int > nodes;

        for (int k = i ; k < j ; k++)
        {
            int u = dsu.find(e[k].u);
            int v = dsu.find(e[k].v);

            if (u == v) continue;

            cur.pb({u , v});

            nodes.pb(u);
            nodes.pb(v);
        }

        map < int , vector<int> > adj;
        map < pair<int,int> , int > cnt;

        for (auto x : cur)
        {
            int u = x.fi;
            int v = x.se;

            adj[u].pb(v);
            adj[v].pb(u);

            if (u > v) swap(u , v);

            cnt[{u , v}]++;
        }

        map < int , int > vis;

        for (auto x : nodes)
        {
            if (vis[x]) continue;

            queue < int > q;
            q.push(x);

            vis[x] = 1;

            int V = 0;
            int E = 0;

            vector < int > comp;

            while (!q.empty())
            {
                int u = q.front();
                q.pop();

                comp.pb(u);
                V++;

                for (auto v : adj[u])
                {
                    E++;

                    if (!vis[v])
                    {
                        vis[v] = 1;
                        q.push(v);
                    }
                }
            }

            E /= 2;

            ans += E - (V - 1);
        }

        for (int k = i ; k < j ; k++)
            dsu.unite(e[k].u , e[k].v);

        i = j;
    }

    cout << ans;
}

