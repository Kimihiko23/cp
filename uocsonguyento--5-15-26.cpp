void solve()
{

    for (int i = 2; i <= 1000000; i++)
    {
        if (cnt[i] == 0) 
        {
            for (int j = i; j <= 1000000; j += i)
            {
                cnt[j]++;
            }
        }
    }
    for (int k = 0; k <= 7; k++)
    {
        for (int i = 1; i <= 1000000; i++)
        {
            pref[k][i] = pref[k][i - 1] + (cnt[i] >= k);
        }
    }
    while (q--)
    {
        int a, b, k;
        cin >> a >> b >> k;

        cout << pref[k][b] - pref[k][a - 1] << '\n';
    }
}

