#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e5+23;
vector<pair<int,int>> g[N];
int n, m, st, ed;
void dijsktra()
{
    priority_queue<pair<int,int>, vector<pair<int,int>>, greater<pair<int,int>>> pq;
    vector<int> dist(n+1, LLONG_MAX);
    dist[st] = 0;
    pq.push({0, st});
    while(!pq.empty())
    {
        auto [d, u] = pq.top();
        pq.pop();
        if(d > dist[u]) continue;
        for(auto [v, w] : g[u])
        {
            if(dist[u] + w < dist[v])
            {
                dist[v] = dist[u] + w;
                pq.push({dist[v], v});
            }
        }
    }
    if(dist[ed] == LLONG_MAX) cout << -1 << endl;
    else cout << dist[ed] << endl;
}
void read()
{
    cin >> n >> m >> st >> ed;
    for(int i = 1; i <= m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
    }
}
void solve()
{
   dijsktra();
}
