#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
}
struct ed
{
    int u, v, w;
};
ed edge[N];
int a[N];
int n, m, q;
struct qe
{
    int u, v, k;
};
bool cmp(ed a, ed b)
{
    return a.w < b.w;
}
qe query[N];
int par[N];
int find(int u)
{
    if (par[u] == u) return u;
    return par[u] = find(par[u]);
}
set<int> s[N];
int sz[N];
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if (u == v) return;
    if (sz[u] < sz[v]) swap(u, v);
    sz[u] += sz[v];
    par[v] = u;
    for (auto x : s[v]) s[u].insert(x);
}
int L[N], R[N], ans[N];
vector<int> ned[N];
void read()
{
    cin >> n >> m >> q;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
        par[i] = i;
        s[i].insert(a[i]);
        sz[i] = 1;
    }
    for(int i = 1; i <= m; i++)
    {
        cin >> edge[i].u >> edge[i].v >> edge[i].w;
    }
    for(int i = 1; i <= q; i++)
    {
        cin >> query[i].u >> query[i].v >> query[i].k;
        L[i] = 0;
        R[i] = m;
        ans[i] = -1;
    }
}
void solve()
{
    sort(edge + 1, edge + m + 1, cmp);
    while(1)
    {
        bool stop = true;
        for(int i = 1; i <= q; i++)
        {
            if(L[i] > R[i]) continue;
            stop = false;
            int mid = (L[i] + R[i]) / 2;
            ned[mid].pb(i);
        }
        if(stop) break;
        for(int i = 1; i <= n; i++)
        {
            par[i] = i;
            s[i].clear();
            s[i].insert(a[i]);
            sz[i] = 1;
        }
        for(int i = 0; i <= m; i++)
        {
            if(i > 0)
                join(edge[i].u, edge[i].v);
            for(auto id : ned[i])
            {
                int u = query[id].u;
                int v = query[id].v;
                int k = query[id].k;
                u = find(u);
                v = find(v);
                if(u != v || s[u].size() < k)
                {
                    L[id] = i + 1;
                    // continue;
                }
                else
                {
                    ans[id] = edge[i].w;
                    R[id] = i - 1;
                }
            }
        }
        for(int i = 1; i <= m; i++) ned[i].clear();
    }
    for(int i = 1; i <= q; i++)
    {
        cout << ans[i] << "\n";
    }
}
