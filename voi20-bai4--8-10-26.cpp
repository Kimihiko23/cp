int n, m, k;
vector<vector<pair<int, int>>> stw;
vector<vector<int>> a;
int mod3(int x)
{
    return (x % 3 + 3) % 3;
}
int check(int tar)
{
   vector<vector<int>> val;
   vector<vector<int>> dif;
   int res = 0;
   val.assign(n + 2, vector<int>(m + 2));
   dif.assign(n + 2, vector<int>(m + 2));
   for(int i = 1; i <= n; i++)
   {
        for(int j = 1; j <= m; j++)
        {
            //get the value like dif 2d
            val[i][j] = val[i - 1][j] + val[i][j - 1] - val[i - 1][j - 1] + dif[i][j];
            val[i][j] = mod3(val[i][j]);
            int ned = mod3(tar - mod3(val[i][j] + a[i][j]));
            if(ned > 0)
            {
                if(stw[i][j] == make_pair((int)-1, (int)-1))
                    return 1e18;
                //update path
                res += ned;
                int nx = stw[i][j].fi;
                int ny = stw[i][j].se;
                dif[i][ny + 1] = mod3(dif[i][ny + 1] - ned);
                dif[nx + 1][j] = mod3(dif[nx + 1][j] - ned);
                dif[nx + 1][ny + 1] = mod3(dif[nx + 1][ny + 1] + ned);
                val[i][j] = mod3(val[i][j] + ned);
            }
        }
   }
   return res; 
}
void read()
{
    cin >> n >> m >> k;
    a.assign(n + 2, vector<int>(m + 2));
    stw.assign(n + 2, vector<pair<int, int>>(m + 2));
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            stw[i][j] = {-1, -1};
        }
    }
    int stx, sty, edx, edy;
    for(int i = 1; i <= k; i++)
    {
        cin >> stx >> sty >> edx >> edy;
        stw[stx][sty] = {edx, edy};
    }
}
void solve()
{
    int cas1 = check(1);
    int cas2 = check(2);
    int ans = min(cas1, cas2);
    if(ans == 1e18)
        cout << -1;
    else
        cout << ans;
}
