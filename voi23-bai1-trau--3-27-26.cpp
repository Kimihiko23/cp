using namespace std;
const int N =1e5+23;
int ans = 1e18;
string s;
int n = 0;
vector<int> res;
vector<char> ch{'A', 'T', 'G', 'X'};
void check(string ip)
{
    string tem = s;
    int vt = 0;
    for(int i = 0; i < s.size(); i++)
    {
        if(tem[i] == '?')
        {
            tem[i] = ip[vt];
            vt++;
        }
    }
    int i = 0;
    tem += " ";
    res.clear();
    while(i < s.size())
    {
        int dem = 1;
        while(tem[i] == tem[i + 1])
        {
            dem++;
            i++;
        }
        i++;
        res.pb(dem);
    }
    int sum = s.size() * (s.size() - 1) / 2;
    for(auto i : res)
    {
        sum -= i * (i - 1) / 2;
    }
    ans = min(ans, sum);
}
void sinh(string tam)
{
    if(tam.size() == n)
    {
        check(tam);
        return;
    }
    for(auto i : ch)
    {
        sinh(tam + i);
    }
}
void read()
{
    cin >> s;
}
void solve()
{
    for(auto i : s)
    {
        if(i == '?')
        {
            n++;
        }
    }
    sinh("");
    cout << ans;
}
