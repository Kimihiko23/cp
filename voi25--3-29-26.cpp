using namespace std;
const int N =2e5+23;
int h[N];
int n, m;
vector<int> g[N];
int par[N][30];
int mx[N][30];
vector<int> k[N];
int ansmx = -1e18;
int W[N];
int dp[N];
void dfs(int u, int old)
{
    if (old == -1) mx[u][0] = W[u];
    for(auto i : g[u])
    {
        int v = i;
        if(v != old)
        {
            h[v] = h[u] + 1;
            par[v][0] = u;
            mx[v][0] = max(W[u], W[v]);
            dfs(v, u);
        }
    }
}
void init()
{
    for(int j = 1; j <= log2(n); j++)
    {
        for(int i = 1; i <= n; i++)
        {
            par[i][j] = par[par[i][j - 1]][j - 1];
            mx[i][j] = max(mx[i][j - 1], mx[par[i][j - 1]][j - 1]);
        }
    }
}
int lca(int u, int v)
{
    ansmx = -1e18;
    if(h[v] > h[u])
        swap(u, v);
    int x = h[u] - h[v];
    int tam = log2(n);

    for(int i = tam; i >= 0; i--)
    {
        if((1 << i) <= x)
        {
            ansmx = max(ansmx, mx[u][i]);
            x -= (1 << i);
            u = par[u][i];
            
        }
    }
    
    if(u == v)
    {
        ansmx = max(ansmx, W[u]);
        return u;
    }
    for(int i = tam; i >= 0; i--)
    {
        if(par[u][i] != par[v][i])
        {

            ansmx = max(ansmx, mx[u][i]);
            ansmx = max(ansmx, mx[v][i]);
            u = par[u][i];
            v = par[v][i];
            
            
        }
    }
    ansmx = max(ansmx, mx[u][0]);
    ansmx = max(ansmx, mx[v][0]);
    ansmx = max(ansmx, W[par[u][0]]);
    return par[u][0];
}
