void solve()
{
    for(int i = 1; i <= n; i++)
    {
        for(int j = 0; j <= 29; j++)
        {
            mx[i][j] = -1e18;
        }
    }
    dfs(1, -1);
    init();
    dp[1] = 0;
    for(int i = 2; i <= n; i++)
    {
        dp[i] = -1e18;
    }
    int q;
    cin >> q;
    while(q--)
    {
        int u, v;
        cin >> u >> v;
        lca(u, v);
        dp[v] = max(dp[v], dp[u] + ansmx);
    }
    cout << *max_element(dp + 1, dp + n + 1);
    

}
