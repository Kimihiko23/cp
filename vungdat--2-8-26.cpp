#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N =1e3+23;
vector<pair<int, pair<int, int>>> pq;
int n, m, q;
int a[N][N];
bool out[N][N];
int ans[N * N];
int dem = 0;
vector<pair<int, int>> que;
int par[N * N];
int sz[N * N];
int conve(int x, int y)
{
    return m * (x- 1) + y;
}
int find(int u)
{
    if(par[u] == u) return u;
    return par[u] = find(par[u]);
}
void join(int u, int v)
{
    u = find(u);
    v = find(v);
    if(u == v) return;
    dem--;
    if(sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
}
void read()
{
    cin >> n >> m;
    for(int i = 1; i <= n; i++)
    {
        for(int j = 1; j <= m; j++)
        {
            cin >> a[i][j];
            pq.pb({a[i][j], {i, j}});
            par[conve(i, j)] = conve(i, j);
            sz[conve(i, j)] = 1;
        }
    }
    cin >> q;
    for(int i = 1; i <= q; i++)
    {
        int x;
        cin >> x;
        que.pb({x, i});
    }
   
}
void solve()
{
   
   sort(que.begin(), que.end(), greater());
   sort(pq.begin(), pq.end());
    int j = n * m - 1;
   for(auto i : que)
   {
        while(j >= 0 && pq[j].fi > i.fi)
        {
            dem++;
            int x = pq[j].se.fi;
            int y = pq[j].se.se;
            out[x][y] = 1;
            int id1 = conve(x, y);
            vector<int> dx = {0, 0, 1, -1};
            vector<int> dy = {1, -1, 0, 0};
            for(int dir = 0; dir < 4; dir++)
            {
                int nx = x + dx[dir];
                int ny = y + dy[dir];
                if(nx >= 1 && nx <= n && ny >= 1 && ny <= m && a[nx][ny] > i.fi)
                {
                    int id2 = conve(nx, ny);
                    join(id1, id2);
                    
                }
            }
            j--;
        }
        ans[i.se] = dem;
    }
    for(int i = 1 ; i <= q ; i++)
    {
          cout << ans[i] << "\n";
    }
   
}
siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    freopen("input.txt","r",stdin);
    freopen("output.txt","w",stdout);
    read();
    solve();
  

   
    
} 
