const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
string L, R;
int ans = 0;
int dp[105][11][2][2];
int g(string &num)
{
    for(int i = 0; i < num.size() - 1; i++)
    {
        if(num[i] == num[i + 1])
            return 0;
    }
    return 1;
}
int f(string &num, int pos, int old, int tight, int lead)
{
    if(pos == 0)
        return 1;
    if(dp[pos][old][tight][lead] != -1)
        return dp[pos][old][tight][lead];
    int limit = 9;
    if(tight)
        limit = num[num.size() - pos] - '0';
    int ans = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(i == 0)
        {
            if(lead == 1)
            {
                ans += f(num, pos - 1, 0, tight & (i == limit), 1);
                ans %= MOD;
            }
            else if(old != 0)
            {
                ans += f(num, pos - 1, 0, tight & (i == limit), 0);
                ans %= MOD;
            }
        }
        else if (i != old)
        {
            ans += f(num, pos - 1, i, tight & (i == limit), 0);
            ans %= MOD;
        }
    }
    dp[pos][old][tight][lead] = ans;
    return ans;
}
