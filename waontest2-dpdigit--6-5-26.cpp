void solve()
{
    memset(dp, -1, sizeof(dp));
    int ansr = f(R, R.size(), 10, 1, 1);
    memset(dp, -1, sizeof(dp));
    int ansl = f(L, L.size(), 10, 1, 1);
    cout << (ansr - ansl + g(L) + MOD) % MOD;

}
