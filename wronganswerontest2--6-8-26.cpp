#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
int dp[105][2][2], way[105][2][2];
string l, r, k;
int g(string &s)
{
    int res = 0;
    for(auto i : s)
    {
        if(i == k[0]) 
        res++;
    }
    return res;
}
pair<int, int> f(string &s, int pos, int tight, int lead)
{
    if(pos == 0)
    {
        // cout << "gay";
        return {0, 1};
    }
    if(dp[pos][tight][lead] != -1)
    {
        return {dp[pos][tight][lead], way[pos][tight][lead]};
    }
    int ans1 = 0, ans2 = 0;
    int limit = 9;
    if(tight)
    {
        limit = s[s.size() - pos] - '0';
    }
    for(int i = 0; i <= limit; i++)
    {
        if(i == 0)
        {
            if(lead == 1)
            {
                auto tmp = f(s, pos - 1, (tight && (i == limit)), 1);
                ans1 += tmp.fi;
                ans2 += tmp.se;

                ans1 %= MOD;
                ans2 %= MOD;
            }
            else
            {
                auto tmp = f(s, pos - 1, (tight && (i == limit)), 0);
                ans1 += tmp.fi;
                if(k == "0")
                {
                    ans1 += tmp.se;
                }
                ans2 += tmp.se;

                ans1 %= MOD;
                ans2 %= MOD;
            }
        }
        else
        {
            auto tmp = f(s, pos - 1, (tight && (i == limit)), 0);
            ans1 += tmp.fi;
            if(i == k[0] - '0')
            {
                ans1 += tmp.se;
            }
            ans2 += tmp.se;

            ans1 %= MOD;
            ans2 %= MOD;
        }
    }
    dp[pos][tight][lead] = ans1;
    way[pos][tight][lead] = ans2;
    return {ans1, ans2};
}
void read()
{
    cin >> l >> r >> k;
}
void solve()
{
    memset(dp, -1, sizeof(dp));
    auto tmp1 = f(r, r.size(), 1, 1);
    memset(dp, -1, sizeof(dp));
    auto tmp2 = f(l, l.size(), 1, 1);
    int ans = (tmp1.fi - tmp2.fi + g(l) + MOD) % MOD;
    // string blah = "1111";
    // cout << g(blah);
    cout << ans;
}
