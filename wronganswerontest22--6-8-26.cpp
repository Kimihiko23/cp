const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 1e5 + 23;
string l, r, p;
int k;
int g(string &s)
{
    int dem = 0;
    for(auto i : s)
    {
        if(i == p[0]) dem++;
    }
    if(dem > k) return 0;
    return 1;
}
int dp[105][105][2][2];
int f(string &s, int pos, int cnt, int lead, int tight)
{
    if(pos == 0)
    {
        return (cnt >= 0);
    }
    if(cnt < 0) return 0;
    if(dp[pos][cnt][lead][tight] != -1) return dp[pos][cnt][lead][tight];
    int limit = 9;
    if(tight) limit = s[s.size() - pos] - '0';
    int res = 0;
    for(int i = 0; i <= limit; i++)
    {
        if(i == 0)
        {
            if(lead)
            {
                res += f(s, pos - 1, cnt, 1, tight && (i == limit));
                res %= MOD;
            }
            else
            {
                if(p[0] == '0') 
                    res += f(s, pos - 1, cnt - 1, 0, tight && (i == limit));
                else 
                    res += f(s, pos - 1, cnt, 0, tight && (i == limit));
                res %= MOD;
            }
        }
        else
        {
            if(p[0] - '0' == i) 
                res += f(s, pos - 1, cnt - 1, 0, tight && (i == limit));
            else 
                res += f(s, pos - 1, cnt, 0, tight && (i == limit));
            res %= MOD;
        }
    }
    return dp[pos][cnt][lead][tight] = res;
}
void read()
{
    cin >> l >> r >> k >> p;
}
void solve()
{
    memset(dp, -1, sizeof(dp));
    int ansr = f(r, r.size(), k, 1, 1);
    memset(dp, -1, sizeof(dp));
    int ansl = f(l, l.size(), k, 1, 1);
    int res = ansr - ansl;
    if(g(l)) res++;
    cout << (res + MOD) % MOD;
}
