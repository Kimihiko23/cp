#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
const int N = 1e5 + 23;

int n, m;
int x[N], y[N], p[N], sz[N];
int mnx[N], mxx[N], mny[N], mxy[N];

int find(int u)
{
    return p[u] == u ? u : p[u] = find(p[u]);
}

void uni(int a, int b)
{
    a = find(a);
    b = find(b);
    if (a == b) return;
    if (sz[a] < sz[b]) swap(a, b);
    p[b] = a;
    sz[a] += sz[b];
    mnx[a] = min(mnx[a], mnx[b]);
    mxx[a] = max(mxx[a], mxx[b]);
    mny[a] = min(mny[a], mny[b]);
    mxy[a] = max(mxy[a], mxy[b]);
}

void read()
{
    cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        cin >> x[i] >> y[i];
        p[i] = i;
        sz[i] = 1;
        mnx[i] = mxx[i] = x[i];
        mny[i] = mxy[i] = y[i];
    }
    for (int i = 1; i <= m; i++)
    {
        int a, b;
        cin >> a >> b;
        uni(a, b);
    }
}

void solve()
{
    int ans = LLONG_MAX;
    for (int i = 1; i <= n; i++)
    {
        if (find(i) == i)
        {
            int dx = mxx[i] - mnx[i];
            int dy = mxy[i] - mny[i];
            ans = min(ans, 2 * (dx + dy));
        }
    }
    cout << ans;
}

siesta()
{
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    if (fopen("input.txt", "r"))
    {
        freopen("input.txt", "r", stdin);
        freopen("output.txt", "w", stdout);
    }
    read();
    solve();
}
