using namespace std;
#define name "input"
const int MOD = 1e9 + 7;
const int N = 1e6 + 23;
int m, n, k;
int dp[N][(1 << 4)];
void read()
{
    cin >> m >> n >> k;
}
void solve()
{
    dp[0][0] = 1;
    for(int i = 1; i <= n; i++)
    {
        for(int mask = 0; mask < (1 << 4); mask++)
        {
            for(int j = 0; j < 4; j++)
            {
                if(mask & (1 << j))
                {
                    dp[i][mask] += dp[i - 1][mask] + dp[i - 1][mask ^ (1 << j)];
                    dp[i][mask] %= MOD;
                }
            }
        }
    }
    int x = 0;
    for(int mask = 0; mask < (1 << 4); mask++)
        if(__builtin_popcountll(mask) >= k)
        {
            x += dp[n][mask];
            x %= MOD;
        }
    int ans = 1;
    for(int i = 1; i <= m; i++)
    {
        ans *= x;
        ans %= MOD;
    }
    cout << ans;
}
