struct node
{
    int sum;
    int mx;
};
node st[N * 4];
int lz[N * 4];
int n;
int a[N];
int m;
node merg(node l, node r)
{
    return {l.sum + r.sum, max(l.mx, r.mx)};
}
void build(int l, int r, int id)
{
    if(l == r)
    {
        st[id].sum = a[l];
        st[id].mx = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(l, mid, id * 2);
    build(mid + 1, r, id * 2 + 1);
    st[id] = merg(st[id * 2], st[id * 2 + 1]);
}
void push(int id, int l, int r, int mid)
{
    if(lz[id] == -1)
        return;
    int x = lz[id];
    lz[id] = -1;

    lz[id * 2] = x;
    lz[id * 2 + 1] = x;

    st[id * 2].sum = (mid - l + 1) * x;
    st[id * 2 + 1].sum = (r - mid) * x;

    st[id * 2].mx = x;
    st[id * 2 + 1].mx = x;

}
void update(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u)
        return;
    if(l >= u && r <= v)
    {
        st[id].sum = (r - l + 1) * val;
        st[id].mx = val;
        lz[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    update(l, mid, id * 2, u, v, val);
    update(mid + 1, r, id * 2 + 1,u ,v, val);
    st[id] = merg(st[id * 2], st[id * 2 + 1]);
}
int get(int l, int r, int id, int u, int v, int val)
{
    if(l > v || r < u)
        return 0;
    if(l >= u && r <= v)
    {
        int res = st[id].sum;
        // update(1, n, 1, l, r, val);
        return res;
    }
    int mid = (l + r) / 2;
    push(id, l, r, mid);
    return get(l, mid, id * 2, u, v, val) + 
           get(mid + 1, r, id * 2 + 1, u, v, val);
}
void read()
{
    cin >> n;
    for(int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }
    cin >> m;
}
void solve()
{
    memset(lz, -1, sizeof(lz));
    build(1, n, 1);
    int vt, len;
    while(m--)
    {
        cin >> vt >> len;
        int val = get(1, n, 1, vt, vt, 0);
        int ans = get(1, n, 1, vt + 1, vt + len, val);
        update(1, n, 1, vt + 1, vt + len, val);
        cout << ans - len * val  << "\n";
    }
}
