#include <bits/stdc++.h>
#define int long long
#define pb push_back
#define fi first
#define ll long long
#define se second
#define siesta main
using namespace std;
#define name "input"
const int MOD1 = 1000020409;
const int MOD = 1e9 + 7;
const int N = 2e5 + 23;
const int INF = 1e18;
const int NINF = -1e18;
mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

int rand(int l, int r) 
{
    return uniform_int_distribution<int>(l, r)(rng);
} 
int n;
vector<pair<int, int>> g[N];
int one[N], zero[N];
int res = 0, ans = 0;
void dfs(int u, int p, int bit)
{
    int c1 = 0;
    int c0 = 1;
    for(auto i : g[u])
    {
        int v = i.fi;
        int w = i.se;
        if(v == p)
            continue;
        dfs(v, u, bit);
        int x  = one[v];
        int y  = zero[v];
        if((w >> bit) & 1) swap(x, y);
        res += 1LL * x * c0 + 1LL * y * c1;
        c1 += x;
        c0 += y;
    }

    one[u] += c1;
    zero[u] += c0;
}
void read()
{
    cin >> n;
    int u, v, w;
    for(int i = 1; i < n; i++)
    {
        cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
    }
}
void solve()
{
    for(int bi = 0; bi < 30; bi++)
    {
        memset(one, 0, sizeof(one));
        memset(zero, 0, sizeof(zero));
        res = 0;
        dfs(1, 0, bi);
        ans += res * (1LL << bi);
    }
    cout << ans;
}
